#!/usr/bin/env python3
"""Generate the unconditional OFFSETCLOSURE{M3,0,3} / PUSHOFFSETCLOSURE{M3,0,3}
rows and the operand OFFSETCLOSURE n / PUSHOFFSETCLOSURE n loop-head
simulations over ClosureOffsetRows.lean."""
import argparse
from census import ROOT

HEADER = '''/-! GENERATED by scripts/gen_offset_rows.py. Closure-offset rows of the F1
arm table: `ClosureOffset` from the step and the represented environment,
pushes from the budget and the runtime-framing contract. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives
'''

NOPUSH = '''
/-- **The {op} row.** -/
theorem {lower}_row {{L : OCaml.Layout}} {{P : Prog}} (stable : MemoryStable L.runtimeOk) :
    OCaml.OpArm P (OCaml.LoopAt L P) .{op} := by
  intro s c i reach h hd op _
  obtain ⟨o, args⟩ := i
  cases op
  cases args with
  | cons a as => exact trivial
  | nil =>
    apply OCaml.ArmOutcome.of_next
    · intro s' step
      exact closure_offset_next (d := {d}) (width := 1)
        (fun _ _ _ _ _ _ _ _ input sel => {lower}_arm stable input sel) h (decode_fetch hd).1 step
    · intro e w step
      change (match s.env with
        | .ptr l k => if (k : Int) + {d} < 0 then Res.wrong else
            .next {{ (s.adv 1) with accu := .ptr l ((k : Int) + {d}).toNat }}
        | _ => .wrong) = .halt e w at step
      split at step
      · split at step <;> simp_all
      · cases step
'''

PUSH = '''
/-- **The {op} row.** -/
theorem {lower}_row {{L : OCaml.Layout}} {{B : OCaml.Budget}} {{P : Prog}} {{high0 dom0 : Nat}}
    (rf : RuntimeFrame L high0 dom0) (fits : OCaml.Fits B P) (capacity : StackCapacity B) :
    OCaml.OpArm P (OCaml.LoopAt L P) .{op} := by
  intro s c i reach h hd op _
  obtain ⟨o, args⟩ := i
  cases op
  cases args with
  | cons a as => exact trivial
  | nil =>
    apply OCaml.ArmOutcome.of_next
    · intro s' step
      exact push_closure_offset_next (d := {d}) (width := 1) rf
        (fun _ _ _ _ _ _ _ _ _ stable input space sel pushed => {lower}_arm stable input space sel pushed)
        h (decode_fetch hd).1 (stack_fits fits capacity reach) step
    · intro e w step
      change (match s.env with
        | .ptr l k => if (k : Int) + {d} < 0 then Res.wrong else
            .next {{ ((pushAccu s).adv 1) with accu := .ptr l ((k : Int) + {d}).toNat }}
        | _ => .wrong) = .halt e w at step
      split at step
      · split at step <;> simp_all
      · cases step
'''

OPERAND = '''
/-- **OFFSETCLOSURE n from the loop head.** -/
theorem offsetclosure_next {L : OCaml.Layout} {P : Prog} {s s' : St} {c : Config} {w : BitVec 32}
    (stable : MemoryStable L.runtimeOk) (h : OCaml.LoopAt L P s c)
    (code : DispatchCode P s .OFFSETCLOSURE) (fetch : P.code[s.pc + 1]? = some w)
    (step : stepI P s ⟨.OFFSETCLOSURE, [w.toInt]⟩ = .next s') :
    ∃ c', OCaml.Plus c c' ∧ OCaml.LoopAt L P s' c' :=
  closure_offset_next (d := w.toInt) (width := 2)
    (fun _ _ _ _ _ _ _ _ input sel =>
      offsetclosure_arm stable input (OperandAt.of_fetch input.geometry fetch) sel) h code step

/-- **PUSHOFFSETCLOSURE n from the loop head.** -/
theorem pushoffsetclosure_next {L : OCaml.Layout} {P : Prog} {s s' : St} {c : Config}
    {w : BitVec 32} {high0 dom0 : Nat} (rf : RuntimeFrame L high0 dom0) (h : OCaml.LoopAt L P s c)
    (code : DispatchCode P s .PUSHOFFSETCLOSURE) (fetch : P.code[s.pc + 1]? = some w)
    (space : 8 * (s.stack.length + 1) ≤ Layout.stackBytes)
    (step : stepI P s ⟨.PUSHOFFSETCLOSURE, [w.toInt]⟩ = .next s') :
    ∃ c', OCaml.Plus c c' ∧ OCaml.LoopAt L P s' c' :=
  push_closure_offset_next (d := w.toInt) (width := 2) rf
    (fun _ _ _ _ _ _ _ _ _ stable input space sel pushed =>
      pushoffsetclosure_arm stable input space (OperandAt.of_fetch input.geometry fetch) sel pushed)
    h code space step
'''


def outputs():
    nullary = [('OFFSETCLOSUREM3', 'offsetclosurem3', '(-3)', NOPUSH), ('OFFSETCLOSURE0', 'offsetclosure0', '0', NOPUSH),
               ('OFFSETCLOSURE3', 'offsetclosure3', '3', NOPUSH),
               ('PUSHOFFSETCLOSUREM3', 'pushoffsetclosurem3', '(-3)', PUSH),
               ('PUSHOFFSETCLOSURE0', 'pushoffsetclosure0', '0', PUSH),
               ('PUSHOFFSETCLOSURE3', 'pushoffsetclosure3', '3', PUSH)]
    imports = ''.join(f'import OCaml.Vm.Sim.{lower.capitalize()}\n' for _, lower, _, _ in nullary)
    imports += 'import OCaml.Vm.Sim.Offsetclosure\nimport OCaml.Vm.Sim.Pushoffsetclosure\n'
    body = ''.join(t.format(op=op, lower=lower, d=d) for op, lower, d, t in nullary) + OPERAND
    return {ROOT / 'OCaml/Vm/Sim/OffsetRows.lean':
            imports + 'import OCaml.Vm.Sim.ClosureOffsetRows\nimport OCaml.Vm.Sim.StackRows\nimport OCaml.Vm.Sim.DecodeFetch\n\n'
            + HEADER + body + '\nend OCaml.Vm.Sim\n'}


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'offset row drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Closure-offset rows current')
