#!/usr/bin/env python3
"""Generate counted allocating rows from the existing generic opcode proofs."""
import argparse
from census import ROOT
from gen_counted_stack_rows import channel_certificate

ROWS = {
    'MAKEBLOCK': 'makeblock_row af fits g1_capacity f1_budgetSmall good',
    'MAKEBLOCK1': 'makeblock1_row af fits g1_capacity',
    'MAKEBLOCK2': 'makeblock2_row af fits g1_capacity',
    'MAKEBLOCK3': 'makeblock3_row af fits g1_capacity',
    'CLOSURE': 'closure_row rf af fits g1_capacity good',
    'CLOSUREREC': 'closurerec_row rf af fits g1_capacity good',
    'GRAB': 'grab_row stable af fits g1_capacity f1_budgetSmall',
}
HEADER = '''import OCaml.Vm.Sim.CountedAllocFrame
import OCaml.Vm.Sim.MakeblockNRows
import OCaml.Vm.Sim.ClosureAllocRows
import OCaml.Vm.Sim.ClosurerecAllocRows
import OCaml.Vm.Sim.GrabAllocRows
import OCaml.Vm.Sim.G1Capacity

/-! GENERATED by scripts/gen_counted_alloc_rows.py. Nursery allocating opcode
rows reuse native execution and existing GoodF1/Fits/capacity guards. The
physical channel frame is supplied by counted_allocFrame at the entry. -/

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine OCaml.Vm.Primitives

/-- Supported allocating opcodes; GC and primitive calls remain separate. -/
def countedAllocOpcode : Opcode → Bool
'''


def output():
    out = HEADER + ''.join(f'  | .{op} => true\n' for op in ROWS) + '  | _ => false\n'
    for op in ROWS:
        definitions = ('stepI, makeBlock' if op.startswith('MAKEBLOCK') else
                       'stepI' if op == 'GRAB' else 'stepI, opt')
        out += channel_certificate(op, definitions, variable=(op == 'CLOSUREREC'))
    for op, row in ROWS.items():
        good = ' (good : OCaml.GoodF1 P)' if 'good' in row else ''
        out += f'''
/-- Counted {op}, with every frame supplied from the actual entry runtime. -/
theorem counted_{op.lower()}_row {{P : Prog}}
    {{Ready : Nat → Config → Prop}} {{state Customs : Config → Nat → Prop}}
    (custom : Gc.CustomMemCall Ready state Customs)
    (fits : OCaml.Fits Gc.f1Layout.budget P){good} :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  counted_alloc_row custom (fun _ _ af rf stable => {row})
    (fun _ i _ opcode effect => counted_{op.lower()}_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    return out + '\nend OCaml.Vm.Sim\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'OCaml/Vm/Sim/CountedAllocRows.lean'
    content = output()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('counted allocation row drift')
    else:
        target.write_text(content)
    print(f'Counted allocation rows current ({len(ROWS)} rows)')
