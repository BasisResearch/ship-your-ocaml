#!/usr/bin/env python3
"""Generate immediate-comparison branch bridges through shared control restoration."""
import argparse
import json
from census import ROOT
from gen_binary_arms import COMPARISONS


def comparison_value(semantic):
    import re
    return re.sub(r'\b(a|b)\b', lambda m: '(BitVec.ofInt 64 imm.toInt)' if m[0] == 'a' else '(longVal n)', semantic)


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    comparisons = dict(COMPARISONS, EQ=('a == b', 'native_eq'), NEQ=('a != b', 'native_neq'))
    for cmpop, (semantic, guard_lemma) in comparisons.items():
        op = 'B' + cmpop
        stem_base = op.title()
        comparison = comparison_value(semantic)
        for jumping in [True, False]:
            stem = stem_base + ('Jump' if jumping else 'Next')
            lower = op.lower() + ('_jump' if jumping else '_next')
            entry = arms[op]['addr']
            target = 'dest' if jumping else 's.pc + 3'
            extra_binders = ' {dest : Nat} {ofs : BitVec 32}' if jumping else ''
            extra_inputs = '''    (offset : OperandAt P pl (s.pc + 2) ofs)
    (jump : target s.pc 1 ofs.toInt = some dest)
''' if jumping else ''
            extra_reads = '''  have readOffset : bytesT4 d.σ.mem (pl.codeBase + 4 * (s.pc + 2)) = ofs :=
    offset.read32 h.code dp.memory
  have offsetBase : BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 8#64 =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 2)) := codePc_add pl s.pc 2
''' if jumping else ''
            increment_simp = ('show sign_extend (m := 64) (0x008#12) = 8#64 from by decide' if jumping else
                              'show sign_extend (m := 64) (0x00c#12) = 12#64 from by decide')
            extra_simp = 'offsetBase, offset.geometry.toNat, readOffset, ' if jumping else ''
            extra_args = ' offset.geometry.lower offset.geometry.upper offset.geometry.htif' if jumping else ''
            pc_proof = '''  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) +
          ((BitVec.ofInt 64 ofs.toInt <<< (2 : Nat)) + 8#64)) := PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [compare_code_word pl jump] using hp
''' if jumping else '''  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 12#64) := PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [show BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 12#64 =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 3)) from codePc_add pl s.pc 3] using hp
'''
            # Native branch always selects the non-jumping semantic result.
            guard_fn = {'native_sge': 'zopz0zKzJ_s', 'native_slt': 'zopz0zI_s',
                        'native_uge': 'zopz0zKzJ_u', 'native_ult': 'zopz0zI_u',
                        'native_eq': '', 'native_neq': ''}[guard_lemma]
            reversed_args = cmpop in ('LEINT', 'GTINT')
            args = '(longVal n) (BitVec.ofInt 64 imm.toInt)' if reversed_args else '(BitVec.ofInt 64 imm.toInt) (longVal n)'
            guard = f'''  have guard : {guard_fn} {args} = {str(not jumping).lower()} := by
    simp only [{guard_lemma}, test, Bool.not_{str(jumping).lower()}]'''
            if cmpop in ('EQ', 'NEQ'):
                taken = jumping if cmpop == 'EQ' else not jumping
                proof = 'exact test' if cmpop == 'EQ' else 'simpa only [bne, Bool.not_not, Bool.not_true, Bool.not_false] using congrArg Bool.not test'
                guard = f'''  have guard : ((BitVec.ofInt 64 imm.toInt) == longVal n) = {str(taken).lower()} := by
    {proof}'''
            result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.BranchCompare
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_compare_branch_arms.py. Immediate-comparison branch path. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The {'jump' if jumping else 'fallthrough'} path of {op} preserves the represented accumulator.
The generated branch guard is derived from the exact semantic comparison. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{n : BitVec 63}} {{imm : BitVec 32}}{extra_binders}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (accu : s.accu = .int n)
    (operand : OperandAt P pl (s.pc + 1) imm)
    (test : ({comparison}) = {str(jumping).lower()})
{extra_inputs}    : ∃ c', Plus c c' ∧ Running L P {{s with pc := {target}}} c' := by
  apply control_arm stable h
  intro d dp w accuWord value
  have represented : valWord pl s.accu = some (tag64 n) := by rw [accu]; rfl
  have equal : w = tag64 n := Option.some.inj (value.symm.trans represented)
  subst w
  have read : bytesT4 d.σ.mem (pl.codeBase + 4 * (s.pc + 1)) = imm :=
    operand.read32 h.code dp.memory
{extra_reads}{guard}
  have bp : SegSt ({entry}#64)
      [⟨Register.x8, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)⟩, ⟨Register.x21, tag64 n⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨(dp.frame.frame Register.x8 (by decide)).trans h.pc, accuWord, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)) (tag64 n) d.σ.mem d.σ
  simp only [show sign_extend (m := 64) (0x004#12) = 4#64 from by decide,
    {increment_simp},
    codePc_succ, operand.geometry.toNat, read, {extra_simp}longVal_native] at run
  obtain ⟨nb, after, _, hb, post⟩ := run operand.geometry.lower operand.geometry.upper
    operand.geometry.htif guard{extra_args} d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
{pc_proof}  · exact (frame.frame Register.x21 (by decide)).trans accuWord

end OCaml.Vm.Sim
'''
        integer_input = '    (integer : s.accu.isInt = true)\n' if cmpop in ('EQ', 'NEQ') else ''
        step_proof = 'step'
        if cmpop in ('EQ', 'NEQ'):
            step_proof = '''by
    obtain ⟨value, accu⟩ : ∃ value, s.accu = .int value := by
      cases ha : s.accu <;> simp_all [Val.isInt]
    simpa [stepI, accu] using step'''
        result[ROOT / f'OCaml/Vm/Sim/{stem_base}.lean'] = f'''import OCaml.Vm.Sim.{stem_base}Jump
import OCaml.Vm.Sim.{stem_base}Next

/-! GENERATED by scripts/gen_compare_branch_arms.py. Immediate branch composition. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine
open OCaml.Vm.Primitives

/-- Both paths of {op} implement the successful semantic step. -/
theorem {op.lower()}_step_arm {{L : OCaml.Layout}} {{P : Prog}} {{s s' : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{imm ofs : BitVec 32}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
{integer_input}    (operand : OperandAt P pl (s.pc + 1) imm)
    (offset : OperandAt P pl (s.pc + 2) ofs)
    (step : stepI P s ⟨.{op}, [imm.toInt, ofs.toInt]⟩ = .next s') :
    ∃ c', Plus c c' ∧ Running L P s' c' := by
  have step' : brOp s imm.toInt ofs.toInt (fun a b => {semantic}) = .next s' := {step_proof}
  obtain ⟨n, accu⟩ := brOp_accu step'
  cases test : ({comparison}) with
  | false =>
    have state : {{s with pc := s.pc + 3}} = s' := by
      simpa [brOp, accu, test, St.adv] using step'
    rw [← state]
    exact {op.lower()}_next_arm stable h accu operand test
  | true =>
    cases ht : target s.pc 1 ofs.toInt with
    | none => simp [brOp, accu, test, ht, opt] at step'
    | some dest =>
      have state : {{s with pc := dest}} = s' := by
        simpa [brOp, accu, test, ht, opt] using step'
      rw [← state]
      exact {op.lower()}_jump_arm stable h accu operand test offset ht

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'comparison branch drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Immediate-comparison branch bridges current')
