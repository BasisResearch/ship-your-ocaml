#!/usr/bin/env python3
"""Generate counted stack/load rows by reusing the checked ordinary rows."""
import argparse
from census import ROOT
from gen_opcodes import nargs

# Modes describe the existing generic row's arguments, never its execution.
ROWS = [(op, 'rf') for op in ['PUSH', *(f'PUSHACC{i}' for i in range(8)),
    'PUSHACC', 'ASSIGN', *(f'PUSHENVACC{i}' for i in range(1, 5)), 'PUSHENVACC',
    'PUSHGETGLOBAL', 'PUSHGETGLOBALFIELD', 'PUSHATOM0', 'PUSHATOM',
    *(f'PUSHCONST{i}' for i in range(4)), 'PUSHCONSTINT',
    'PUSHOFFSETCLOSUREM3', 'PUSHOFFSETCLOSURE0', 'PUSHOFFSETCLOSURE3',
    'PUSHOFFSETCLOSURE', 'PUSH_RETADDR', 'PUSHTRAP', 'POPTRAP']]
ROWS += [(op, 'stable_budget') for op in [*(f'ACC{i}' for i in range(8)), 'ACC']]
ROWS += [(op, 'stable') for op in ['POP', *(f'ENVACC{i}' for i in range(1, 5)),
    'ENVACC', *(f'GETFIELD{i}' for i in range(4)), 'GETFIELD', 'GETGLOBAL',
    'GETGLOBALFIELD', 'OFFSETCLOSUREM3', 'OFFSETCLOSURE0', 'OFFSETCLOSURE3', 'OFFSETCLOSURE']]

HEADER = '''import OCaml.Vm.Sim.CountedRuntime
import OCaml.Vm.Sim.PushRows
import OCaml.Vm.Sim.AccRows
import OCaml.Vm.Sim.FieldRows
import OCaml.Vm.Sim.FieldOperandRows
import OCaml.Vm.Sim.A2TableRows
import OCaml.Vm.Sim.ControlRows
import OCaml.Vm.Sim.G1Capacity

/-! GENERATED by scripts/gen_counted_stack_rows.py. Counted stack-writing,
stack-load and assignment families. Native execution, use-site guards,
reachability, stack bounds and geometry come from the existing generic rows.
Only their runtime contract is lifted; allocation/barrier effects are absent. -/

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine OCaml.Vm.Primitives

/-- Exactly the ordinary opcode families instantiated below. -/
def countedStackOpcode : Opcode → Bool
'''

def output():
    out = HEADER + ''.join(f'  | .{op} => true\n' for op, _ in ROWS) + '  | _ => false\n'
    # Reuse the authoritative OCaml fixed-operand-count parser.
    operands = nargs()
    for op, _ in ROWS:
        shape = ['cases args',
                 'rcases args with _ | ⟨a, _ | ⟨b, rest⟩⟩',
                 'rcases args with _ | ⟨a, _ | ⟨b, _ | ⟨c, rest⟩⟩⟩'][operands.get(op, 0)]
        out += f'''
/-- BcSem channel preservation for {op}; physical framing is independent. -/
theorem counted_{op.lower()}_channels {{P : Prog}} {{s s' : St}} {{args : List Int}}
    (effect : stepI P s ⟨.{op}, args⟩ = .next s') : s'.world.chans = s.world.chans := by
  {shape}
  all_goals
    simp only [stepI, opt] at effect
    repeat' split at effect
    all_goals cases effect <;> rfl
'''
    for op, mode in ROWS:
        name = op.lower()
        budget = mode != 'stable'
        args = 'rf fits g1_capacity' if mode == 'rf' else ('stable fits g1_capacity' if budget else 'stable')
        out += f'''
/-- Counted {op}, reusing {name}_row at countedLayout. -/
theorem counted_{name}_row {{P : Prog}}
    {{Ready : Nat → Config → Prop}} {{state Customs : Config → Nat → Prop}}
    (custom : Gc.CustomMemCall Ready state Customs)'''
        if budget:
            out += ' (fits : OCaml.Fits Gc.f1Layout.budget P)'
        out += f''' :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  counted_stack_row custom (fun _ rf stable => {name}_row {args})
    (fun _ i _ opcode effect => counted_{name}_channels (P := P) (args := i.args) (by cases i; cases opcode; exact effect))
'''
    return out + '\nend OCaml.Vm.Sim\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'OCaml/Vm/Sim/CountedStackRows.lean'
    content = output()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('counted stack row drift')
    else:
        target.write_text(content)
    print(f'Counted stack rows current ({len(ROWS)} rows)')
