#!/usr/bin/env python3
"""Certify every while_min PRIM name against the observed dynamic pointer table."""
import argparse
import gzip
import json
import re
from pathlib import Path
from boot_certificate import emit_read, finite_cases
from gen_primitive_entries import entries

ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check', action='store_true')
args=ap.parse_args()
layout={k:int(v,0) for k,v in re.findall(r'^def (\w+) : Nat := (\w+)$',
    (ROOT/'OCaml/Vm/Layout.lean').read_text(), re.M)}
mem={}
for _,a,n,v in map(json.loads,gzip.open(ROOT/'results/boot/while_min-stores.jsonl.gz')):
    for i in range(n):mem[a+i]=(v>>(8*i))&255

def read(a):return sum(mem[a+i]<<(8*i) for i in range(8))
source=(ROOT/'OCaml/Programs/WhileMin.lean').read_text()
names=json.loads(source.split('def whileMinPrims : Array String := #')[1].split('\n\n')[0])
pointer=layout['sym_caml_prim_table']+layout['off_prim_contents']
base=read(pointer)
known=dict(entries())
out=['import OCaml.Vm.Boot.WhileMinLogChecks','import Vsa.Sim.Boot.Bytes',
     'import OCaml.Vm.Boot.Primitives','import OCaml.Programs.WhileMin','',
     '/-! GENERATED by scripts/gen_boot_primitives.py. All observed primitive bindings. -/',
     'namespace OCaml.Vm.Boot.WhileMinPrimitives',
     'open OCaml.Bytecode OCaml.Programs Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog','',
     f'def table : Nat := {base:#x}',
     'variable {c : Config} {initial : Vsa.MemRepr.Mem}','']
emit_read(out,'table','Layout.sym_caml_prim_table + Layout.off_prim_contents',base)
for i,name in enumerate(names):
    entry=read(base+8*i)
    assert known[name]==entry
    emit_read(out,f'entry{i}',f'table + 8 * {i}',entry)
    out += [f'def row{i} : PrimitiveRow := ⟨{json.dumps(name)}, {entry:#x}⟩',
            f'theorem binding{i} (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    PrimitiveRowAt whileMin c {i} row{i} where',
            '  program := by decide +kernel', '  resolver := by decide +kernel',
            '  target := by', '    unfold primitiveTarget', '    rw [read_table memory]',
            f'    exact read_entry{i} memory','']
outputs={'OCaml/Vm/Boot/WhileMinPrimitiveReads.lean': '\n'.join(out+['end OCaml.Vm.Boot.WhileMinPrimitives',''])}
out=['import OCaml.Vm.Boot.WhileMinPrimitiveReads','',
     '/-! GENERATED by scripts/gen_boot_primitives.py. Finite row assembly. -/',
     'namespace OCaml.Vm.Boot.WhileMinPrimitives',
     'open OCaml.Bytecode OCaml.Programs Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog','',
     'variable {c : Config} {initial : Vsa.MemRepr.Mem}','',
     f'theorem prims_size : whileMin.prims.size = {len(names)} := by decide +kernel','']
for lo in range(0,len(names),24):
    hi=min(lo+24,len(names))
    out += [f'theorem bindings_{lo}_{hi} (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    ∀ i : Fin {hi-lo}, ∃ row, PrimitiveRowAt whileMin c ({lo} + i.val) row :=',
            '  '+finite_cases([f'⟨row{i}, binding{i} memory⟩' for i in range(lo,hi)]),'']
out += ['theorem bindings (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        '    PrimitiveBindings whileMin c where',
        '  targets := by', '    intro i name hi',
        '    have bound := (Array.getElem?_eq_some_iff.mp hi).1',
        '    rw [prims_size] at bound']
for lo in range(0,len(names),24):
    hi=min(lo+24,len(names))
    out += [f'    by_cases h{hi} : i < {hi}',
            f'    · have low : {lo} ≤ i := by omega',
            f'      have index : i - {lo} < {hi-lo} := by omega',
            f'      obtain ⟨row, hr⟩ := bindings_{lo}_{hi} memory ⟨i - {lo}, index⟩',
            "      rw [Nat.add_sub_cancel' low] at hr", '      exact hr.binding hi']
out += ['    omega','end OCaml.Vm.Boot.WhileMinPrimitives','']
outputs['OCaml/Vm/Boot/WhileMinPrimitives.lean']='\n'.join(out)
for rel,text in outputs.items():
    path=ROOT/rel
    if args.check:
        if not path.exists() or path.read_text()!=text:raise SystemExit(f'boot primitive binding drift: {rel}')
    elif not path.exists() or path.read_text()!=text:path.write_text(text)
print(f'Primitive bindings: {len(names)} entries at {base:#x}')
