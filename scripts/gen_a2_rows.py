#!/usr/bin/env python3
"""Generate the F1 arm-table rows (OpArm) for a2-sem's opcode families.

Each row instantiates a loop-head simulation (`*_next`, IntRows /
ImmediateRows / OperandRows / PushConstRows / HeapRows) through
`opArm_of_next0/1/2` (DecodeFetch.lean). Mis-shaped operand lists are
`shape0`/`shape1`/`shape2`; non-halting is `no_halt`. Contracts become row
premises: `stable` (MemoryStable), `rf` (RuntimeFrame), `fits`/`capacity`
(stack budget), `values` (ValuesInRange), and the named obligations
`scratch`, `zero`, `integer`, `field`."""
import argparse
from census import ROOT

OUT = ROOT / 'OCaml/Vm/Sim/A2TableRows.lean'

HEADER = '''import OCaml.Vm.Sim.OperandTableRows
import OCaml.Vm.Sim.IntRows
import OCaml.Vm.Sim.ImmediateRows
import OCaml.Vm.Sim.OperandRows
import OCaml.Vm.Sim.PushConstRows
import OCaml.Vm.Sim.HeapRows

/-! GENERATED by scripts/gen_a2_rows.py. F1 arm-table rows for the integer,
comparison, constant, branch, push-constant and OFFSETREF families (a2-sem):
each instantiates its loop-head simulation through `opArm_of_next0/1/2`. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives

/-- Mis-shaped operand lists of an operand-free opcode do not step. -/
theorem shape0 {P : Prog} {op : Opcode} (more : ∀ s a rest, stepI P s ⟨op, a :: rest⟩ = .unsupported) :
    ∀ s args, args ≠ [] → stepI P s ⟨op, args⟩ = .wrong ∨ stepI P s ⟨op, args⟩ = .unsupported := by
  intro s args ne
  rcases args with _ | ⟨a, rest⟩
  · exact absurd rfl ne
  · exact Or.inr (more s a rest)
'''

# premise snippets
P = {
    'stable': '(stable : MemoryStable L.runtimeOk)',
    'rf': '(rf : RuntimeFrame L high0 dom0)',
    'budget': '(fits : OCaml.Fits B P) (capacity : StackCapacity B)',
    'values': '(values : ValuesInRange P)',
    'scratch': '(scratch : ∀ s c, Reach P s → OCaml.LoopAt L P s c → BinaryLibScratch c)',
    'field': '(field : ∀ s c, Reach P s → OCaml.LoopAt L P s c → FieldWriteReady L P s c)',
}
SPACE0 = '(by simpa using stack_fits fits capacity reach (k := 0))'
SPACE1 = '(stack_fits fits capacity reach)'

def row(op, arity, prem, call, doc, extra_prem='', reach_used=False, nohalt_term=None):
    lower = op.lower()
    implicit = '{L : OCaml.Layout}' + (' {B : OCaml.Budget}' if 'budget' in prem else '') + ' {P : Prog}' + \
        (' {high0 dom0 : Nat}' if 'rf' in prem else '')
    premises = ' '.join(P[p] for p in prem) + (f'\n    {extra_prem}' if extra_prem else '')
    r = 'reach' if reach_used else '_'
    if arity == 0:
        lam = f'fun s _ _ {r} _ h code step =>'
        shape = 'shape0 (fun _ _ _ => rfl)'
        nohalt = 'fun s e w step => by no_halt step'
        fn = 'opArm_of_next0'
    elif arity == 1:
        lam = f'fun s _ _ _ {r} _ h code fetch step =>'
        shape = 'shape1 (fun _ => rfl) (fun _ _ _ _ => rfl)'
        nohalt = 'fun s a e w step => by no_halt step'
        fn = 'opArm_of_next1'
    else:
        lam = f'fun s _ _ _ _ {r} _ h code fetch fetchOfs step =>'
        shape = 'shape2 (fun _ => rfl) (fun _ _ => rfl) (fun _ _ _ _ _ => rfl)'
        nohalt = 'fun s a b e w step => by no_halt step'
        fn = 'opArm_of_next2'
    if nohalt_term is not None:
        nohalt = nohalt_term
    return f'''
/-- **The {op} row**{doc}. -/
theorem {lower}_row {implicit}
    {premises} :
    OCaml.OpArm P (OCaml.LoopAt L P) .{op} :=
  {fn} ({lam}
      {call})
    ({shape}) ({nohalt})
'''

ROWS = []
# the semantic operation of each binary opcode (stepI), named so the no-halt
# fact is checked against the unfolded step without higher-order unification
BINARY = [
    ('ADDINT', 'intOp', 'fun a b => a + b - 1'),
    ('SUBINT', 'intOp', 'fun a b => a - b + 1'),
    ('ANDINT', 'intOp', 'fun a b => a &&& b'),
    ('ORINT', 'intOp', 'fun a b => a ||| b'),
    ('XORINT', 'intOp', 'fun a b => (a ^^^ b) ||| 1'),
    ('LSLINT', 'intOp', 'fun a b => ((a - 1) <<< ((untag b).toNat % 64)) + 1'),
    ('LSRINT', 'intOp', 'fun a b => (a >>> ((untag b).toNat % 64)) ||| 1'),
    ('ASRINT', 'intOp', 'fun a b => (a.sshiftRight ((untag b).toNat % 64)) ||| 1'),
    ('LTINT', 'cmpOp', 'fun a b => a.slt b'),
    ('LEINT', 'cmpOp', 'fun a b => a.sle b'),
    ('GTINT', 'cmpOp', 'fun a b => b.slt a'),
    ('GEINT', 'cmpOp', 'fun a b => b.sle a'),
    ('ULTINT', 'cmpOp', 'fun a b => a.ult b'),
    ('UGEINT', 'cmpOp', 'fun a b => b.ule a'),
]
for op, helper, f in BINARY:
    ROWS.append(row(op, 0, ['stable','budget'], f'{op.lower()}_next stable h code {SPACE0} step', '',
        reach_used=True, nohalt_term=f'fun _ _ _ => {helper}_no_halt (f := {f})'))
ROWS.append(row('MULINT', 0, ['stable','budget'],
    f'mulint_next stable h code {SPACE0} step', '', reach_used=True, nohalt_term='fun _ _ _ => intOp_no_halt (f := fun a b => tag64 (untag a * untag b))'))
for op, kind in [('DIVINT','quotient'),('MODINT','remainder')]:
    ROWS.append(row(op, 0, ['stable','budget','scratch'],
        f'division_next .{kind} stable h code {SPACE0} (scratch s _ reach h) (zero s _ _ reach h code step) step',
        '; a zero divisor is the named `zero` (the raise row)',
        nohalt_term=f'fun _ _ _ => division_no_halt .{kind}',
        extra_prem=f'(zero : ∀ s s\' c, Reach P s → OCaml.LoopAt L P s c → DispatchCode P s .{op} →\n      stepI P s ⟨.{op}, []⟩ = .next s\' →\n      ∀ rest, s.stack = .int 0 :: rest → ∃ c\', OCaml.Plus c c\' ∧ OCaml.Running L P s\' c\')',
        reach_used=True))
for op in ['EQ','NEQ']:
    ROWS.append(row(op, 0, ['stable','budget','values'],
        f'{op.lower()}_next stable h code {SPACE0} (values s reach) step', '', reach_used=True))
for op in ['CONST0','CONST1','CONST2','CONST3','ATOM0','NEGINT','BOOLNOT','ISINT']:
    ROWS.append(row(op, 0, ['stable'], f'{op.lower()}_next stable h code step', ''))
for op in ['OFFSETINT','CONSTINT','BRANCH','ATOM']:
    ROWS.append(row(op, 1, ['stable'], f'{op.lower()}_next stable h code fetch step', ''))
for op in ['BRANCHIF','BRANCHIFNOT']:
    ROWS.append(row(op, 1, ['stable','values'],
        f'{op.lower()}_next stable h code fetch (values.accu_notRaw reach) step', '', reach_used=True))
BRANCH = [('BLTINT', 'fun a b => a.slt b'), ('BLEINT', 'fun a b => a.sle b'),
          ('BGTINT', 'fun a b => b.slt a'), ('BGEINT', 'fun a b => b.sle a'),
          ('BULTINT', 'fun a b => a.ult b'), ('BUGEINT', 'fun a b => b.ule a')]
for op, f in BRANCH:
    ROWS.append(row(op, 2, ['stable'], f'{op.lower()}_next stable h code fetch fetchOfs step', '',
        nohalt_term=f'fun _ _ _ _ _ => brOp_no_halt (f := {f})'))
for op in ['BEQ','BNEQ']:
    ROWS.append(row(op, 2, ['stable'],
        f'{op.lower()}_next stable h code fetch fetchOfs (ints.integer s reach (.{"inl" if op == "BEQ" else "inr"} code.fetch)) step',
        '; an integer accumulator comes from `BranchInts` (`beq_pointer_guard_obstruction`)',
        extra_prem='(ints : BranchInts P)',
        reach_used=True, nohalt_term=f'fun _ _ _ _ _ => {op.lower()}_no_halt'))
for op in ['PUSHCONST0','PUSHCONST1','PUSHCONST2','PUSHCONST3','PUSHATOM0']:
    ROWS.append(row(op, 0, ['rf','budget'], f'{op.lower()}_next rf h code {SPACE1} step', '', reach_used=True))
for op in ['PUSHCONSTINT','PUSHATOM']:
    ROWS.append(row(op, 1, ['rf','budget'], f'{op.lower()}_next rf h code fetch {SPACE1} step', '', reach_used=True))
ROWS.append(row('OFFSETREF', 1, ['field'], 'offsetref_next h code fetch (field s _ reach h) step',
    '; field-write framing is the named `field`', reach_used=True))


def outputs():
    return {OUT: HEADER + ''.join(ROWS) + '\nend OCaml.Vm.Sim\n'}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    for p, text in outputs().items():
        if a.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'a2 table row drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('a2 table rows current')


if __name__ == '__main__':
    main()
