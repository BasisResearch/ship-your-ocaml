#!/usr/bin/env python3
"""Generate certified symbolic bytecode windows from 4.14.4 dumpobj + CODE.

Each basic block ends at a transfer (including calls) or a 16-instruction
cut. Closure entry points partition the function regions. Signed operands
come from CODE, not dumpobj's pretty-printed absolute addresses/names.
Every dumpobj opcode/address is cross-checked against the executable.

Regenerate: python3 scripts/gen_bc_rules.py
Check drift: python3 scripts/gen_bc_rules.py --check
"""
import argparse
import hashlib
import json
import re
import struct
import subprocess
from pathlib import Path
from gen_opcodes import opcodes, nargs

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DUMP = Path.home() / 'toolchains/build/ocaml-4.14.4/tools/dumpobj'
MODULES = ['Translcore', 'Matching', 'Bytegen', 'Emitcode']
OUT = ROOT / 'OCaml/Programs/Generated'
INST = re.compile(r'^\s*(\d+)\s+([A-Z_0-9]+)(?:\s+(.*))?$')
TRANSFER = {'BRANCH', 'BRANCHIF', 'BRANCHIFNOT', 'SWITCH', 'RETURN',
            'RAISE', 'RERAISE', 'RAISE_NOTRACE', 'STOP', 'GRAB', 'RESTART',
            'PUSHTRAP', 'POPTRAP', 'PUSH_RETADDR', 'CHECK_SIGNALS'}


def code_words(path):
    data = path.read_bytes()
    if data[-12:] != b'Caml1999X031':
        raise ValueError('not an OCaml 4.14 executable')
    count = struct.unpack('>I', data[-16:-12])[0]
    start = len(data) - 16 - count * 8
    sections = [(data[k:k+4], struct.unpack('>I', data[k+4:k+8])[0])
                for k in range(start, len(data)-16, 8)]
    pos = start - sum(size for _, size in sections)
    for name, size in sections:
        if name == b'CODE':
            return list(struct.unpack('<' + 'I' * (size//4), data[pos:pos+size]))
        pos += size
    raise ValueError('missing CODE')


def signed(n):
    return n if n < 2**31 else n - 2**32


def inputs(exe, dumpobj):
    words = code_words(exe)
    dump = subprocess.run([str(dumpobj), str(exe)], check=True,
                          text=True, capture_output=True).stdout
    rows = [(int(m[1]), m[2], m[3] or '') for line in dump.splitlines()
            if (m := INST.match(line))]
    names, arities = opcodes(), nargs()
    decoded = {}
    pc = 0
    while pc < len(words):
        op = names[words[pc]]
        count = arities.get(op, 0)
        if op == 'SWITCH':
            sizes = words[pc+1]
            count = 1 + sizes % 65536 + sizes // 65536
        elif op == 'CLOSUREREC':
            count = 2 + words[pc+1]
        decoded[pc] = (op, [signed(x) for x in words[pc+1:pc+1+count]], count+1)
        pc += count+1
    if [(pc, op) for pc, op, _ in rows] != [(pc, op) for pc, (op, _, _) in decoded.items()]:
        raise ValueError('dumpobj instruction boundaries/opcodes differ from CODE')
    units = {}
    begin = 0
    for pc, op, arg in rows:
        if op == 'SETGLOBAL':
            end = pc + decoded[pc][2]
            units[arg.split()[0]] = (begin, end)
            begin = end
    entries, targets = set(), set()
    for pc, (op, args, size) in decoded.items():
        if op == 'CLOSURE':
            entries.add(pc+2+args[1])
        elif op == 'CLOSUREREC':
            entries.update(pc+3+off for off in args[2:])
        if op in {'BRANCH', 'BRANCHIF', 'BRANCHIFNOT', 'PUSHTRAP', 'PUSH_RETADDR'}:
            targets.add(pc+1+args[0])
        elif op in {'BEQ', 'BNEQ', 'BLTINT', 'BLEINT', 'BGTINT', 'BGEINT', 'BULTINT', 'BUGEINT'}:
            targets.add(pc+2+args[1])
        elif op == 'SWITCH':
            targets.update(pc+2+off for off in args[1:])
    if not entries.issubset(decoded) or not targets.issubset(decoded):
        raise ValueError('control-flow target is not an instruction boundary')
    return words, decoded, units, entries, targets


def module_text(name, words, decoded, units, entries, targets):
    begin, end = units[name]
    pcs = [p for p in decoded if begin <= p < end]
    cuts = {begin, end} | {p for p in entries | targets if begin <= p < end}
    for pc in pcs:
        op, _, size = decoded[pc]
        if op in TRANSFER or op.startswith(('APPLY', 'APPTERM', 'C_CALL')) or op in {
                'BEQ', 'BNEQ', 'BLTINT', 'BLEINT', 'BGTINT', 'BGEINT', 'BULTINT', 'BUGEINT'}:
            cuts.add(pc+size)
    groups, group = [], []
    for pc in pcs:
        if group and (pc in cuts or len(group) == 16):
            groups.append(group)
            group = []
        group.append(pc)
    if group:
        groups.append(group)
    lines = ['-- GENERATED by scripts/gen_bc_rules.py. Do not edit.',
             'import OCaml.Logic.Block', '',
             f'namespace OCaml.Programs.Generated.{name}', 'open OCaml.Bytecode', '']
    fn = begin
    functions = []
    for group in groups:
        base = group[0]
        if base == begin or base in entries:
            fn = base
            functions.append({'entry': fn, 'blocks': []})
        stop = group[-1] + decoded[group[-1]][2]
        # One lookahead word certifies variable-length decoder locality even
        # for a last one-word instruction. It is not an executable site.
        raw = words[base:stop+1]
        ident = f'f{fn}_b{base}'
        functions[-1]['blocks'].append({'pc': base, 'end': stop, 'instructions': len(group)})
        lines += [f'def {ident}_code : Code := #[{", ".join(str(w)+"#32" for w in raw)}]',
                  f'def {ident} : CertifiedBlock :=',
                  f'  ⟨{base}, {ident}_code, [']
        sites = []
        for pc in group:
            op, args, size = decoded[pc]
            argtext = ', '.join(str(x) if x >= 0 else f'({x})' for x in args)
            sites.append(f'    ⟨{pc-base}, ⟨.{op}, [{argtext}]⟩, {size}, by decide, rfl, rfl, rfl⟩')
        lines += [',\n'.join(sites) + ']⟩', '',
                  f'theorem {ident}_run (P : Prog)',
                  f'    (pin : P.code.extract {base} {base+len(raw)} = {ident}_code)',
                  f'    (n : Nat) (s t : St)',
                  f'    (h : OCaml.Run.iter (decodedK P {ident}.decode) n s = .ok t) :',
                  f'    OCaml.Run.iter (bcK P) n s = .ok t :=',
                  f'  {ident}.run P pin n s t h', '']
    lines += [f'end OCaml.Programs.Generated.{name}', '']
    if sum(len(g) for g in groups) != len(pcs) or [p for g in groups for p in g] != pcs:
        raise ValueError('block partition does not cover the module exactly')
    return '\n'.join(lines), {'instructions': len(pcs), 'words': end-begin,
                             'blocks': len(groups), 'functions': functions}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--exe', type=Path, default=ROOT/'vendor/ocaml-4.14.4/boot/ocamlc')
    parser.add_argument('--dumpobj', type=Path, default=DEFAULT_DUMP)
    parser.add_argument('--modules', nargs='+', default=MODULES)
    args = parser.parse_args()
    data = inputs(args.exe, args.dumpobj)
    manifest = {'generator': 'scripts/gen_bc_rules.py',
                'executable_sha256': hashlib.sha256(args.exe.read_bytes()).hexdigest(),
                'code_words': len(data[0]), 'modules': {}}
    artifacts = {}
    for name in args.modules:
        text, stats = module_text(name, *data)
        artifacts[OUT/f'{name}.lean'] = text
        manifest['modules'][name] = stats
        print(f'{name}: {stats["instructions"]} instructions, {stats["blocks"]} blocks, '
              f'{len(stats["functions"])} function regions')
    audit = ['-- GENERATED by scripts/gen_bc_rules.py. Do not edit.']
    audit += [f'import OCaml.Programs.Generated.{name}' for name in args.modules]
    audit += ['']
    for name, stats in manifest['modules'].items():
        for fn in stats['functions']:
            audit += [f'#print axioms OCaml.Programs.Generated.{name}.f{fn["entry"]}_b{b["pc"]}_run'
                      for b in fn['blocks']]
    artifacts[OUT/'Audit.lean'] = '\n'.join(audit) + '\n'
    artifacts[OUT/'manifest.json'] = json.dumps(manifest, indent=2) + '\n' 
    for path, text in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated file differs: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)


if __name__ == '__main__':
    main()
