#!/usr/bin/env python3
"""Generate both represented first-function metadata adapters for CLOSUREREC."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def render(kind):
    more=kind=='more';stem=kind.title()
    spec=json.loads((ROOT/f'scripts/syi/segments/closurerec_first_{kind}.json').read_text())
    code_lo=min(int(step['addr'],16) for step in spec['steps'])
    code_hi=max(int(step['addr'],16) for step in spec['steps'])+4
    regs=[p['reg'] for p in spec['pins']]
    vals={'x26':'count','x23':'closureSource sp count','x21':'a','x8':'pl.codeBase + 4 * s.pc','x27':'3 * functions - 1','x16':'pl.codeBase + 4 * (s.pc + 3)','x15':'a','x17':'functions'}
    proofs={'x26':'front.fields.countReg','x23':'front.fields.sourceReg','x21':'front.accu','x8':'(front.frame.frame Register.x8 (by decide)).trans h.pc','x27':'front.fields.environmentOffset','x16':'front.fields.codeBase','x15':'front.value','x17':'front.fields.functionsReg'}
    pins=', '.join(f'⟨Register.{r}, BitVec.ofNat 64 ({vals[r]})⟩' for r in regs)
    args=' '.join(f'(BitVec.ofNat 64 ({vals[r]}))' for r in regs)
    holds=', '.join(proofs[r] for r in regs)
    for st in spec['steps']:
        r=st.get('rd')
        if r:regs=[r]+[x for x in regs if x!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    extra='''  have twice := closurerec_twice functions (by omega)
  have triple := addw_nat_add (2 * functions) functions (by omega)
  have tripleEq : 2 * functions + functions = 3 * functions := by omega
  rw [tripleEq] at triple
  have tailArity : BitVec.ofNat 64 (2 * (3 * functions - 1)) + sign_extend (m := 64) (0xffb#12) =
      BitVec.ofNat 64 (2 * (3 * functions - 4) + 1) := by
    rw [show sign_extend (m := 64) (0xffb#12) = -(5#64) from by decide,
      ← BitVec.sub_eq_add_neg, BitVec.ofNat_sub_ofNat_of_le _ 5 (by decide) (by omega)]
    congr 1
    omega
  have targetAddress : BitVec.ofNat 64 a + sign_extend (m := 64) (0x018#12) = BitVec.ofNat 64 (a + 24) := by
    rw [BitVec.ofNat_add]; rfl
''' if more else ''
    guard='''by
    unfold zopz0zKzJ_s
    rw [nat64_toInt functions (by omega)]
    exact decide_eq_false (by change ¬ (1 : Int) ≥ (functions : Int); omega)''' if more else 'by rw [branch]; decide'
    copied=f'''  · intro _
    exact ⟨{get('x15')}, {get('x8')}, {get('x11')}, {get('x13')}, {get('x10')}, {get('x12')}⟩''' if more else '''  · intro impossible
    omega'''
    return f'''-- GENERATED by scripts/gen_closurerec_first.py; do not edit.
import OCaml.Vm.Sim.ClosurerecFirstInput
import OCaml.Vm.Sim.ClosurerecFirst{stem}Segment
import OCaml.Vm.Sim.ClosurerecFirst{stem}Pins
import OCaml.Vm.Sim.StackPush

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The actual first-function metadata path, with {'remaining infix functions' if more else 'a single function'}. -/
theorem closurerec_first_{kind} {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c d : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high functions count dest a domain : Nat}}
    {{accu : BitVec 64}} {{ofs : BitVec 32}}
    (h : ArmInput L P s .CLOSUREREC c pl cp sp high)
    (operand : OperandAt P pl (s.pc + 3) ofs) (jump : target s.pc 2 ofs.toInt = some dest)
    (space : ClosurerecFirstInput c pl s.pc sp functions count dest a domain accu)
    (branch : {'1 < functions' if more else 'functions = 1'})
    (front : ClosurerecReady c pl s.pc sp functions count a domain accu d) :
    ∃ nb after, StepsN nb d after ∧ ClosurerecFirst c pl s.pc sp functions count dest a domain accu after := by
  have positive := front.fields.positive
  have small := front.fields.nurseryBound
  unfold closurerecSize at small
  have captureEnd := closure_capture_end sp count space.captureRoom
  have stackAddress := push_address space.stackRoom
  have stackNat : (BitVec.ofNat 64 (sp + 8 * (count - 1) - 8)).toNat = closurerecStackStart sp count := space.stackWrite.read.toNat
  have pc3 := codePc_add pl s.pc 3
  have destination : BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 3)) +
      Sail.shift_bits_left (sign_extend (m := 64) ofs) (Sail.BitVec.extractLsb (0x02#6) 5 0) =
      BitVec.ofNat 64 (pl.codeBase + 4 * dest) := relative_code_word pl jump
  have arityAddress : BitVec.ofNat 64 a + sign_extend (m := 64) (0x008#12) = BitVec.ofNat 64 (a + 8) := by
    rw [BitVec.ofNat_add]; rfl
  have envShift : Sail.shift_bits_left (BitVec.ofNat 64 (3 * functions - 1)) (Sail.BitVec.extractLsb (0x01#6) 5 0) =
      BitVec.ofNat 64 (2 * (3 * functions - 1)) := by
    change (BitVec.ofNat 64 (3 * functions - 1) <<< (1 : Nat)) = _
    exact nat_shift_word _ 1
  have arityWord : BitVec.ofNat 64 (2 * (3 * functions - 1)) + 1#64 = BitVec.ofNat 64 (2 * (3 * functions - 1) + 1) := by
    rw [BitVec.ofNat_add]
  have guard : zopz0zKzJ_s (1#64) (BitVec.ofNat 64 functions) = {'false' if more else 'true'} := {guard}
{extra}  obtain ⟨m1, written1⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 d.σ.mem (closurerecStackStart sp count) (sdData_val (BitVec.ofNat 64 a)) := ⟨_, rfl⟩
  obtain ⟨m2, written2⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 m1 a (sdData_val (BitVec.ofNat 64 (pl.codeBase + 4 * dest))) := ⟨_, rfl⟩
  obtain ⟨m3, written3⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 m2 (a + 8) (sdData_val (BitVec.ofNat 64 (2 * (3 * functions - 1) + 1))) := ⟨_, rfl⟩
  have firstMemory : m1 = writeLog c.σ.mem (closurerecReadyLog c sp functions count a domain accu ++
      [(closurerecStackStart sp count, 8, BitVec.ofNat 64 a)]) := by
    rw [written1, front.memory, writeLog_append]; rfl
  have read := operand.read32_mem_log h.code space.operandOutside firstMemory
  have fullMemory : m3 = writeLog d.σ.mem (closurerecFirstLog pl sp functions count dest a) := by
    rw [written3, written2, written1]; rfl
  have code (address : Nat) (value : BitVec 64) (member : (address, 8, value) ∈ closurerecFirstLog pl sp functions count dest a) :
      address + 8 ≤ 0x{code_lo:x} ∨ 0x{code_hi:x} ≤ address :=
    image_entry_code space.image member (by decide) (by decide)
  have bp : SegSt ({spec['entry']}#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.CamlClosurerecFirst{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨front.good, front.pcAt, ⟨{holds}, trivial⟩,
      front.good.minstret, front.tick, closurerec_first_{kind}_loaded front.image, rfl, rfl⟩
  have run := tr_closurerec_first_{kind} {args} d.σ.mem d.σ
  simp only [captureEnd, stackAddress, envShift, arityAddress,
    show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    show sign_extend (m := 64) (0x00c#12) = 12#64 from by decide,
    show sign_extend (m := 64) (0x001#12) = 1#64 from by decide,
    BitVec.add_zero, BitVec.zero_add, arityWord, pc3, operand.geometry.toNat,
    stackNat, space.codeWrite.read.toNat, space.arityWrite.read.toNat] at run
  have first := run space.stackWrite.lower space.stackWrite.upper space.stackWrite.htif space.stackWrite.aligned
    (code _ (BitVec.ofNat 64 (a)) (by simp [closurerecFirstLog])) m1 written1
    operand.geometry.lower operand.geometry.upper operand.geometry.htif (sign_extend (m := 64) ofs) (by rw [read])
  simp only [destination] at first
{'  simp only [twice, triple, tailArity, targetAddress, show sign_extend (m := 64) (0x010#12) = 16#64 from by decide, codePc_add pl s.pc 4, show sign_extend (m := 64) (0x003#12) = 3#64 from by decide, BitVec.zero_add] at first' if more else ''}
  obtain ⟨nb, after, _, steps, post⟩ := first space.codeWrite.lower space.codeWrite.upper space.codeWrite.htif space.codeWrite.aligned
    (code _ (BitVec.ofNat 64 (pl.codeBase + 4 * dest)) (by simp [closurerecFirstLog])) m2 written2
    space.arityWrite.lower space.arityWrite.upper space.arityWrite.htif space.arityWrite.aligned
    (code _ (BitVec.ofNat 64 (2 * (3 * functions - 1) + 1)) (by simp [closurerecFirstLog])) m3 written3 guard d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := closurerecFirstWrites) (by decide)
  have localMemory := memory.trans fullMemory
  refine ⟨nb, after, steps, post.good, post.tick, image_of_writeLog front.image space.image localMemory,
    ?_, front.fields.frame frame (by decide), (frame.frame Register.x21 (by decide)).trans front.accu,
    {get('x9')}, ?_, ?_, (front.frame.trans frame).widenChecked (allowed := closurerecMetadataWrites) (by decide)⟩
  · simp only [{'branch, ite_true' if more else 'branch, Nat.lt_irrefl, ite_false'}]; exact post.pcAt
{copied}
  · rw [localMemory, front.memory, writeLog_append]

end OCaml.Vm.Sim
'''

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for kind in ['one','more']:
        p=ROOT/f'OCaml/Vm/Sim/ClosurerecFirst{kind.title()}.lean';out=render(kind)
        if args.check:
            if not p.exists() or p.read_text()!=out:raise SystemExit(f'drift: {p}')
        else:p.write_text(out)
    print('Recursive closure first-function adapters current')
