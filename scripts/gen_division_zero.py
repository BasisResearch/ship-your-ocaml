#!/usr/bin/env python3
"""Both integer zero-divisor branches through generated native segments."""
import argparse
from gen_arm_pilot import ROOT


def outputs():
    result = {}
    for stem, pc in [('Divint', '0x80002d10'), ('Modint', '0x80002ce4')]:
        name = stem.lower() + '_zero'
        result[ROOT / f'OCaml/Vm/Sim/{stem}Zero.lean'] = f'''import OCaml.Vm.Sim.DivisionZeroState
import OCaml.Vm.Sim.{stem}ZeroSegment
import OCaml.Vm.Sim.{stem}ZeroPins
import Vsa.Sim.FnSummary

/-! GENERATED by scripts/gen_division_zero.py. Native zero-divisor selection. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- Execute the actual zero branch, ending at the common exception setup. -/
theorem {name} {{sp : BitVec 64}} {{c : Config}} (h : DivisionZeroInput sp c) :
    FnSummary {pc}#64 (fun start => start = c) (DivisionZeroPost sp c) := by
  constructor
  intro start initial
  obtain ⟨pc, eq⟩ := initial
  subst start
  have loaded : sign_extend (m := 64) (bytesT8 c.σ.mem sp.toNat) = 1#64 := by
    simpa only [word, bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq] using h.zero
  have bp : SegSt {pc}#64 [⟨Register.x9, sp⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}ZeroLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, pc, ⟨h.stack, trivial⟩, h.good.minstret, h.tick, {name}_loaded h.image, rfl, rfl⟩
  have native := tr_{name} sp c.σ.mem c.σ
  simp only [show sign_extend (m := 64) (0x000#12) = 0#64 from rfl, BitVec.add_zero] at native
  obtain ⟨count, after, _, run, post⟩ := native h.read.lower h.read.upper h.read.htif 1#64 loaded.symm (by decide) c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  exact ⟨after, run.toSteps, post.good, image_of_writeLog (log := []) h.image ⟨trivial, trivial⟩ memory,
    post.tick, post.pcAt, PinsHold.get post.pins ⟨1, by simp⟩, memory, frame.widenChecked (by decide)⟩

end OCaml.Vm.Sim
'''
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Zero-divisor artifact drift: {path}')
        else:
            path.write_text(content)
    print('Zero-divisor branch adapters current')
