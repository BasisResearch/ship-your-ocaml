#!/usr/bin/env python3
"""Interpreter epilogue summary with ABI offsets extracted into Layout."""
import argparse
import json
import re
import sys
from gen_arm_pilot import ROOT
sys.path.insert(0, str(ROOT / 'scripts/syi'))
from gen_segment import SegmentEmitter


def output(kind='interp_return'):
    spec = json.loads((ROOT / f'scripts/syi/segments/{kind}.json').read_text())
    em = SegmentEmitter(spec)
    em.emit()
    pins = {r: i for i, (r, _) in enumerate(em.pins)}
    loads = []
    norms = []
    for step in spec['steps']:
        if not step.get('rd_val', '').startswith('loaded_'):
            continue
        reg = int(step['rd'][1:])
        tag = step['rd_val'].removeprefix('loaded_')
        param = next(p for p in spec['params'] if p.startswith(f'(hlo_{tag}'))
        imm = re.search(r'0x([0-9a-f]+)#12', param).group(1)
        loads.append(reg)
        norms += [f'show sign_extend (m := 64) (0x{imm}#12) = BitVec.ofNat 64 (Layout.interpSaveOffset {reg}) from by decide',
                  f'(h.frame.reads {reg} (by decide)).toNat']
    norms += ['show sign_extend (m := 64) (0x210#12) = BitVec.ofNat 64 Layout.interpFrameBytes from by decide',
              '← BitVec.ofNat_add']
    arguments = '\n    '.join(f'(h.frame.reads {r} (by decide)).lower (h.frame.reads {r} (by decide)).upper (h.frame.reads {r} (by decide)).htif\n    (saved {r}) (read {r} (by decide)).symm' for r in loads)
    saved_regs = sorted(loads)
    cases = '\n'.join(f'    · exact PinsHold.get post.pins ⟨{pins[f"x{r}"]}, by simp⟩' for r in saved_regs)
    norm_text = ',\n    '.join(norms)
    result = f'''import OCaml.Vm.Sim.InterpReturnState
import OCaml.Vm.Sim.InterpReturnSegment
import OCaml.Vm.Sim.InterpReturnPins

/-! GENERATED by scripts/gen_interp_return.py. Complete native interpreter epilogue. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- Execute the actual epilogue, restoring all saved ABI registers and returning the accumulator. -/
theorem interp_return {{nativeSp : Nat}} {{saved : Nat → BitVec 64}} {{value : BitVec 64}} {{c : Config}}
    (h : InterpReturnInput nativeSp saved value c) :
    ∃ count after, StepsN count c after ∧ InterpReturnPost c nativeSp saved value after := by
  have read (r : Nat) (hr : r ∈ Layout.interpSavedRegs) :
      sign_extend (m := 64) (bytesT8 c.σ.mem (nativeSp + Layout.interpSaveOffset r)) = saved r := by
    simpa only [word, bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq] using h.frame.words r hr
  have bp : SegSt ({spec['entry']}#64) [⟨Register.x2, BitVec.ofNat 64 nativeSp⟩, ⟨Register.x21, value⟩]
      (fun σ => Vsa.Sim.Code.CamlInterpReturnLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, h.pc, ⟨h.stack, h.value, trivial⟩, h.good.minstret, h.tick, interp_return_loaded h.image, rfl, rfl⟩
  have native := tr_interp_return (BitVec.ofNat 64 nativeSp) value c.σ.mem c.σ
  simp only [{norm_text}] at native
  have target : Sail.BitVec.update (saved 1 + sign_extend (m := 64) (0x000#12)) 0 0#1 = saved 1 := by
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from rfl, BitVec.add_zero] using ret_tgt (saved 1) h.aligned
  obtain ⟨count, after, _, run, post⟩ := native {arguments}
    (by rw [target]; exact h.aligned) c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  refine ⟨count, after, run, post.good, image_of_writeLog (log := []) h.image ⟨trivial, trivial⟩ memory,
    post.tick, ?_, ?_, ?_, ?_, memory, frame.widenChecked (allowed := interpReturnWrites) (by decide)⟩
  · have observed : pcOf after = some (Sail.BitVec.update (saved 1 + sign_extend (m := 64) (0x000#12)) 0 0#1) := post.pcAt
    simpa only [target] using observed
  · exact PinsHold.get post.pins ⟨{pins['x2']}, by simp⟩
  · have observed : gpr after 10 = some (value + sign_extend (m := 64) (0x000#12)) := PinsHold.get post.pins ⟨{pins['x10']}, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from rfl, BitVec.add_zero] using observed
  · intro r member
    simp only [Layout.interpSavedRegs, List.mem_cons, List.not_mem_nil, or_false] at member
    rcases member with {' | '.join(['rfl'] * len(saved_regs))}
{cases}

end OCaml.Vm.Sim
'''

    if kind == 'caml_main_return':
        result = result.replace('InterpReturn', 'CamlMainReturn').replace('interp_return', 'caml_main_return')
        result = result.replace('Layout.interpSaveOffset', 'Layout.camlMainSaveOffset').replace('Layout.interpSavedRegs', 'Layout.camlMainSavedRegs')
        result = result.replace('Layout.interpFrameBytes', 'Layout.camlMainFrameBytes').replace('interpReturnWrites', 'camlMainReturnWrites')
        result = result.replace('0x210#12', '0x070#12')
        result = result.replace('[⟨Register.x2, BitVec.ofNat 64 nativeSp⟩, ⟨Register.x21, value⟩]',
                                '[⟨Register.x10, value⟩, ⟨Register.x2, BitVec.ofNat 64 nativeSp⟩]')
        result = result.replace('⟨h.stack, h.value, trivial⟩', '⟨h.value, h.stack, trivial⟩')
        result = result.replace('tr_caml_main_return (BitVec.ofNat 64 nativeSp) value',
                                'tr_caml_main_return value (BitVec.ofNat 64 nativeSp)')
        result = result.replace(':= native (h.frame.reads', ':= native (by simpa only [show sign_extend (m := 64) (0x003#12) = 3#64 from rfl, show (0#64) + sign_extend (m := 64) (0x002#12) = 2#64 from rfl, beq_eq_false_iff_ne] using h.ordinary) (h.frame.reads')
        start = result.index('  · have observed : gpr after 10')
        end = result.index('  · intro r member', start)
        result = result[:start] + f'  · exact PinsHold.get post.pins ⟨{pins["x10"]}, by simp⟩\n' + result[end:]
        result = result.replace('scripts/gen_caml_main_return.py', 'scripts/gen_interp_return.py')
        result = result.replace('Complete native interpreter epilogue.', 'Normal native caml_main return.')
        result = result.replace('Execute the actual epilogue, restoring all saved ABI registers and returning the accumulator.',
                                'Check the normal interpreter result and restore the complete caml_main frame.')
    return result


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    for kind, stem in [('interp_return', 'InterpReturn'), ('caml_main_return', 'CamlMainReturn')]:
        path = ROOT / f'OCaml/Vm/Sim/{stem}.lean'
        content = output(kind)
        if args.check:
            if not path.exists() or path.read_text() != content:
                sys.exit(f'{stem} adapter drift')
        else:
            path.write_text(content)
    print('Native return adapters current')
