#!/usr/bin/env python3
"""Generate represented fixed-arity C_CALL returns from checked suffix inputs.

The common saved-frame contract and root/stack restoration live in CcallReturn.
This adapter consumes each generated machine triple, never steps instructions.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = r'''-- GENERATED by scripts/gen_ccall_returns.py; do not edit.
import OCaml.Vm.Sim.CcallReturn
import OCaml.Vm.Sim.Ccall@ARITY@SuffixSegment
import OCaml.Vm.Sim.Ccall@ARITY@SuffixPins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The generated return suffix restores Running from a represented primitive
result, including saved VM registers and the complete platform invariant. -/
theorem c_call@ARITY@_return {L : OCaml.Layout} {P : Prog} {s : St} {pl : Place}
    {cp : ChanPlace} {sp high : Nat} {domain frameSp result env : BitVec 64} {c : Config}
    (stable : MemoryStable L.runtimeOk)
    (h : CcallReturn (@PC@#64) L P s pl cp sp high domain frameSp result env c)@BOUND@ :
    ∃ after, Plus c after ∧ Running L P @STATE@ after := by
  have loaded (a : Nat) : sign_extend (m := 64) (bytesT8 c.σ.mem a) = word c a := by
    simp only [word, bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq]
  have bp : SegSt (@PC@#64)
      [⟨Register.x25, BitVec.ofNat 64 Layout.sym_Caml_state⟩, ⟨Register.x10, result⟩]
      (fun σ => Vsa.Sim.Code.CamlCcall@ARITY@SuffixLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.platform.control, h.returnPC, ⟨h.domainReg, h.resultReg, trivial⟩,
      h.platform.control.minstret, h.tick, c_call@ARITY@_suffix_loaded h.platform.image, rfl, rfl⟩
  have run := tr_c_call@ARITY@_suffix (BitVec.ofNat 64 Layout.sym_Caml_state) result c.σ.mem c.σ
  simp only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, loaded,
    show (BitVec.ofNat 64 Layout.sym_Caml_state).toNat = Layout.sym_Caml_state from by decide,
    show sign_extend (m := 64) (@OFFSET@#12) = BitVec.ofNat 64 Layout.off_extern_sp from by decide] at run
  obtain ⟨n, after, count, steps, post⟩ := run
    h.domainRead.lower h.domainRead.upper h.domainRead.htif domain h.domainWord
    h.stackRead.lower h.stackRead.upper h.stackRead.htif frameSp h.savedStack
    h.envRead.lower h.envRead.upper h.envRead.htif env h.savedEnv c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  refine ⟨after, ⟨n - 1, by simpa only [show n - 1 + 1 = n from by omega] using steps⟩, ?_⟩
  apply ccall_return_restore stable h (count := @COUNT@) @BOUND_PROOF@ ?_ ?_ post.good memory frame.out
    (frame.frame (gprReg 2) (by decide))
  · refine ⟨post.pcAt, ?_, ?_, ⟨result, ?_, h.resultRepr⟩,
      ⟨env, PinsHold.get post.pins ⟨1, by simp⟩, h.envRepr⟩, ?_⟩
    · exact (frame.frame Register.x8 (by decide)).trans h.pc
    · have hp : gpr after Layout.reg_sp = some (frameSp + sign_extend (m := 64) (@INCREMENT@#12)) :=
        PinsHold.get post.pins ⟨0, by simp⟩
      simpa only [show sign_extend (m := 64) (@INCREMENT@#12) = BitVec.ofNat 64 (16 + 8 * @COUNT@) from by decide,
        ccall_return_sp h.restoreStack @COUNT@] using hp
    · exact PinsHold.get post.pins ⟨2, by simp⟩
    · exact (frame.frame (gprReg Layout.reg_extra) (by decide)).trans h.extra
  · exact loopRegisters_frame
      (fun r hr => frame.frame r (by revert r; decide)) h.loop

/-- Triple interface for the generated represented return, for callSeg splices. -/
theorem c_call@ARITY@_return_triple {L : OCaml.Layout} {P : Prog} {s : St} {pl : Place}
    {cp : ChanPlace} {sp high : Nat} {domain frameSp result env : BitVec 64}
    (stable : MemoryStable L.runtimeOk)@BOUND@ :
    Vsa.Logic.Triple (CcallReturn (@PC@#64) L P s pl cp sp high domain frameSp result env) (Running L P @STATE@) := by
  intro c h
  obtain ⟨after, ⟨n, steps⟩, repr⟩ := c_call@ARITY@_return stable h@BOUND_ARG@
  exact ⟨after, steps.toSteps, repr⟩

end OCaml.Vm.Sim
'''


def render(arity):
    spec = json.loads((ROOT / f"scripts/syi/segments/c_call{arity}_suffix.json").read_text())
    steps = spec["steps"]
    assert len(steps) == 6
    assert [s.get("rd") for s in steps[:5]] == ["x15", "x21", "x9", "x25", "x9"]
    increment = re.search(r"(0x[0-9a-f]+)#12", steps[4]["rd_val"])[1]
    offset = re.search(r"(0x[0-9a-f]+)#12", steps[2]["raw_val"])[1]
    count = arity - 1
    assert int(increment, 16) == 16 + 8 * count
    values = {
        "ARITY": str(arity), "PC": spec["entry"], "OFFSET": offset,
        "COUNT": str(count), "INCREMENT": increment,
        "STATE": "s" if arity == 1 else "{s with stack := s.stack.drop " + str(count) + "}",
        "BOUND": "" if arity == 1 else "\n    (bound : " + str(count) + " ≤ s.stack.length)",
        "BOUND_PROOF": "(Nat.zero_le _)" if arity == 1 else "bound",
        "BOUND_ARG": "" if arity == 1 else " bound",
    }
    out = TEMPLATE
    for name, value in values.items():
        out = out.replace("@" + name + "@", value)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for arity in range(1, 6):
        path = ROOT / f"OCaml/Vm/Sim/Ccall{arity}Return.lean"
        out = render(arity)
        if args.check:
            if not path.exists() or path.read_text() != out:
                raise SystemExit(f"represented C_CALL return drift: {path}")
        else:
            path.write_text(out)


if __name__ == "__main__":
    main()
