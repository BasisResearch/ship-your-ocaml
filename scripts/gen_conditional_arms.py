#!/usr/bin/env python3
"""Generate represented conditional-branch paths over guarded machine segments."""
import argparse
import json
from census import ROOT


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    for op, stem_base, isnot in [('BRANCHIF', 'Branchif', False), ('BRANCHIFNOT', 'Branchifnot', True)]:
        for jumping in [True, False]:
            stem = stem_base + ('Jump' if jumping else 'Next')
            lower = op.lower() + ('_jump' if jumping else '_next')
            zero = jumping == isnot
            entry = arms[op]['addr']
            test = 's.accu = .int 0' if zero else 's.accu ≠ .int 0'
            alignment = '' if zero else '''    (aligned : EvenPlace pl) (notRaw : ∀ x, s.accu ≠ .raw x)
'''
            branch_input = '''    (operand : OperandAt P pl (s.pc + 1) w)
    (jump : target s.pc 0 w.toInt = some dest)
''' if jumping else ''
            guard = '''  have guard : (accu == 1#64) = true := by
    apply beq_iff_eq.mpr
    rw [test] at value
    exact (Option.some.inj value).symm
''' if zero else '''  have guard : (accu == 1#64) = false :=
    beq_eq_false_iff_ne.mpr (fun hw => test ((false_word_iff aligned value notRaw).mp hw))
'''
            read = '''  have read : bytesT4 d.σ.mem (pl.codeBase + 4 * (s.pc + 1)) = w :=
    operand.read32 h.code dp.memory
''' if jumping else ''
            extra_pin = ',\n       ⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩' if jumping else ''
            extra_hold = ', dp.nextCode' if jumping else ''
            extra_arg = '\n    (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64)' if jumping else ''
            simp = '''    codePc_succ, operand.geometry.toNat, read,
''' if jumping else ''
            run_args = ''' guard operand.geometry.lower operand.geometry.upper
    operand.geometry.htif d (by simpa only [codePc_succ] using bp)''' if jumping else ' guard d bp'
            pc_proof = '''  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 1)) +
          (BitVec.ofInt 64 w.toInt <<< (2 : Nat))) := PinsHold.get post.pins ⟨0, by simp⟩
    have address : BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 1)) +
        (BitVec.ofInt 64 w.toInt <<< (2 : Nat)) = BitVec.ofNat 64 (pl.codeBase + 4 * dest) := by
      simpa only [Nat.add_zero] using relative_code_word pl jump
    simpa only [address] using hp
''' if jumping else '''  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 8#64) := PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [show BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 8#64 =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 2)) from codePc_add pl s.pc 2] using hp
'''
            result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.IsintArithmetic
import OCaml.Vm.Sim.BranchArithmetic
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_conditional_arms.py. Guarded represented branch path. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The {'jump' if jumping else 'fallthrough'} path of {op}, with the exact abstract false test.
The native branch guard is proved from the represented accumulator. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high{' dest' if jumping else ''} : Nat}}{' {w : BitVec 32}' if jumping else ''}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
{alignment}    (test : {test})
{branch_input}    : ∃ c', Plus c c' ∧ Running L P {{s with pc := {'dest' if jumping else 's.pc + 2'}}} c' := by
  apply control_arm stable h
  intro d dp accu haccu value
{guard}{read}  have bp : SegSt ({entry}#64)
      [⟨Register.x21, accu⟩, ⟨Register.x8, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)⟩{extra_pin}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨haccu, (dp.frame.frame Register.x8 (by decide)).trans h.pc{extra_hold}, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} accu (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)){extra_arg} d.σ.mem d.σ
  simp only [{'show sign_extend (m := 64) (0x004#12) = 4#64 from by decide,' if jumping else ''}
{simp}    show (0#64 + sign_extend (m := 64) (0x001#12)) = 1#64 from by decide] at run
  obtain ⟨nb, after, _, hb, post⟩ := run{run_args}
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
{pc_proof}  · exact (frame.frame Register.x21 (by decide)).trans haccu

end OCaml.Vm.Sim
'''
        jump_case = f"""    cases ht : target s.pc 0 w.toInt with
    | none => simp [stepI, test, ht, opt] at step
    | some dest =>
      have state : {{s with pc := dest}} = s' := by
        simpa [stepI, test, ht, opt] using step
      rw [← state]
      exact {op.lower()}_jump_arm stable h {'test' if isnot else 'aligned notRaw test'} operand ht"""
        next_case = f"""    have state : {{s with pc := s.pc + 2}} = s' := by
      simpa [stepI, test, St.adv] using step
    rw [← state]
    exact {op.lower()}_next_arm stable h {'aligned notRaw test' if isnot else 'test'}"""
        result[ROOT / f'OCaml/Vm/Sim/{stem_base}.lean'] = f"""import OCaml.Vm.Sim.{stem_base}Jump
import OCaml.Vm.Sim.{stem_base}Next

/-! GENERATED by scripts/gen_conditional_arms.py. Conditional branch composition. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine
open OCaml.Vm.Primitives

/-- Both paths of {op} implement its successful semantic step.
Alignment and exclusion of raw values identify the native false word. -/
theorem {op.lower()}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s s' : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{w : BitVec 32}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (aligned : EvenPlace pl) (notRaw : ∀ x, s.accu ≠ .raw x)
    (operand : OperandAt P pl (s.pc + 1) w)
    (step : stepI P s ⟨.{op}, [w.toInt]⟩ = .next s') :
    ∃ c', Plus c c' ∧ Running L P s' c' := by
  by_cases test : s.accu = .int (0#63)
  ·
{jump_case if isnot else next_case}
  ·
{next_case if isnot else jump_case}

end OCaml.Vm.Sim
"""
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'conditional arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Conditional arm bridges current')
