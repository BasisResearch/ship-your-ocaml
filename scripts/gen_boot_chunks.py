#!/usr/bin/env python3
"""Generate the newlib heap chunks live at the while_min cut from the checked store log."""
import argparse
import gzip
import json
from pathlib import Path
from boot_certificate import emit_read

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check', action='store_true')
args = ap.parse_args()
memory = {}
for _, a, width, value in map(json.loads, gzip.open(ROOT/'results/boot/while_min-stores.jsonl.gz')):
    for i in range(width):
        memory[a+i] = (value >> (8*i)) & 255

def read(a, width=8):
    return sum(memory[a+i] << (8*i) for i in range(width))

# The runtime's own blocks, by payload address (dlmalloc chunk = payload - 16).
NAMED = [('camlState', 0x8007d150, 'the `Caml_state` record'),
         ('refTable', 0x8007d500, 'the minor ref table'),
         ('minorHeap', 0x80081730, 'the minor heap block'),
         ('majorHeap', 0x80282740, 'the first major heap chunk'),
         ('vmStack', 0x803837b0, 'the VM stack'),
         ('codeBuffer', 0x8038d7f0, 'the bytecode buffer'),
         ('primTable', 0x8038fb10, 'the primitive table')]
HEAP_START = 0x8007d140
walk, chunk = set(), HEAP_START
while all(chunk + 8 + i in memory for i in range(8)) and read(chunk + 8) & ~7:
    walk.add(chunk + 16)
    chunk += read(chunk + 8) & ~7
out = ['import OCaml.Vm.Boot.WhileMinLogChecks', 'import OCaml.Vm.Boot.WhileMinObservation',
       'import Vsa.Sim.Boot.Bytes', '',
       '/-! GENERATED by scripts/gen_boot_chunks.py. The runtime\'s newlib heap chunks in the observed',
       'memory candidate: each payload, its chunk size, and the in-use bit in the next chunk\'s header.',
       'No execution or reachability claim. -/',
       'namespace OCaml.Vm.Boot.WhileMinHeapChunks',
       'open Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog', '',
       'variable {c : Config} {initial : Vsa.MemRepr.Mem}', '']
for name, payload, what in NAMED:
    assert payload in walk, hex(payload)
    header = read(payload - 8)
    size = header & ~7
    following = read(payload + size - 8)
    assert following & 1, name
    out += [f'/-- {what[0].upper() + what[1:]}. -/', f'def {name}Payload : Nat := {payload:#x}',
            f'def {name}Chunk : Nat := {size}', '']
    emit_read(out, f'{name}_header', f'{name}Payload - 8', header)
    emit_read(out, f'{name}_next', f'{name}Payload + {name}Chunk - 8', following)
    out += [f'theorem {name}_size (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    (word c ({name}Payload - 8)).toNat / 8 * 8 = {name}Chunk := by',
            f'  rw [read_{name}_header memory]; decide', '',
            f'theorem {name}_inUse (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    (word c ({name}Payload + {name}Chunk - 8)).toNat % 2 = 1 := by',
            f'  rw [read_{name}_next memory]; decide', '']
out += ['end OCaml.Vm.Boot.WhileMinHeapChunks', '']
path = ROOT/'OCaml/Vm/Boot/WhileMinHeapChunks.lean'
text = '\n'.join(out)
if args.check:
    if not path.exists() or path.read_text() != text: raise SystemExit('boot heap chunk drift')
elif not path.exists() or path.read_text() != text:
    path.write_text(text)
print(f'Heap chunks: {len(NAMED)} named of {len(walk)} walked')
