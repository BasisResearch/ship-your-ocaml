#!/usr/bin/env python3
"""Regenerate the six A0 library code predicates directly from this ELF."""
import argparse
import importlib.util
from census import ROOT, disasm

FUNCTIONS = ('strcmp', '__ssprint_r', '__ssputs_r', '_malloc_r', '_free_r', '_svfprintf_r', 'memmove')
spec = importlib.util.spec_from_file_location('code_lemmas', ROOT / 'experiments/syi/gen_code_lemmas.py')
code = importlib.util.module_from_spec(spec)
spec.loader.exec_module(code)


def outputs():
    fs = disasm(ROOT / 'c/ocamlrun-riscv-htif.elf')
    result = {}
    for name in FUNCTIONS:
        f = code.lean_ident(name)
        f = f[0].upper() + f[1:]
        text = code.render(name, [(pc, w) for pc, w, _, _ in fs[name]['insts']])
        text = text.replace('generated by experiments/gen_code_lemmas.py', 'GENERATED by scripts/gen_library_pins.py (experiments/syi/gen_code_lemmas.py)')
        result[ROOT / f'Vsa/Sim/Code/{f}.lean'] = text
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, s in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != s:
                raise SystemExit(f'library code pin drift: {p.relative_to(ROOT)}')
        elif not p.exists() or p.read_text() != s:
            p.write_text(s)
    print('A0 library pins: six function regions and memmove current')
