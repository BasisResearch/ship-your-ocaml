#!/usr/bin/env python3
"""Generate the unconditional PUSH / PUSHACC0..PUSHACC7 rows of the F1 arm table.

Each row instantiates the shared loop-head simulations of StackRows.lean
(push_next, push_read_next) with the generated represented arm."""
import argparse
from census import ROOT

HEADER = '''/-! GENERATED by scripts/gen_push_rows.py. Unconditional PUSH and PUSHACCn
rows of the F1 arm table: every premise of the represented push arm comes
from `LoopAt`, the dispatch code facts, the budget's stack capacity and the
runtime-framing contract (`StackRows.lean`). -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives
'''

PREMISES = '''{{L : OCaml.Layout}} {{B : OCaml.Budget}} {{P : Prog}} {{high0 dom0 : Nat}}
    (rf : RuntimeFrame L high0 dom0) (fits : OCaml.Fits B P) (capacity : StackCapacity B)'''


def plain(op, lower):
    return f'''
/-- **The {op} row**: push the accumulator from any loop head of the budget. -/
theorem {lower}_row {PREMISES.format(op=op)} :
    OCaml.OpArm P (OCaml.LoopAt L P) .{op} := by
  intro s c i reach h hd op _
  obtain ⟨o, args⟩ := i
  cases op
  cases args with
  | cons a as => exact trivial
  | nil =>
    apply OCaml.ArmOutcome.of_next
    · intro s' step
      cases step
      exact push_next rf (fun _ _ _ _ _ stable input space pushed => {lower}_arm stable input space pushed)
        h (decode_fetch hd).1 (stack_fits fits capacity reach)
    · intro e w step
      cases step
'''


def reading(op, lower, n):
    return f'''
/-- **The {op} row**: push the accumulator and load old slot {n}. -/
theorem {lower}_row {PREMISES.format(op=op)} :
    OCaml.OpArm P (OCaml.LoopAt L P) .{op} := by
  intro s c i reach h hd op _
  obtain ⟨o, args⟩ := i
  cases op
  cases args with
  | cons a as => exact trivial
  | nil =>
    apply OCaml.ArmOutcome.of_next
    · intro s' step
      exact push_read_next (n := {n}) rf
        (fun _ _ _ _ _ _ stable input space selected read pushed =>
          {lower}_arm stable input space selected read pushed)
        h (decode_fetch hd).1 (stack_fits fits capacity reach) step
    · intro e w
      exact opt_not_halt
'''


def outputs():
    ops = [('PUSH', 'push', None), ('PUSHACC0', 'pushacc0', None)] + \
          [(f'PUSHACC{k}', f'pushacc{k}', k - 1) for k in range(1, 8)]
    imports = ''.join(f'import OCaml.Vm.Sim.{lower.capitalize()}\n' for _, lower, _ in ops)
    body = ''.join(plain(op, lower) if n is None else reading(op, lower, n) for op, lower, n in ops)
    return {ROOT / 'OCaml/Vm/Sim/PushRows.lean':
            imports + 'import OCaml.Vm.Sim.StackRows\nimport OCaml.Vm.Sim.DecodeFetch\n\n' + HEADER + body + '\nend OCaml.Vm.Sim\n'}


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'push row drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Push rows current')
