#!/usr/bin/env python3
"""Quiet caught-exception arms sharing native selection and handler restoration."""
import argparse
import json
import sys
from gen_arm_pilot import ROOT
sys.path.insert(0, str(ROOT / 'scripts/syi'))
from gen_segment import SegmentEmitter


def outputs():
    result = {}
    for opcode, stem, family in [('RAISE','RaiseQuiet','raise_quiet'), ('RERAISE','ReraiseQuiet','reraise_quiet'), ('RAISE_NOTRACE','RaiseNotraceQuiet','raise_notrace_quiet')]:
        spec = json.loads((ROOT / f'scripts/syi/segments/{family}.json').read_text())
        em = SegmentEmitter(spec)
        em.emit()
        pins = {r: i for i, (r, _) in enumerate(em.pins)}
        global_addr = next(p for p in spec['params'] if p.startswith('(hlo_')).split(' ≤ ',1)[1].removesuffix('.toNat)')
        value = 'BitVec.ofNat 64 (high - 8 * s.trap)'
        barrier = '(word c ((word c Layout.sym_Caml_state).toNat + Layout.off_trap_barrier))'
        load_args = []
        for field, word, eq in [('trap','('+value+')','context.trap_word'), ('barrier',barrier,None)]:
            proof = f'(by rw [load, {eq}])' if eq else '(load _).symm'
            load_args.append(f'quiet.{field}Read.lower quiet.{field}Read.upper quiet.{field}Read.htif {word} {proof}')
        if opcode == 'RAISE_NOTRACE':
            load_args.append('below')
        else:
            load_args += ['(by simp only [native_uge, quiet.below context.caught_guard, Bool.not_true])',
                'quiet.backtraceRead.lower quiet.backtraceRead.upper quiet.backtraceRead.htif 0#64 (by rw [load, quiet.backtrace])',
                '(by decide)',
                f'quiet.trapRead.lower quiet.trapRead.upper quiet.trapRead.htif ({value}) (by rw [load, context.trap_word])']
        target = '{s with pc := dest, env := env, extra := extra.toNat, stack := rest, trap := s.trap - link.toNat}'
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.RaiseQuietState
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_raise_quiet.py. Quiet caught-exception caller composition. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- The native quiet path reaches the common caught-handler check. -/
theorem {family}_setup {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{pl : Place}} {{cp : ChanPlace}}
    {{sp high dest : Nat}} {{link extra : BitVec 63}} {{env : Val}} {{rest : List Val}} {{c d : Config}}
    (h : ArmInput L P s .{opcode} c pl cp sp high) (frame : RaiseFrame s dest link env extra rest)
    (quiet : RaiseQuietReady high c) (stable : MemoryStable L.runtimeOk)
    (dp : DispatchPost c .{opcode} (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)) d) :
    ∃ count after, StepsN count d after ∧ RaiseReadPost (0x80001ed4#64) c L P s pl cp sp high dest link env extra rest after := by
  have context := raise_context h frame
  have load (a : Nat) : sign_extend (m := 64) (bytesT8 d.σ.mem a) = word c a :=
    word_read_writeLog_out (log := []) trivial dp.memory
  have globalAddress : {global_addr} = BitVec.ofNat 64 Layout.sym_Caml_state := by decide
  have bp : SegSt ({spec['entry']}#64) []
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, trivial, dp.good.minstret, dp.tick, {family}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have native := tr_{family} d.σ.mem d.σ
  simp only [globalAddress, show (BitVec.ofNat 64 Layout.sym_Caml_state).toNat = Layout.sym_Caml_state from by decide] at native
  have domainStep := native (by decide) (by decide) (by decide) (word c Layout.sym_Caml_state) (load _).symm
  simp only [show sign_extend (m := 64) (0x0a8#12) = BitVec.ofNat 64 Layout.off_trapsp from by decide,
    show sign_extend (m := 64) (0x0b0#12) = BitVec.ofNat 64 Layout.off_trap_barrier from by decide,
    show sign_extend (m := 64) (0x0e8#12) = BitVec.ofNat 64 Layout.off_backtrace_active from by decide,
    domain_field_address, quiet.trapRead.toNat, quiet.barrierRead.toNat, quiet.backtraceRead.toNat] at domainStep
  have below : zopz0zI_u ({value}) {barrier} = true := by
    simpa only [native_ult, BitVec.ule_eq_not_ult, Bool.not_not] using quiet.below context.caught_guard
  obtain ⟨count, after, _, run, post⟩ := domainStep {' '.join(load_args)} d bp
  obtain ⟨_, memory, nativeFrame⟩ := post.extra
  have trapReg : gpr after 14 = some ({value}) := PinsHold.get post.pins ⟨{pins['x14']}, by simp⟩
  have domainReg : gpr after 15 = some (word c Layout.sym_Caml_state) := PinsHold.get post.pins ⟨{pins['x15']}, by simp⟩
  have memoryAll := memory.trans dp.memory
  refine ⟨count, after, run, ?_, memoryAll,
    (nativeFrame.frame Register.x2 (by decide)).trans (dp.frame.frame Register.x2 (by decide))⟩
  refine {{
    toRaiseContext := context.after_read stable post.good post.tick memoryAll (nativeFrame.out.trans dp.frame.out)
      ((nativeFrame.frame _ (by decide)).trans (dp.frame.frame _ (by decide)))
      ((nativeFrame.frame (gprReg 2) (by decide)).trans (dp.frame.frame (gprReg 2) (by decide)))
      ((nativeFrame.frame Register.htif_payload_writes (by decide)).trans
        (dp.frame.frame Register.htif_payload_writes (by decide)))
    pc := post.pcAt, trapReg := trapReg, domainReg := ?_ }}
  simpa only [word, memoryAll] using domainReg

/-- Execute the quiet caught exception, including handler selection and restoration. -/
theorem {family}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{pl : Place}} {{cp : ChanPlace}}
    {{sp high dest nativeSp : Nat}} {{link extra : BitVec 63}} {{env : Val}} {{rest : List Val}} {{c : Config}}
    (h : ArmInput L P s .{opcode} c pl cp sp high) (frame : RaiseFrame s dest link env extra rest)
    (quiet : RaiseQuietReady high c) (stable : MemoryStable L.runtimeOk)
    (saved : RaiseStackFrame nativeSp c) (nonnegative : 0 ≤ extra.toInt)
    (writeStable : WindowStable L.runtimeOk [⟨(word c Layout.sym_Caml_state).toNat + Layout.off_trapsp,
      (word c Layout.sym_Caml_state).toNat + Layout.off_trapsp + 8⟩])
    (reads : RaiseFrameReads (high - 8 * s.trap))
    (space : TrapWriteOk P s c pl cp sp high (s.trap - link.toNat)) :
    ∃ after, Plus c after ∧ Running L P {target} after := by
  apply dispatch_compose h.dispatch
  intro d dp
  obtain ⟨prefixCount, check, prefixRun, entered⟩ := {family}_setup h frame quiet stable dp
  have highRead : RamReadAt ((word check Layout.sym_Caml_state).toNat + Layout.off_stack_high) 8 := by
    simpa only [word, entered.memory] using quiet.highRead
  obtain ⟨checkCount, handler, checkRun, checked⟩ := raise_check entered.state stable
    (saved.frame entered.memory entered.nativeStack) highRead
  have memory := checked.memory.trans entered.memory
  have runtime : WindowStable L.runtimeOk [⟨(word handler Layout.sym_Caml_state).toNat + Layout.off_trapsp,
      (word handler Layout.sym_Caml_state).toNat + Layout.off_trapsp + 8⟩] := by
    simpa only [word, memory] using writeStable
  obtain ⟨handlerCount, after, handlerRun, result⟩ := raise_handler checked.state nonnegative runtime reads (space.frame memory)
  exact ⟨prefixCount + checkCount + handlerCount, after, (prefixRun.append checkRun).append handlerRun, result⟩

/-- Match the actual bytecode raise rule to the represented caught path. -/
theorem {family}_step_arm {{L : OCaml.Layout}} {{P : Prog}} {{s s' : St}} {{pl : Place}} {{cp : ChanPlace}}
    {{sp high dest nativeSp : Nat}} {{link extra : BitVec 63}} {{env : Val}} {{rest : List Val}} {{c : Config}}
    (h : ArmInput L P s .{opcode} c pl cp sp high) (frame : RaiseFrame s dest link env extra rest)
    (quiet : RaiseQuietReady high c) (stable : MemoryStable L.runtimeOk)
    (saved : RaiseStackFrame nativeSp c) (nonnegative : 0 ≤ extra.toInt)
    (writeStable : WindowStable L.runtimeOk [⟨(word c Layout.sym_Caml_state).toNat + Layout.off_trapsp,
      (word c Layout.sym_Caml_state).toNat + Layout.off_trapsp + 8⟩])
    (reads : RaiseFrameReads (high - 8 * s.trap))
    (space : TrapWriteOk P s c pl cp sp high (s.trap - link.toNat))
    (step : stepI P s ⟨.{opcode}, []⟩ = .next s') :
    ∃ after, Plus c after ∧ Running L P s' after := by
  have state := frame.state_of_step (by simpa only [stepI] using step)
  rw [← state]
  exact {family}_arm h frame quiet stable saved nonnegative writeStable reads space

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    drift = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if drift:
        sys.exit('Quiet raise adapter drift: ' + ', '.join(drift))
    print('Quiet raise adapters current')
