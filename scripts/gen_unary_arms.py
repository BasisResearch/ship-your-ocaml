#!/usr/bin/env python3
"""Generate NEGINT and BOOLNOT bridges from one tagged-subtraction template."""
import argparse
import json
from census import ROOT

TEMPLATE = r'''
import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.ImmediateArithmetic
import OCaml.Vm.Sim.@STEM@Segment
import OCaml.Vm.Sim.@STEM@Pins

/-! GENERATED by scripts/gen_unary_arms.py. Tagged constant subtraction. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- Represented @OP@, using generated dispatch/body runs and the shared
immediate-result restoration rule. Dispatch readiness remains explicit. -/
theorem @LOWER@_arm {L : OCaml.Layout} {P : Prog} {s : St} {c : Config}
    {pl : Place} {cp : ChanPlace} {sp high : Nat} {n : BitVec 63}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .@OP@ c pl cp sp high) (accu : s.accu = .int n) :
    ∃ c', Plus c c' ∧ Running L P {s with pc := s.pc + 1, accu := .int (@RESULT@)} c' := by
@NORMALIZE@  have hc : gpr c Layout.reg_accu = some (tag64 n) := by
    obtain ⟨w, hw, hv⟩ := h.accu
    rw [accu] at hv
    cases hv
    exact hw
  apply immediate_arm stable h
  intro d dp
  have bp : SegSt (@ENTRY@#64)
      [⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩,
       ⟨Register.x21, tag64 n⟩]
      (fun σ => Vsa.Sim.Code.Caml@STEM@Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨dp.nextCode, (dp.frame.frame Register.x21 (by decide)).trans hc, trivial⟩,
      dp.good.minstret, dp.tick, @LOWER@_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  obtain ⟨nb, after, hnb, hb, post⟩ := tr_@LOWER@ _ _ d.σ.mem d.σ d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
  · have hp : gpr after Layout.reg_pc = some
          ((BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
      BitVec.add_zero, codePc_succ] using hp
  · have hp : gpr after Layout.reg_accu = some
          ((0#64 + sign_extend (m := 64) (@IMM@#12)) - tag64 n) :=
      PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [show sign_extend (m := 64) (@IMM@#12) = @WORD@ from by decide,
      BitVec.zero_add, @ARITH@] using hp

end OCaml.Vm.Sim
'''


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    for op, stem, word, result_expr, arithmetic, normalize in [
        ('NEGINT', 'Negint', 2, 'untag (2#64 - tag64 n)', 'tag_neg', '  rw [untag_neg]\n'),
        ('BOOLNOT', 'Boolnot', 4, '1 - n', 'tag_not', ''),
    ]:
        text = TEMPLATE.lstrip()
        values = {'STEM': stem, 'OP': op, 'LOWER': op.lower(), 'WORD': f'{word}#64',
                  'IMM': f'0x{word:03x}', 'ENTRY': arms[op]['addr'], 'RESULT': result_expr,
                  'ARITH': arithmetic, 'NORMALIZE': normalize}
        for key, value in values.items():
            text = text.replace('@'+key+'@', value)
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = text
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'unary arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Unary arm bridges current')
