#!/usr/bin/env python3
"""Generate checked dispatch-table contents from the pinned ELF and census.

Each byte projection is a separate small kernel check. Data addresses in
contracts use Layout.jumpTable; instruction targets come from the census.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
from census import ROOT, opcode_names
from gen_ocaml_image import sections


def outputs():
    elf = (ROOT / 'c/ocamlrun-riscv-htif.elf').read_bytes()
    if hashlib.sha256(elf).hexdigest() != (ROOT / 'c/ELF.sha256').read_text().split()[0]:
        raise ValueError('unpinned ELF')
    census = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']
    names = opcode_names(ROOT / 'vendor/ocaml-4.14.4/runtime/caml/instruct.h')
    base, raw = sections(elf)['.rodata']
    table = int(census['table'], 16)
    entries = []
    for i, name in enumerate(names):
        offset = table - base + 4 * i
        word = struct.unpack_from('<I', raw, offset)[0]
        signed = struct.unpack_from('<i', raw, offset)[0]
        target = int(census['arms'][name]['addr'], 16)
        if table + signed != target:
            raise ValueError(f'{name}: jump table and census disagree')
        entries.append((i, name, offset, word, target))
    out = {}
    prefix = ['import OCaml.Vm.Platform', 'import Vsa.Sim.RamReadLoad', '',
              '/-! GENERATED by scripts/gen_dispatch_table.py. Pinned switch-table data. -/',
              'namespace OCaml.Vm.Sim', 'set_option autoImplicit false', 'open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable.Functions', '']
    data = prefix + ['def dispatchOffset : Opcode → BitVec 32']
    data += [f'  | .{n} => 0x{w:08x}#32' for _, n, _, w, _ in entries]
    data += ['', 'def dispatchTarget : Opcode → Nat']
    data += [f'  | .{n} => 0x{target:x}' for _, n, _, _, target in entries]
    data += ['', 'end OCaml.Vm.Sim', '']
    out[ROOT / 'OCaml/Vm/Sim/DispatchTableData.lean'] = '\n'.join(data)
    chunks = []
    for part, start in enumerate(range(0, len(entries), 24)):
        module = f'OCaml.Vm.Sim.DispatchTable.Part{part:02d}'
        chunks.append(module)
        lines = ['import OCaml.Vm.Sim.DispatchTableData', *prefix[2:]]
        for i, name, offset, word, target in entries[start:start + 24]:
            address = f'(Layout.jumpTable + 4 * Opcode.{name}.toNat)'
            lines += [f'theorem dispatchOffset_{name.lower()} {{c : Config}} (h : ExecutableImage c) :',
                      f'    word32 c {address} = dispatchOffset .{name} := by']
            for k in range(4):
                byte = (word >> (8 * k)) & 255
                addr = address if k == 0 else f'({address} + {k})'
                lines += [f'  have h{k} : c.σ.mem[{addr}]? = some (0x{byte:02x}#8) := by',
                          f'    have hb := h.rodata {offset+k} (by decide)',
                          f'    have he : Image.rodataByte {offset+k} = (0x{byte:02x}#8) := by decide +kernel',
                          '    rw [he] at hb', '    exact hb']
            lines += ['  simp only [word32, bytesT_four_eq, bytesT4, h0, h1, h2, h3, Option.getD_some] <;> decide', '',
                      f'theorem dispatchTarget_{name.lower()} :',
                      f'    sign_extend (m := 64) (dispatchOffset .{name}) + BitVec.ofNat 64 Layout.jumpTable =',
                      f'      BitVec.ofNat 64 (dispatchTarget .{name}) := by decide', '',
                      f'theorem dispatchIndex_{name.lower()} :',
                      f'    Sail.shift_bits_left (sign_extend (m := 64) (BitVec.ofNat 32 Opcode.{name}.toNat))',
                      '      (Sail.BitVec.extractLsb (0x02#6) 5 0) + BitVec.ofNat 64 Layout.jumpTable =',
                      f'      BitVec.ofNat 64 (Layout.jumpTable + 4 * Opcode.{name}.toNat) := by apply BitVec.eq_of_toNat_eq; decide', '']
        lines += ['end OCaml.Vm.Sim', '']
        out[ROOT / (module.replace('.', '/') + '.lean')] = '\n'.join(lines)
    lines = ['import ' + m for m in chunks] + prefix[2:]
    lines += ['theorem dispatchOffset_loaded {c : Config} (h : ExecutableImage c) (op : Opcode) :',
              '    word32 c (Layout.jumpTable + 4 * op.toNat) = dispatchOffset op := by',
              '  cases op with']
    lines += [f'  | {name} => exact dispatchOffset_{name.lower()} h' for _, name, _, _, _ in entries]
    lines += ['', 'theorem dispatchOffset_target (op : Opcode) :',
              '    sign_extend (m := 64) (dispatchOffset op) + BitVec.ofNat 64 Layout.jumpTable =',
              '      BitVec.ofNat 64 (dispatchTarget op) := by', '  cases op with']
    lines += [f'  | {name} => exact dispatchTarget_{name.lower()}' for _, name, _, _, _ in entries]
    lines += ['', 'theorem dispatchOpcode_guard (op : Opcode) :',
              '    zopz0zKzJ_u (BitVec.ofNat 64 Layout.opcodeBound)',
              '      (sign_extend (m := 64) (BitVec.ofNat 32 op.toNat)) = true := by',
              '  cases op <;> decide', '', 'theorem dispatchTarget_aligned (op : Opcode) :',
              '    (BitVec.ofNat 64 (dispatchTarget op)).toNat % 4 = 0 := by',
              '  cases op <;> decide', '',
              'theorem dispatchTarget_clear (op : Opcode) :',
              '    Sail.BitVec.update (BitVec.ofNat 64 (dispatchTarget op)) 0 0#1 =',
              '      BitVec.ofNat 64 (dispatchTarget op) := by',
              '  cases op <;> decide', '',
              'theorem dispatchIndex (op : Opcode) :',
              '    Sail.shift_bits_left (sign_extend (m := 64) (BitVec.ofNat 32 op.toNat))',
              '      (Sail.BitVec.extractLsb (0x02#6) 5 0) + BitVec.ofNat 64 Layout.jumpTable =',
              '      BitVec.ofNat 64 (Layout.jumpTable + 4 * op.toNat) := by',
              '  cases op with']
    lines += [f'  | {name} => exact dispatchIndex_{name.lower()}' for _, name, _, _, _ in entries]
    lines += ['',
              'theorem dispatchIndex_nat (op : Opcode) :',
              '    (BitVec.ofNat 64 (Layout.jumpTable + 4 * op.toNat)).toNat =',
              '      Layout.jumpTable + 4 * op.toNat := by',
              '  cases op <;> decide', '',
              'theorem dispatchIndex_lower (op : Opcode) :',
              '    0x80000000 ≤ Layout.jumpTable + 4 * op.toNat := by',
              '  cases op <;> decide', '',
              'theorem dispatchIndex_upper (op : Opcode) :',
              '    Layout.jumpTable + 4 * op.toNat + 4 ≤ 0x100000000 := by',
              '  cases op <;> decide', '',
              'theorem dispatchIndex_htif (op : Opcode) :',
              '    Layout.jumpTable + 4 * op.toNat + 4 ≤ tohostAddr ∨',
              '      tohostAddr + 8 ≤ Layout.jumpTable + 4 * op.toNat := by',
              '  cases op <;> decide', '', 'end OCaml.Vm.Sim', '']
    out[ROOT / 'OCaml/Vm/Sim/DispatchTable.lean'] = '\n'.join(lines)
    return out


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'dispatch table drift: {p.relative_to(ROOT)}')
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    print('Dispatch table artifacts current')
