#!/usr/bin/env python3
"""Generate composed global/field reads through shared reachability observations."""
import argparse
import json
from census import ROOT


def outputs():
    result = {}
    for push in [False, True]:
        op = ('PUSH' if push else '') + 'GETGLOBALFIELD'
        stem, lower = op.title(), op.lower()
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
        regs = [p['reg'] for p in spec['pins']]
        for step in spec['steps']:
            if step.get('rd'):
                regs = [step['rd']] + [r for r in regs if r != step['rd']]
        pc_pin, accu_pin = regs.index('x8'), regs.index('x21')
        ea = [p for p in spec['params'] if p.startswith('(hlo_')][1 + push].split(' ≤ ', 1)[1].removesuffix('.toNat)')
        values = {'x8': 'BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)', 'x9': 'BitVec.ofNat 64 sp', 'x21': 'w'}
        holds = {'x8': '(dp.frame.frame Register.x8 (by decide)).trans h.pc',
                 'x9': '(dp.frame.frame Register.x9 (by decide)).trans h.spReg',
                 'x21': '(dp.frame.frame Register.x21 (by decide)).trans source'}
        pins = ',\n       '.join(f'⟨Register.{p["reg"]}, {values[p["reg"]]}⟩' for p in spec['pins'])
        pin_holds = ',\n       '.join(holds[p['reg']] for p in spec['pins'])
        args = ' '.join(f'({values[p["reg"]]})' for p in spec['pins'])
        a1, a2 = 'a + 8 * (k + n.toInt.toNat)', 'b + 8 * (j + m.toInt.toNat)'
        source = '  have source := represented_register h.accu pushed\n' if push else ''
        store_inputs = '''    (space : PushWriteOk P s c pl cp sp w)
    (pushed : valWord pl s.accu = some w)
''' if push else ''
        memory = 'memoryAfter' if push else 'd.σ.mem'
        reads = '''  have readN := operandN.read32 h.code dp.memory
  have readM := operandM.read32 h.code dp.memory
'''
        native_reads = f'''  have globalRead : sign_extend (m := 64) (bytesT8 d.σ.mem Layout.sym_caml_global_data) =
      BitVec.ofNat 64 (a + 8 * k) := by
    simpa only [dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using globalWord
  have firstRead : sign_extend (m := 64) (bytesT8 d.σ.mem ({a1})) =
      BitVec.ofNat 64 (b + 8 * j) := by
    simpa only [dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using firstWord
  have secondRead : sign_extend (m := 64) (bytesT8 d.σ.mem ({a2})) = word c ({a2}) := by
    simp only [dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq]
'''
        run_setup = f'  have body := tr_{lower} {args} d.σ.mem d.σ\n'
        final = '''  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩'''
        stack_result, preserved = '', ''
        if push:
            lo = int(spec['entry'], 16)
            hi = max(int(s['addr'], 16) for s in spec['steps']) + 4
            reads = f'''  have code : sp - 8 + 8 ≤ 0x{lo:x} ∨ 0x{hi:x} ≤ sp - 8 :=
    space.code (by decide) (by decide)
  obtain ⟨memoryAfter, memoryEq⟩ : ∃ mem : Std.ExtHashMap Nat (BitVec 8),
      mem = writeLog d.σ.mem (pushLog sp w) := ⟨_, rfl⟩
  have memory := memoryEq.trans (congrArg (fun mem => writeLog mem (pushLog sp w)) dp.memory)
  have readN := space.operand_read32 h.code operandN memory
  have readM := space.operand_read32 h.code operandM memory
'''
            native_reads = '''  have globalRead := (space.word_read space.payload.globals memory).trans globalWord
  have firstRead := (first.load_frame payload (fun _ hl => Live.root (by simp [roots]) hl)
    space.payload memory).trans firstWord
  have secondRead := second.load_frame payload firstValue.root space.payload memory
'''
            run_setup = f'''  have run := tr_{lower} {args} d.σ.mem d.σ
  simp only [push_address space.room] at run
  have body := run space.window.lower space.window.upper
    space.window.htif space.window.aligned (by simpa only [space.toNat] using code)
    memoryAfter (by rw [space.toNat]; exact memoryEq)
'''
            final = '  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, ?_, hm.trans memoryEq, frame.out, ?_⟩'
            stack_result = f'  · exact PinsHold.get post.pins ⟨{regs.index("x9")}, by simp⟩\n'
            preserved = '''
  · intro r hr
    exact frame.frame r (by revert r; decide)'''
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.StackStore
import OCaml.Vm.Sim.FieldRead
import OCaml.Vm.Sim.IndexWord
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_global_field_arms.py. Composed reachable-field reads. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} follows the global root and then a reachable object's field.
Index signs, RAM windows and runtime preservation remain invariant-adapter obligations. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a k loc b j : Nat}} {{mid v : Val}}
    {{n m : BitVec 32}}{' {w : BitVec 64}' if push else ''}
    (stable : {'WindowStable L.runtimeOk [⟨sp - 8, sp⟩]' if push else 'MemoryStable L.runtimeOk'})
    (h : ArmInput L P s .{op} c pl cp sp high)
{store_inputs}    (operandN : OperandAt P pl (s.pc + 1) n)
    (operandM : OperandAt P pl (s.pc + 2) m)
    (nonnegativeN : 0 ≤ n.toInt) (nonnegativeM : 0 ≤ m.toInt)
    (first : FieldSelection s.heap pl P.globals n.toInt.toNat mid l a k)
    (second : FieldSelection s.heap pl mid m.toInt.toNat v loc b j)
    (firstWindow : RamReadAt ({a1}) 8)
    (secondWindow : RamReadAt ({a2}) 8) :
    ∃ c', Plus c c' ∧ Running L P
      {{s with pc := s.pc + 3, accu := v{', stack := s.accu :: s.stack' if push else ''}}} c' := by
{source}  have payload := payload_of_repr h.toVmReprAt
  have firstValue := first.read_payload payload (by simp [roots])
  have value := second.read_reachable payload firstValue.root
  have globalWord : word c Layout.sym_caml_global_data = BitVec.ofNat 64 (a + 8 * k) :=
    Option.some.inj (h.globals.symm.trans first.sourceWord)
  have firstWord : word c ({a1}) = BitVec.ofNat 64 (b + 8 * j) :=
    Option.some.inj (firstValue.word.symm.trans second.sourceWord)
  apply {'push_value_arm stable h space pushed' if push else 'accu_arm stable h'} value.word value.root
  intro d dp
{reads}  have globalWindow : RamReadAt Layout.sym_caml_global_data 8 := ⟨by decide, by decide, by decide⟩
  have globalAddress : {ea} = BitVec.ofNat 64 Layout.sym_caml_global_data := by decide
{native_reads}  have firstAddress : BitVec.ofNat 64 (8 * n.toInt.toNat) + BitVec.ofNat 64 (a + 8 * k) =
      BitVec.ofNat 64 ({a1}) := by
    rw [BitVec.add_comm]
    simp only [Nat.mul_add, ← Nat.add_assoc, BitVec.ofNat_add]
  have secondAddress : BitVec.ofNat 64 (8 * m.toInt.toNat) + BitVec.ofNat 64 (b + 8 * j) =
      BitVec.ofNat 64 ({a2}) := by
    rw [BitVec.add_comm]
    simp only [Nat.mul_add, ← Nat.add_assoc, BitVec.ofNat_add]
  have bp : SegSt ({spec['entry']}#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨{pin_holds}, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
{run_setup}  simp only [show sign_extend (m := 64) (0x004#12) = 4#64 from by decide,
    show sign_extend (m := 64) (0x008#12) = 8#64 from by decide,
    show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, codePc_succ, codePc_add pl s.pc 2,
    operandN.geometry.toNat, operandM.geometry.toNat, readN, readM,
    globalAddress, globalWindow.toNat, globalRead,
    index_word n nonnegativeN, index_word m nonnegativeM,
    firstAddress, firstWindow.toNat, firstRead,
    secondAddress, secondWindow.toNat, secondRead] at body
  obtain ⟨nb, after, _, hb, post⟩ := body
    operandN.geometry.lower operandN.geometry.upper operandN.geometry.htif
    globalWindow.lower globalWindow.upper globalWindow.htif
    operandM.geometry.lower operandM.geometry.upper operandM.geometry.htif
    firstWindow.lower firstWindow.upper firstWindow.htif
    secondWindow.lower secondWindow.upper secondWindow.htif d bp
  obtain ⟨_, hm, frame⟩ := post.extra
{final}
  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 12#64) :=
      PinsHold.get post.pins ⟨{pc_pin}, by simp⟩
    simpa only [show BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 12#64 =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 3)) from codePc_add pl s.pc 3] using hp
{stack_result}  · exact PinsHold.get post.pins ⟨{accu_pin}, by simp⟩{preserved}

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'global field arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Global field arm bridges current')
