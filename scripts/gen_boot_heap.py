#!/usr/bin/env python3
"""Generate while_min placement and object certificates from the checked store log."""
import argparse
import gzip
import json
import re
from pathlib import Path
from boot_certificate import emit_read, finite_cases

ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check',action='store_true')
args=ap.parse_args()
layout={k:int(v,0) for k,v in re.findall(r'^def (\w+) : Nat := (\w+)$',
    (ROOT/'OCaml/Vm/Layout.lean').read_text(),re.M)}
mem={}
for _,a,n,v in map(json.loads,gzip.open(ROOT/'results/boot/while_min-stores.jsonl.gz')):
    for i in range(n):mem[a+i]=(v>>(8*i))&255

def read(a,n=8):return sum(mem[a+i]<<(8*i) for i in range(n))
source=(ROOT/'OCaml/Programs/WhileMin.lean').read_text()
heap=source.split('def whileMinHeap : List Obj := [')[1].split('\n\n')[0]
objects=[]
for line in heap.splitlines():
    if not line.strip():continue
    lean=line.strip().removesuffix(',').removesuffix(']')
    if '.block' in line:
        tag=int(re.search(r'\.block (\d+)',line)[1])
        fields=[(m[1],int(m[2]),int(m[3] or 0)) for m in
                re.finditer(r'\(\.(ptr|int) (\d+)(?: (\d+)|#63)\)',line)]
        objects.append(('block',tag,fields,lean))
    elif '.bytes' in line:
        contents=[int(x) for x in re.search(r'\[([^]]*)\]',line)[1].split(', ')]
        objects.append(('bytes',252,contents,lean))
    else:raise SystemExit('unrecognized fixture object: '+line)
placements={}
root_indices=[int(x) for x in re.findall(r'\(\.ptr (\d+) 0\)',source.split('def whileMin : Prog :=')[1])]
assert len(root_indices)==2
pending=[(root_indices[0],read(layout['sym_caml_global_data'])),
         (root_indices[1],read(layout['sym_main_argv']))]
while pending:
    l,a=pending.pop()
    if l in placements:
        assert placements[l]==a
        continue
    placements[l]=a
    kind,tag,contents,_=objects[l]
    header=read(a-8)
    assert header%256==tag
    if kind=='block':
        assert header//1024==len(contents)
        for i,(v,n,k) in enumerate(contents):
            raw=read(a+8*i)
            if v=='ptr':pending.append((n,raw-8*k))
            else:assert raw==2*n+1
    else:
        assert [read(a+i,1) for i in range(len(contents))]==contents
        assert header//1024*8-read(a+header//1024*8-1,1)-1==len(contents)
assert len(placements)==len(objects)
out=['import OCaml.Vm.Boot.WhileMinLogChecks','import Vsa.Sim.Boot.Bytes',
     'import OCaml.Vm.Boot.Heap','import OCaml.Programs.WhileMin','',
     '/-! GENERATED by scripts/gen_boot_heap.py. Object facts for the observed memory candidate. -/',
     'namespace OCaml.Vm.Boot.WhileMinHeap','open OCaml.Bytecode OCaml.Programs',
     'open Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog','',
     'def addresses : List Nat := ['+', '.join(hex(placements[i]) for i in range(len(objects)))+']',
     f'def place : Place := ⟨fun l => addresses[l]?, {read(layout["sym_caml_start_code"]):#x}⟩',
     'variable {c : Config} {initial : Vsa.MemRepr.Mem} {cp : ChanPlace}', '']
for i,(kind,tag,contents,lean) in enumerate(objects):
    a=placements[i]
    out.append(f'def obj{i} : Obj := {lean}')
    emit_read(out,f'header{i}',f'{a:#x} - 8',read(a-8))
    proofs=[]
    for j in range(len(contents)):
        width=8 if kind=='block' else 1
        addr=a+width*j
        emit_read(out,f'obj{i}_{j}',f'{a:#x} + {width*j}',read(addr,width),width)
        if kind=='block':proofs.append(f'(congrArg some (read_obj{i}_{j} memory)).symm')
        else:proofs.append(f'read_obj{i}_{j} memory')
    if kind=='bytes':
        pad=a+read(a-8)//1024*8-1
        emit_read(out,f'pad{i}',f'{a:#x} + 8 * obj{i}.wosize - 1',read(pad,1),1)
    out += [f'theorem object{i} (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    ObjAt c place cp {a:#x} obj{i} := by',
            '  constructor',f'  · rw [read_header{i} memory]; unfold HeaderOk; decide +kernel']
    if kind=='block':
        out += ['  · apply list_get_of_fin','    exact '+finite_cases(proofs)]
    else:
        out += ['  · constructor','    · apply list_get_of_fin','      exact '+finite_cases(proofs),
                f'    · rw [read_pad{i} memory]; decide +kernel']
    out.append('')
out += ['theorem objects (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        '    ∀ l o, whileMin.heap0.get? l = some o →',
        '      ∃ a, place.φ l = some a ∧ ObjAt c place cp a o := by',
        '  change ∀ l o, whileMinHeap[l]? = some o → ∃ a, place.φ l = some a ∧ ObjAt c place cp a o',
        '  refine list_get_of_fin (xs := whileMinHeap) (R := fun l o => ∃ a, place.φ l = some a ∧ ObjAt c place cp a o) ?_',
        '  exact '+finite_cases([f'⟨{placements[i]:#x}, rfl, object{i} memory⟩' for i in range(len(objects))]), '']
for i,(kind,tag,contents,lean) in enumerate(objects):
    out += [f'theorem closed{i} : ∀ tag fs, obj{i} = .block tag fs →',
            '    ∀ v ∈ fs, ∀ target, v.loc? = some target → ∃ o, whileMin.heap0.get? target = some o := by',
            '  intro tag fs eq', '  cases eq']
    if kind=='block':
        out += ['  intro v hv target hp',
                '  simp only [List.mem_cons, List.not_mem_nil, or_false] at hv',
                '  rcases hv with '+' | '.join(['rfl']*len(contents)),
                '  all_goals cases hp', '  all_goals exact ⟨_, rfl⟩']
    out.append('')
out += ['theorem closed : HeapClosed whileMin.heap0 (roots whileMin whileMin.init) where',
        '  roots := by', '    intro v hv target hp',
        f'    change v ∈ [Val.int 0, Val.atom 0, Val.ptr {root_indices[0]} 0, Val.ptr {root_indices[1]} 0] at hv',
        '    simp only [List.mem_cons, List.not_mem_nil, or_false] at hv',
        '    rcases hv with rfl | rfl | rfl | rfl',
        '    all_goals cases hp', '    all_goals exact ⟨_, rfl⟩',
        '  fields := by',
        '    have all : ∀ (l : Nat) (o : Obj), whileMinHeap[l]? = some o →',
        '        ∀ tag fs, o = .block tag fs → ∀ v ∈ fs, ∀ target,',
        '          v.loc? = some target → ∃ obj, whileMin.heap0.get? target = some obj :=',
        '      list_get_of_fin ('+finite_cases([f'closed{i}' for i in range(len(objects))])+')',
        '    intro l tag fs hg', '    exact all l _ hg tag fs rfl', '',
        'theorem separated : ∀ i j : Fin whileMinHeap.length, i ≠ j →',
        "    addresses[i.val]'(by exact i.isLt) + 8 * whileMinHeap[i.val].wosize ≤ addresses[j.val]'(by exact j.isLt) - 8 ∨",
        "    addresses[j.val]'(by exact j.isLt) + 8 * whileMinHeap[j.val].wosize ≤ addresses[i.val]'(by exact i.isLt) - 8 := by",
        '  decide +kernel', '']
out += ['end OCaml.Vm.Boot.WhileMinHeap','']
path=ROOT/'OCaml/Vm/Boot/WhileMinHeapObjects.lean'
text='\n'.join(out)
if args.check:
    if not path.exists() or path.read_text()!=text:raise SystemExit('boot heap certificate drift')
elif not path.exists() or path.read_text()!=text:path.write_text(text)
print(f'Heap certificate: {len(objects)} objects')
