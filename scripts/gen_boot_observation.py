#!/usr/bin/env python3
"""Emit small kernel checks of boot_cut.py's observed runtime projection.

This does NOT certify that the projection is reached by the Sail machine.
The machine-to-projection certificate remains open.
"""
import argparse
import json
from pathlib import Path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("observation", type=Path)
    args = ap.parse_args()
    cut = json.loads(args.observation.read_text())
    fields = cut["fields"]
    if fields["young_ptr"] == fields["young_alloc_end"]:
        raise SystemExit("expected the recorded nonempty-nursery observation")
    print('''import OCaml.Vm.Runtime

/-!
# Observed while_min startup facts

GENERATED by `scripts/gen_boot_observation.py` from
`results/boot/while_min-cut.json`. Do not edit.
Only facts about this small projection are kernel checked. Connecting it
to a reachable Sail configuration remains an open obligation.
-/

namespace OCaml.Vm.Boot.WhileMinObservation

open Vsa.Machine
''')
    print(f'/-- SHA-256 of the measured ELF (not the pinned while.ml ELF). -/\n'
          f'def elfSha256 : String := "{cut["elf_sha256"]}"\n')
    print(f'def cutStep : Nat := {cut["cut_step"]}\n')
    print('def observed : RuntimeFields where')
    for lean, c in [("youngStart", "young_start"), ("youngEnd", "young_end"),
                    ("allocStart", "young_alloc_start"), ("allocEnd", "young_alloc_end"),
                    ("youngPtr", "young_ptr"), ("youngLimit", "young_limit")]:
        print(f'  {lean} := {fields[c]:#x}')
    print(f'  somethingToDo := {cut["something_to_do"]}\n')
    print('''theorem bounds : MinorHeapBounds observed := by
  constructor <;> decide +kernel

theorem noPending : observed.somethingToDo = 0 := by decide +kernel

/-- Startup promotion does not empty the nursery; this is allowed by RuntimeOk. -/
theorem nursery_not_empty : observed.youngPtr ≠ observed.allocEnd := by decide +kernel

end OCaml.Vm.Boot.WhileMinObservation''')


if __name__ == "__main__":
    main()
