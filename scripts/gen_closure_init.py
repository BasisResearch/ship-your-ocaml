#!/usr/bin/env python3
"""Compose both CLOSURE initializers with shared capture and metadata contracts."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def render(kind):
    more=kind=='more';stem=kind.title()
    spec=json.loads((ROOT/f'scripts/syi/segments/closure_init_{kind}.json').read_text())
    regs=[p['reg'] for p in spec['pins']]
    vals={'x26':'(BitVec.ofNat 64 (count + 2))','x15':'(BitVec.ofNat 64 (a - 8))','x17':'(BitVec.ofNat 64 count)','x23':'(BitVec.ofNat 64 (closureSource sp count))'}
    proofs={'x26':'front.fields.fieldCount','x15':'front.header','x17':'front.fields.countReg','x23':'front.fields.sourceReg'}
    pins=', '.join(f'⟨Register.{r}, {vals[r]}⟩' for r in regs);args=' '.join(vals[r] for r in regs);pinproof=', '.join(proofs[r] for r in regs)
    for st in spec['steps']:
        r=st.get('rd')
        if r:regs=[r]+[x for x in regs if x!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    guard='return_more_guard count branch (by omega)' if more else 'by rw [branch]; decide'
    copy=f'''  · intro _
    exact ⟨{get('x13')}, {get('x15')}, {get('x11')}⟩''' if more else '''  · intro impossible
    omega'''
    return f'''-- GENERATED by scripts/gen_closure_init.py; do not edit.
import OCaml.Vm.Sim.ClosureInitInput
import OCaml.Vm.Sim.ClosureInit{stem}Segment
import OCaml.Vm.Sim.ClosureInit{stem}Pins
import OCaml.Vm.Sim.ClosureInit{stem}Layout

namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The actual {kind} initializer writes the closure header and prepares the capture path. -/
theorem closure_initialize_{kind} {{pl : Place}} {{pc sp count a domain limit : Nat}} {{accu : BitVec 64}} {{c d : Config}}
    (nursery : NurseryInput (count + 2) a domain limit c)
    (space : ClosureInitInput sp count a domain accu c)
    (branch : {'0 < count' if more else 'count = 0'})
    (front : ClosureReserved c pl pc sp count a domain accu d) :
    ∃ nb after, StepsN nb d after ∧ ClosureInitialized c pl pc sp count a domain accu after := by
  have small := front.fields.nurseryBound
  have domainRead : RamReadAt Layout.sym_Caml_state 8 := ⟨by decide, by decide, by decide⟩
  have youngRead := nursery.youngWrite.read
  have headerNat := nursery.headerWrite.read.toNat
  have youngAddress : BitVec.ofNat 64 domain + sign_extend (m := 64) (0x008#12) =
      BitVec.ofNat 64 (domain + Layout.off_young_ptr) := by rw [BitVec.ofNat_add]; rfl
  have valueAddress : BitVec.ofNat 64 (a - 8) + sign_extend (m := 64) (0x008#12) = BitVec.ofNat 64 a := by
    change BitVec.ofNat 64 (a - 8) + BitVec.ofNat 64 8 = _
    rw [← BitVec.ofNat_add]; congr 1; have room := nursery.room; omega
  have headerValue : Sail.shift_bits_left (BitVec.ofNat 64 (count + 2)) (Sail.BitVec.extractLsb (0x0a#6) 5 0) +
      sign_extend (m := 64) (0x0f7#12) = blockHeader (count + 2) OCaml.Bytecode.closureTag := rfl
  have sizeWord := addiw_nat_add count 2 (offset := 0x002#12) (by decide) (by omega)
  have guard : zopz0zKzJ_s (0#64) (BitVec.ofNat 64 count) = {'false' if more else 'true'} := {guard}
  obtain ⟨headerMemory, headerWritten⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 d.σ.mem (a - 8) (sdData_val (blockHeader (count + 2) OCaml.Bytecode.closureTag)) := ⟨_, rfl⟩
  have headerLog : headerMemory = writeLog c.σ.mem (closureSetupLog sp count a domain accu) := by
    rw [headerWritten, front.memory, closureSetupLog]
    simp only [writeLog_append]; rfl
  have tailLog : headerMemory = writeLog (writeLog c.σ.mem (closurePushLog sp count accu))
      (grabReserveLog domain a ++ closureHeaderLog a count) := by
    rw [headerLog, closureSetupLog, writeLog_append]
  have domainValue := (word_read_writeLog_out space.domainOutside headerLog).trans nursery.domainValue
  have youngWord : bytesT headerMemory (domain + Layout.off_young_ptr) 8 = BitVec.ofNat 64 (a - 8) := by
    rw [tailLog]
    exact word_writeLog_at _ _ 0 _ _ rfl space.youngOutside
  have youngValue : sign_extend (m := 64) (bytesT8 headerMemory (domain + Layout.off_young_ptr)) =
      BitVec.ofNat 64 (a - 8) := by
    simpa only [bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq] using youngWord
  have bp : SegSt (0x80002a10#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.CamlClosureInit{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨front.good, front.pcAt, ⟨{pinproof}, trivial⟩,
      front.good.minstret, front.tick, closure_init_{kind}_loaded front.image, rfl, rfl⟩
  have run := tr_closure_init_{kind} {args} d.σ.mem d.σ
  simp only [closure_init_{kind}_domain, show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, headerNat, domainRead.toNat, headerValue] at run
  have first := run nursery.headerWrite.lower nursery.headerWrite.upper nursery.headerWrite.htif nursery.headerWrite.aligned
    (image_entry_code space.headerImage (by exact List.mem_cons_self) (by decide) (by decide)) headerMemory headerWritten
    domainRead.lower domainRead.upper domainRead.htif (BitVec.ofNat 64 domain) domainValue.symm
  simp only [youngAddress, youngRead.toNat] at first
  have second := first youngRead.lower youngRead.upper youngRead.htif (BitVec.ofNat 64 (a - 8)) youngValue.symm
  simp only [valueAddress{', sizeWord' if more else ''}] at second
{'  simp only [show sign_extend (m := 64) (0x002#12) = 2#64 from by decide, BitVec.zero_add] at second' if more else ''}
  obtain ⟨nb, after, _, steps, post⟩ := second guard d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := closureInitWrites) (by decide)
  have initialized : after.σ.mem = writeLog d.σ.mem (closureHeaderLog a count) := by
    rw [memory, headerWritten]; rfl
  refine ⟨nb, after, steps, post.good, post.tick, image_of_writeLog front.image space.headerImage initialized,
    ?_, front.fields.frame frame (by decide), {get('x21')}, {get('x10')}, {get('x16')}, ?_, memory.trans headerLog,
    (front.frame.trans frame).widenChecked (allowed := closureSetupWrites) (by decide)⟩
  · simp only [{'branch, ite_true' if more else 'branch, Nat.lt_irrefl, ite_false'}]; exact post.pcAt
{copy}

end OCaml.Vm.Sim
'''

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for kind in ['more','zero']:
        p=ROOT/f'OCaml/Vm/Sim/ClosureInitialize{kind.title()}.lean';out=render(kind)
        if args.check:
            if not p.exists() or p.read_text()!=out:raise SystemExit(f'drift: {p}')
        else:p.write_text(out)
    print('CLOSURE initializer adapters current')
