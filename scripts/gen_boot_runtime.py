#!/usr/bin/env python3
"""Generate concrete runtime reads from the checked while_min store log."""
import argparse
import gzip
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check', action='store_true')
args = ap.parse_args()
layout = {k: int(v, 0) for k, v in re.findall(
    r'^def (\w+) : Nat := (\w+)$', (ROOT/'OCaml/Vm/Layout.lean').read_text(), re.M)}
cut = json.loads((ROOT/'results/boot/while_min-cut.json').read_text())
memory = {}
for _, a, width, value in map(json.loads, gzip.open(ROOT/'results/boot/while_min-stores.jsonl.gz')):
    for i in range(width):
        memory[a+i] = (value >> (8*i)) & 255

def read(a, width=8):
    return sum(memory[a+i] << (8*i) for i in range(width))

domain = read(layout['sym_Caml_state'])
assert domain == cut['domain']
block = read(layout['sym_bf_large_tree'])
words = read(block-layout['header_bytes']) // 1024
out = ['import OCaml.Vm.Boot.WhileMinLogChecks', 'import OCaml.Vm.Boot.FreeList',
       'import OCaml.Vm.Boot.WhileMinObservation', 'import Vsa.Sim.Boot.Bytes', '',
       '/-! GENERATED by scripts/gen_boot_runtime.py. Reads of the observed memory candidate.\nNo execution or reachability claim. -/',
       'namespace OCaml.Vm.Boot.WhileMinRuntime',
       'open Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog', '',
       f'def domain : Nat := {domain:#x}',
       f'def freeBlock : FreeBlock := ⟨{block:#x}, {words}⟩', '',
       'variable {c : Config} {initial : Vsa.MemRepr.Mem}', '']

def fact(name, expr, addr, width=8):
    val=read(addr,width)
    op='word' if width==8 else 'word32'
    out.extend([f'theorem read_{name} (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        f'    {op} c ({expr}) = {val:#x}#{width*8} := by',
        f'  unfold {op}',
        f'  rw [bytesT_memEqv memory, observedMem_bytes_stored logOk (a := {expr}) (w := {width}) (by decide +kernel)]',
        '  decide +kernel', ''])
    return f'read_{name} memory'

fact('domain', 'Layout.sym_Caml_state',layout['sym_Caml_state'])
fields=['young_start','young_end','young_alloc_start','young_alloc_end','young_ptr','young_limit']
for f in fields:
    fact(f, f'domain + Layout.off_{f}',domain+layout['off_'+f])
fact('pending','Layout.sym_caml_something_to_do',layout['sym_caml_something_to_do'],4)
for key, width in [('bf_small_map',4),('bf_large_tree',8),('bf_large_least',8),('caml_fl_cur_wsz',8)]:
    fact(key,f'Layout.sym_{key}',layout['sym_'+key],width)
fact('header','freeBlock.block - Layout.header_bytes',block-layout['header_bytes'])
for f in ['isnode','left','right','prev','next']:
    fact(f,f'freeBlock.block + Layout.off_bf_{f}',block+layout['off_bf_'+f],4 if f=='isnode' else 8)
for i in range(1,layout['bf_small_count']+1):
    for f in ['free','merge']:
        fact(f'small_{i}_{f}', f'smallSlot {i} + Layout.off_bf_small_{f}',
             layout['sym_bf_small_fl']+i*layout['bf_small_size']+layout['off_bf_small_'+f])
out += ['theorem small_lists (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        '    ∀ i, 1 ≤ i → i ≤ Layout.bf_small_count → EmptySmall c i := by',
        '  have all : ∀ i : Fin Layout.bf_small_count, EmptySmall c (i.val + 1) :=']
term='fun i => Fin.elim0 i'
for i in range(layout['bf_small_count'],0,-1):
    term=f'Fin.cases ⟨read_small_{i}_free memory, congrArg BitVec.toNat (read_small_{i}_merge memory)⟩ ({term})'
out += ['    '+term, '  intro i low high',
        '  have hi : i - 1 < Layout.bf_small_count := by omega',
        '  simpa only [Nat.sub_add_cancel low] using all ⟨i - 1, hi⟩', '']
out += ['end OCaml.Vm.Boot.WhileMinRuntime','']
path=ROOT/'OCaml/Vm/Boot/WhileMinRuntimeReads.lean'
text='\n'.join(out)
if args.check:
    if not path.exists() or path.read_text()!=text:raise SystemExit('boot runtime read drift')
elif not path.exists() or path.read_text()!=text:
    path.write_text(text)
print(f'Runtime reads: domain {domain:#x}, free block {block:#x} ({words} payload words)')
