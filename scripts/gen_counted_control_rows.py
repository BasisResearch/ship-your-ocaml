#!/usr/bin/env python3
"""Generate ordinary counted memory/control rows and their exact F1 census."""
import argparse
from census import ROOT
from gen_opcodes import opcodes
from gen_f1_table import NON_F1
from gen_counted_stack_rows import ROWS as STACK_ROWS, channel_certificate
from gen_counted_alloc_rows import ROWS as ALLOC_ROWS
from gen_counted_field_rows import BARRIERS

MEMORY = [(op, 'stable') for op in [
    'CONST0', 'CONST1', 'CONST2', 'CONST3', 'CONSTINT', 'ATOM0', 'ATOM',
    'NEGINT', 'BOOLNOT', 'ISINT', 'OFFSETINT',
    'BRANCH', 'BRANCHIF', 'BRANCHIFNOT', 'SWITCH',
    'BEQ', 'BNEQ', 'BLTINT', 'BLEINT', 'BGTINT', 'BGEINT', 'BULTINT', 'BUGEINT']]
MEMORY += [(op, 'budget') for op in [
    'ADDINT', 'SUBINT', 'MULINT', 'ANDINT', 'ORINT', 'XORINT',
    'LSLINT', 'LSRINT', 'ASRINT', 'EQ', 'NEQ',
    'LTINT', 'LEINT', 'GTINT', 'GEINT', 'ULTINT', 'UGEINT', 'RETURN']]
CONTROL = {
    'APPLY': 'apply_row stable rf fits g1_capacity',
    **{f'APPLY{i}': f'apply{i}_row rf fits g1_capacity' for i in range(1, 4)},
    'APPTERM': 'appterm_row rf fits g1_capacity',
    **{f'APPTERM{i}': f'appterm{i}_row rf fits g1_capacity' for i in range(1, 4)},
    'RESTART': 'restart_row rf fits g1_capacity',
    'CHECK_SIGNALS': 'check_signals_row stable rf',
    **{op: f'{op.lower()}_row stable rf fits g1_capacity good'
       for op in ['RAISE', 'RERAISE', 'RAISE_NOTRACE']},
}
DIVISION = ['DIVINT', 'MODINT']
WRONG_ARITY = {'C_CALL3': 2, 'C_CALL5': 4}
CONSOLE = ['C_CALL4']
REMAINING = ['C_CALL1', 'C_CALL2']
OPERATIONS = {}
for operation, ops in {
    'enter': ['APPLY', 'APPLY1', 'APPLY2', 'APPLY3', 'APPTERM', 'APPTERM1', 'APPTERM2', 'APPTERM3', 'RETURN'],
    'raiseTo': ['RAISE', 'RERAISE', 'RAISE_NOTRACE', 'DIVINT', 'MODINT'],
    'intOp': ['ADDINT', 'SUBINT', 'MULINT', 'ANDINT', 'ORINT', 'XORINT', 'LSLINT', 'LSRINT', 'ASRINT'],
    'cmpOp': ['LTINT', 'LEINT', 'GTINT', 'GEINT', 'ULTINT', 'UGEINT'],
    'brOp': ['BEQ', 'BNEQ', 'BLTINT', 'BLEINT', 'BGTINT', 'BGEINT', 'BULTINT', 'BUGEINT'],
}.items():
    OPERATIONS.update({op: f'counted_{operation}_channels' for op in ops})


def certificate(op):
    options = op in ['BRANCH', 'BRANCHIF', 'BRANCHIFNOT', 'SWITCH', 'EQ', 'NEQ',
                     'BEQ', 'BNEQ', 'DIVINT', 'MODINT']
    # SWITCH is variable: cases args exposes its packed size word and keeps
    # the entire table tail; no fixed-arity restriction is imposed on it.
    return channel_certificate(op, 'stepI, opt' if options else 'stepI', operation=OPERATIONS.get(op))


def header(imports, description):
    return '\n'.join(f'import OCaml.Vm.Sim.{name}' for name in imports) + f'''

/-! GENERATED by scripts/gen_counted_control_rows.py. {description}
Native execution and all use-site guards come from existing checked rows. -/

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine OCaml.Vm.Primitives
'''


def memory_output():
    out = header(['CountedRuntime', 'A2TableRows', 'SwitchRows', 'G1Capacity'],
                 'Ordinary counted memory rows.')
    out += '\n/-- Exactly the generated memory-row families. -/\ndef countedMemoryOpcode : Opcode → Bool\n'
    out += ''.join(f'  | .{op} => true\n' for op, _ in MEMORY) + '  | _ => false\n'
    for op, _ in MEMORY:
        out += certificate(op)
    for op, mode in MEMORY:
        extra = '\n    (fits : OCaml.Fits Gc.f1Layout.budget P)' if mode == 'budget' else ''
        call = f'{op.lower()}_row stable' + (' fits g1_capacity' if mode == 'budget' else '')
        out += f'''
/-- Counted {op}, preserving the ordinary row's guards and reachable bounds. -/
theorem counted_{op.lower()}_row {{L : OCaml.Layout}} {{P : Prog}}
    {{Customs : Config → Nat → Prop}} {{Ready : Nat → Config → Prop}} {{state : Config → Nat → Prop}}
    (stable : MemoryStable L.runtimeOk) (accounting : Gc.CustomAccounting Ready state Customs){extra} :
    OCaml.OpArm P (CountedLoopAt Customs L P) .{op} :=
  counted_memory_row stable accounting (fun _ stable => {call})
    (fun _ i _ opcode effect => counted_{op.lower()}_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    return out + '\nend OCaml.Vm.Sim\n'


def control_output():
    out = header(['CountedMemoryRows', 'CountedStackRows', 'CountedAllocRows',
                  'CountedFieldRows', 'ControlRows', 'SignalRows', 'RaiseRows', 'StopRow', 'CcallShort', 'CountedConsoleRows'],
                 'Counted control rows and exact remaining F1 opcode census.')
    out += '\n/-- Exactly the ordinary control rows generated here. -/\ndef countedControlOpcode : Opcode → Bool\n'
    out += ''.join(f'  | .{op} => true\n' for op in [*CONTROL, *DIVISION, 'STOP', *WRONG_ARITY, *CONSOLE]) + '  | _ => false\n'
    for op in [*CONTROL, *DIVISION, 'STOP']:
        out += certificate(op)
    for op, row in CONTROL.items():
        fits = ' (fits : OCaml.Fits Gc.f1Layout.budget P)' if 'fits' in row else ''
        good = ' (good : OCaml.GoodF1 P)' if 'good' in row else ''
        out += f'''
/-- Counted {op} through the actual shared runtime frame. -/
theorem counted_{op.lower()}_row {{P : Prog}}
    {{Ready : Nat → Config → Prop}} {{state Customs : Config → Nat → Prop}}
    (custom : Gc.CustomMemCall Ready state Customs){fits}{good} :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  counted_stack_row custom (fun _ rf stable => {row})
    (fun _ i _ opcode effect => counted_{op.lower()}_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    for op in DIVISION:
        out += f'''
/-- Counted {op}, including the caught zero-divisor native raise path. -/
theorem counted_{op.lower()}_row {{P : Prog}}
    {{Ready : Nat → Config → Prop}} {{state Customs : Config → Nat → Prop}}
    (custom : Gc.CustomMemCall Ready state Customs)
    (fits : OCaml.Fits Gc.f1Layout.budget P) (good : OCaml.GoodF1 P) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  counted_row (fun _ _ => {op.lower()}_row (counted_memoryStable f1_memoryStable custom.accounting)
    (counted_runtimeFrame custom) fits g1_capacity (counted_raiseRuntimeFrame custom) good)
    (fun _ i _ opcode effect => counted_{op.lower()}_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    for op, k in WRONG_ARITY.items():
        out += f'''
/-- Complete counted {op}: the actual F1 primitive model rejects this
arity in every outcome, including exit. GoodF1 therefore cannot reach it;
the row needs no native return, exit or custom-allocation premise. -/
theorem counted_{op.lower()}_row {{P : Prog}} {{Customs : Config → Nat → Prop}} :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  ccall_wrong_arity_row (k := {k}) (by decide) (by decide) (by decide)
    (fun s args => by
      rcases args with _ | ⟨p, _ | ⟨q, rest⟩⟩ <;> rfl)
    (fun _ => rfl)
'''
    out += '''
/-- STOP retains the entry's actual exit globals and HTIF idleness. A halt
has no successor count obligation in counted_row. -/
theorem counted_stop_row {P : Prog} {Customs : Config → Nat → Prop}
    (good : OCaml.GoodF1 P) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .STOP :=
  counted_row (fun _ _ => stop_row good
    (fun _ _ _ h => Gc.f1_exitGlobals h.running.platform.runtime.1)
    (fun _ _ _ h => h.running.loop.htifIdle))
    (fun _ i _ opcode effect => counted_stop_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))

/-- The union records supported OpArm families, relative to their named
suppliers. It does not assert full F1 table closure. -/
def countedOrdinaryOpcode (op : Opcode) : Bool :=
  countedStackOpcode op || countedMemoryOpcode op || countedControlOpcode op || countedAllocOpcode op || op == .OFFSETREF || decide (op ∈ countedBarrierOpcodes)
'''
    # Tie the census to actual OpArm terms, with exactly the existing suppliers.
    calls = {op: f'counted_{op.lower()}_row custom' + (' fits' if mode != 'stable' else '')
             for op, mode in STACK_ROWS}
    calls.update({op: f'counted_{op.lower()}_row custom fits' + (' good' if 'good' in row else '')
                  for op, row in ALLOC_ROWS.items()})
    calls.update({op: f'counted_{op.lower()}_row f1_memoryStable custom.accounting' +
                  (' fits' if mode == 'budget' else '') for op, mode in MEMORY})
    calls.update({op: f'counted_{op.lower()}_row custom' + (' fits' if 'fits' in row else '') +
                  (' good' if 'good' in row else '') for op, row in CONTROL.items()})
    calls.update({op: f'counted_{op.lower()}_row custom fits good' for op in DIVISION})
    calls.update({op: f'counted_{op.lower()}_row' for op in WRONG_ARITY})
    calls['C_CALL4'] = 'counted_c_call4_row custom fits good'
    calls['STOP'] = 'counted_stop_row good'
    calls['OFFSETREF'] = 'counted_offsetref_row custom fits'
    calls.update({op: f'counted_{op.lower()}_row custom fits full' for op in BARRIERS})
    out += '''
/-- Every opcode counted by the census has its actual complete row. This
partial table retains the named custom supplier, counted G2 full growth and
real GoodF1/Fits guards. The six write rows have actual spatial suppliers. -/
theorem counted_supported_row {P : Prog} {op : Opcode}
    {Ready : Nat → Config → Prop} {state Customs : Config → Nat → Prop}
    (custom : Gc.CustomMemCall Ready state Customs)
    (fits : OCaml.Fits Gc.f1Layout.budget P) (good : OCaml.GoodF1 P)
    (full : ∀ cp world, BarrierGrowthFull (countedLayout Gc.f1Layout Customs cp world))
    (supported : countedOrdinaryOpcode op = true) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) op := by
  cases op with
'''
    out += ''.join(f'  | {op} => ' + (f'exact {calls[op]}' if op in calls else 'cases supported') + '\n'
                   for op in opcodes())
    out += '''
/-- C_CALL1/2 still need complete success/effect suppliers. The unary
row includes caml_sys_exit; the binary row includes formatting/registration.
Supported barriers retain counted G2 full growth. -/
def countedRemainingOpcodes : List Opcode :=
'''
    out += '  [' + ', '.join('.' + op for op in REMAINING) + ']\n'
    out += '''
/-- Exact complement against the authoritative F1 opcode classification. -/
theorem counted_opcode_census (op : Opcode) :
    op.fragment = .F1 ↔ countedOrdinaryOpcode op = true ∨ op ∈ countedRemainingOpcodes := by
  cases op <;> decide

/-- Number of supported complete counted ordinary opcode rows. -/
theorem counted_opcode_count : (Opcode.all.filter countedOrdinaryOpcode).length = 132 := by decide +kernel

/-- The remaining list has exactly two distinct opcode obligations. -/
theorem counted_remaining_count : countedRemainingOpcodes.length = 2 ∧ countedRemainingOpcodes.Nodup := by decide

end OCaml.Vm.Sim
'''
    return out


def outputs():
    supported = [op for op, _ in STACK_ROWS] + list(ALLOC_ROWS) + [op for op, _ in MEMORY] + list(CONTROL) + DIVISION + ['STOP', 'OFFSETREF'] + BARRIERS + list(WRONG_ARITY) + CONSOLE
    assert len(supported) == len(set(supported)) == 132
    assert set(supported).isdisjoint(REMAINING)
    assert set(supported) | set(REMAINING) == set(opcodes()) - set(NON_F1)
    return {ROOT / 'OCaml/Vm/Sim/CountedMemoryRows.lean': memory_output(),
            ROOT / 'OCaml/Vm/Sim/CountedControlRows.lean': control_output(),
            ROOT / 'OCaml/Vm/Sim/CountedArityAudit.lean': arity_audits()}


def arity_audits():
    names = ['OCaml.Bytecode.primF1Impl_wrong_arity', 'OCaml.Bytecode.primF1Impl_arity',
             'OCaml.Bytecode.primF1Impl_exit',
             'OCaml.Vm.Sim.PrimReturnsAtD.of_arity',
             'OCaml.Vm.Sim.ccall_wrong_arity_step', 'OCaml.Vm.Sim.ccall_wrong_arity_row']
    names += [f'OCaml.Vm.Sim.counted_{op.lower()}_row' for op in WRONG_ARITY]
    names += ['OCaml.Vm.Sim.' + name for name in [
        'counted_supported_row', 'counted_opcode_census', 'counted_opcode_count', 'counted_remaining_count']]
    return '''import OCaml.Vm.Sim.CountedControlRows

/-! GENERATED by scripts/gen_counted_control_rows.py. Focused F1 arity audit.
Full OCaml.Audit remains the lead gate. -/
''' + ''.join(f'#print axioms {name}\n' for name in names)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for target, content in outputs().items():
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'counted control row drift: {target.relative_to(ROOT)}')
        else:
            target.write_text(content)
    print('Counted ordinary rows current (132/134 F1 opcodes relative to counted G2 full growth; 2 remaining)')
