#!/usr/bin/env python3
"""Compose native CLOSUREREC infix iterations with grouped write logs."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def render(kind):
    more=kind=='more';stem=kind.title()
    spec=json.loads((ROOT/f'scripts/syi/segments/closurerec_infix_{kind}.json').read_text())
    regs=[p['reg'] for p in spec['pins']]
    vals={'x13':'(BitVec.ofNat 64 (3 * (i + 1)))','x15':'(BitVec.ofNat 64 (a + 24 * (i + 1)))','x11':'(BitVec.ofNat 64 (stackStart - 8 * i))','x8':'(BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 4 + i)))','x12':'(infixArityWord (targets.length + 1) (i + 1))','x16':'(BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 3)))','x10':'(BitVec.ofNat 64 (3 * (targets.length + 1)))'}
    proofs={'x13':'h.regs.counter','x15':'h.regs.targetReg','x11':'h.regs.stackReg','x8':'h.regs.codeReg','x12':'h.regs.arity','x16':'h.regs.codeBase','x10':'h.regs.limit'}
    pins=', '.join(f'⟨Register.{r}, {vals[r]}⟩' for r in regs);args=' '.join(vals[r] for r in regs);holds=', '.join(proofs[r] for r in regs)
    for st in spec['steps']:
        r=st.get('rd')
        if r:regs=[r]+[x for x in regs if x!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    guard='infix_more_guard targets.length i branch region.small' if more else 'by rw [← branch]; simp only [Nat.add_assoc, bne_self_eq_false]'
    return f'''-- GENERATED by scripts/gen_closurerec_infix.py; do not edit.
import OCaml.Vm.Sim.ClosurerecInfixArithmetic
import OCaml.Vm.Sim.ClosurerecInfix{stem}Segment
import OCaml.Vm.Sim.ClosurerecInfix{stem}Pins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- One actual {'continuing' if more else 'final'} infix iteration installs its four metadata/stack words. -/
theorem infix_{kind} {{pl : Place}} {{pc a stackStart i : Nat}} {{targets : List Nat}}
    {{offsets : Nat → BitVec 32}} {{initial c : Config}}
    (region : InfixRegion pl pc a stackStart targets offsets initial)
    (h : InfixAt pl pc a stackStart targets initial i c) (bound : i < targets.length)
    (branch : {'i + 1 < targets.length' if more else 'i + 1 = targets.length'}) :
    ∃ nb after, StepsN nb c after ∧ InfixAt pl pc a stackStart targets initial (i + 1) after := by
  have writes := region.writes i bound
  have read := region.reads i bound
  have gb : i < (infixGroups pl a stackStart targets).length := by rw [infix_groups_length]; exact bound
  have headerAddress := push_address (show 8 ≤ a + 24 * (i + 1) by omega)
  have stackAddress := infix_stack_step stackStart i (by have room := region.room; omega)
  have arityAddress : BitVec.ofNat 64 (a + 24 * (i + 1)) + sign_extend (m := 64) (0x008#12) =
      BitVec.ofNat 64 (a + 24 * (i + 1) + 8) := by
    rw [show sign_extend (m := 64) (0x008#12) = BitVec.ofNat 64 8 from by decide, ← BitVec.ofNat_add]
  have headerValue : Sail.shift_bits_left (BitVec.ofNat 64 (3 * (i + 1))) (Sail.BitVec.extractLsb (0x0a#6) 5 0) +
      sign_extend (m := 64) (0x0f9#12) = blockHeader (3 * (i + 1)) infixTag := rfl
  have counterStep := addiw_nat_add (3 * (i + 1)) 3 (offset := 0x003#12) (by decide) (by have small := region.small; omega)
  have nextCounter : 3 * (i + 1) + 3 = 3 * ((i + 1) + 1) := by omega
  rw [nextCounter] at counterStep
  have codeStep : BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 4 + i)) + sign_extend (m := 64) (0x004#12) =
      BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 4 + (i + 1))) := by
    change BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 4 + i)) + 4#64 = _
    rw [codePc_succ, Nat.add_assoc (pc + 4) i 1]
  have destination : BitVec.ofNat 64 (pl.codeBase + 4 * (pc + 3)) +
      Sail.shift_bits_left (sign_extend (m := 64) (offsets i)) (Sail.BitVec.extractLsb (0x02#6) 5 0) =
      BitVec.ofNat 64 (pl.codeBase + 4 * targets[i]) := relative_code_word pl (region.jump i bound)
  have guard : (BitVec.ofNat 64 (3 * (targets.length + 1)) != BitVec.ofNat 64 (3 * (i + 2))) = {'true' if more else 'false'} := {guard}
  obtain ⟨m1, written1⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 c.σ.mem (a + 24 * (i + 1) - 8) (sdData_val (blockHeader (3 * (i + 1)) infixTag)) := ⟨_, rfl⟩
  obtain ⟨m2, written2⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 m1 (stackStart - 8 * (i + 1)) (sdData_val (BitVec.ofNat 64 (a + 24 * (i + 1)))) := ⟨_, rfl⟩
  obtain ⟨m3, written3⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 m2 (a + 24 * (i + 1) + 8) (sdData_val (infixArityWord (targets.length + 1) (i + 1))) := ⟨_, rfl⟩
  obtain ⟨m4, written4⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 m3 (a + 24 * (i + 1)) (sdData_val (BitVec.ofNat 64 (pl.codeBase + 4 * targets[i]))) := ⟨_, rfl⟩
  have prefixMemory : m2 = writeLog c.σ.mem ((infixStores pl a stackStart (targets.length + 1) (i + 1) targets[i]).take 2) := by
    rw [written2, written1]; rfl
  have offsetRead := h.read_after region bound prefixMemory
  have fullMemory : m4 = writeLog c.σ.mem (infixStores pl a stackStart (targets.length + 1) (i + 1) targets[i]) := by
    rw [written4, written3, written2, written1]; rfl
  have code (address : Nat) (value : BitVec 64)
      (member : (address, 8, value) ∈ infixStores pl a stackStart (targets.length + 1) (i + 1) targets[i]) :
      address + 8 ≤ 0x8000296c ∨ 0x800029a8 ≤ address := by
    have inLog : (address, 8, value) ∈ (infixGroups pl a stackStart targets).flatten := by
      apply grouped_log_member gb
      rw [infix_group_at pl a stackStart targets i bound]
      exact member
    exact image_entry_code region.image inLog (by decide) (by decide)
  have bp : SegSt ({spec['entry']}#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.CamlClosurerecInfix{stem}Loaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, by change pcOf c = some ({spec['entry']}#64); simpa only [bound, ite_true] using h.pcAt, ⟨{holds}, trivial⟩,
      h.good.minstret, h.tick, closurerec_infix_{kind}_loaded h.image, rfl, rfl⟩
  have run := tr_closurerec_infix_{kind} {args} c.σ.mem c.σ
  simp only [headerAddress, stackAddress, arityAddress, headerValue,
    show sign_extend (m := 64) (0x000#12) = 0#64 from by decide, BitVec.add_zero,
    read.toNat, writes.header.read.toNat, writes.stack.read.toNat, writes.arity.read.toNat, writes.code.read.toNat,
    counterStep, codeStep, infix_target_step, infix_arity_step] at run
  have first := run writes.header.lower writes.header.upper writes.header.htif writes.header.aligned
    (code _ (blockHeader (3 * (i + 1)) infixTag) (by simp [infixStores])) m1 written1
    writes.stack.lower writes.stack.upper writes.stack.htif writes.stack.aligned
    (code _ (BitVec.ofNat 64 (a + 24 * (i + 1))) (by simp [infixStores])) m2 written2
    read.lower read.upper read.htif (sign_extend (m := 64) (offsets i)) (by rw [offsetRead])
  simp only [destination] at first
  obtain ⟨nb, after, _, steps, post⟩ := first writes.arity.lower writes.arity.upper writes.arity.htif writes.arity.aligned
    (code _ (infixArityWord (targets.length + 1) (i + 1)) (by simp [infixStores])) m3 written3
    writes.code.lower writes.code.upper writes.code.htif writes.code.aligned
    (code _ (BitVec.ofNat 64 (pl.codeBase + 4 * targets[i])) (by simp [infixStores])) m4 written4 guard c bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have observed : InfixPost pl pc a stackStart targets i c after := by
    refine ⟨post.good, post.tick, ?_, ⟨{get('x13')}, {get('x15')}, {get('x11')}, {get('x8')}, {get('x12')}, {get('x16')}, {get('x10')}⟩, ?_,
      rawFrame.widenChecked (allowed := infixWrites) (by decide)⟩
    · simp only [{'branch, ite_true' if more else 'branch, Nat.lt_irrefl, ite_false'}]; exact post.pcAt
    · simpa only [List.getElem?_eq_getElem bound, Option.getD_some] using memory.trans fullMemory
  exact ⟨nb, after, steps, h.advance region bound observed⟩

end OCaml.Vm.Sim
'''

RUN='''-- GENERATED by scripts/gen_closurerec_infix.py; do not edit.
import OCaml.Vm.Sim.ClosurerecInfixMore
import OCaml.Vm.Sim.ClosurerecInfixLast

namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim

/-- The actual arbitrary-count native loop installs every remaining infix function. -/
theorem infix_run {pl : Place} {pc a stackStart : Nat} {targets : List Nat}
    {offsets : Nat → BitVec 32} {initial : Config}
    (region : InfixRegion pl pc a stackStart targets offsets initial) :
    Vsa.Logic.Triple (InfixAt pl pc a stackStart targets initial 0)
      (InfixAt pl pc a stackStart targets initial targets.length) :=
  infix_run_of_branches region
    (fun _ _ h bound more => infix_more region h bound more)
    (fun _ _ h bound last => infix_last region h bound last)

end OCaml.Vm.Sim
'''
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    outputs={ROOT/f'OCaml/Vm/Sim/ClosurerecInfix{kind.title()}.lean':render(kind) for kind in ['more','last']}
    outputs[ROOT/'OCaml/Vm/Sim/ClosurerecInfix.lean']=RUN
    for p,out in outputs.items():
        if args.check:
            if not p.exists() or p.read_text()!=out:raise SystemExit(f'drift: {p}')
        else:p.write_text(out)
    print('Recursive closure infix-loop adapters current')
