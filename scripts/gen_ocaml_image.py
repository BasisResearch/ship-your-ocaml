#!/usr/bin/env python3
"""Emit compact .text/.rodata pins for the repository's approved OCaml ELF.

Uses the packed-page representation of Vsa/Sim/Code/FixedImageData.lean,
with a balanced lookup tree so one byte does not reduce the whole image.
No execution claim is generated. check_all compares the output byte-for-byte.
"""
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parent.parent
PAGE = 256


def sections(data):
    if data[:6] != b'\x7fELF\x02\x01':
        raise ValueError('expected ELF64 little endian')
    offset = struct.unpack_from('<Q', data, 40)[0]
    stride, count, strings = struct.unpack_from('<HHH', data, 58)
    rows = [struct.unpack_from('<IIQQQQIIQQ', data, offset + stride * i)
            for i in range(count)]
    names = data[rows[strings][4]:rows[strings][4] + rows[strings][5]]
    return {names[r[0]:].split(b'\0')[0].decode():
            (r[3], data[r[4]:r[4] + r[5]]) for r in rows if r[1] == 1}


def tree(name, lo, hi):
    if hi - lo == 1:
        return f'{name}Page{lo}'
    mid = (lo + hi) // 2
    return f'(if page < {mid} then {tree(name, lo, mid)} else {tree(name, mid, hi)})'


def main():
    data = (ROOT / 'c/ocamlrun-riscv-htif.elf').read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    expected = (ROOT / 'c/ELF.sha256').read_text().split()[0]
    if sha != expected:
        raise ValueError('ELF does not match c/ELF.sha256')
    print('import Vsa.Machine\n\n/-! GENERATED by `scripts/gen_ocaml_image.py`. Do not edit.\n'
          f'OCaml ELF SHA256: {sha}. Packed literals only. -/\n\nnamespace OCaml.Vm.Image\n')
    for section, name in [('.text', 'text'), ('.rodata', 'rodata')]:
        base, raw = sections(data)[section]
        count = (len(raw) + PAGE - 1) // PAGE
        for i in range(count):
            value = int.from_bytes(raw[i * PAGE:(i + 1) * PAGE], 'little')
            print(f'private def {name}Page{i} : Nat := 0x{value:x}')
        print(f'\nprivate def {name}Page (page : Nat) : Nat :=\n'
              f'  if page < {count} then {tree(name, 0, count)} else 0\n')
        print(f'def {name}Base : Nat := 0x{base:x}\n'
              f'def {name}Size : Nat := {len(raw)}\n'
              f'def {name}Byte (offset : Nat) : BitVec 8 :=\n'
              f'  BitVec.ofNat 8 ({name}Page (offset / {PAGE}) / 2 ^ (8 * (offset % {PAGE})))\n')
    print('end OCaml.Vm.Image')


if __name__ == '__main__':
    main()
