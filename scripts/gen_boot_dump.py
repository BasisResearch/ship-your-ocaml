#!/usr/bin/env python3
"""Emit a native observation utility for every Sail register at a cut.

The utility uses Vsa.setupElf and Vsa.stepOnce without modifying the model.
Its output is a candidate literal register table, not an execution proof.
"""
import argparse
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check',action='store_true')
args=ap.parse_args()
defs=(ROOT/'riscv-lean/Lean_RV64D_executable/LeanRV64DExecutable/Defs.lean').read_text()
part=defs.split('inductive Register : Type where')[1].split('  deriving')[0]
registers=re.findall(r'^  \| (\w+)\s*$',part,re.M)
assert registers
out=['import Vsa.Machine','',
     '/-! GENERATED by scripts/gen_boot_dump.py. Native observation only. -/',
     'open Vsa.Machine LeanRV64DExecutable Sail ConcurrencyInterfaceV1','',
     'def dumpRegister (σ : MState) (r : Register) : String :=', '  match r with']
for r in registers:
    out += [f'  | .{r} => match σ.regs.get? .{r} with',
            '    | none => ""',
            f'    | some v => "⟨Register.{r}, " ++ reprStr v ++ "⟩,"']
out += ['', 'def allRegisters : List Register := ['+', '.join('.'+r for r in registers)+']','',
'''def main (args : List String) : IO Unit := do
  let (path, countStr, checkPath) ← match args with
    | [path, count] => pure (path, count, none)
    | [path, count, check] => pure (path, count, some check)
    | _ => throw (IO.userError "usage: bootdump ELF STEPS [EXPECTED-MEMORY]")
  let some count := countStr.toNat? | throw (IO.userError "invalid step count")
  let .ok (.elf64 elf) ← readElf path | throw (IO.userError "expected ELF64")
  let initial : MState := ⟨{}, (), initializeMemory .B64 elf, (), 0, #[]⟩
  let .ok _ σ := (Vsa.setupElf elf).run initial | throw (IO.userError "setup failed")
  let mut c : Config := ⟨σ, 0, 0⟩
  for _ in [:count] do
    match (Vsa.stepOnce c.tick c.steps).run c.σ with
    | .ok (.inr (tick, steps)) σ' => c := ⟨σ', tick, steps⟩
    | _ => throw (IO.userError s!"stopped before cut at {c.steps}")
  if let some check := checkPath then
    let bytes ← IO.FS.readBinFile check
    unless bytes.size % 9 == 0 do throw (IO.userError "invalid memory input")
    let n := bytes.size / 9
    unless c.σ.mem.size == n do throw (IO.userError s!"memory size mismatch: {c.σ.mem.size} != {n}")
    let mut previous : Option Nat := none
    for i in [:n] do
      let mut a := 0
      for j in [:8] do a := a + bytes[i * 9 + j]!.toNat * 2 ^ (8 * j)
      if let some prior := previous then
        unless prior < a do throw (IO.userError "memory input is not strictly ordered")
      previous := some a
      unless c.σ.mem[a]? == some bytes[i * 9 + 8]!.toBitVec do
        throw (IO.userError s!"memory byte mismatch at {a}")
    IO.println s!"-- memory-checked {n} bytes"
  IO.println s!"-- steps {c.steps}, tick {c.tick}, cycles {c.σ.cycleCount}, registers {c.σ.regs.size}, output {reprStr c.σ.sailOutput}"
  for r in allRegisters do
    let row := dumpRegister c.σ r
    unless row.isEmpty do IO.println row
''']
text='\n'.join(out)
p=ROOT/'scripts/boot_dump.lean'
if args.check:
    if not p.exists() or p.read_text()!=text:raise SystemExit('boot dump generator drift')
elif not p.exists() or p.read_text()!=text:p.write_text(text)
print(f'Observation utility: {len(registers)} registers')
