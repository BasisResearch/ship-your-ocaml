#!/usr/bin/env python3
"""Instantiate fixed-arity nursery allocation over shared represented restoration."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render(n):
    spec = json.loads((ROOT / f'scripts/syi/segments/makeblock{n}_fast.json').read_text())
    steps = spec['steps']
    tagload = next(s['addr'][2:] for s in steps if s['asm'].startswith('lw '))
    stores = [s for s in steps if s['class'] == 'sd']
    header = stores[1]['src_val'].replace('loaded_' + tagload, '(sign_extend (m := 64) tag)').replace('shift_bits_right', 'Sail.shift_bits_right').replace('shift_bits_left', 'Sail.shift_bits_left')
    pc = 'BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)'
    log = f'makeblockLog c sp {n} tag.toInt.toNat a domain accu'
    address = lambda base, off: base if off == 0 else f'{base} + {off}'
    words = ['accu'] + [f'word c ({address("sp", 8*i)})' for i in range(n-1)]
    addresses = ['domain + Layout.off_young_ptr', 'a - 8'] + [address('a',8*i) for i in range(n)]
    values = ['BitVec.ofNat 64 (a - 8)', f'blockHeader {n} tag.toInt.toNat'] + words
    entries = [f'({a}, 8, {v})' for a,v in zip(addresses, values)]
    registers = {'x8':f'({pc})', 'x9':'(BitVec.ofNat 64 sp)', 'x21':'accu'}
    proofs = {'x8':'h.pc', 'x9':'h.spReg', 'x21':'(represented_register h.accu value)'}
    lines = [f'''-- GENERATED by scripts/gen_makeblock_fixed.py; do not edit.
import OCaml.Vm.Sim.MakeblockInput
import OCaml.Vm.Sim.Makeblock{n}FastSegment
import OCaml.Vm.Sim.Makeblock{n}FastPins
import OCaml.Vm.Sim.Makeblock{n}FastLayout
import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.StackPush

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- MAKEBLOCK{n} initializes a fresh nursery block through the generated body. -/
theorem makeblock{n}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high a domain limit : Nat}} {{accu : BitVec 64}} {{tag : BitVec 32}}
    (runtime : AllocationRuntime L.runtimeOk c ({log}))
    (h : ArmInput L P s .MAKEBLOCK{n} c pl cp sp high)
    (operand : OperandAt P pl (s.pc + 1) tag) (nonnegative : 0 ≤ tag.toInt)
    (value : valWord pl s.accu = some accu)
    (space : MakeblockInput P s c pl cp sp high {n} tag.toInt.toNat a domain limit accu) :
    ∃ after, Plus c after ∧ Running L P (makeblockState s 2 {n} tag.toInt.toNat) after := by
  have room := space.room
  have logEq : {log} = [{', '.join(entries)}] := by
    simp [makeblockLog, grabReserveLog, blockLog, makeblockWords, valueLog, indexedLog, valueEntries,
      stackWords, List.range_succ]
  have domainRead : RamReadAt Layout.sym_Caml_state 8 := ⟨by decide, by decide, by decide⟩
  have youngRead := space.youngWrite.read
  have limitRead : RamReadAt domain 8 := by simpa only [Layout.off_young_limit, Nat.add_zero] using space.limitRead
  have headerWord : {header} = blockHeader {n} tag.toInt.toNat := by
    rw [makeblock_tag_word tag nonnegative space.tagBound]
    try rw [BitVec.add_assoc]
    exact makeblock_header_word {n} tag.toInt.toNat
  have youngAddress : BitVec.ofNat 64 domain + sign_extend (m := 64) (0x008#12) =
      BitVec.ofNat 64 (domain + Layout.off_young_ptr) := by rw [BitVec.ofNat_add]; rfl
  have reserveAddress : BitVec.ofNat 64 (a + {8*n}) + sign_extend (m := 64) (0x{(-8*(n+1))%4096:03x}#12) =
      BitVec.ofNat 64 (a - 8) := by
    have raw := stack_decrement (sp := a + {8*n}) (n := {8*(n+1)}) (by omega) (by decide)
      (show sign_extend (m := 64) (0x{(-8*(n+1))%4096:03x}#12) = -BitVec.ofNat 64 {8*(n+1)} from by decide)
    simpa only [show a + {8*n} - {8*(n+1)} = a - 8 by omega] using raw
  have nextCode : {pc} + sign_extend (m := 64) (0x008#12) =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 2)) := codePc_add _ _ 2
''']
    simps = [f'makeblock{n}_fast_domain0', f'makeblock{n}_fast_domain1', 'youngAddress',
             'reserveAddress', 'headerWord', 'nextCode', 'codePc_succ',
             'show sign_extend (m := 64) (0x004#12) = 4#64 from by decide',
             'show sign_extend (m := 64) (0x000#12) = 0#64 from by decide', 'BitVec.add_zero',
             'domainRead.toNat', 'youngRead.toNat', 'limitRead.toNat', 'operand.geometry.toNat', 'space.headerWrite.read.toNat']
    for i in range(n):
        lines.append(f'''  have fieldWrite{i} : RamWriteAt ({address('a',8*i)}) 8 := by
    simpa using space.fieldWrites {i} (by decide)
  have fieldAddress{i} : BitVec.ofNat 64 (a - 8) + sign_extend (m := 64) (0x{8*(i+1):03x}#12) =
      BitVec.ofNat 64 ({address('a',8*i)}) := by
    change BitVec.ofNat 64 (a - 8) + BitVec.ofNat 64 {8*(i+1)} = _
    rw [← BitVec.ofNat_add]; congr 1; omega
''')
        simps += [f'fieldAddress{i}', f'fieldWrite{i}.read.toNat']
    if n>1:
        lines.append(f'''  have newSp : BitVec.ofNat 64 sp + sign_extend (m := 64) (0x{8*(n-1):03x}#12) =
      BitVec.ofNat 64 (sp + {8*(n-1)}) := by rw [BitVec.ofNat_add]; rfl
''')
        simps.append('newSp')
    for i in range(n-1):
        lines.append(f'''  have read{i} : RamReadAt ({address('sp',8*i)}) 8 := by simpa using space.reads {i} (by decide)
  have sourceAddress{i} : BitVec.ofNat 64 (sp + {8*(n-1)}) + sign_extend (m := 64) (0x{(8*(i-(n-1)))%4096:03x}#12) =
      BitVec.ofNat 64 ({address('sp',8*i)}) := by
    have raw := stack_decrement (sp := sp + {8*(n-1)}) (n := {8*(n-1-i)}) (by omega) (by decide)
      (show sign_extend (m := 64) (0x{8*(i-(n-1))%4096:03x}#12) = -BitVec.ofNat 64 {8*(n-1-i)} from by decide)
    simpa only [show sp + {8*(n-1)} - {8*(n-1-i)} = {address('sp',8*i)} by omega] using raw
''')
        simps += [f'sourceAddress{i}', f'read{i}.toNat']
    for j,e in enumerate(entries,1):
        lines.append(f'  have member{j} : {e} ∈ {log} := by rw [logEq]; simp\n')
    lines.append('''  have limitNat : (BitVec.ofNat 64 limit).toNat = limit :=
    Nat.mod_eq_of_lt (by have upper := space.headerWrite.upper; have capacity := space.capacity; omega)
  have capacity : zopz0zKzJ_u (BitVec.ofNat 64 (a - 8)) (BitVec.ofNat 64 limit) = true := by
    apply bgeu_of_le
    rw [space.headerWrite.read.toNat, limitNat]
    exact space.capacity
  apply dispatch_compose h.dispatch
  intro d dp
''')
    for j,(a,v) in enumerate(zip(addresses,values),1):
        prev = 'd.σ.mem' if j==1 else f'm{j-1}'
        lines.append(f'''  obtain ⟨m{j}, hm{j}⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 {prev} ({a}) (sdData_val ({v})) := ⟨_, rfl⟩
  have memory{j} : m{j} = writeLog c.σ.mem (({log}).take {j}) := by
    rw [logEq, {', '.join(f'hm{k}' for k in range(j,0,-1))}, dp.memory]; rfl
''')
    lines.append(f'''  have fullMemory : m{n+2} = writeLog c.σ.mem ({log}) := by
    rw [logEq, {', '.join(f'hm{k}' for k in range(n+2,0,-1))}, dp.memory]; rfl
  have youngAfter : sign_extend (m := 64) (bytesT8 m2 (domain + Layout.off_young_ptr)) = BitVec.ofNat 64 (a - 8) := by
    have read : bytesT m2 (domain + Layout.off_young_ptr) 8 = BitVec.ofNat 64 (a - 8) := by
      rw [memory2, logEq]
      exact word_writeLog_at c.σ.mem _ 0 _ _ rfl space.headerYoungOutside
    simpa only [bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq] using read
''')
    pinregs=[p['reg'] for p in spec['pins']]
    lines.append(f'''  have bp : SegSt ({spec['entry']}#64)
      [{', '.join(f'⟨Register.{r}, {registers[r]}⟩' for r in pinregs)}]
      (fun σ => Vsa.Sim.Code.CamlMakeblock{n}FastLoaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨{', '.join(f'(dp.frame.frame Register.{r} (by decide)).trans {proofs[r]}' for r in pinregs)}, trivial⟩,
      dp.good.minstret, dp.tick, makeblock{n}_fast_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run0 := tr_makeblock{n}_fast {' '.join(registers[r] for r in pinregs)} d.σ.mem d.σ
''')
    stage=written=0;source=0;global_reads=0
    for step in steps:
        asm=step['asm']
        if step['class']=='sd':
            written+=1; geo=['space.youngWrite','space.headerWrite']+[f'fieldWrite{i}' for i in range(n)]
            geo=geo[written-1]
            args=f'{geo}.lower {geo}.upper {geo}.htif {geo}.aligned\n    (image_entry_code space.image member{written} (by decide) (by decide)) m{written} hm{written}'
        elif asm.startswith('lw '):
            args='operand.geometry.lower operand.geometry.upper operand.geometry.htif\n    (sign_extend (m := 64) tag) (by rw [operand.read32 h.code dp.memory])'
        elif asm.startswith('ld '):
            if '(s1)' in asm:
                geo=f'read{source}'; value=f'(word c ({address("sp",8*source)}))'
                outside=f'(outLRange_sublist (List.take_sublist {written} _) (payload_stack_outside space.payload (by have bound := space.bound; omega : {source} < s.stack.length)))'
                proof=f'(word_read_writeLog_out {outside} memory{written}).symm'
                source+=1
            elif '(a6)' in asm or '<Caml_state>' in asm:
                geo='domainRead';value='(BitVec.ofNat 64 domain)'
                if global_reads==0:proof='((word_read_writeLog_out (log := []) trivial dp.memory).trans space.domainValue).symm'
                else:proof=f'((word_read_writeLog_out (outLRange_sublist (List.take_sublist {written} _) space.payload.domain) memory{written}).trans space.domainValue).symm'
                global_reads+=1
            elif ',8(' in asm:
                geo='youngRead';value=f'(BitVec.ofNat 64 (a + {8*n}))' if written==0 else '(BitVec.ofNat 64 (a - 8))'
                proof='((word_read_writeLog_out (log := []) trivial dp.memory).trans space.youngValue).symm' if written==0 else 'youngAfter.symm'
            else:
                assert ',0(' in asm
                geo='limitRead';value='(BitVec.ofNat 64 limit)'
                proof='(by simpa only [Layout.off_young_limit, Nat.add_zero] using ((word_read_writeLog_out (log := []) trivial dp.memory).trans space.limitValue).symm)'
            args=f'{geo}.lower {geo}.upper {geo}.htif {value}\n    ({proof})'
        elif step['class'] in ['btaken','bnottaken']:args='capacity'
        else:continue
        lines.append(f'  try simp only [{", ".join(simps)}] at run{stage}\n  have run{stage+1} := run{stage} {args}\n');stage+=1
    for step in steps:
        r=step.get('rd')
        if r and r!='x0':pinregs=[r]+[p for p in pinregs if p!=r]
    pin=lambda r:f'PinsHold.get post.pins ⟨{pinregs.index(r)}, by simp⟩'
    writes=sorted({s['rd'] for s in steps if s.get('rd') and s['rd']!='x0'})
    allowed='['+', '.join('Register.'+r for r in writes)+'] ++ noiseRegs'
    spProof=pin('x9') if n>1 else '(frame.frame Register.x9 (by decide)).trans ((dp.frame.frame Register.x9 (by decide)).trans h.spReg)'
    lines.append(f'''  obtain ⟨nb, after, _, steps, post⟩ := run{stage} d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := {allowed}) (by decide)
  have observed : MakeblockPost c s pl sp 2 {n} tag.toInt.toNat a domain accu after := by
    refine ⟨⟨post.pcAt, {pin('x8')}, ?_, ⟨BitVec.ofNat 64 a, {pin('x21')}, ?_⟩, ?_, ?_⟩,
      post.good, memory.trans fullMemory, frame.out.trans dp.frame.out, ?_,
      (frame.frame (gprReg 2) (by decide)).trans (dp.frame.frame (gprReg 2) (by decide))⟩
    · exact {spProof}
    · simp only [makeblockState, valWord, space.placed, Option.map_some, Nat.mul_zero, Nat.add_zero]
    · obtain ⟨w, reg, value⟩ := h.env
      exact ⟨w, (frame.frame Register.x25 (by decide)).trans ((dp.frame.frame Register.x25 (by decide)).trans reg), value⟩
    · exact (frame.frame Register.x18 (by decide)).trans ((dp.frame.frame Register.x18 (by decide)).trans h.extra)
    · exact loopRegisters_frame (fun r hr =>
        (frame.frame r (by revert r; decide)).trans (dp.frame.frame r (by revert r; decide))) h.dispatch.loop
  exact ⟨nb, after, steps, makeblock_restore runtime h.toVmReprAt h.running.platform value space.toMakeblockWriteOk observed h.geometry h.native⟩

/-- The successful fixed-arity bytecode constructor selects this represented block. -/
theorem makeblock{n}_step_arm {{L : OCaml.Layout}} {{P : Prog}} {{s s' : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high a domain limit : Nat}} {{accu : BitVec 64}} {{tag : BitVec 32}}
    (runtime : AllocationRuntime L.runtimeOk c ({log}))
    (h : ArmInput L P s .MAKEBLOCK{n} c pl cp sp high)
    (operand : OperandAt P pl (s.pc + 1) tag) (nonnegative : 0 ≤ tag.toInt)
    (value : valWord pl s.accu = some accu)
    (space : MakeblockInput P s c pl cp sp high {n} tag.toInt.toNat a domain limit accu)
    (step : stepI P s ⟨.MAKEBLOCK{n}, [tag.toInt]⟩ = .next s') :
    ∃ after, Plus c after ∧ Running L P s' after := by
  have enough : ¬ s.stack.length < {n} - 1 := by have bound := space.bound; omega
  have state : makeblockState s 2 {n} tag.toInt.toNat = s' := by
    simpa only [stepI, makeBlock, show ¬ ({n} : Nat) = 0 by decide, enough, ite_false,
      makeblockState, makeblockObject, Res.next.injEq] using step
  rw [← state]
  exact makeblock{n}_arm runtime h operand nonnegative value space

end OCaml.Vm.Sim
''')
    return ''.join(lines)

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for n in [1,2,3]:
        path=ROOT/f'OCaml/Vm/Sim/Makeblock{n}.lean';out=render(n)
        if args.check:
            if not path.exists() or path.read_text()!=out:raise SystemExit(f'drift: {path}')
        else:path.write_text(out)
    print('Fixed-arity MAKEBLOCK adapters current')
