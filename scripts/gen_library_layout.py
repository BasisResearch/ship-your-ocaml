#!/usr/bin/env python3
"""Generate library entry and global-pointer constants from the linked ELF."""
import argparse
from pathlib import Path
from census import ROOT, symbols


def output(elf):
    syms = symbols(elf)
    return f'''-- GENERATED by scripts/gen_library_layout.py; do not edit.
import Std

namespace Vsa.Alloc
def mallocEntry : Nat := 0x{syms['malloc'][0]:x}
def freeEntry : Nat := 0x{syms['free'][0]:x}
end Vsa.Alloc

namespace Vsa.Sim.LibraryLayout
def gpV : BitVec 64 := 0x{syms['__global_pointer$'][0]:x}#64
abbrev tohostAddr : Nat := 0x{syms['tohost'][0]:x}
end Vsa.Sim.LibraryLayout
'''


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--elf', type=Path, default=ROOT / 'c/ocamlrun-riscv-htif.elf')
    ap.add_argument('--output-root', type=Path, default=ROOT)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    p = args.output_root / 'Vsa/Sim/LibraryLayout.lean'
    s = output(args.elf)
    if args.check:
        if not p.exists() or p.read_text() != s:
            raise SystemExit('library layout drift')
    else:
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text() != s:
            p.write_text(s)
    print('Library ELF layout current')
