def declarations(path):
    namespace = []
    blocks = []
    for line in (ROOT / path).read_text().splitlines():
        if match := re.match(r'^namespace (\S+)', line):
            namespace.append(match[1])
            blocks.append('namespace')
        elif re.match(r'^section(?: |$)', line):
            blocks.append('section')
        elif re.match(r'^end(?: |$)', line):
            if blocks and blocks.pop() == 'namespace':
                namespace.pop()
        elif match := re.match(r"^(?:theorem|#derive_case) ([\w.']+)", line):
            name = match[1] + ('_seg' if line.startswith('#derive_case') else '')
            yield '.'.join([*namespace, name])


def audit_names():
    names = [name for path in FILES for name in declarations(path)] + REGRESSIONS
    assert len(names) == len(set(names)), 'duplicate audit registration'
    return names


def output():
    imports = ['OCaml.Vm.Gc.F1Barrier', 'OCaml.Vm.Sim.OutListObstruction', 'OCaml.Vm.Sim.OutListF1Runtime',
               'OCaml.Vm.Sim.CountedChannelRows']
    return '\n'.join([*('import ' + module for module in imports), '',
        '/-! GENERATED by scripts/gen_outlist_runtime_audit.py. Full Audit remains the lead gate. -/',
        *('#print axioms ' + name for name in audit_names()), ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'OCaml/Vm/Sim/OutListRuntimeAudit.lean'
