#!/usr/bin/env python3
"""Generate a bounded view of the exact while_min ELF for kernel parser proofs.

The archived file is pinned by the existing cut's SHA256. Loader-covered bytes
reuse WhileMinImage.imageByte; all other file bytes use sparse packed pages.
No parser, memory, or execution theorem is assumed by this data generator.
"""
import argparse
import gzip
import hashlib
import json
import struct
from pathlib import Path
from packed_bytes import emit_packed_bytes

ROOT = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--capture', type=Path)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    archive = ROOT / 'results/boot/while_min-elf.bin.gz'
    pin = json.loads((ROOT / 'results/boot/while_min-cut.json').read_text())['elf_sha256']
    if args.capture:
        assert not args.check
        raw = args.capture.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == pin
        archive.write_bytes(gzip.compress(raw, mtime=0))
    raw = gzip.decompress(archive.read_bytes())
    assert hashlib.sha256(raw).hexdigest() == pin
    assert raw[:6] == b'\x7fELF\x02\x01'
    saved = json.loads(gzip.decompress((ROOT / 'results/boot/while_min-initial.json.gz').read_bytes()))
    assert saved['elf_sha256'] == pin
    pieces = [(a, bytes(bs)) for a, bs in saved['pieces']]
    phoff = struct.unpack_from('<Q', raw, 32)[0]
    phsize, phnum = struct.unpack_from('<HH', raw, 54)
    assert phnum <= len(pieces)
    views = []
    for i in range(phnum):
        _, _, offset, base, _, size, _, _ = struct.unpack_from('<IIQQQQQQ', raw, phoff+i*phsize)
        addr, body = pieces[i]
        assert addr == base and body == raw[offset:offset+size] and len(body) == size
        if size:
            views.append((offset, base, size))
    for addr, body in pieces[phnum:]:
        assert body == raw[addr:addr+len(body)]
        if body:
            views.append((addr, addr, len(body)))
    extra = bytearray(raw)
    for i, (off, _, size) in enumerate(views):
        assert all(off+size <= other or other+n <= off for other, _, n in views[:i])
        extra[off:off+size] = bytes(size)
    out = ['import OCaml.Vm.Boot.WhileMinImageData', 'import Vsa.Sim.Boot.ByteView', '',
           '/-! GENERATED by scripts/gen_boot_elf.py. Exact archived ELF bytes.',
           f'ELF SHA256: {pin}. Parser correspondence is proved separately. -/',
           'namespace OCaml.Vm.Boot.WhileMinElfData', 'open Vsa.Sim.Boot', '']
    emit_packed_bytes(out, 'extra', extra)
    out += [f'def fileSize : Nat := {len(raw)}', '', 'def fileByte (a : Nat) : BitVec 8 :=']
    for i, (off, base, size) in enumerate(views):
        kw = 'if' if i == 0 else 'else if'
        out.append(f'  {kw} {off} ≤ a ∧ a < {off+size} then WhileMinImage.imageByte ({base} + (a - {off}))')
    out += ['  else extraByte a', '', 'def fileBytes : ByteArray := bytesOfView fileSize fileByte', '',
            'def expectedHeader : ELF64Header := {',
            '  e_ident := ⟨⟨#[' + ', '.join(str(b) for b in raw[:16]) + ']⟩, rfl⟩']
    fields = ['e_type', 'e_machine', 'e_version', 'e_entry', 'e_phoff', 'e_shoff', 'e_flags',
              'e_ehsize', 'e_phentsize', 'e_phnum', 'e_shentsize', 'e_shnum', 'e_shstrndx']
    for field, value in zip(fields, struct.unpack_from('<HHIQQQIHHHHHH', raw, 16)):
        out.append(f'  {field} := {value}')
    out += ['}', '']
    shoff = struct.unpack_from('<Q', raw, 40)[0]
    shsize, shnum = struct.unpack_from('<HH', raw, 58)
    tables = [
        ('Program', 'program', phoff, phsize, phnum, '<IIQQQQQQ',
         ['p_type', 'p_flags', 'p_offset', 'p_vaddr', 'p_paddr', 'p_filesz', 'p_memsz', 'p_align']),
        ('Section', 'section', shoff, shsize, shnum, '<IIQQQQIIQQ',
         ['sh_name', 'sh_type', 'sh_flags', 'sh_addr', 'sh_offset', 'sh_size', 'sh_link', 'sh_info',
          'sh_addralign', 'sh_entsize'])]
    proofs = ['import OCaml.Vm.Boot.WhileMinElfSort', 'import OCaml.Vm.Boot.WhileMinElfHeader', 'import Vsa.Sim.Boot.ElfEntries', '',
              '/-! GENERATED by scripts/gen_boot_elf.py. Bounded parser certificates. -/',
              'namespace OCaml.Vm.Boot.WhileMinElfParse',
              'open Vsa.Sim.Boot WhileMinElfData', '']
    for kind, stem, offset, stride, count, fmt, fields in tables:
        width = struct.calcsize(fmt)
        assert stride == width
        for i in range(count):
            off = offset + i*stride
            out.append(f'def {stem}{i} : ELF64{kind}HeaderTableEntry := {{')
            for field, value in zip(fields, struct.unpack_from(fmt, raw, off)):
                out.append(f'  {field} := {value}')
            out += ['}', '']
            proofs += [f'theorem {stem}{i}_parse : mkELF64{kind}HeaderTableEntry? false fileBytes {off} =',
                       f'    .ok {stem}{i} := by',
                       '  rw [show fileBytes = bytesOfView fileSize fileByte from rfl,',
                       f'    elf{kind}Header_parse_view fileSize fileByte {off} false (by decide)]',
                       '  rfl', '']
        out += [f'def {stem}s : List ELF64{kind}HeaderTableEntry := [' +
                ', '.join(f'{stem}{i}' for i in range(count)) + ']', '']
        offsets = '[' + ', '.join(str(offset+i*stride) for i in range(count)) + ']'
        certs = ', '.join(f'{stem}{i}_parse' for i in range(count))
        proofs += [f'theorem {stem}_table_parse : expectedHeader.mkELF64{kind}HeaderTable? fileBytes =',
                   f'    .ok {stem}s := by',
                   '  have endian : ELFHeader.isBigendian expectedHeader = false := by decide +kernel',
                   f'  have offsets : ELFHeader.get{kind}HeaderOffsets expectedHeader = {offsets} := by decide +kernel',
                   f'  change List.mapM (fun off => mkELF64{kind}HeaderTableEntry? (ELFHeader.isBigendian expectedHeader) fileBytes off)',
                   f'    (ELFHeader.get{kind}HeaderOffsets expectedHeader) = _',
                   '  rw [endian, offsets]',
                   f'  simp [{stem}s, {certs}]', '  rfl', '']
    inhabited = [(0, 64), (phoff, phoff + phsize * phnum), (shoff, shoff + shsize * shnum)]
    for i in range(phnum):
        ph = struct.unpack_from('<IIQQQQQQ', raw, phoff + i * phsize)
        inhabited.append((ph[2], ph[2] + ph[5]))
    for i in range(shnum):
        sh = struct.unpack_from('<IIQQQQIIQQ', raw, shoff + i * shsize)
        inhabited.append((sh[4], sh[4] + sh[5]))
    out += ['def inhabitedSorted : List (Nat × Nat) := [' +
            ', '.join(f'({a}, {b})' for a, b in sorted(inhabited)) + ']', '']
    proofs += ['theorem ranges_sorted :',
               '    ((getInhabitedRanges expectedHeader sections programs).toArray.qsort',
               '      (fun a b => a.1 < b.1)).toList = inhabitedSorted := WhileMinElfSort.ranges_sorted', '']
    out += ['def gapRanges : List (Nat × Nat) := [' +
            ', '.join(f'({a}, {len(bs)})' for a, bs in pieces[phnum:]) + ']', '',
            'end OCaml.Vm.Boot.WhileMinElfData', '']
    proofs += ['end OCaml.Vm.Boot.WhileMinElfParse', '']
    literal = lambda xs: '[' + ', '.join(f'({a}, {b})' for a, b in xs) + ']'
    sort_proof = ['module', 'import all Init.Data.Array.QSort.Basic', 'public import Init', '',
                  '/-! GENERATED by scripts/gen_boot_elf.py. Finite metadata sorting only. -/',
                  'public section', 'namespace OCaml.Vm.Boot.WhileMinElfSort', '',
                  'theorem ranges_sorted :',
                  f'    (({literal(inhabited)} : List (Nat × Nat)).toArray.qsort',
                  f'      (fun a b => a.1 < b.1)).toList = {literal(sorted(inhabited))} := by',
                  '  simp [Array.qsort, Array.qsort.sort, Array.qpartition, Array.qpartition.loop]', '',
                  'end OCaml.Vm.Boot.WhileMinElfSort', '']
    outputs = {'OCaml/Vm/Boot/WhileMinElfData.lean': '\n'.join(out),
               'OCaml/Vm/Boot/WhileMinElfTables.lean': '\n'.join(proofs),
               'OCaml/Vm/Boot/WhileMinElfSort.lean': '\n'.join(sort_proof)}
    for name, text in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit('boot ELF data drift: ' + name)
        elif not path.exists() or path.read_text() != text:
            path.write_text(text)
    print(f'Pinned while_min ELF: {len(raw)} bytes, {len(views)} shared image views')


if __name__ == '__main__':
    main()
