#!/usr/bin/env python3
"""Generate the custom-table request route using gen_fn and shared gen_chain.

The wrapper supplies the actual element size; the existing generic-table rows
supply the null-base branch, nursery shift and reserve. No native malloc or
physical accounting return is asserted here. --check never writes outputs.
"""
import argparse
import contextlib
import importlib.util
import io
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from census import ROOT, TOOLS
from gen_layout import collector_layout
import gen_chain
sys.path.insert(0, str(ROOT / 'scripts/syi'))
import gen_fn
spec = importlib.util.spec_from_file_location('custom_code', ROOT / 'experiments/syi/gen_code_lemmas.py')
code = importlib.util.module_from_spec(spec)
spec.loader.exec_module(code)


def publish(path, text, check):
    if check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit(f'custom-table credit drift: {path.relative_to(ROOT)}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(path.relative_to(ROOT))


def generate(check):
    with tempfile.TemporaryDirectory() as directory:
        tmp = Path(directory)
        disasm = tmp / 'disasm.txt'
        with disasm.open('w') as output:
            subprocess.run([TOOLS + 'objdump', '-d', str(ROOT / 'c/ocamlrun-riscv-htif.elf')],
                           stdout=output, check=True)
        di = gen_fn.lib.parse_disasm(str(disasm))
        extents = gen_fn.function_extents(str(disasm))
        name = 'caml_realloc_custom_table'
        entry, end = extents[name]
        words = [(a, di[a].word) for a in sorted(di) if entry <= a < end]
        pins = code.render(name, words, transport=True).replace(
            'generated by experiments/gen_code_lemmas.py',
            'GENERATED by scripts/gen_custom_table_credit.py via experiments/syi/gen_code_lemmas.py')
        publish(ROOT / 'Vsa/Sim/Code/Caml_realloc_custom_table.lean', pins, check)
        index = tmp / 'index.tsv'
        index.write_text('\n'.join(w + '\tVsa.Sim.ElfDecode.' + p.stem
            for p in sorted((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean'))
            for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)) + '\n')
        path = tmp / 'CustomRealloc.lean'
        with contextlib.redirect_stdout(io.StringIO()):
            gen_fn.emit_fn(name, entry, str(path), verify=False,
                           disasm_path=str(disasm), decode_index=str(index))
        wrapper = path.read_text().replace('GENERATED by `scripts/gen_fn.py',
            'GENERATED by scripts/gen_custom_table_credit.py via `scripts/syi/gen_fn.py').replace(
            'from `experiments/disasm.txt`', 'from the pinned runtime ELF')
        wrapper_path = 'OCaml/Vm/Gc/Generated/CustomRealloc.lean'
        publish(ROOT / wrapper_path, wrapper, check)
        segment = re.search(r'^#derive_case (\w+)', wrapper, re.M).group(1)
        custom = (wrapper_path, 'Code.Caml_realloc_custom_tableLoaded',
                  'Vsa.Sim.Code.caml_realloc_custom_table_at_')
        gen_chain.CHAINS = [(
            'OCaml/Vm/Gc/Generated/CustomReallocEntry.lean', 'OCaml.Vm.Gc.CustomReallocEntry',
            'Custom-table null-base route to the actual size-product call.\n'
            'The wrapper supplies 24-byte elements; shared generic-table rows\n'
            'supply the nursery shift and 256-entry reserve.',
            [(custom, segment), (gen_chain.GEN, 'realloc_generic_table_isra_0X961cTSeg'),
             (gen_chain.GEN, 'realloc_generic_table_isra_0X9750Seg')], (gen_chain.GEN, 0x80009774))]
        for path, text in gen_chain.generate().items():
            publish(path, text.replace('GENERATED by scripts/gen_chain.py',
                'GENERATED by scripts/gen_custom_table_credit.py via scripts/gen_chain.py'), check)
        layout = collector_layout(custom_geometry=True)
        text = ['import OCaml.Vm.Layout', '',
                '/-! GENERATED by scripts/gen_custom_table_credit.py from the target ABI. -/',
                'namespace OCaml.Vm.Gc.CustomTable', '']
        for field in ('threshold', 'limit', 'size', 'reserve'):
            text.append(f'def off_{field} : Nat := {layout["off_custom_table_" + field]}')
        text += ['', 'end OCaml.Vm.Gc.CustomTable', '']
        publish(ROOT / 'OCaml/Vm/Gc/Generated/CustomTableGeometry.lean', '\n'.join(text), check)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
