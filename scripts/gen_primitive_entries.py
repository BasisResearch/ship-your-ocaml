#!/usr/bin/env python3
"""Extract the primitive resolver from the pinned ELF's parallel builtin tables.

The generated balanced lookup contains function addresses, not data addresses.
Every table entry is checked against its ELF symbol and the executable section.
"""
import argparse
import hashlib
import struct
import subprocess
from census import ROOT
from gen_layout import TOOLS
from gen_ocaml_image import sections
from gen_primitive_census import primitive_names


def entries():
    elf = (ROOT / 'c/ocamlrun-riscv-htif.elf').read_bytes()
    if hashlib.sha256(elf).hexdigest() != (ROOT / 'c/ELF.sha256').read_text().split()[0]:
        raise ValueError('unpinned ELF')
    symbols = {}
    for line in subprocess.check_output([TOOLS + 'nm', str(ROOT / 'c/ocamlrun-riscv-htif.elf')], text=True).splitlines():
        parts = line.split()
        if len(parts) == 3:
            symbols[parts[2]] = int(parts[0], 16)
    sec = sections(elf)
    def read(a, n):
        for base, raw in sec.values():
            if base <= a and a + n <= base + len(raw):
                return raw[a-base:a-base+n]
        raise ValueError(f'ELF address outside file-backed sections: {a:x}')
    def word(a):
        return struct.unpack('<Q', read(a, 8))[0]
    def name(a):
        result = bytearray()
        for i in range(256):
            b = read(a+i, 1)[0]
            if b == 0:
                return result.decode('ascii')
            result.append(b)
        raise ValueError('unterminated primitive name')
    text_base, text = sec['.text']
    found = {}
    for i in range(10000):
        p = word(symbols['caml_names_of_builtin_cprim'] + 8*i)
        entry = word(symbols['caml_builtin_cprim'] + 8*i)
        if p == 0:
            if entry != 0:
                raise ValueError('mismatched builtin table terminators')
            return sorted(found.items())
        key = name(p)
        if key in found or symbols.get(key) != entry or not text_base <= entry < text_base+len(text) or entry % 4:
            raise ValueError(f'invalid primitive entry: {key}')
        found[key] = entry
    raise ValueError('unterminated builtin tables')


def tree(rows, indent=2):
    if not rows:
        return 'none'
    mid = len(rows)//2
    name, address = rows[mid]
    pad = ' '*indent
    return (f'if name = "{name}" then some 0x{address:x}\n{pad}'
            f'else if name < "{name}" then\n{pad}  {tree(rows[:mid],indent+2)}\n{pad}'
            f'else\n{pad}  {tree(rows[mid+1:],indent+2)}')


def output():
    rows = entries()
    lines = ['import OCaml.Vm.Layout', '',
             '/-! GENERATED by scripts/gen_primitive_entries.py from the pinned ELF. -/',
             'namespace OCaml.Vm.PrimitiveEntries', 'set_option autoImplicit false', '',
             f'/-- All {len(rows)} native primitive names resolved by this runtime image. -/',
             'def lookup (name : String) : Option Nat :=', '  '+tree(rows), '']
    for name in primitive_names():
        if name not in dict(rows):
            raise ValueError(f'F1 primitive absent: {name}')
        lines += [f'theorem entry_{name} : lookup "{name}" = some Layout.sym_{name} := by decide', '']
    lines += ['end OCaml.Vm.PrimitiveEntries', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    p = ROOT / 'OCaml/Vm/PrimitiveEntries.lean'
    text = output()
    if args.check:
        if not p.exists() or p.read_text() != text:
            raise SystemExit('primitive entry lookup drift')
    else:
        p.write_text(text)
    print('Primitive entry lookup current')
