#!/usr/bin/env python3
"""Restore represented generic blocks from the generated constructor suffixes."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render(kind):
    more=kind=='more';stem='MakeblockSuffix' if more else 'MakeblockOneSuffix'
    native='makeblock_suffix' if more else 'makeblock_one_suffix'
    spec=json.loads((ROOT/f'scripts/syi/segments/{native}.json').read_text())
    regs=[p['reg'] for p in spec['pins']]
    vals={'x9':'(BitVec.ofNat 64 sp)','x10':'(BitVec.ofNat 64 (8 * (count - 1)))','x11':'(BitVec.ofNat 64 (a - 8))','x26':'(BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 3)))'}
    proofs={'x9':'stackReg','x10':'bytesReg','x11':'headerReg','x26':'codeReg'}
    pins=', '.join(f'⟨Register.{r}, {vals[r]}⟩' for r in regs)
    pinproof=', '.join(proofs[r] for r in regs);args=' '.join(vals[r] for r in regs)
    for st in spec['steps']:
        r=st.get('rd')
        if r:regs=[r]+[x for x in regs if x!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    before='start' if more else 'd'
    copyparam='''
    (copied : MakeblockCopyAt sp (a + 8) (stackWords c sp (count - 1)) start
      (stackWords c sp (count - 1)).length d)''' if more else ''
    setup='''  have baseFrame := (front.frame.trans copied.frame).widenChecked (allowed := makeblockSetupWrites) (by decide)
  have stackReg := (copied.frame.frame Register.x9 (by decide)).trans front.stack
  have headerReg := (copied.frame.frame Register.x11 (by decide)).trans front.header
  have codeReg := (copied.frame.frame Register.x26 (by decide)).trans front.nextCode
  have bytesReg := (copied.frame.frame Register.x10 (by decide)).trans (front.copyRegisters branch).bytes
  have pcAt : pcOf d = some (0x800026e0#64) := by
    simpa only [Nat.lt_irrefl, ite_false] using copied.pc
  have fullMemory : d.σ.mem = writeLog c.σ.mem (makeblockLog c sp count tag a domain accu) := by
    rw [copied.memory, forward_copy_log_complete, front.memory, ← writeLog_append,
      makeblock_log_parts c sp count tag a domain accu space.positive]
''' if more else '''  have baseFrame := front.frame
  have headerReg := front.header
  have codeReg := front.nextCode
  have pcAt : pcOf d = some (0x80003c74#64) := by
    simpa only [branch, Nat.lt_irrefl, ite_false] using front.pcAt
  have fullMemory : d.σ.mem = writeLog c.σ.mem (makeblockLog c sp count tag a domain accu) := by
    rw [front.memory, ← makeblock_log_parts c sp count tag a domain accu space.positive]
    simp only [branch, Nat.sub_self, stackWords, List.range_zero, List.map_nil,
      valueLog, valueEntries, indexedLog, List.length_nil, List.append_nil]
'''
    poststack=f'exact {get("x9")}' if more else '''simp only [branch, Nat.sub_self, Nat.mul_zero, Nat.add_zero]
      exact (rawFrame.frame Register.x9 (by decide)).trans front.stack'''
    return f'''-- GENERATED by scripts/gen_makeblock_finish.py; do not edit.
import OCaml.Vm.Sim.MakeblockInitInput
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The generated {kind} suffix restores the represented newly allocated block. -/
theorem makeblock_finish_{kind} {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c {'start ' if more else ''}d : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high count tag a domain : Nat}} {{accu : BitVec 64}}
    (runtime : AllocationRuntime L.runtimeOk c (makeblockLog c sp count tag a domain accu))
    (h : ArmInput L P s .MAKEBLOCK c pl cp sp high) (value : valWord pl s.accu = some accu)
    (space : MakeblockWriteOk P s c pl cp sp high count tag a domain accu)
    (branch : {'1 < count' if more else 'count = 1'})
    (front : MakeblockInitialized c pl s.pc sp count tag a domain accu {before}){copyparam} :
    ∃ nb after, StepsN nb d after ∧ Running L P (makeblockState s 3 count tag) after := by
{setup}  have valueAddress : BitVec.ofNat 64 (a - 8) + sign_extend (m := 64) (0x008#12) = BitVec.ofNat 64 a := by
    change BitVec.ofNat 64 (a - 8) + BitVec.ofNat 64 8 = _
    rw [← BitVec.ofNat_add]; congr 1; have room := space.room; omega
  have stackAddress : BitVec.ofNat 64 sp + BitVec.ofNat 64 (8 * (count - 1)) = BitVec.ofNat 64 (sp + 8 * (count - 1)) :=
    (BitVec.ofNat_add _ _).symm
  have bp : SegSt ({spec['entry']}#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨{'copied' if more else 'front'}.good, pcAt, ⟨{pinproof}, trivial⟩,
      {'copied' if more else 'front'}.good.minstret, {'copied' if more else 'front'}.tick,
      {native}_loaded {'copied' if more else 'front'}.image, rfl, rfl⟩
  have run := tr_{native} {args} d.σ.mem d.σ
  simp only [valueAddress, stackAddress, show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero] at run
  obtain ⟨nb, after, _, steps, post⟩ := run d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := (baseFrame.trans rawFrame).widenChecked
    (allowed := [Register.x8, Register.x9, Register.x10, Register.x11, Register.x12, Register.x13,
      Register.x14, Register.x15, Register.x16, Register.x21, Register.x23, Register.x26] ++ noiseRegs) (by decide)
  have observed : MakeblockPost c s pl sp 3 count tag a domain accu after := by
    refine ⟨⟨post.pcAt, {get('x8')}, ?_, ⟨BitVec.ofNat 64 a, {get('x21')}, ?_⟩, ?_, ?_⟩,
      post.good, memory.trans fullMemory, frame.out, ?_⟩
    · {poststack}
    · simp only [makeblockState, valWord, space.placed, Option.map_some, Nat.mul_zero, Nat.add_zero]
    · obtain ⟨w, reg, value⟩ := h.env
      exact ⟨w, (frame.frame Register.x25 (by decide)).trans reg, value⟩
    · exact (frame.frame Register.x18 (by decide)).trans h.extra
    · exact loopRegisters_frame (fun r hr => frame.frame r (by revert r; decide)) h.dispatch.loop
  exact ⟨nb, after, steps, makeblock_restore runtime h.toVmReprAt h.running.platform value space observed⟩

end OCaml.Vm.Sim
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for kind in ['more','one']:
        path=ROOT/f'OCaml/Vm/Sim/MakeblockFinish{kind.title()}.lean';out=render(kind)
        if args.check:
            if not path.exists() or path.read_text()!=out:raise SystemExit(f'drift: {path}')
        else:path.write_text(out)
    print('Generic MAKEBLOCK suffix adapters current')
