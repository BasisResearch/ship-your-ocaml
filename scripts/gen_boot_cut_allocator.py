#!/usr/bin/env python3
"""Emit bounded kernel certificates of the complete captured newlib allocator.

Python extracts witnesses only. Every read and invariant is checked by Lean;
no native validation result is imported as a premise. Regenerate, or --check.
"""
import argparse
import gzip
import json
import re
from pathlib import Path
from boot_certificate import emit_finite_family

ROOT = Path(__file__).resolve().parents[1]


def generate():
    initial = json.load(gzip.open(ROOT / 'results/boot/while_min-initial.json.gz'))
    memory = {a+i: b for a, bs in initial['pieces'] for i, b in enumerate(bs)}
    stored = set()
    for _, a, width, value in map(json.loads, gzip.open(ROOT / 'results/boot/while_min-stores.jsonl.gz')):
        for i in range(width):
            memory[a+i] = (value >> (8*i)) & 255
            stored.add(a+i)

    def read(a):
        return sum(memory.get(a+i, 0) << (8*i) for i in range(8))

    av, start = 0x80063b90, 0x8007d140
    top, brk = read(av+16), read(0x80064910)
    chunks, p = [], start
    while p < top:
        h = read(p+8)
        size = h // 4 * 4
        if size < 32 or size % 16 or h % 4 >= 2:
            raise ValueError(f'ChunkWalk obstruction at {p:#x}: header {h:#x}')
        chunks.append((p, size, bool(read(p+size+8) % 2)))
        p += size
    assert p == top
    bins = {}
    for i in range(1, 128):
        b, qs = av+16*i, []
        q = read(b+16)
        while q != b:
            if q in qs or len(qs) > len(chunks):
                raise ValueError(f'cyclic bin {i} at {q:#x}')
            qs.append(q)
            q = read(q+16)
        bins[i] = qs

    out = ['import OCaml.Vm.Boot.Startup.AllocatorReads',
           'import OCaml.Vm.Boot.Startup.HeapFrame',
           'import OCaml.Vm.Boot.WhileMinImage',
           'import OCaml.Vm.Boot.WhileMinRuntime', '',
           '/-! GENERATED by scripts/gen_boot_cut_allocator.py. Complete allocator memory',
           'certificate at the captured cut; no reset execution or reachability claim.',
           'Checks are bounded to individual words, chunks and bin chains. The live',
           'ledger uses actual usable sizes, without inferring original requests. -/',
           'namespace OCaml.Vm.Boot.WhileMinAllocator',
           'open Vsa.Machine Vsa.MemRepr Vsa.Sim Vsa.Sim.Boot Vsa.Sim.DlHeap',
           'open VsaIris.VsaHeap Startup WhileMinLog', '',
           'noncomputable def memory : Mem :=',
           '  Vsa.Densify.fillZeroMem (observedMem WhileMinImage.initialMem log)',
           f'def top : Nat := {top:#x}', f'def brk : Nat := {brk:#x}', '',
           '/-- Convert total observed reads to allocator reads using RAM presence. -/',
           'theorem read_word (a : Nat) (v : BitVec 64)',
           '    (lo : Vsa.Densify.ramBase ≤ a) (hi : a + 8 ≤ Vsa.Densify.ramBase + Vsa.Densify.ramSize)',
           '    (value : bytesT (observedMem WhileMinImage.initialMem log) a 8 = v) :',
           '    read64 memory a = some v.toNat := by',
           '  apply read64_of_word (v := v)',
           '  · intro i hi',
           '    rw [memory, Vsa.Densify.fillZeroMem_ram _ (by omega) (by omega)]',
           '    rfl',
           '  · exact (bytesT_memEqv (Vsa.Densify.memEqv_fillZeroMem _).symm a 8).trans value', '']
    reads = {}

    def cert(a):
        if a in reads:
            return reads[a]
        name = f'read_{a:x}'
        reads[a] = name
        out.extend([f'theorem {name} : read64 memory {a:#x} = some {read(a):#x} := by',
                    f'  apply read_word {a:#x} {read(a):#x}#64 (by decide) (by decide)'])
        if all(a+i in stored for i in range(8)):
            out.extend([f'  rw [observedMem_bytes_stored logOk (a := {a:#x}) (w := 8) (by decide +kernel)]'])
        else:
            out.append('  rw [WhileMinImage.observed_bytes_view]')
        out.extend(['  decide +kernel', ''])
        return name

    for a in [0x800648e8, 0x80064910, av+16, top+8, 0x80064d30, 0x80064d28,
              0x8007c9e8, av+8]:
        cert(a)
    for a, size, used in chunks:
        cert(a+8)
        if not used:
            for x in [a+16, a+24, a+size]:
                cert(x)
    n = len(chunks)
    for i, (a, size, used) in enumerate(chunks):
        out.extend([f'def chunk{i} : Chunk := ⟨{a:#x}, {size}, {str(used).lower()}⟩'])
    out.extend(['', f'def chunks{n} : List Chunk := []'])
    for i in reversed(range(n)):
        out.append(f'def chunks{i} : List Chunk := chunk{i} :: chunks{i+1}')
    out.extend(['', 'def chunks : List Chunk := chunks0', '',
                f'theorem walk{n} : ChunkWalk memory top top chunks{n} := .top', ''])
    for k, (_, _, used) in enumerate(chunks):
        if not used:
            term = 'List.mem_cons_self'
            for _ in range(k):
                term = f'List.mem_cons_of_mem _ ({term})'
            out.extend([f'theorem member{k} : chunk{k} ∈ chunks := {term}', ''])
    for i in reversed(range(n)):
        a, size, used = chunks[i]
        out.extend([f'theorem walk{i} : ChunkWalk memory {a:#x} top chunks{i} :=',
                    f'  .chunk {cert(a+8)} (by decide) (by decide) (by decide)',
                    f'    {cert(a+size+8)} walk{i+1}', ''])
    out.extend(['theorem walk : ChunkWalk memory heapStart top chunks := walk0', '',
                'def bins (i : Nat) : List Nat :='])
    for i, qs in bins.items():
        if qs:
            out.append(f'  if i = {i} then [' + ', '.join(f'{q:#x}' for q in qs) + '] else')
    out.extend(['  []', ''])
    proofs = []
    for i, qs in bins.items():
        b = av+16*i
        head, close = cert(b+16), cert(b+24)
        name = f'bin{i}'
        out.extend([f'theorem {name} : BinList memory {i} (bins {i}) :=',
                    f'  ⟨{read(b+16):#x}, {head},'])
        prev = b
        for q in qs:
            out.append(f'    .link (by decide) {cert(q+24)} {cert(q+16)} (')
            prev = q
        out.append(f'    .close {close}' + ')' * len(qs) + '⟩')
        out.append('')
        proofs.append(name)
    emit_finite_family(out, 'bin_lists', proofs,
                       lambda i: f'BinList memory {i} (bins {i})', start=1)
    out.extend(['theorem cert_cons {α : Type} {P : α → Prop} {x : α} {xs : List α}',
                '    (head : P x) (tail : ∀ y ∈ xs, P y) : ∀ y ∈ x :: xs, P y := by',
                '  intro y hy', '  rcases List.mem_cons.mp hy with rfl | hy',
                '  · exact head', '  · exact tail y hy', '',
                f'theorem adjacent : ∀ i : Fin {n-1},',
                f'    (chunks[i.val]\'(by have := i.isLt; change i.val < {n}; omega)).inuse = true ∨',
                f'    (chunks[i.val + 1]\'(by have := i.isLt; change i.val + 1 < {n}; omega)).inuse = true := by',
                '  decide +kernel', '',
                'theorem coalesced : ∀ i (hi : i + 1 < chunks.length),',
                '    chunks[i].inuse = true ∨ chunks[i + 1].inuse = true := by',
                '  intro i hi', f'  have bound : i < {n-1} := by change i + 1 < '+str(n)+' at hi; omega',
                '  exact adjacent ⟨i, bound⟩', ''])
    for i, (a, size, used) in enumerate(chunks):
        out.extend([f'theorem footer{i} : chunk{i}.inuse = false →',
                    f'    read64 memory (chunk{i}.addr + chunk{i}.size) = some chunk{i}.size :='])
        out.append('  by intro h; cases h' if used else f'  fun _ => {cert(a+size)}')
        out.append('')
    tail = 'fun _ h => nomatch h'
    for i in reversed(range(n)):
        tail = f'cert_cons footer{i} ({tail})'
    out.extend(['theorem footers : ∀ c ∈ chunks, c.inuse = false →',
                '    read64 memory (c.addr + c.size) = some c.size :=', '  '+tail, '',
                'theorem bins_unique (i j q : Nat) (hi : q ∈ bins i) (hj : q ∈ bins j) : j = i := by',
                '  by_cases hi1 : i = 1 <;> by_cases hi10 : i = 10 <;>',
                '    by_cases hj1 : j = 1 <;> by_cases hj10 : j = 10 <;>',
                '    simp_all [bins]', '',
                'theorem bin_free : ∀ i q, 0 < i → i < numBins → q ∈ bins i →',
                '    ∃ c ∈ chunks, c.addr = q ∧ c.inuse = false ∧ (1 < i → binIndex c.size = i) := by',
                '  intro i q _ _ member'])
    for i, qs in bins.items():
        if not qs:
            continue
        out.extend([f'  by_cases h{i} : i = {i}', '  · subst i',
                    '    have members : q ∈ ['+', '.join(f'{q:#x}' for q in qs)+'] := member',
                    '    simp only [List.mem_cons, List.not_mem_nil, or_false] at members'])
        if len(qs) > 1:
            out.append('    rcases members with ' + ' | '.join('rfl' for _ in qs))
        else:
            out.append('    subst q')
        for q in qs:
            k = next(k for k, c in enumerate(chunks) if c[0] == q)
            out.append(('    · ' if len(qs)>1 else '    ') + f'exact ⟨chunk{k}, member{k}, rfl, rfl, by decide⟩')
    out.extend(['  simp [bins, *] at member', ''])
    for k, (a, size, used) in enumerate(chunks):
        out.extend([f'theorem free_binned{k} : chunk{k}.inuse = false →',
                    '    ∃ i, 0 < i ∧ i < numBins ∧ chunk'+str(k)+'.addr ∈ bins i ∧',
                    '      ∀ j, 0 < j → j < numBins → chunk'+str(k)+'.addr ∈ bins j → j = i :='])
        if used:
            out.append('  by intro h; cases h')
        else:
            i = next(i for i, qs in bins.items() if a in qs)
            out.extend([f'  fun _ => ⟨{i}, by decide, by decide, by decide,',
                        f'    fun j _ _ hj => bins_unique {i} j chunk{k}.addr (by decide) hj⟩'])
        out.append('')
    tail = 'fun _ h => nomatch h'
    for i in reversed(range(n)):
        tail = f'cert_cons free_binned{i} ({tail})'
    out.extend(['theorem free_binned : ∀ c ∈ chunks, c.inuse = false →',
                '    ∃ i, 0 < i ∧ i < numBins ∧ c.addr ∈ bins i ∧',
                '      ∀ j, 0 < j → j < numBins → c.addr ∈ bins j → j = i :=', '  '+tail, ''])
    emit_finite_family(out, 'bins_nodup', ['by decide']*128,
                       lambda i: f'(bins {i}).Nodup')
    out.extend(['theorem binblocks : ∀ i, 1 < i → i < numBins → bins i ≠ [] →',
                f'    {read(av+8)} / 2 ^ (i / 4) % 2 = 1 := by',
                '  intro i low high nonempty'])
    # Only bins >1 constrain the bitmap. Split by the extracted nonempty bins.
    for i, qs in bins.items():
        if qs and i > 1:
            out.extend([f'  by_cases h{i} : i = {i}', '  · subst i; decide'])
    out.extend(['  have : i ≠ 1 := by omega', '  simp [bins, *] at nonempty', '',
                '/-- Complete raw shape; the live ledger is derived from this walk below. -/',
                'theorem raw_heap : HeapAt memory [] (fun _ => False) top brk chunks bins where',
                f'  sbrk_base := {cert(0x800648e8)}', f'  brk := {cert(0x80064910)}',
                '  brk_le := by decide', f'  top_ptr := {cert(av+16)}',
                '  top_le := by decide', '  top_size := by decide',
                f'  top_header := {cert(top+8)}', f'  top_pad := {cert(0x80064d30)}',
                f'  max_sbrked := by rw [maxSbrkedAddr, {cert(0x80064d28)}]; rfl',
                f'  mallinfo := by rw [mallinfoAddr, {cert(0x8007c9e8)}]; rfl',
                f'  first_prev := by rw [heapStart, {cert(start+8)}]; decide',
                '  walk := walk', '  coalesced := coalesced', '  footer := footers',
                '  bins_list := fun i low high => bin_lists i low high',
                '  bins_nodup := fun i => by',
                '    by_cases hi : i < 128', '    · exact bins_nodup i (by omega) hi',
                '    · have h1 : i ≠ 1 := by omega', '      have h10 : i ≠ 10 := by omega',
                '      simp [bins, h1, h10]',
                '  bin_free := bin_free', '  free_binned := free_binned',
                '  remainder := by decide', f'  binblocks_present := by rw [binblocksAddr, avAddr, {cert(av+8)}]; rfl',
                f'  binblocks := fun bb hb => by', f'    rw [binblocksAddr, avAddr, {cert(av+8)}] at hb',
                '    cases hb', '    exact binblocks',
                '  live := fun _ h => nomatch h', '  exact := fun _ h => nomatch h', '',
                '/-- All in-use chunks at their checked usable sizes; not a request-size guess. -/',
                'def liveBlocks : List (Nat × Nat) := inuseBlocks chunks', '',
                'theorem heap : PHeapAt memory liveBlocks top brk chunks bins where',
                '  heap := (blockHeapAt_of_heapAt raw_heap (by decide)).1',
                '  brk_page := by decide', '  bb_lt := by', '    intro bb hb',
                f'    rw [binblocksAddr, avAddr, {cert(av+8)}] at hb', '    cases hb', '    decide', '',
                'theorem starts : Starts liveBlocks := starts_inuseBlocks walk', '',
                'theorem capacity : 2 * 2 ^ 24 + extendSlack ≤ heapEnd - top := by decide', '',
                'theorem foot_ram {a : Nat} (ha : vsaFoot liveBlocks a) :',
                '    Vsa.Densify.ramBase ≤ a ∧ a < Vsa.Densify.ramBase + Vsa.Densify.ramSize := by',
                '  rcases ha with globals | arena',
                '  · unfold allocGlobal InRange at globals',
                '    unfold Vsa.Densify.ramBase Vsa.Densify.ramSize', '    omega',
                '  · unfold heapStart heapEnd at arena',
                '    unfold Vsa.Densify.ramBase Vsa.Densify.ramSize', '    omega', '',
                '/-- The dense witness agrees with any zero-equivalent captured configuration. -/',
                'theorem image_on {c : Config}',
                '    (eqv : Vsa.Densify.MemEqv c.σ.mem (observedMem WhileMinImage.initialMem log)) :',
                '    ImgOn (vsaFoot liveBlocks) ((VsaIris.Inst.vsaModel startupLive).mem c) memory := by',
                '  intro a ha',
                '  have bounds := foot_ram ha',
                '  rw [memory, Vsa.Densify.fillZeroMem_ram _ bounds.1 bounds.2]',
                '  exact congrArg some (eqv a).symm', '',
                'theorem dense_agree {c : Config}',
                '    (eqv : Vsa.Densify.MemEqv c.σ.mem (observedMem WhileMinImage.initialMem log)) :',
                '    AgreeP (fun a => Vsa.Densify.ramBase ≤ a ∧',
                '      a < Vsa.Densify.ramBase + Vsa.Densify.ramSize)',
                '      memory (Vsa.Densify.fillZeroMem c.σ.mem) := by',
                '  intro a ha',
                '  rw [memory, Vsa.Densify.fillZeroMem_ram _ ha.1 ha.2,',
                '    Vsa.Densify.fillZeroMem_ram _ ha.1 ha.2]',
                '  exact congrArg some (eqv a).symm', '',
                '/-- Reuse the allocator transport, including ChunkWalk.transport_headers',
                'and BinChain.transport_links, at any densified captured configuration. -/',
                'theorem heap_transport {c : Config}',
                '    (eqv : Vsa.Densify.MemEqv c.σ.mem (observedMem WhileMinImage.initialMem log)) :',
                '    PHeapAt (Vsa.Densify.fillZeroMem c.σ.mem) liveBlocks top brk chunks bins where',
                '  heap := heap.heap.transport_read ((dense_agree eqv).mono fun _ h => foot_ram h.1)',
                '  brk_page := heap.brk_page',
                '  bb_lt := by',
                '    intro bb hb',
                '    apply heap.bb_lt bb',
                '    refine (read64_agreeP (dense_agree eqv) ?_).trans hb',
                '    intro k hk',
                '    unfold binblocksAddr avAddr Vsa.Densify.ramBase Vsa.Densify.ramSize',
                '    omega', '',
                'theorem room {c : Config}',
                '    (eqv : Vsa.Densify.MemEqv c.σ.mem (observedMem WhileMinImage.initialMem log)) :',
                '    vsaRoomB ((VsaIris.Inst.vsaModel startupLive).mem c) liveBlocks (2 ^ 24) :=',
                '  ⟨starts, Vsa.Densify.fillZeroMem c.σ.mem, top, brk, chunks, bins,',
                '    fun a ha => ((dense_agree eqv) a (foot_ram ha)).symm.trans (image_on eqv a ha),',
                '    heap_transport eqv, capacity⟩', '',
                '/-- Distinct owned extents are disjoint, derived from the certified walk. -/',
                'theorem live_disjoint {e f : Nat × Nat} (he : e ∈ liveBlocks) (hf : f ∈ liveBlocks) :',
                '    e = f ∨ e.1 + e.2 ≤ f.1 ∨ f.1 + f.2 ≤ e.1 := by',
                '  obtain ⟨c, hc, _, rfl⟩ := mem_inuseBlocks.mp he',
                '  obtain ⟨d, hd, _, rfl⟩ := mem_inuseBlocks.mp hf',
                '  have cb := walk.chunk_bounds c hc',
                '  have db := walk.chunk_bounds d hd',
                '  rcases walk.chunk_sep c hc d hd with rfl | cd | dc',
                '  · exact Or.inl rfl',
                '  · exact Or.inr (Or.inl (by dsimp; omega))',
                '  · exact Or.inr (Or.inr (by dsimp; omega))', '',
                '/-- The allocator reentrancy pointer is untouched in this capture. -/',
                'theorem impure (i : Nat) (hi : i < 8) :',
                '    WhileMin.cut.σ.mem[allocatorImpureAddr + i]? = some (allocatorImpureByte i) := by',
                '  have untouched : ∀ j : Fin 8, runs.fin (allocatorImpureAddr + j.val) = none := by decide +kernel',
                '  rw [show WhileMin.cut.σ.mem = observedMem WhileMinImage.initialMem log from WhileMin.memory_eq,',
                '    observedMem_get logOk]',
                '  unfold logView',
                '  rw [untouched ⟨i, hi⟩]',
                '  exact allocator_initial_impure i (by omega) hi', '',
                '/-- Complete captured readiness, with the actual shape and 16 MiB of credits. -/',
                'theorem ready {c : Config}',
                '    (eqv : Vsa.Densify.MemEqv c.σ.mem (observedMem WhileMinImage.initialMem log)) :',
                '    HeapReady liveBlocks (2 ^ 24) c where',
                '  room := room eqv',
                '  text := by',
                '    have loaded := allocator_loaded (WhileMinImage.executable WhileMin.memory_eq) impure',
                '    intro pin hp',
                '    exact (eqv pin.1).trans ((WhileMin.memory_equiv pin.1).symm.trans',
                '      (lpin_of_present (loaded pin hp)))',
                '  domainWord := WhileMinRuntime.read_domain eqv',
                '  poolZero := WhileMinRuntime.poolZero eqv', '',
                'theorem cut_ready : HeapReady liveBlocks (2 ^ 24) (Vsa.Densify.fillZero WhileMin.cut) :=',
                '  ready ((Vsa.Densify.memEqv_fillZeroMem WhileMin.cut.σ.mem).symm.trans WhileMin.memory_equiv)', '',
                'theorem cut_heapReady : WhileMin.cut_heapReady_Statement :=',
                '  ⟨liveBlocks, 2 ^ 24, Nat.le_refl _, cut_ready⟩', '',
                'end OCaml.Vm.Boot.WhileMinAllocator', ''])
    return '\n'.join(out), len(chunks), sum(bool(qs) for qs in bins.values())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text, chunks, bins = generate()
    path = ROOT / 'OCaml/Vm/Boot/WhileMinAllocator.lean'
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('cut allocator certificate drift')
    else:
        path.write_text(text)
    names = ['OCaml.Vm.Boot.WhileMinAllocator.' + n
             for n in re.findall(r'^theorem (\w+)', text, re.M)]
    names += ['OCaml.Vm.Boot.WhileMinRuntime.read_pool_' + str(i) for i in range(8)]
    names += ['OCaml.Vm.Boot.WhileMinRuntime.poolZero',
              'OCaml.Vm.Boot.WhileMinImage.observed_bytes_view',
              'OCaml.Vm.Gc.whileMin_allocator_covers',
              'OCaml.Vm.Gc.whileMin_allocator_exact',
              'OCaml.Vm.Boot.WhileMin.cut_heapReady_covers',
              'OCaml.Vm.Gc.whileMin_libHeap']
    begin = '-- BEGIN GENERATED cut allocator audits (scripts/gen_boot_cut_allocator.py)'
    end = '-- END GENERATED cut allocator audits'
    block = begin + '\n' + '\n'.join('#print axioms ' + n for n in names) + '\n' + end
    audit_path = ROOT / 'OCaml/Audit.lean'
    audit = audit_path.read_text()
    if begin in audit:
        expected = audit[:audit.index(begin)] + block + audit[audit.index(end)+len(end):]
    else:
        expected = audit.rstrip() + '\n\n' + block + '\n'
    if args.check:
        if audit != expected:
            raise SystemExit('cut allocator audit registration drift')
    elif audit != expected:
        audit_path.write_text(expected)
    focused_path = ROOT / 'OCaml/Vm/Boot/WhileMinAllocatorAudit.lean'
    focused = ('import OCaml.Vm.Sim.F1Headline\n\n'
               '-- GENERATED by scripts/gen_boot_cut_allocator.py. Focused standard-axiom audit.\n'
               + '\n'.join('#print axioms ' + n for n in names + [
                   'OCaml.Vm.Gc.whileMin_loaded_f1', 'OCaml.Vm.Gc.whileMin_loaded_f1_fillZero',
                   'OCaml.Vm.Sim.whileMin_halts_f1']) + '\n')
    if args.check:
        if not focused_path.exists() or focused_path.read_text() != focused:
            raise SystemExit('cut allocator focused audit drift')
    else:
        focused_path.write_text(focused)
    print(f'Cut allocator: {chunks} chunks, {bins} nonempty bins; bounded kernel certificates')
