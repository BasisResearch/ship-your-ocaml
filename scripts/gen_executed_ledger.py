#!/usr/bin/env python3
"""Emit the finite execution census as Lean data (measurement, not a proof of execution)."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / 'OCaml/Programs/OcamlcExecuted.lean'

def render():
    d = json.loads((ROOT / 'results/ocamlc-executed.json').read_text())
    assert d['compiler_exit'] == 0
    ops = ',\n  '.join('.' + x for x in d['opcodes'])
    ps = ',\n  '.join(json.dumps(x) for x in d['primitives'])
    return f'''-- GENERATED by scripts/gen_executed_ledger.py; do not edit.
import OCaml.Bytecode.Opcode

/-! Measured successful host execution of boot/ocamlc compiling hello.ml.
Source hash and exact invocation: results/ocamlc-executed.json.
This finite census is validation evidence, not a Lean execution certificate. -/
namespace OCaml.Bytecode

def ocamlcExecutedOpcodes : List Opcode := [
  {ops}]

def ocamlcExecutedPrimitives : List String := [
  {ps}]

end OCaml.Bytecode
'''

def main():
    p = argparse.ArgumentParser(__doc__); p.add_argument('--check', action='store_true'); a = p.parse_args()
    text = render()
    if a.check:
        if not DEST.is_file() or DEST.read_text() != text:
            raise SystemExit('executed compiler ledger drift')
    else:
        DEST.write_text(text)

if __name__ == '__main__':
    main()
