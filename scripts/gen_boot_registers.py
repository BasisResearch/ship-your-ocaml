#!/usr/bin/env python3
"""Generate the complete defined-register table observed at the while_min cut.

The capture must come from bootdump with exact candidate-memory checking.
Generated proofs establish register lookup facts, not startup reachability.
"""
import argparse
import gzip
import hashlib
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--capture',type=Path)
ap.add_argument('--check',action='store_true')
args=ap.parse_args()
path=ROOT/'results/boot/while_min-registers.txt'
raw=args.capture.read_text() if args.capture else path.read_text()
cut=json.loads((ROOT/'results/boot/while_min-cut.json').read_text())
checked=re.search(r'^-- memory-checked (\d+) bytes$',raw,re.M)
meta=re.search(r'^-- steps (\d+), tick (\d+), cycles (\d+), registers (\d+), output (.*)$',raw,re.M)
assert checked and meta, 'capture lacks full-state metadata or exact memory check'
steps,tick,cycles,count=map(int,meta.group(1,2,3,4))
assert steps==cut['cut_step']
rows=list(re.finditer(r'^⟨Register\.(\w+), ',raw,re.M))
values={}
for i,m in enumerate(rows):
    row=raw[m.end():rows[i+1].start() if i+1<len(rows) else len(raw)].strip()
    assert row.endswith('⟩,')
    val=row[:-2].strip().replace('\n', ' ').replace('size_toArray := _','size_toArray := by decide +kernel')
    assert not re.search(r'\b_\b',val), 'unhandled erased field in register representation'
    values[m[1]]=val
assert len(values)==len(rows)==count
for name,val in [('PC',cut['pc'])]+[(f'x{i}',cut['gprs'][i]) for i in range(1,32)]:
    assert int(re.fullmatch(r'0x([0-9a-fA-F]+)#64',values[name])[1],16)==val
assert meta[5]=='#[]', 'unexpected console at cut'
if args.capture:
    assert not args.check
    path.write_text(raw)
out=['import Vsa.Sim.GoodState','import Std.Data.ExtDHashMap.Lemmas','',
     '/-! GENERATED by scripts/gen_boot_registers.py. Complete native register observation.',
     f'ELF SHA256: {cut["elf_sha256"]}. Startup reachability is not proved here. -/',
     'namespace OCaml.Vm.Boot.WhileMinRegisters',
     'open LeanRV64DExecutable Sail ConcurrencyInterfaceV1','',
     f'def steps : Nat := {steps}',f'def tick : Nat := {tick}',f'def cycles : Nat := {cycles}',
     f'def console : Array String := {meta[5]}',f'def memorySize : Nat := {checked[1]}','']
for name,val in values.items():
    out.append(f'def value_{name} : RegisterType .{name} := {val}')
out += ['', 'def assignments : List ((r : Register) × RegisterType r) := [',
        ',\n'.join(f'  ⟨Register.{name}, value_{name}⟩' for name in values)+']','',
        'theorem assignments_distinct : assignments.Pairwise (fun a b => (a.1 == b.1) = false) := by',
        '  decide +kernel','',
        'def registers : Std.ExtDHashMap Register RegisterType := Std.ExtDHashMap.ofList assignments','',
        'theorem register_get {r : Register} {v : RegisterType r}',
        '    (h : ⟨r, v⟩ ∈ assignments) : registers.get? r = some v := by',
        '  simpa [registers] using Std.ExtDHashMap.get?_ofList_of_mem',
        '    (k := r) (k\' := r) (by simp) assignments_distinct h','']
for i,name in enumerate(values):
    out += [f'theorem get_{name} : registers.get? .{name} = some value_{name} :=',
            f'  register_get (List.mem_of_getElem? (show assignments[{i}]? = some ⟨Register.{name}, value_{name}⟩ from rfl))','']
good=(ROOT/'Vsa/Sim/GoodState.lean').read_text().split('structure GoodState')[1].split('/-- The PC')[0]
fields=list(re.finditer(r'^  (\w+)\s*:',good,re.M))
out += ['def state (m : Std.ExtHashMap Nat (BitVec 8)) : Vsa.Machine.MState :=',
        '  ⟨registers, (), m, (), cycles, console⟩','',
        'theorem good_state (m : Std.ExtHashMap Nat (BitVec 8)) : Vsa.Sim.GoodState (state m) where']
for i,field in enumerate(fields):
    name=field[1]
    body=good[field.end():fields[i+1].start() if i+1<len(fields) else len(good)]
    assert name in values
    proof=f'⟨_, get_{name}⟩' if '∃' in body else f'get_{name}'
    out.append(f'  {name} := {proof}')
out.append('')
out += ['end OCaml.Vm.Boot.WhileMinRegisters','']
dest=ROOT/'OCaml/Vm/Boot/WhileMinRegisterData.lean'
text='\n'.join(out)
if args.check:
    if not dest.exists() or dest.read_text()!=text:raise SystemExit('boot register data drift')
elif not dest.exists() or dest.read_text()!=text:dest.write_text(text)
print(f'Registers: {count} defined, cycles {cycles}, exact memory check {checked[1]} bytes')

initial_raw=gzip.decompress((ROOT/'results/boot/while_min-initial.json.gz').read_bytes())
initial=json.loads(initial_raw)
assert initial['elf_sha256']==cut['elf_sha256']
store_raw=gzip.decompress((ROOT/'results/boot/while_min-stores.jsonl.gz').read_bytes())
expected={a+i:b for a,body in initial['pieces'] for i,b in enumerate(body)}
for _,a,n,v in map(json.loads,store_raw.splitlines()):
    for i in range(n):expected[a+i]=(v>>(8*i))&255
assert int(checked[1])==len(expected)
report={
    'status':'native exact full-state capture; kernel Loaded theorem is separate from startup reachability',
    'elf_sha256':cut['elf_sha256'], 'cut_step':steps, 'tick':tick, 'cycles':cycles,
    'defined_registers':count, 'memory_bytes':len(expected),
    'register_capture_sha256':hashlib.sha256(raw.encode()).hexdigest(),
    'initial_capture_sha256':hashlib.sha256(initial_raw).hexdigest(),
    'store_trace_sha256':hashlib.sha256(store_raw).hexdigest(),
    'expected_memory_sha256':hashlib.sha256(b''.join(a.to_bytes(8,'little')+bytes([b])
        for a,b in sorted(expected.items()))).hexdigest(),
}
report_path=ROOT/'results/boot/while_min-snapshot.json'
report_text=json.dumps(report,indent=2)+'\n'
if args.check:
    if not report_path.exists() or report_path.read_text()!=report_text:raise SystemExit('boot snapshot report drift')
elif not report_path.exists() or report_path.read_text()!=report_text:report_path.write_text(report_text)
