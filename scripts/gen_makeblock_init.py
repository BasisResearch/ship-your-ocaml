#!/usr/bin/env python3
"""Compose both generic MAKEBLOCK initializers with one represented contract."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render(kind):
    stem=kind.title(); more=kind=='more'
    spec=json.loads((ROOT/f'scripts/syi/segments/makeblock_init_{kind}.json').read_text())
    regs=[p['reg'] for p in spec['pins']]
    vals={'x8':'(sign_extend (m := 64) tag)','x23':'(BitVec.ofNat 64 count)','x14':'(BitVec.ofNat 64 (a - 8))','x21':'accu','x9':'(BitVec.ofNat 64 sp)'}
    proofs={'x8':'front.tagReg','x23':'front.countReg','x14':'front.header','x21':'(front.frame.frame Register.x21 (by decide)).trans (represented_register h.accu value)','x9':'(front.frame.frame Register.x9 (by decide)).trans h.spReg'}
    pins=',\n       '.join(f'⟨Register.{r}, {vals[r]}⟩' for r in regs)
    pinproof=',\n       '.join(proofs[r] for r in regs)
    args=' '.join(vals[r] for r in regs)
    for st in spec['steps']:
        r=st.get('rd')
        if r:regs=[r]+[x for x in regs if x!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    guard='''    unfold zopz0zI_u
    simp only [Sail.BitVec.toNatInt, BitVec.toNat_ofNat, Nat.mod_eq_of_lt (show count < 2^64 by have small := space.small; omega)]
    exact decide_eq_true (Int.ofNat_lt.mpr branch)''' if more else '''    subst count
    decide'''
    cpregs=f'''  · intro _
    exact ⟨{get('x15')}, {get('x14')}, {get('x12')}, {get('x10')}⟩''' if more else '''  · intro impossible
    omega'''
    return f'''-- GENERATED by scripts/gen_makeblock_init.py; do not edit.
import OCaml.Vm.Sim.MakeblockInitInput
import OCaml.Vm.Sim.MakeblockInit{stem}Segment
import OCaml.Vm.Sim.MakeblockInit{stem}Pins
import OCaml.Vm.Sim.MakeblockInit{stem}Layout
import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.StackPush

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The actual {kind} initializer writes the represented header and first field. -/
theorem makeblock_initialize_{kind} {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c d : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high count a domain limit : Nat}} {{tag : BitVec 32}} {{accu : BitVec 64}}
    (h : ArmInput L P s .MAKEBLOCK c pl cp sp high) (value : valWord pl s.accu = some accu)
    (nonnegative : 0 ≤ tag.toInt) (branch : {'1 < count' if more else 'count = 1'})
    (space : MakeblockInput P s c pl cp sp high count tag.toInt.toNat a domain limit accu)
    (front : MakeblockReserved c pl s.pc count a domain tag d) :
    ∃ nb after, StepsN nb d after ∧ MakeblockInitialized c pl s.pc sp count tag.toInt.toNat a domain accu after := by
  have parts := makeblock_log_parts c sp count tag.toInt.toNat a domain accu space.positive
  have setupSub : (makeblockSetupLog domain a count tag.toInt.toNat accu).Sublist
      (makeblockLog c sp count tag.toInt.toNat a domain accu) := by
    rw [← parts]; exact List.sublist_append_left _ _
  have setupImage := imageOutside_sublist setupSub space.image
  have headerMember : (a - 8, 8, blockHeader count tag.toInt.toNat) ∈ makeblockSetupLog domain a count tag.toInt.toNat accu := by
    simp [makeblockSetupLog]
  have fieldMember : (a, 8, accu) ∈ makeblockSetupLog domain a count tag.toInt.toNat accu := by
    simp [makeblockSetupLog]
  have domainRead : RamReadAt Layout.sym_Caml_state 8 := ⟨by decide, by decide, by decide⟩
  have headerNat := space.headerWrite.read.toNat
  have youngRead := space.youngWrite.read
  have fieldWrite : RamWriteAt a 8 := by simpa only [Nat.mul_zero, Nat.add_zero] using space.fieldWrites 0 space.positive
  have youngAddress : BitVec.ofNat 64 domain + sign_extend (m := 64) (0x008#12) =
      BitVec.ofNat 64 (domain + Layout.off_young_ptr) := by rw [BitVec.ofNat_add]; rfl
  have valueAddress : BitVec.ofNat 64 (a - 8) + sign_extend (m := 64) (0x008#12) = BitVec.ofNat 64 a := by
    change BitVec.ofNat 64 (a - 8) + BitVec.ofNat 64 8 = _
    rw [← BitVec.ofNat_add]; congr 1; have room := space.room; omega
  have copyAddress : BitVec.ofNat 64 (a - 8) + sign_extend (m := 64) (0x010#12) = BitVec.ofNat 64 (a + 8) := by
    change BitVec.ofNat 64 (a - 8) + BitVec.ofNat 64 16 = _
    rw [← BitVec.ofNat_add]; congr 1; have room := space.room; omega
  have headerValue : Sail.shift_bits_left (BitVec.ofNat 64 count) (Sail.BitVec.extractLsb (0x0a#6) 5 0) +
      Sail.shift_bits_right (Sail.shift_bits_left (sign_extend (m := 64) tag) (Sail.BitVec.extractLsb (0x20#6) 5 0))
        (Sail.BitVec.extractLsb (0x20#6) 5 0) = blockHeader count tag.toInt.toNat := by
    rw [makeblock_tag_word tag nonnegative space.tagBound]; rfl
  have bytes : Sail.shift_bits_left (BitVec.ofNat 64 count) (Sail.BitVec.extractLsb (0x03#6) 5 0) +
      sign_extend (m := 64) (0xff8#12) = BitVec.ofNat 64 (8 * (count - 1)) := by
    change (BitVec.ofNat 64 count <<< (3 : Nat)) + _ = _
    rw [nat_shift_word, stack_decrement (n := 8) (by have positive := space.positive; omega) (by decide) (by decide)]
    congr 1
    omega
  have sourceEnd : BitVec.ofNat 64 sp + BitVec.ofNat 64 (8 * (count - 1)) = BitVec.ofNat 64 (sp + 8 * (count - 1)) :=
    (BitVec.ofNat_add _ _).symm
  have guard : zopz0zI_u (1#64) (BitVec.ofNat 64 count) = {'true' if more else 'false'} := by
{guard}
  obtain ⟨headerMemory, headerWritten⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 d.σ.mem (a - 8) (sdData_val (blockHeader count tag.toInt.toNat)) := ⟨_, rfl⟩
  have headerLog : headerMemory = writeLog c.σ.mem
      (grabReserveLog domain a ++ [(a - 8, 8, blockHeader count tag.toInt.toNat)]) := by
    rw [headerWritten, front.memory, writeLog_append]; rfl
  have headerSub : (grabReserveLog domain a ++ [(a - 8, 8, blockHeader count tag.toInt.toNat)]).Sublist
      (makeblockLog c sp count tag.toInt.toNat a domain accu) := by
    apply List.Sublist.trans _ setupSub
    exact List.sublist_append_left _ _
  have domainOutside := outLRange_sublist headerSub space.payload.domain
  have domainValue := (word_read_writeLog_out domainOutside headerLog).trans space.domainValue
  have youngWord : bytesT headerMemory (domain + Layout.off_young_ptr) 8 = BitVec.ofNat 64 (a - 8) := by
    rw [headerLog]
    exact word_writeLog_at c.σ.mem _ 0 _ _ rfl space.headerYoungOutside
  have youngValue : sign_extend (m := 64) (bytesT8 headerMemory (domain + Layout.off_young_ptr)) =
      BitVec.ofNat 64 (a - 8) := by
    simpa only [bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq] using youngWord
  obtain ⟨nextMemory, written⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 headerMemory a (sdData_val accu) := ⟨_, rfl⟩
  have bp : SegSt (0x80002688#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.CamlMakeblockInit{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨front.good, front.pcAt, ⟨{pinproof}, trivial⟩,
      front.good.minstret, front.tick, makeblock_init_{kind}_loaded front.image, rfl, rfl⟩
  have run := tr_makeblock_init_{kind} {args} d.σ.mem d.σ
  simp only [makeblock_init_{kind}_domain, show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, headerNat, domainRead.toNat, headerValue] at run
  have first := run space.headerWrite.lower space.headerWrite.upper space.headerWrite.htif space.headerWrite.aligned
    (image_entry_code setupImage headerMember (by decide) (by decide)) headerMemory headerWritten
    domainRead.lower domainRead.upper domainRead.htif (BitVec.ofNat 64 domain) domainValue.symm
  simp only [youngAddress, youngRead.toNat] at first
  have second := first youngRead.lower youngRead.upper youngRead.htif (BitVec.ofNat 64 (a - 8)) youngValue.symm
  simp only [valueAddress, fieldWrite.read.toNat, copyAddress, bytes, sourceEnd,
    show sign_extend (m := 64) (0x001#12) = 1#64 from by decide, BitVec.zero_add] at second
  obtain ⟨nb, after, _, steps, post⟩ := second fieldWrite.lower fieldWrite.upper fieldWrite.htif fieldWrite.aligned
    (image_entry_code setupImage fieldMember (by decide) (by decide)) nextMemory written guard d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := makeblockInitWrites) (by decide)
  have fullMemory : after.σ.mem = writeLog c.σ.mem (makeblockSetupLog domain a count tag.toInt.toNat accu) := by
    rw [memory, written, headerWritten, front.memory, makeblockSetupLog, writeLog_append]; rfl
  refine ⟨nb, after, steps, post.good, post.tick, image_of_writeLog h.dispatch.image setupImage fullMemory,
    ?_, {get('x11')}, ?_, ?_, ?_, fullMemory,
    (front.frame.trans frame).widenChecked (allowed := makeblockSetupWrites) (by decide)⟩
  · simp only [{'branch, ite_true' if more else 'branch, Nat.lt_irrefl, ite_false'}]; exact post.pcAt
  · exact (frame.frame Register.x9 (by decide)).trans ((front.frame.frame Register.x9 (by decide)).trans h.spReg)
  · exact (frame.frame Register.x26 (by decide)).trans front.nextCode
{cpregs}

end OCaml.Vm.Sim
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for kind in ['more','one']:
        path=ROOT/f'OCaml/Vm/Sim/MakeblockInitialize{kind.title()}.lean';out=render(kind)
        if args.check:
            if not path.exists() or path.read_text()!=out:raise SystemExit(f'drift: {path}')
        else:path.write_text(out)
    print('Generic MAKEBLOCK initializers current')
