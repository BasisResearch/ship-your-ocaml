#!/usr/bin/env python3
"""Pinned nonlocal-jump functions through gen_fn's whole-function block emitter."""
import argparse
import contextlib
import io
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from census import ROOT, TOOLS, disasm
from gen_arm_pilot import code, image_projection
from gen_ocaml_image import sections
sys.path.insert(0, str(ROOT / 'scripts/syi'))
import gen_fn
from ocaml_block_certificates import emit_call


def outputs():
    functions = disasm(ROOT / 'c/ocamlrun-riscv-htif.elf')
    text_base = sections((ROOT / 'c/ocamlrun-riscv-htif.elf').read_bytes())['.text'][0]
    result = {}
    audit_imports = []
    audit_facts = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        dump = tmp / 'image.dis'
        dump.write_text(subprocess.run([TOOLS + 'objdump', '-d', str(ROOT / 'c/ocamlrun-riscv-htif.elf')],
                                      capture_output=True, text=True, check=True).stdout)
        index = tmp / 'decode.tsv'
        index.write_text('\n'.join(f'{w}\tVsa.Sim.ElfDecode.{p.stem}'
            for p in sorted((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean'))
            for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)) + '\n')
        for fn, stem in [('longjmp', 'Longjmp'), ('check_global_data', 'CheckGlobalData'), ('caml_process_pending_actions_with_root_exn', 'PendingRoot'), ('caml_raise', 'RaiseRuntime'), ('caml_raise_zero_divide', 'RaiseZeroDivide')]:
            instructions = functions[fn]['insts']
            code_name = code.lean_ident(fn)
            code_name = code_name[0].upper() + code_name[1:]
            result[ROOT / f'Vsa/Sim/Code/{code_name}.lean'] = code.render(fn, [(a, w) for a, w, _, _ in instructions]).replace(
                'generated by experiments/gen_code_lemmas.py', 'GENERATED by scripts/gen_nonlocal.py')
            result[ROOT / f'OCaml/Vm/Sim/{stem}Image.lean'] = image_projection(
                instructions, f'Vsa.Sim.Code.{code_name}Loaded', f'Vsa.Sim.Code.{code_name}',
                [f'Vsa.Sim.Code.{fn}Chunk{i}' for i in range((len(instructions) + code.CHUNK - 1) // code.CHUNK)],
                f'{fn}_loaded', text_base).replace('GENERATED by scripts/gen_arm_pilot.py.', 'GENERATED by scripts/gen_nonlocal.py.')
            words = {w for _, w, _, _ in instructions}
            imports = '\n'.join('import Vsa.Sim.ElfDecode.' + p.stem
                for p in sorted((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean'))
                if any(int(w, 16) in words for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)))
            row = tmp / f'{stem}.lean'
            with contextlib.redirect_stdout(io.StringIO()):
                blocks, _ = gen_fn.emit_fn(fn, instructions[0][0], str(row), verify=False,
                               disasm_path=str(dump), decode_index=str(index))
            result[ROOT / f'OCaml/Vm/Sim/{stem}Rows.lean'] = (imports + '\n' + row.read_text()).replace('set_option maxRecDepth 100000\n', '').replace(
                'GENERATED by `scripts/gen_fn.py', 'GENERATED by scripts/gen_nonlocal.py via `scripts/syi/gen_fn.py').replace(
                'from `experiments/disasm.txt`', 'from the pinned runtime ELF')
            calls = [b for b in blocks if b.kind == 'jal' and b.callee in functions]
            if calls:
                E = gen_fn.lib.Emitter()
                E(f'import OCaml.Vm.Sim.{stem}Image', 'import OCaml.Vm.Primitives.Call', imports,
                  '', '/-! GENERATED by scripts/gen_nonlocal.py. Pinned direct-call seams. -/',
                  'namespace OCaml.Vm.Sim', 'open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives', '')
                for b in calls:
                    name = f'{fn}_{b.term.addr:08x}'
                    emit_call(E, fn, b, name, functions, gen_fn.lib, loaded=f'{fn}_loaded')
                    audit_facts += [f'#print axioms OCaml.Vm.Sim.{name}_call_{suffix}'
                                    for suffix in ['shape', 'decode', 'target', 'pins']]
                E('end OCaml.Vm.Sim', '')
                result[ROOT / f'OCaml/Vm/Sim/{stem}Calls.lean'] = '\n'.join(E.lines)
                audit_imports.append(f'import OCaml.Vm.Sim.{stem}Calls')
            if fn != 'longjmp':
                audit_imports += [f'import OCaml.Vm.Sim.{stem}Rows', f'import OCaml.Vm.Sim.{stem}Image']
                audit_facts += ['#print axioms Vsa.Sim.' + name for name in re.findall(r'^#print axioms (\w+)$', row.read_text(), re.M)]
                audit_facts.append(f'#print axioms OCaml.Vm.Sim.{fn}_loaded')
                continue
            row_name = f'{fn}X{instructions[0][0] & 0xffff:04x}'
            result[ROOT / f'OCaml/Vm/Sim/{stem}Structure.lean'] = f'''import OCaml.Vm.Sim.{stem}Rows
import OCaml.Vm.Primitives.Control

/-! GENERATED by scripts/gen_nonlocal.py. Structural whole-function certificates. -/
namespace OCaml.Vm.Sim
open Vsa.Sim

/-- All source-register and PC transitions of the generated function are valid. -/
theorem {fn}_shape : ChainOK ({hex(instructions[0][0])}#64) [10, 11] {row_name}Seg := by decide

/-- The nonlocal restoration reads memory without writing it. -/
theorem {fn}_readonly : OCaml.Vm.Primitives.ReadOnlyBody ({row_name}Seg[0]).body := by unfold OCaml.Vm.Primitives.ReadOnlyBody; decide

/-- seqz is the unsigned immediate comparison required by the native return-value rule. -/
theorem {fn}_seqz_decode : decodeM (0x0015b513#32) = some (.slti true, 10, 11, 0, 1#12) := by decide

end OCaml.Vm.Sim
'''
    result[ROOT / 'OCaml/Vm/Sim/NonlocalAudit.lean'] = '\n'.join(audit_imports + ['', '/-! GENERATED by scripts/gen_nonlocal.py. Runtime raising-helper audit. -/', ''] + audit_facts + [''])
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Nonlocal-jump artifact drift: {path}')
        else:
            path.write_text(content)
    print('Nonlocal-jump artifacts current')
