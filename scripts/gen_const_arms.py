#!/usr/bin/env python3
"""Generate represented CONST0..CONST3 bridges over their checked segments."""
import argparse
import json
from pathlib import Path
from census import ROOT


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    for n in range(4):
        op = f'CONST{n}'
        stem = f'Const{n}'
        lower = op.lower()
        entry = int(arms[op]['addr'], 16)
        lines = f'''import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_const_arms.py. Represented immediate arm. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} restores the represented VM and platform under explicit dispatch
readiness. The machine body is the census-generated segment. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high) :
    ∃ c', Plus c c' ∧ Running L P {{s with pc := s.pc + 1, accu := .int {n}}} c' := by
  apply immediate_arm stable h
  intro d dp
  have bp : SegSt (0x{entry:x}#64)
      [⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨dp.nextCode, trivial⟩, dp.good.minstret, dp.tick,
      {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  obtain ⟨nb, after, _, hb, post⟩ := tr_{lower} _ d.σ.mem d.σ d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
  · have hp : gpr after Layout.reg_pc = some
        ((BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
      BitVec.add_zero, codePc_succ] using hp
  · exact PinsHold.get post.pins ⟨0, by simp⟩

end OCaml.Vm.Sim
'''
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = lines
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'constant arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Constant arm bridges current')
