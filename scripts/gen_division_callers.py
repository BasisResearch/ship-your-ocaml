#!/usr/bin/env python3
"""Represented DIVINT/MODINT caller boundaries, sharing signed libgcc summaries."""
import argparse
import json
import sys
from gen_arm_pilot import ROOT, FAMILIES
sys.path.insert(0, str(ROOT / 'scripts/syi'))
from gen_segment import SegmentEmitter


def outputs():
    result = {}
    for opcode, stem, kind in [('DIVINT', 'Divint', 'quotient'), ('MODINT', 'Modint', 'remainder')]:
        lower = opcode.lower()
        specs = {}
        for part in ('prefix', 'suffix'):
            spec = json.loads((ROOT / f'scripts/syi/segments/{lower}_{part}.json').read_text())
            em = SegmentEmitter(spec)
            em.emit()
            specs[part] = (spec, {r: i for i, (r, _) in enumerate(em.pins)})
        pre, pp = specs['prefix']
        suf, sp = specs['suffix']
        guard = ('((tag64 y).sshiftRight 1 == 0#64) = false' if opcode == 'DIVINT' else
                 '((tag64 y).sshiftRight 1 != 0#64) = true')
        text = f'''import OCaml.Vm.Sim.DivisionCall
import OCaml.Vm.Sim.BinarySemantics
import OCaml.Vm.Sim.{stem}PrefixSegment
import OCaml.Vm.Sim.{stem}PrefixPins
import OCaml.Vm.Sim.{stem}SuffixSegment
import OCaml.Vm.Sim.{stem}SuffixPins

/-! GENERATED by scripts/gen_division_callers.py. Represented binary call boundaries. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- The actual nonzero caller prefix establishes the signed library interface. -/
theorem {lower}_setup {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c d : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{x y : BitVec 63}} {{rest : List Val}}
    (h : ArmInput L P s .{opcode} c pl cp sp high)
    (accu : s.accu = .int x) (stack : s.stack = .int y :: rest) (nonzero : y ≠ 0)
    (read : ReadWindow (BitVec.ofNat 64 sp) 8)
    (dp : DispatchPost c .{opcode} (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)) d) :
    ∃ n after, StepsN n d after ∧ DivisionCall .{kind} d pl (s.pc + 1) sp x y after := by
  have source := represented_register h.accu (by rw [accu]; rfl : valWord pl s.accu = some (tag64 x))
  have slot := stack_integer_word h.toVmReprAt stack
  have selected : s.stack[0]? = some (.int y) := by simp only [stack, List.getElem?_cons_zero]
  have natAddress : (BitVec.ofNat 64 sp).toNat = sp := by
    simpa only [Nat.mul_zero, Nat.add_zero] using stack_slot_nat h.toVmReprAt selected
  have loaded : sign_extend (m := 64) (bytesT8 d.σ.mem (BitVec.ofNat 64 sp).toNat) = tag64 y := by
    simpa only [natAddress, dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using slot
  have guard : {guard} := by simpa using division_unbox_nonzero nonzero
  have bp : SegSt ({pre['entry']}#64) [⟨Register.x9, BitVec.ofNat 64 sp⟩, ⟨Register.x21, tag64 x⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}PrefixLoaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨(dp.frame.frame Register.x9 (by decide)).trans h.spReg,
      (dp.frame.frame Register.x21 (by decide)).trans source, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_prefix_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have native := tr_{lower}_prefix (BitVec.ofNat 64 sp) (tag64 x) d.σ.mem d.σ
  simp only [show sign_extend (m := 64) (0x000#12) = 0#64 from rfl, BitVec.add_zero] at native
  obtain ⟨n, after, _, run, post⟩ := native read.lower read.upper read.htif (tag64 y) (by rw [loaded]) guard d bp
  obtain ⟨_, memory, frame⟩ := post.extra
  have image := image_of_writeLog (log := []) (dp.image h.dispatch.image) ⟨trivial, trivial⟩ memory
  refine ⟨n, after, run, ?_⟩
  refine {{
    good := post.good, image := image, minstret := post.good.minstret,
    raReg := PinsHold.get post.pins ⟨{pp['x1']}, by simp⟩, aligned := by decide, tick := post.tick,
    left := PinsHold.get post.pins ⟨{pp['x10']}, by simp⟩, right := PinsHold.get post.pins ⟨{pp['x11']}, by simp⟩,
    nonzero := division_unbox_nonzero nonzero,
    nextCode := ?_, stack := PinsHold.get post.pins ⟨{pp['x9']}, by simp⟩,
    memory := memory, output := frame.out,
    preserved := fun r hr => frame.frame r (by revert r; decide), calleePC := post.pcAt }}
  · have observed : gpr after 23 = some (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) :=
      (frame.frame Register.x23 (by decide)).trans dp.nextCode
    simpa only [codePc_succ] using observed

/-- The generated suffix consumes the divisor and retags the proved signed result. -/
theorem {lower}_return {{before : Config}} {{pl : Place}} {{pc sp : Nat}} {{x y : BitVec 63}} :
    Vsa.Logic.Triple (DivisionReturn .{kind} before pl pc sp x y)
      (ConsumePost before pl pc (sp + 8) (divisionResult .{kind} x y)) := by
  intro c h
  let value := divisionResult .{kind} ((tag64 x).sshiftRight 1) ((tag64 y).sshiftRight 1)
  have bp : SegSt ({suf['entry']}#64)
      [⟨Register.x10, value⟩, ⟨Register.x9, BitVec.ofNat 64 sp⟩, ⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * pc)⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}SuffixLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, h.returnPC, ⟨h.result, h.stack, h.nextCode, trivial⟩,
      h.minstret, h.tick, {lower}_suffix_loaded h.image, rfl, rfl⟩
  obtain ⟨_, after, _, run, post⟩ := tr_{lower}_suffix value (BitVec.ofNat 64 sp)
    (BitVec.ofNat 64 (pl.codeBase + 4 * pc)) c.σ.mem c.σ c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  refine ⟨after, run.toSteps, post.good, post.pcAt, ?_, ?_, ?_,
    memory.trans h.memory, frame.out.trans h.output,
    fun r hr => (frame.frame r (by revert r; decide)).trans (h.preserved r hr)⟩
  · have observed : gpr after Layout.reg_pc = some (BitVec.ofNat 64 (pl.codeBase + 4 * pc) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨{sp['x8']}, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from rfl, BitVec.add_zero] using observed
  · have observed : gpr after Layout.reg_sp = some (BitVec.ofNat 64 sp + sign_extend (m := 64) (0x008#12)) :=
      PinsHold.get post.pins ⟨{sp['x9']}, by simp⟩
    simpa only [show sign_extend (m := 64) (0x008#12) = 8#64 from rfl, BitVec.ofNat_add] using observed
  · have observed : gpr after Layout.reg_accu = some ((value <<< 1) + 1#64) :=
      PinsHold.get post.pins ⟨{sp['x21']}, by simp⟩
    simpa only [value, tag_division_native] using observed

end OCaml.Vm.Sim
'''
        result[ROOT / f'OCaml/Vm/Sim/{stem}Call.lean'] = text
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'division caller drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
    print('Division caller adapters current')
