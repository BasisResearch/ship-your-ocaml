#!/usr/bin/env python3
"""Adapt generated libgcc sign-normalization cuts to one unsigned-core interface."""
import argparse
import json
from pathlib import Path
import re
import sys
from gen_arm_pilot import ROOT, FAMILIES
sys.path.insert(0, str(ROOT / 'scripts/syi'))
from gen_segment import SegmentEmitter


def outputs():
    result = {}
    for family in FAMILIES:
        if not re.fullmatch(r'S(DIV|MOD)_(POS|NEG)_(POS|NEG)', family):
            continue
        stem = FAMILIES[family][0]
        lower = family.lower()
        kind = 'quotient' if family.startswith('SDIV_') else 'remainder'
        _, sx, sy = family.split('_')
        hx, hy = str(sx == 'NEG').lower(), str(sy == 'NEG').lower()
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
        emitter = SegmentEmitter(spec)
        emitter.emit()
        positions = {r: i for i, (r, _) in enumerate(emitter.pins)}
        values = {'v10': 'x', 'v11': 'y', 'v1': 'ra'}
        input_fields = {'x10': 'input.left', 'x11': 'input.right', 'x1': 'input.raReg'}
        pins = ', '.join(f'⟨Register.{p["reg"]}, {values[p["val"]]}⟩' for p in spec['pins'])
        proofs = ', '.join(input_fields[p['reg']] for p in spec['pins'])
        args = ' '.join(values[v] for v in re.findall(r'v\d+', spec['params'][0]))
        guard_lines, guards = [], []
        for param in spec['params'][3:]:
            name, expression = param[1:-1].split(' : ', 1)
            expression = re.sub(r'\bv\d+\b', lambda m: values[m[0]], expression)
            guards.append(name)
            if 'zopz0zI_s (0#64) y' in expression:
                proof = ('by change (0#64).slt y = true; exact division_positive_guard input.nonzero hy'
                         if expression.endswith('true') else
                         'by change decide ((0 : Int) < y.toInt) = false; simp only [decide_eq_false_iff_not]; '
                         'have negative := BitVec.toInt_neg_of_msb_true hy; omega')
            elif 'zopz0zKzJ_s x' in expression:
                proof = ('by change (0#64).sle x = _; '
                         'simp only [BitVec.zero_sle_eq_not_msb, hx, Bool.not_false, Bool.not_true]')
            else:
                var = 'x' if 'zopz0zI_s x' in expression else 'y'
                hyp = 'hx' if var == 'x' else 'hy'
                proof = f'by change {var}.slt (0#64) = _; simpa only [BitVec.slt_zero_eq_msb] using {hyp}'
            guard_lines.append(f'  have {name} : {expression} := {proof}')
        simp = ('divisionReturn, divisionNegative, divisionMagnitude, hx, hy, Bool.false_eq_true, '
                'Bool.true_eq_false, Bool.bne_false, Bool.bne_true, '
                'ite_true, ite_false, Bool.not_false, Bool.not_true, '
                'show Functions.sign_extend (m := 64) (0x000#12) = 0#64 from rfl, '
                'BitVec.add_zero, BitVec.zero_sub')
        def observed(reg):
            if reg in positions:
                return f'PinsHold.get post.pins ⟨{positions[reg]}, by simp⟩'
            return f'(rawFrame.frame Register.{reg} (by decide)).trans {input_fields[reg]}'
        texts = [f'import OCaml.Vm.Sim.{stem}Segment', f'import OCaml.Vm.Sim.{stem}Pins',
                 'import OCaml.Vm.Sim.SignedDivisionPrepare', '',
                 '/-! GENERATED by scripts/gen_signed_division.py. Native normalization adapter. -/',
                 'namespace OCaml.Vm.Sim', 'set_option autoImplicit false',
                 'open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions', '',
                 f'theorem {lower}_prepare {{c : Config}} {{x y ra : BitVec 64}}',
                 '    (input : SignedDivisionInput x y ra c)',
                 f'    (pc : pcOf c = some ({spec["entry"]}#64)) (hx : x.msb = {hx}) (hy : y.msb = {hy}) :',
                 f'    ∃ n after, StepsN n c after ∧ SignedDivisionPrepared .{kind} c x y ra after := by',
                 *guard_lines,
                 f'  have bp : SegSt ({spec["entry"]}#64) [{pins}]',
                 f'      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=',
                 f'    ⟨input.good, pc, ⟨{proofs}, trivial⟩, input.minstret, input.tick, {lower}_loaded input.image, rfl, rfl⟩',
                 f'  obtain ⟨n, after, _, run, post⟩ := tr_{lower} {args} c.σ.mem c.σ {" ".join(guards)} c bp',
                 '  obtain ⟨_, memory, rawFrame⟩ := post.extra',
                 '  have frame := rawFrame.widenChecked (allowed := divisionPrefixWrites) (by decide)',
                 '  refine ⟨n, after, run, division_prepared input post.good post.tick post.pcAt ?_ ?_ ?_ ?_ memory frame⟩']
        def result_lines(reg, indent):
            expression = dict(emitter.pins).get(reg, {'x1': 'v1'}.get(reg))
            expression = re.sub(r'\bv\d+\b', lambda m: values[m[0]], expression)
            return [f'{indent}have observed : gpr after {reg[1:]} = some ({expression}) := {observed(reg)}',
                    f'{indent}simpa only [{simp}] using observed']
        for reg in ('x1', 'x10', 'x11'):
            texts.append('  ·')
            texts.extend(result_lines(reg, '    '))
        if kind == 'remainder' or sx != sy:
            texts += ['  · intro _'] + result_lines('x5', '    ')
        else:
            texts += ['  · intro impossible', f'    simp [divisionNegative, hx, hy] at impossible']
        texts += ['', 'end OCaml.Vm.Sim', '']
        result[ROOT / f'OCaml/Vm/Sim/{stem}Prepare.lean'] = '\n'.join(texts)
    return result


def finish_outputs():
    result = {}
    for family, kind, negative in [('SDIV_NEGATE', 'quotient', 'true'),
                                   ('SMOD_POS_RETURN', 'remainder', 'false'),
                                   ('SMOD_NEG_RETURN', 'remainder', 'true')]:
        stem = FAMILIES[family][0]
        lower = family.lower()
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
        emitter = SegmentEmitter(spec)
        emitter.emit()
        positions = {r: i for i, (r, _) in enumerate(emitter.pins)}
        pins = ', '.join(f'⟨Register.{p["reg"]}, {"ra" if p["reg"] == "x5" else "unsigned"}⟩' for p in spec['pins'])
        value_field = 'h.quotientReg' if kind == 'quotient' else 'h.remainderReg'
        saved = 'h.savedReturn (Or.inr negative)' if kind == 'quotient' else 'h.savedReturn (Or.inl rfl)'
        proofs = ', '.join(saved if p['reg'] == 'x5' else value_field for p in spec['pins'])
        expression = dict(emitter.pins)['x10']
        expression = re.sub(r'\bv(?:10|11)\b', 'unsigned', expression)
        text = f'''import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins
import OCaml.Vm.Sim.SignedDivisionCore

/-! GENERATED by scripts/gen_signed_division.py. Actual signed return fixup. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

theorem {lower}_finish {{before c : Config}} {{x y ra : BitVec 64}}
    (h : SignedDivisionDivided .{kind} before x y ra c)
    (negative : divisionNegative .{kind} x y = {negative}) :
    ∃ n after, StepsN n c after ∧ SignedDivisionPost before ra (divisionResult .{kind} x y) after := by
  let unsigned := divisionUnsigned .{kind} x y
  have pc : pcOf c = some ({spec['entry']}#64) := by
    simpa only [divisionReturn, negative, Bool.false_eq_true, ite_true, ite_false] using h.pc
  have bp : SegSt ({spec['entry']}#64) [{pins}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, pc, ⟨{proofs}, trivial⟩, h.minstret, h.tick, {lower}_loaded h.image, rfl, rfl⟩
  obtain ⟨n, after, _, run, post⟩ := tr_{lower} unsigned ra c.σ.mem c.σ
    (by rw [ret_tgt ra h.returnAligned]; exact h.returnAligned) c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  refine ⟨n, after, run, post.good, image_of_writeLog (log := []) h.image ⟨trivial, trivial⟩ memory,
    post.good.minstret, post.tick, ?_, ?_, memory.trans h.memory,
    (h.frame.trans frame).widenChecked (allowed := divisionWrites) (by decide)⟩
  · have observedPc : pcOf after = some (Sail.BitVec.update (ra + sign_extend (m := 64) (0x000#12)) 0 0#1) := post.pcAt
    simpa only [ret_tgt ra h.returnAligned] using observedPc
  · have observed : gpr after 10 = some ({expression}) := PinsHold.get post.pins ⟨{positions['x10']}, by simp⟩
    rw [division_result_sign, negative]
    simpa only [unsigned, show sign_extend (m := 64) (0x000#12) = 0#64 from rfl,
      BitVec.add_zero, BitVec.zero_sub, Bool.false_eq_true, ite_true, ite_false] using observed

end OCaml.Vm.Sim
'''
        result[ROOT / f'OCaml/Vm/Sim/{stem}Finish.lean'] = text
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in (outputs() | finish_outputs()).items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'signed division generator drift: {path.relative_to(ROOT)}')
        else:
            path.write_text(text)
    print('Signed division adapters current')
