"""Executable-name global load and native constructor tail boundary."""
from ocaml_certificates import emit_loaded
from ocaml_block_certificates import emit_block


def emit_executable(root, functions, decode, code, text_base, lib, build_cfg, literal):
    fn = 'caml_sys_executable_name'
    ins = functions[fn]['insts']
    di = {a: lib.Instr(a,w,op,args,f'{op} {args}') for a,w,op,args in ins}
    _, blocks = build_cfg(fn,ins[0][0],di,{fn:(ins[0][0],ins[-1][0]+4)})
    assert len(blocks)==1 and [i[2] for i in ins]==['auipc','ld','j']
    stem = 'Caml_sys_executable_name'
    pred = f'Vsa.Sim.Code.{stem}Loaded'
    result = {root/f'Vsa/Sim/Code/{stem}.lean':code.render(fn,[(a,w) for a,w,_,_ in ins]).replace(
        'generated by experiments/gen_code_lemmas.py','GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper')}
    E = lib.Emitter()
    for module in ['OCaml.Vm.Primitives.AccessPlan','OCaml.Vm.Primitives.Read','OCaml.Vm.Primitives.Effects',
                   'Vsa.Sim.ChainFactsTac',f'Vsa.Sim.Code.{stem}']+sorted({decode[w] for _,w,_,_ in ins}):
        E('import '+module)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/',
      'namespace OCaml.Vm.Primitives.ExecutableNameTail', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable', '')
    emit_loaded(E,fn,ins,pred,text_base)
    emit_block(E,fn,blocks[0],'tail',[1],lib,literal)
    E('def globalAddress : BitVec 64 := BitVec.ofNat 64 Layout.sym_caml_exe_name',
      'theorem global_read : ReadWindow globalAddress 8 := by constructor <;> decide',
      'theorem global_nat : globalAddress.toNat = Layout.sym_caml_exe_name := by decide',
      'theorem tail_eval (R : Nat → BitVec 64) (bs : List (BitVec 8)) :',
      '    runGM tail_body (tail_input R) [bs] = [(10, bytesVal .ld bs), (1, R 1)] := by',
      '  simp [tail_body, tail_input, runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG]', '',
      'theorem tail_fast (c : Config) (ra : BitVec 64) (h : LeafInput ra c) :',
      '    FnSummary (BitVec.ofNat 64 Layout.sym_caml_sys_executable_name) (fun d => d = c)',
      f'      (RegistersPost [10] c.σ.mem c 0x{functions["caml_copy_string"]["insts"][0][0]:08x}#64',
      '        (word c Layout.sym_caml_exe_name) [(10, word c Layout.sym_caml_exe_name), (1, ra)]) := by',
      '  let R := fun (_ : Nat) => ra',
      '  let bs := read8 c.σ.mem Layout.sym_caml_exe_name',
      '  have value : bytesVal .ld bs = word c Layout.sym_caml_exe_name := read8_value _ _',
      '  have access : AccessPlan c.σ.mem (tail_input R) [bs] tail_body := by',
      '    simp only [AccessPlan, tail_body]', '    chain_facts True.intro',
      '    apply global_read.ld rfl',
      '    · simp [eaddrM, srcVal, lookupG, tail_input, stepGM, wvalM, imm20Of,',
      '        Functions.sign_extend, Sail.BitVec.signExtend, globalAddress, Layout.sym_caml_exe_name]',
      '    · simpa [global_nat, stepMemM, stepLdsM, List.headD, bs] using (read8_pins c.σ.mem Layout.sym_caml_exe_name)',
      '  apply registers_of_blocks h.image (log := []) ⟨True.intro, True.intro⟩',
      '    (tail_summary c ra R [bs] h ⟨h.raReg, True.intro⟩ access True.intro)',
      '  · exact readonly_log _ (by unfold ReadOnlyBody; decide) _ _',
      '  · rfl', '  · change runGM tail_body (tail_input R) [bs] = _', '    rw [tail_eval, value]', '  · rfl', '  · decide', '',
      'end OCaml.Vm.Primitives.ExecutableNameTail','')
    result[root/'OCaml/Vm/Primitives/ExecutableNameTail.lean']=E.text()
    result[root/'OCaml/Vm/Primitives/CamlSysExecutableName.lean'] = """import OCaml.Vm.Primitives.ExecutableNameContract

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/
namespace OCaml.Vm.Primitives
open OCaml.Bytecode Vsa.Machine Vsa.Sim StringCopy

theorem caml_sys_executable_name_primitive {runtimeOk P s pl cp sp high ra nativeSp arg live Dt DA a g domain young limit c}
    (h : ExecutableNameInput runtimeOk P s pl cp sp high ra nativeSp arg live Dt DA a g domain young limit c)
    (runtime : ObservationRuntime runtimeOk c (copyMemory c ra nativeSp a s.world.exeName.length g domain young)) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_sys_executable_name) (fun d => d = c)
      (LibraryPrimitivePost runtimeOk P s pl cp sp high "caml_sys_executable_name" [arg]
        (.ptr (s.heap.alloc (.bytes s.world.exeName)).2 0) (resultWord young s.world.exeName.length)
        (s.heap.alloc (.bytes s.world.exeName)).1 s.world ra) :=
  executable_name_contract h runtime

end OCaml.Vm.Primitives
"""
    return result
