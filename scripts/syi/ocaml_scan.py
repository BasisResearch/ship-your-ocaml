"""Read-only scan CFG certificates for gen_fn's OCaml backend."""

def emit_scan(root, functions, decode, code, text_base, lib, build_cfg, literal):
    fn = 'caml_string_equal'
    ins = functions[fn]['insts']
    di = {a: lib.Instr(a, w, op, args, f'{op} {args}') for a,w,op,args in ins}
    _, blocks = build_cfg(fn, ins[0][0], di, {fn:(ins[0][0],ins[-1][0]+4)})
    pred = 'Vsa.Sim.Code.Caml_string_equalLoaded'
    result = {root/'Vsa/Sim/Code/Caml_string_equal.lean': code.render(fn,[(a,w) for a,w,_,_ in ins]).replace('generated by experiments/gen_code_lemmas.py','GENERATED by scripts/syi/gen_fn.py --ocaml-string-scan')}
    # Fixed-point register liveness keeps loop-carried values at every join.
    uses, defs, live = {}, {}, {}
    for block in blocks:
        used, defined = {1}, set()
        for instr in block.instrs:
            w = instr.word; op = w & 127
            for r in ([(w >> 15) & 31, (w >> 20) & 31] if op == 0x33 else [(w >> 15) & 31]):
                if r and r not in defined: used.add(r)
            defined.add((w >> 7) & 31)
        if block.term:
            td = lib.decode_terminator(block.term, taken=True)
            for r in [td['rs1'], td['rs2']]:
                if r and r not in defined: used.add(r)
        uses[block.start], defs[block.start], live[block.start] = used, defined, used.copy()
    changed = True
    while changed:
        changed = False
        for block in reversed(blocks):
            outgoing = set().union(*(live.get(pc, set()) for pc in block.succs))
            incoming = uses[block.start] | (outgoing - defs[block.start])
            if incoming != live[block.start]: live[block.start] = incoming; changed = True
    E = lib.Emitter()
    for m in ['OCaml.Vm.Primitives.Boundary','OCaml.Vm.Primitives.Control','OCaml.Vm.Primitives.Read','Vsa.Sim.ChainFactsTac','Vsa.Sim.Code.Caml_string_equal']+sorted({decode[w] for a,w,_,_ in ins}): E('import '+m)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-scan. -/',
      'namespace OCaml.Vm.Primitives.StringScan',
      'open Vsa.Machine Vsa.Sim LeanRV64DExecutable','',
      f'theorem loaded {{c : Config}} (h : ExecutableImage c) : {pred} c.σ.mem := by',
      '  unfold '+pred+' '+ ' '.join('Vsa.Sim.Code.'+fn+'Chunk'+str(i) for i in range((len(ins)+15)//16)),
      "  repeat' apply And.intro")
    for a,w,_,_ in ins:
        for k in range(4):
            off=a+k-text_base
            E(f'  · have hb := h.text {off} (by decide)',
              f'    have he : Image.textByte {off} = 0x{(w>>(8*k))&255:02x}#8 := by decide +kernel',
              '    rw [he] at hb','    exact hb')
    for b in blocks:
        name=f'b{b.start-ins[0][0]:02x}'
        seen={1}; need={1}
        for instr in b.instrs:
            w=instr.word; op=w&127; rs1=(w>>15)&31;rs2=(w>>20)&31;rd=(w>>7)&31
            for r in ([rs1,rs2] if op==0x33 else [rs1]):
                if r and r not in seen:need.add(r);seen.add(r)
            seen.add(rd)
        if b.term:
            t=lib.decode_terminator(b.term,taken=True)
            for r in [t['rs1'],t['rs2']]:
                if r and r not in seen:need.add(r);seen.add(r)
        else:t=None
        inputs=sorted(need | live[b.start])
        names={r:('ra' if r==1 else f'r{r}') for r in inputs}
        vals=dict(names);order=inputs[:];accesses=[]
        def src(r): return vals[r] if r else '0#64'
        for instr in b.instrs:
            w=instr.word;op=w&127;rs1=(w>>15)&31;rs2=(w>>20)&31;rd=(w>>7)&31;f3=(w>>12)&7
            if op==3:
                imm=lib.sext(w>>20,12)
                addr=(f'({src(rs1)} - {-imm}#64)' if imm < 0 else f'({src(rs1)} + {imm}#64)')
                accesses.append(addr);v=f'(bytesVal .ld bs{len(accesses)-1})'
            elif op==0x13:
                imm=lib.sext(w>>20,12)
                if f3==0:v=(f'({src(rs1)} - {-imm}#64)' if imm < 0 else f'({src(rs1)} + {imm}#64)')
                elif f3==1:v=f'({src(rs1)} <<< ({(w>>20)&63} : Nat))'
                elif f3==5:v=f'({src(rs1)} >>> ({(w>>20)&63} : Nat))'
                else:raise ValueError(instr)
            elif op==0x33:
                oper='-' if w>>25 else '+'
                v=f'({src(rs1)} {oper} {src(rs2)})'
            else:raise ValueError(instr)
            vals[rd]=v;order=[rd]+[r for r in order if r!=rd]
        lp='['+', '.join(f'({r}, {names[r]})' for r in inputs)+']'
        out='['+', '.join(f'({r}, {vals[r]})' for r in order)+']'
        av=' '.join(names[r] for r in inputs)
        bp=' '.join(f'bs{i}' for i in range(len(accesses)))
        ld='['+', '.join(f'bs{i}' for i in range(len(accesses)))+']'
        bsdecl=f' ({bp} : List (BitVec 8))' if bp else ''
        br=b.kind=='br';pol=' (taken : Bool)' if br else '';polarg=' taken' if br else ''
        if t:
            tr=t['record'].replace(' true,',' taken,') if br else t['record']
            term='some '+tr
        else:term='none'
        E('',f'def {name}_body : List MInstr := [',',\n'.join('  '+literal(i.addr,i.word) for i in b.instrs),']',
          f'def {name}_blocks{pol} : List BBlock := [{{ body := {name}_body, term := {term} }}]',
          f'def {name}_regs ({av} : BitVec 64){bsdecl} : GRegs := {out}',
          f'theorem {name}_eval ({av} : BitVec 64){bsdecl} :',
          f'    runGM {name}_body {lp} {ld} = {name}_regs {av} {bp} := by',
          f'  simp [{name}_body, {name}_regs, runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG,',
          '    shamtOf, LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend,',
          '    Sail.BitVec.extractLsb, Sail.shift_bits_left, Sail.shift_bits_right, BitVec.sub_eq_add_neg]', '')
        if t and t['kind']=='jr':pc='ra'
        elif br:pc=f'(if taken then 0x{t["target"]:08x}#64 else 0x{b.term.addr+4:08x}#64)'
        elif t:pc=f'0x{t["target"]:08x}#64'
        else:pc=f'0x{b.instrs[-1].addr+4:08x}#64'
        E(f'theorem {name}_shape{pol} : ChainOK 0x{b.start:08x}#64 {inputs} ({name}_blocks{polarg}) := by')
        if br:E('  cases taken <;>')
        E(f'  simp only [ChainOK, BBlockOK, {name}_blocks, {name}_body, BlockOKM]',
          '  all_goals repeat apply And.intro','  all_goals decide','')
        E(f'theorem {name}_code {{c : Config}} (hc : {pred} c.σ.mem) : CodeFacts c.σ.mem {name}_body := by',
          f'  simp only [CodeFacts, {name}_body]',f'  all_goals chain_facts hc with "Vsa.Sim.Code.{fn}_at_"','')
        E(f'theorem {name}_facts (c : Config) ({av} : BitVec 64){bsdecl}',f'    (hc : {pred} c.σ.mem)')
        for i,addr in enumerate(accesses):E(f'    (w{i} : ReadWindow {addr} 8) (p{i} : LPins8 c.σ.mem {addr}.toNat bs{i})')
        E(f'    : ProgFactsM c.σ.mem c.σ.mem {lp} {ld} {name}_body := by')
        if not accesses:E(f'  exact memory_free_facts ({name}_code hc) (by simp [{name}_body, MemoryFree]) _ _ _')
        else:
            E(f'  chain_facts hc with "Vsa.Sim.Code.{fn}_at_"')
            for i,_ in enumerate(accesses):
                E(f'  · apply w{i}.ld rfl ?_ p{i}',
                  '    simp [eaddrM, stepGM, wvalM, srcVal, lookupG, eraseG,',
                  '      LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg]')
        E('')
        E(f'theorem {name}_summary (c : Config) ({av} : BitVec 64){bsdecl}{pol}',
          '    (h : LeafInput ra c)',f'    (hr : GHolds c.σ {lp})')
        for i,addr in enumerate(accesses):E(f'    (w{i} : ReadWindow {addr} 8) (p{i} : LPins8 c.σ.mem {addr}.toNat bs{i})')
        if br:
            E(f'    (branch : guardB {t["op"]} {src(t["rs1"])} {src(t["rs2"])} = taken)')
        E('    : FnSummary '+f'0x{b.start:08x}#64 (fun x => x = c)',
          f'      (BoundaryPost [10, 11, 13, 14, 15] c ra {pc} ({name}_regs {av} {bp})) := by',
          f'  have ht : TermFactsO (runGM {name}_body {lp} {ld}) ({term}) := by',
          f'    rw [{name}_eval]')
        if br:E(f'    simpa [TermFactsO, TermFactsT, {name}_regs, srcVal, lookupG] using branch')
        elif t and t['kind']=='jr':
            E(f'    apply return_facts _ rfl rfl rfl ?_ h.aligned',f'    simp [{name}_regs, srcVal, lookupG]')
        else:E('    trivial')
        E(f'  have S := block_summary ({name}_blocks{polarg}) 0x{b.start:08x}#64 {lp} {ld} c',
          f'    ⟨h.good, h.minstret, hr, (by change KeysOK {inputs}; decide),',
          f'      singleton_chain_facts ({name}_facts c {av} {bp} (loaded h.image) '+ ' '.join(f'w{i} p{i}' for i in range(len(accesses)))+')',
          f'        (by have hc := loaded h.image; chain_facts hc with "Vsa.Sim.Code.{fn}_at_") ht,',
          f'      {name}_shape{polarg}, h.tick⟩',
          '  apply boundary_of_blocks h S',
          f'  · exact readonly_log _ (by unfold ReadOnlyBody; decide) _ _',
          f'  · simp only [evalBlocksPC, {name}_blocks, SegEvalState.init, chainEndPC, endPCB, tgtPCT]')
        if t and t['kind']=='jr':
            E(f'    rw [{name}_eval]',f'    change Sail.BitVec.update (ra + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0#12)) 0 0#1 = ra',
              '    exact ret_tgt ra h.aligned')
        elif br:E('    cases taken <;> rfl')
        else:E('    rfl')
        E(f'  · intro σ hs', f'    exact ({name}_eval {av} {bp}) ▸ hs',
          ('  · cases taken <;> decide' if br else '  · decide'), '  · decide','')
    E('end OCaml.Vm.Primitives.StringScan','')
    result[root/'OCaml/Vm/Primitives/StringScan.lean']=E.text()
    result[root/'OCaml/Vm/Primitives/CamlStringEqual.lean'] = """import OCaml.Vm.Primitives.StringEqualityContract

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-scan. -/
namespace OCaml.Vm.Primitives
open Vsa.Machine Vsa.Sim

theorem caml_string_equal_primitive {runtimeOk : Config → Prop} (stable : MemoryStable runtimeOk)
    {P s pl cp sp high ra l l' a a' bs bs' c}
    (h : StringPairInput runtimeOk P s pl cp sp high ra l l' a a' bs bs' c) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_string_equal) (fun d => d = c)
      (ImmediatePost runtimeOk P s pl cp sp high "caml_string_equal" [.ptr l 0, .ptr l' 0]
        (stringEqualityResult bs bs') StringScan.scanWrites c ra) :=
  string_equal_contract stable h

end OCaml.Vm.Primitives
"""
    return result
