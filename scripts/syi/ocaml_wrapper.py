"""Generated native-stack and direct-call certificates for F1 wrappers."""
from ocaml_certificates import emit_loaded
from ocaml_string_copy import emit_string_copy
from ocaml_executable import emit_executable


def emit_wrapper(root, functions, decode, code, text_base, lib, build_cfg, literal):
    fn='caml_string_notequal'; ins=functions[fn]['insts']
    di={a:lib.Instr(a,w,op,args,f'{op} {args}') for a,w,op,args in ins}
    _,cfg=build_cfg(fn,ins[0][0],di,{fn:(ins[0][0],ins[-1][0]+4)})
    if len(cfg)!=2 or cfg[0].kind!='jal' or cfg[0].callee!='caml_string_equal' or cfg[1].kind!='ret':
        raise ValueError('string inequality call shape changed')
    pred='Vsa.Sim.Code.Caml_string_notequalLoaded'
    result={root/'Vsa/Sim/Code/Caml_string_notequal.lean':code.render(fn,[(a,w) for a,w,_,_ in ins]).replace('generated by experiments/gen_code_lemmas.py','GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper')}
    E=lib.Emitter()
    for module in ['OCaml.Vm.Primitives.Call','OCaml.Vm.Primitives.NativeStack','OCaml.Vm.Primitives.Leaf','OCaml.Vm.Primitives.Control','Vsa.Sim.ChainFactsTac','Vsa.Sim.Code.Caml_string_notequal']+sorted({decode[w] for a,w,_,_ in ins}):E('import '+module)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/',
      'namespace OCaml.Vm.Primitives.StringWrapper', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable','')
    emit_loaded(E,fn,ins,pred,text_base)
    for name,b in zip(('save','restore'),cfg):
        E('',f'def {name}_body : List MInstr := [',',\n'.join('  '+literal(i.addr,i.word) for i in b.instrs),']',
          f'def {name}_blocks : List BBlock := [{{ body := {name}_body, term := '+('none' if name=='save' else 'some '+lib.decode_terminator(b.term)['record'])+' }]', '')
        E(f'theorem {name}_shape : ChainOK 0x{b.start:08x}#64 '+('[1, 2, 10, 11]' if name=='save' else '[2, 10]')+f' {name}_blocks := by',
          f'  simp only [ChainOK, BBlockOK, {name}_blocks, {name}_body, BlockOKM]',
          '  repeat apply And.intro', '  all_goals decide','')
    pc,w,_,_=ins[2];imm=lib._jal_imm(w)
    E('def call : CallInstr := ⟨'+', '.join([f'0x{pc:08x}#64',f'0x{w:08x}#32']+lib.le_bytes(w)+[f'0x{imm:06x}#21'])+'⟩','',
      'theorem call_shape : CallShape call := by constructor <;> decide','',
      'theorem call_decode : CallDecode call := by',
      '  intro s hm hp he', f'  exact Vsa.Sim.ElfDecode.decode_{w:08x} s hm hp he','',
      'theorem call_target : call.target = BitVec.ofNat 64 Layout.sym_caml_string_equal := by decide','',
      'theorem call_pins {c : Config} (h : ExecutableImage c) : CallPins call c := by',
      f'  obtain ⟨h0, h1, h2, h3⟩ := Vsa.Sim.Code.{fn}_at_{pc:08x} (loaded h)',
      '  exact ⟨h0, h1, h2, h3⟩','')
    pure=['runGM','stepGM','stepLdsM','wvalM','srcVal','lookupG','eraseG','LeanRV64DExecutable.Functions.sign_extend','Sail.BitVec.signExtend','BitVec.sub_eq_add_neg']
    saveL='[(1, ra), (2, sp), (10, x), (11, y)]'
    saveRegs='[(2, sp - 16#64), (1, ra), (10, x), (11, y)]'
    E('theorem stack_down : LeanRV64DExecutable.Functions.sign_extend (m := 64) (0xff0#12) = -16#64 := by decide', '', 'theorem save_regs (ra sp x y : BitVec 64) :',f'    runGM save_body {saveL} [] = {saveRegs} := by',
      '  simp [save_body, '+', '.join(pure)+']','',
      'theorem save_log (ra sp x y : BitVec 64) :',
      f'    (evalBlocks save_blocks (SegEvalState.init {saveL} [])).log = savedRaLog sp ra := by',
      '  change [((sp + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0xff0#12) + 8#64).toNat, 8, ra)] = [((sp - 8#64).toNat, 8, ra)]',
      '  rw [stack_down, ← BitVec.sub_eq_add_neg, native_save_address]','',
      'theorem save_summary (c : Config) (ra sp x y : BitVec 64) (h : LeafInput ra c)',
      '    (hs : gpr c 2 = some sp) (hx : gpr c 10 = some x) (hy : gpr c 11 = some y)',
      '    (window : WriteWindow (sp - 8#64) 8) (outside : ImageOutside (savedRaLog sp ra)) :',
      '    FnSummary (BitVec.ofNat 64 Layout.sym_caml_string_notequal) (fun d => d = c)',
      f'      (WriteRegistersPost [2] (savedRaLog sp ra) c call.pc x {saveRegs}) := by',
      f'  have S := block_summary save_blocks (BitVec.ofNat 64 Layout.sym_caml_string_notequal) {saveL} [] c',
      '    ⟨h.good, h.minstret, ⟨h.raReg, hs, hx, hy, True.intro⟩, (by change KeysOK [1, 2, 10, 11]; decide),',
      '      ?_, save_shape, h.tick⟩',
      '  · apply registers_of_blocks h.image outside S',
      '    · exact save_log ra sp x y', '    · rfl', '    · exact save_regs ra sp x y', '    · rfl', '    · decide',
      '  · have hc := loaded h.image', f'    chain_facts hc with "Vsa.Sim.Code.{fn}_at_"',
      '    apply window.sd rfl',
      '    change sp + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0xff0#12) + 8#64 = sp - 8#64',
      '    rw [stack_down, ← BitVec.sub_eq_add_neg, native_save_address]','')
    E('theorem restore_regs (sp result : BitVec 64) (bs : List (BitVec 8)) :',
      '    runGM restore_body [(2, sp - 16#64), (10, result)] [bs] =',
      '      [(2, sp), (10, 4#64 - result), (15, 4#64), (1, bytesVal .ld bs)] := by',
      '  simp [restore_body, '+', '.join(pure)+', BitVec.add_assoc]','',
      'theorem restore_facts (c : Config) (sp result : BitVec 64) (bs : List (BitVec 8))',
      f'    (hc : {pred} c.σ.mem)',
      '    (window : ReadWindow (sp - 8#64) 8) (pins : LPins8 c.σ.mem (sp - 8#64).toNat bs) :',
      '    ProgFactsM c.σ.mem c.σ.mem [(2, sp - 16#64), (10, result)] [bs] restore_body := by',
      f'  chain_facts hc with "Vsa.Sim.Code.{fn}_at_"',
      '  apply window.ld rfl ?_ pins',
      '  change sp - 16#64 + 8#64 = sp - 8#64',
      '  exact native_save_address sp','',
      'theorem restore_summary (c : Config) (link ra sp result : BitVec 64) (h : LeafInput link c)',
      '    (hs : gpr c 2 = some (sp - 16#64)) (hx : gpr c 10 = some result)',
      '    (window : ReadWindow (sp - 8#64) 8)',
      '    (saved : word c (sp - 8#64).toNat = ra) (aligned : ra.toNat % 4 = 0) :',
      f'    FnSummary 0x{ins[3][0]:08x}#64 (fun d => d = c)',
      '      (RegistersPost [1, 2, 10, 15] c.σ.mem c ra (4#64 - result)',
      '        [(2, sp), (10, 4#64 - result), (15, 4#64), (1, ra)]) := by',
      '  let bs := read8 c.σ.mem (sp - 8#64).toNat',
      '  have value : bytesVal .ld bs = ra := (read8_value _ _).trans saved',
      '  have regs : runGM restore_body [(2, sp - 16#64), (10, result)] [bs] =',
      '      [(2, sp), (10, 4#64 - result), (15, 4#64), (1, ra)] := by rw [restore_regs, value]',
      '  have hr : srcVal 1 (runGM restore_body [(2, sp - 16#64), (10, result)] [bs]) = ra := by rw [regs]; rfl',
      f'  have S := block_summary restore_blocks 0x{ins[3][0]:08x}#64 [(2, sp - 16#64), (10, result)] [bs] c',
      '    ⟨h.good, h.minstret, ⟨hs, hx, True.intro⟩, (by change KeysOK [2, 10]; decide),',
      '      singleton_chain_facts (restore_facts c sp result bs (loaded h.image) window (read8_pins _ _))',
      f'        (by have hc := loaded h.image; chain_facts hc with "Vsa.Sim.Code.{fn}_at_")',
      '        (return_facts _ rfl rfl rfl hr aligned), restore_shape, h.tick⟩',
      '  apply registers_of_blocks h.image (log := []) ⟨True.intro, True.intro⟩ S',
      '  · exact readonly_log _ (by unfold ReadOnlyBody; decide) _ _',
      '  · simp only [evalBlocksPC, restore_blocks, SegEvalState.init, chainEndPC, endPCB, tgtPCT]',
      '    exact (congrArg (fun r : BitVec 64 =>',
      '      Sail.BitVec.update (r + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0#12)) 0 0#1)',
      '      hr).trans (ret_tgt ra aligned)',
      '  · exact regs', '  · rfl', '  · decide','',
      'end OCaml.Vm.Primitives.StringWrapper','')
    result[root/'OCaml/Vm/Primitives/StringWrapper.lean']=E.text()
    result[root/'OCaml/Vm/Primitives/CamlStringNotequal.lean'] = """import OCaml.Vm.Primitives.StringInequalityContract

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/
namespace OCaml.Vm.Primitives
open Vsa.Machine Vsa.Sim

theorem caml_string_notequal_primitive {runtimeOk P s pl cp sp high ra nativeSp l l' a a' bs bs' c}
    (stable : WindowStable runtimeOk (savedRaWindows nativeSp))
    (h : StringNotEqualInput runtimeOk P s pl cp sp high ra nativeSp l l' a a' bs bs' c) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_string_notequal) (fun d => d = c)
      (StringNotEqualPost runtimeOk P s pl cp sp high ra nativeSp l l' bs bs' c) :=
  string_notequal_contract stable h

end OCaml.Vm.Primitives
"""
    result.update(emit_string_copy(root, functions, decode, code, text_base, lib, build_cfg, literal))
    result.update(emit_executable(root, functions, decode, code, text_base, lib, build_cfg, literal))
    return result
