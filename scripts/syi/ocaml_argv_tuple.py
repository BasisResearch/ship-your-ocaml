"""Generated call boundaries for the executable-name/argv pair."""
from ocaml_certificates import emit_loaded
from ocaml_symbolic_chunks import emit_log_chunks
from ocaml_block_certificates import emit_block, emit_call, emit_indirect


def shifts(b):
    """Immediate shifts need their shift-amount projections unfolded."""
    return any(i.word & 127 in (0x13, 0x1b) and (i.word >> 12) & 7 in (1, 5) for i in b.instrs)


def emit_tuple_blocks(root, functions, decode, code, text_base, lib, build_cfg, literal,
                      fn, stem, namespace, out, selected, starts=None,
                      chunked=('prepare', 'finish'), flag='--ocaml-string-wrapper', route=None):
    """Block certificates of selected CFG blocks of one native function. By
    default: a caller that copies a C string with `caml_copy_string`,
    allocates a small block and fills its fields (all three blocks). With
    `starts`, the blocks with those entry addresses, in that order."""
    ins = functions[fn]['insts']
    di = {a: lib.Instr(a,w,op,args,f'{op} {args}') for a,w,op,args in ins}
    _, cfg = build_cfg(fn, ins[0][0], di, {fn:(ins[0][0],ins[-1][0]+4)}, route=route)
    if starts is None:
        assert [b.kind for b in cfg] == ['jal','jal','ret']
        assert [b.callee for b in cfg[:2]] == ['caml_copy_string','caml_alloc_small']
    else:
        by_start = {b.start: b for b in cfg}
        cfg = [by_start[a] for a in starts]
    pred = f'Vsa.Sim.Code.{stem}Loaded'
    result = {root/f'Vsa/Sim/Code/{stem}.lean':code.render(fn,[(a,w) for a,w,_,_ in ins]).replace(
        'generated by experiments/gen_code_lemmas.py',f'GENERATED by scripts/syi/gen_fn.py {flag}')}
    E = lib.Emitter()
    for module in ['OCaml.Vm.Primitives.AccessPlan','OCaml.Vm.Primitives.Call']+(['OCaml.Vm.Primitives.IndirectCall'] if any(b.kind == 'jalrcall' for b in cfg) else [])+[
                   'OCaml.Vm.Primitives.DoubleAllocation','OCaml.Vm.Primitives.SymbolicAppend','Vsa.Sim.ChainFactsTac',f'Vsa.Sim.Code.{stem}']+sorted({decode[w] for _,w,_,_ in ins}):
        E('import '+module)
    E('', f'/-! GENERATED by scripts/syi/gen_fn.py {flag}. -/',
      f'namespace {namespace}', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable','')
    emit_loaded(E,fn,ins,pred,text_base)
    for sel,b in zip(selected,cfg):
        name, keys, regs = sel[:3]
        emit_block(E,fn,b,name,keys,lib,literal,taken=sel[3] if len(sel) > 3 else False)
        E(f'def {name}_regs (R : Nat → BitVec 64) (loads : List (List (BitVec 8))) : GRegs :=', '  '+regs,
          f'theorem {name}_eval (R : Nat → BitVec 64) (loads : List (List (BitVec 8))) :',
          f'    runGM {name}_body ({name}_input R) loads = {name}_regs R loads := by',
          f'  simp [{name}_body, {name}_input, {name}_regs, runGM, stepGM, stepLdsM,',
          '    wvalM, srcVal, lookupG, eraseG, imm20Of, DoubleAllocation.domainGlobal, Layout.sym_Caml_state,',
          '    Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg, List.head?_eq_getElem?, BitVec.add_assoc'
          + (', shamtOf, Sail.BitVec.extractLsb, Sail.shift_bits_right, Sail.shift_bits_left' if shifts(b) else '') + ']', '')
        if name in chunked:
            emit_log_chunks(E,name,b.instrs,keys,literal,lib)
        if b.kind == 'jal':
            emit_call(E,fn,b,name,functions,lib)
        elif b.kind == 'jalrcall':
            emit_indirect(E,fn,b,name,lib)
    E(f'end {namespace}','')
    result[root/out]=E.text()
    return result


def emit_argv_tuple(root, functions, decode, code, text_base, lib, build_cfg, literal):
    ld = lambda n: f'bytesVal .ld (loads.getD {n} [])'
    argv = [
      ('prepare',[1,2,8,9,18],
       f'[(14, R 2 - 104#64), (18, 2#64), (15, 1#64), (8, {ld(2)}), (13, R 2 - 96#64), (10, {ld(1)}), (9, DoubleAllocation.domainGlobal), (2, R 2 - 112#64), (1, R 1)]'),
      ('allocate',[1,2,10,18],
       '[(10, R 18), (11, 0#64), (1, R 1), (2, R 2), (18, R 18)]'),
      ('finish',[2,8,9,10],
       f'[(2, R 2 + 112#64), (18, {ld(8)}), (9, {ld(7)}), (8, {ld(6)}), (1, {ld(5)}), (10, {ld(4)}), (15, {ld(3)}), (14, {ld(2)})]')]
    config = [
      ('prepare',[1,2,8,9,18],
       f'[(15, R 2 - 104#64), (10, 0x80055c78#64), (14, 2#64), (9, {ld(1)}), (8, 1#64), (13, R 2 - 96#64), (18, DoubleAllocation.domainGlobal), (2, R 2 - 112#64), (1, R 1)]'),
      ('allocate',[1,2,10],
       '[(10, 3#64), (11, 0#64), (1, R 1), (2, R 2)]'),
      ('finish',[2,8,9,10,18],
       f'[(2, R 2 + 112#64), (18, {ld(8)}), (9, {ld(7)}), (8, {ld(6)}), (1, {ld(5)}), (10, {ld(4)}), (15, {ld(3)}), (14, 129#64)]')]
    args = (root, functions, decode, code, text_base, lib, build_cfg, literal)
    result = emit_tuple_blocks(*args, 'caml_sys_get_argv', 'Caml_sys_get_argv',
        'OCaml.Vm.Primitives.ArgvTuple', 'OCaml/Vm/Primitives/ArgvTuple.lean', argv)
    result.update(emit_tuple_blocks(*args, 'caml_sys_get_config', 'Caml_sys_get_config',
        'OCaml.Vm.Primitives.ConfigTuple', 'OCaml/Vm/Primitives/ConfigTuple.lean', config))
    result[root/'OCaml/Vm/Primitives/CamlSysGetArgv.lean'] = """import OCaml.Vm.Primitives.GetArgvContract

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/
namespace OCaml.Vm.Primitives
open OCaml.Bytecode Vsa.Machine Vsa.Sim ArgvTuple

theorem caml_sys_get_argv_primitive {runtimeOk P s pl cp sp high arg live Dt DA R bd be br a g young limit blockYoung argv c}
    (h : GetArgvInput runtimeOk P s pl cp sp high arg live Dt DA R bd be br a g young limit blockYoung argv c)
    (runtime : ObservationRuntime runtimeOk c (fun x => ((writeLog c.σ.mem (getArgvLog R (bytesVal .ld bd)
      (bytesVal .ld br) young blockYoung argv a s.world.exeName.length g))[x]?).getD 0)) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_sys_get_argv) (fun d => d = c)
      (GetArgvPost runtimeOk P s pl cp sp high arg live R bd br a g young blockYoung argv c) :=
  get_argv_contract h runtime

end OCaml.Vm.Primitives
"""
    result[root/'OCaml/Vm/Primitives/CamlSysGetConfig.lean'] = """import OCaml.Vm.Primitives.GetConfigContract

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/
namespace OCaml.Vm.Primitives
open OCaml.Bytecode Vsa.Machine Vsa.Sim ConfigTuple

theorem caml_sys_get_config_primitive {runtimeOk P s pl cp sp high arg live Dt DA R bd br g young limit blockYoung c}
    (h : GetConfigInput runtimeOk P s pl cp sp high arg live Dt DA R bd br g young limit blockYoung c)
    (runtime : ObservationRuntime runtimeOk c (fun x => ((writeLog c.σ.mem (getConfigLog R (bytesVal .ld bd)
      (bytesVal .ld br) young blockYoung g))[x]?).getD 0)) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_sys_get_config) (fun d => d = c)
      (GetConfigPost runtimeOk P s pl cp sp high arg live R bd br g young blockYoung c) :=
  get_config_contract h runtime

end OCaml.Vm.Primitives
"""
    return result
