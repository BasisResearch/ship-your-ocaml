"""Generated represented-argument load before a direct allocator tail jump."""
from ocaml_certificates import emit_loaded


def emit_int64_tail(root, functions, decode, code, text_base, lib, build_cfg, literal):
    fn='caml_int64_float_of_bits'; ins=functions[fn]['insts']
    di={a:lib.Instr(a,w,op,args,f'{op} {args}') for a,w,op,args in ins}
    _,blocks=build_cfg(fn,ins[0][0],di,{fn:(ins[0][0],ins[-1][0]+4)})
    assert len(ins)==2 and ins[0][2]=='ld' and ins[1][2]=='j'
    body=blocks[0].instrs
    assert len(body)==1
    term=lib.decode_terminator(di[ins[1][0]])['record']
    pred='Vsa.Sim.Code.Caml_int64_float_of_bitsLoaded'
    result={root/'Vsa/Sim/Code/Caml_int64_float_of_bits.lean':code.render(fn,[(a,w) for a,w,_,_ in ins]).replace('generated by experiments/gen_code_lemmas.py','GENERATED by scripts/syi/gen_fn.py --ocaml-allocation')}
    E=lib.Emitter()
    for m in ['OCaml.Vm.Primitives.Boundary','OCaml.Vm.Primitives.Control','OCaml.Vm.Primitives.Read','Vsa.Sim.ChainFactsTac','Vsa.Sim.Code.Caml_int64_float_of_bits']+sorted({decode[w] for a,w,_,_ in ins}): E('import '+m)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-allocation. -/',
      'namespace OCaml.Vm.Primitives.Int64FloatTail', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable', '')
    emit_loaded(E,fn,ins,pred,text_base)
    L='[(1, ra), (10, arg)]'; regs='[(10, bytesVal .ld bs), (1, ra)]'
    E('def body : List MInstr := ['+literal(body[0].addr,body[0].word)+']',
      f'def blocks : List BBlock := [{{ body := body, term := some {term} }}]',
      'theorem shape : ChainOK (BitVec.ofNat 64 Layout.sym_caml_int64_float_of_bits) [1, 10] blocks := by',
      '  simp only [ChainOK, BBlockOK, blocks, body, BlockOKM]',
      '  repeat apply And.intro', '  all_goals decide', '',
      'theorem registers (ra arg : BitVec 64) (bs : List (BitVec 8)) :',
      f'    runGM body {L} [bs] = {regs} := by',
      '  simp [body, runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG]', '',
      'theorem summary (c : Config) (ra arg : BitVec 64) (bs : List (BitVec 8))',
      '    (h : LeafInput ra c) (ha : gpr c 10 = some arg)',
      '    (window : ReadWindow (arg + 8#64) 8) (pins : LPins8 c.σ.mem (arg + 8#64).toNat bs) :',
      '    FnSummary (BitVec.ofNat 64 Layout.sym_caml_int64_float_of_bits) (fun d => d = c)',
      '      (BoundaryPost [10] c ra (BitVec.ofNat 64 Layout.sym_caml_copy_double)',
      f'        {regs}) := by',
      f'  have S := block_summary blocks (BitVec.ofNat 64 Layout.sym_caml_int64_float_of_bits) {L} [bs] c',
      '    ⟨h.good, h.minstret, ⟨h.raReg, ha, True.intro⟩, (by change KeysOK [1, 10]; decide),',
      '      ?_, shape, h.tick⟩',
      '  · apply boundary_of_blocks h S',
      '    · exact readonly_log _ (by unfold ReadOnlyBody; decide) _ _',
      '    · rfl', '    · intro σ hr; exact (registers ra arg bs) ▸ hr', '    · decide', '    · decide',
      '  · have hc := loaded h.image', '    apply singleton_chain_facts',
      f'    · chain_facts hc with "Vsa.Sim.Code.{fn}_at_"',
      '      apply window.ld rfl ?_ pins',
      '      simp [eaddrM, srcVal, lookupG, LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend]',
      f'    · chain_facts hc with "Vsa.Sim.Code.{fn}_at_"', '    · trivial','',
      'end OCaml.Vm.Primitives.Int64FloatTail','')
    result[root/'OCaml/Vm/Primitives/Int64FloatTail.lean']=E.text()
    result[root/'OCaml/Vm/Primitives/CamlInt64FloatOfBits.lean'] = """import OCaml.Vm.Primitives.Int64FloatFast

/-! GENERATED by scripts/syi/gen_fn.py --ocaml-allocation. -/
namespace OCaml.Vm.Primitives
open OCaml.Bytecode Vsa.Machine Vsa.Sim

theorem caml_int64_float_of_bits_primitive {runtimeOk P s pl cp sp high ra l a bits domain young limit c}
    (h : Int64FloatInput runtimeOk P s pl cp sp high ra l a bits domain young limit c)
    (runtime : AllocationRuntime runtimeOk c (DoubleAllocation.allocationLog domain young bits)) :
    FnSummary (BitVec.ofNat 64 Layout.sym_caml_int64_float_of_bits) (fun d => d = c)
      (PrimitivePost runtimeOk P s pl cp sp high "caml_int64_float_of_bits" [.ptr l 0]
        (.ptr (s.heap.alloc (.double bits)).2 0) (BitVec.ofNat 64 ((young - 16#64).toNat + 8))
        (s.heap.alloc (.double bits)).1 s.world DoubleAllocation.doubleWrites
        (writeLog c.σ.mem (DoubleAllocation.allocationLog domain young bits)) c ra) :=
  int64_float_contract h runtime

end OCaml.Vm.Primitives
"""
    return result
