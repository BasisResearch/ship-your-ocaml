"""Generated block certificates of the default process-exit path:
caml_sys_exit -> caml_do_exit -> exit -> __call_exitprocs (empty atexit list)
-> _exit, parked at the HTIF tohost store, plus the one-instruction leaves."""
from ocaml_argv_tuple import emit_tuple_blocks

FLAG = '--ocaml-exit'
# Branch outcomes on the default path: a null stdio exit handler and an
# empty atexit list are taken branches; the GC-verbosity and cleanup tests fall through.
TAKEN = ('handler', 'empty')


def emit_exit(root, functions, decode, code, text_base, lib, build_cfg, literal):
    ld = lambda n, k='ld': f'bytesVal .{k} (loads.getD {n} [])'
    rest = lambda ks: ', '.join(f'({k}, R {k})' for k in ks)
    saved = [18, 19, 20, 21, 22, 23, 24, 25, 26]
    paths = [
      ('caml_sys_exit', 'Caml_sys_exit', 'SysExit', [
        (0x8001c7ac, 'entry', [1, 2, 10],
         '[(10, BitVec.signExtend 64 (BitVec.extractLsb 31 0 (Functions.shift_bits_right_arith (R 10) 1#6))), (2, R 2 - 16#64), (1, R 1)]')]),
      ('caml_do_exit', 'Caml_do_exit', 'DoExit', [
        (0x8001c5c8, 'save', [1, 2, 8, 9, 10] + saved,
         f'[(9, R 10), (15, {ld(0)} &&& 1024#64), (2, R 2 - 96#64), {rest([1, 8, 10] + saved)}]'),
        (0x8001c610, 'debug', [1, 9], '[(10, 3#64), (11, 1#64), (1, R 1), (9, R 9)]'),
        (0x8001c61c, 'cleanup', [1, 9, 10], f'[(15, {ld(0, "lw")}), (1, R 1), (9, R 9), (10, R 10)]'),
        (0x8001c628, 'signals', [1, 9, 10], '[(1, R 1), (9, R 9), (10, R 10)]'),
        (0x8001c62c, 'leave', [1, 9], '[(10, R 9), (1, R 1), (9, R 9)]')]),
      ('exit', 'Exit', 'LibcExit', [
        (0x800373c8, 'enter', [1, 2, 8, 10], '[(8, R 10), (11, 0#64), (2, R 2 - 16#64), (1, R 1), (10, R 10)]'),
        (0x800373e0, 'handler', [1, 8, 10], f'[(15, {ld(0)}), (1, R 1), (8, R 8), (10, R 10)]'),
        (0x800373f0, 'tail', [1, 8], '[(10, R 8), (1, R 1), (8, R 8)]')]),
      ('__call_exitprocs', '__call_exitprocs', 'ExitProcs', [
        (0x80042d28, 'enter', [1, 2, 10, 11, 18, 20, 22, 23, 24],
         f'[(24, R 11), (20, 0x80064d90#64), (10, {ld(0)}), (22, R 10), (23, 0x80064900#64), (2, R 2 - 96#64), (1, R 1), (11, R 11), (18, R 18)]'),
        (0x80042d64, 'empty', [1, 2, 10, 20, 23], f'[(18, {ld(0)}), (1, R 1), (2, R 2), (10, R 10), (20, R 20), (23, R 23)]'),
        (0x80042e04, 'leave', [1, 2, 23],
         f'[(2, R 2 + 96#64), (24, {ld(6)}), (23, {ld(5)}), (22, {ld(4)}), (20, {ld(3)}), (18, {ld(2)}), (1, {ld(1)}), (10, {ld(0)})]')]),
      ('_exit', '_exit', 'HtifExit', [
        (0x800008a0, 'store', [1, 10],
         '[(14, 0x800618ac#64), (15, (R 10 <<< 32) >>> 31 ||| 1#64), (1, R 1), (10, R 10)]')]),
    ]
    for fn, stem in [('caml_debugger', 'Caml_debugger'), ('caml_terminate_signals', 'Caml_terminate_signals'),
                     ('__retarget_lock_acquire_recursive', '__retarget_lock_acquire_recursive'),
                     ('__retarget_lock_release_recursive', '__retarget_lock_release_recursive')]:
        ns = ''.join(x.capitalize() for x in fn.strip('_').split('_'))
        paths.append((fn, stem, ns, [(functions[fn]['insts'][0][0], 'leaf', [1, 10], '[(1, R 1), (10, R 10)]')]))
    result = {}
    for fn, stem, ns, blocks in paths:
        selected = [(name, keys, regs, name in TAKEN) for _, name, keys, regs in blocks]
        result.update(emit_tuple_blocks(root, functions, decode, code, text_base, lib, build_cfg, literal,
            fn, stem, f'OCaml.Vm.Primitives.ExitPath.{ns}', f'OCaml/Vm/Primitives/ExitPath/{ns}.lean',
            selected, starts=[a for a, _, _, _ in blocks], chunked=(), flag=FLAG))
    # The lock stubs' code pins are generated by scripts/gen_startup_rows.py; reuse them.
    for stem in ('__retarget_lock_acquire_recursive', '__retarget_lock_release_recursive'):
        del result[root/f'Vsa/Sim/Code/{stem}.lean']
    return result
