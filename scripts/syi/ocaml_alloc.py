"""Nursery constructor certificates from the pinned ELF CFG."""
from ocaml_certificates import emit_loaded


def emit_alloc(root, functions, decode, code, text_base, lib, build_cfg, literal):
    fn='caml_copy_double'; ins=functions[fn]['insts']
    di={a:lib.Instr(a,w,op,args,f'{op} {args}') for a,w,op,args in ins}
    _,blocks=build_cfg(fn,ins[0][0],di,{fn:(ins[0][0],ins[-1][0]+4)})
    first,second=blocks[:2]
    assert first.kind=='br' and second.kind=='ret'
    pred='Vsa.Sim.Code.Caml_copy_doubleLoaded'
    result={root/'Vsa/Sim/Code/Caml_copy_double.lean':code.render(fn,[(a,w) for a,w,_,_ in ins]).replace('generated by experiments/gen_code_lemmas.py','GENERATED by scripts/syi/gen_fn.py --ocaml-allocation')}
    E=lib.Emitter()
    for m in ['OCaml.Vm.Primitives.Effects','OCaml.Vm.Primitives.Leaf','OCaml.Vm.Primitives.Control','OCaml.Vm.Primitives.Write','Vsa.Sim.ChainFactsTac','Vsa.Sim.Code.Caml_copy_double']+sorted({decode[i.word] for b in [first,second] for i in b.instrs+[b.term]}):E('import '+m)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-allocation. Nursery fast-path certificates; the collector path remains a separate obligation. -/',
      'namespace OCaml.Vm.Primitives.DoubleAllocation', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable','')
    emit_loaded(E,fn,ins,pred,text_base)
    E('def domainGlobal : BitVec 64 := BitVec.ofNat 64 Layout.sym_Caml_state',
      'def youngSlot (domain : BitVec 64) : BitVec 64 := domain + BitVec.ofNat 64 Layout.off_young_ptr',
      'def limitSlot (domain : BitVec 64) : BitVec 64 := domain + BitVec.ofNat 64 Layout.off_young_limit',
      'def reserveLog (domain young : BitVec 64) : List WEntry := [( (youngSlot domain).toNat, 8, young - 16#64)]',
      'def headerLog (header : BitVec 64) : List WEntry := [(header.toNat, 8, 1277#64)]',
      'def initializeLog (header young bits : BitVec 64) : List WEntry := headerLog header ++ [((young + 8#64).toNat, 8, bits)]','')
    pure='runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG, imm20Of, LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg'
    for name,b,keys,L,params,loads,regs in [
        ('reserve',first,[1,10],'[(1, ra), (10, bits)]','ra bits','[bd, byoung, blimit]',
         '[(15, bytesVal .ld byoung - 16#64), (13, bytesVal .ld blimit), (17, bits), (14, bytesVal .ld bd), (16, domainGlobal), (1, ra), (10, bits)]'),
        ('initialize',second,[1,15,16,17],'[(1, ra), (15, header), (16, domainGlobal), (17, bits)]','ra header bits','[bd, byoung]',
         '[(10, bytesVal .ld byoung + 8#64), (15, bytesVal .ld bd), (14, 1277#64), (1, ra), (16, domainGlobal), (17, bits)]')]:
        bs='bd byoung blimit' if name=='reserve' else 'bd byoung'
        term=lib.decode_terminator(b.term,taken=False)['record']
        E(f'def {name}_body : List MInstr := [',',\n'.join('  '+literal(i.addr,i.word) for i in b.instrs),']',
          f'def {name}_blocks : List BBlock := [{{ body := {name}_body, term := some {term} }}]',
          f'def {name}_regs ({params} : BitVec 64) ({bs} : List (BitVec 8)) : GRegs := {regs}',
          f'theorem {name}_eval ({params} : BitVec 64) ({bs} : List (BitVec 8)) :',
          f'    runGM {name}_body {L} {loads} = {name}_regs {params} {bs} := by',
          f'  simp [{name}_body, {name}_regs, domainGlobal, Layout.sym_Caml_state, {pure}]','',
          f'theorem {name}_shape : ChainOK 0x{b.start:08x}#64 {keys} {name}_blocks := by',
          f'  simp only [ChainOK, BBlockOK, {name}_blocks, {name}_body, BlockOKM]',
          '  repeat apply And.intro', '  all_goals decide','')
        E(f'theorem {name}_facts (c : Config) ({params} : BitVec 64) ({bs} : List (BitVec 8))',f'    (hc : {pred} c.σ.mem)')
        if name=='reserve':
            E('    (globalRead : ReadWindow domainGlobal 8)',
              '    (youngRead : ReadWindow (youngSlot (bytesVal .ld bd)) 8)',
              '    (limitRead : ReadWindow (limitSlot (bytesVal .ld bd)) 8)',
              '    (youngWrite : WriteWindow (youngSlot (bytesVal .ld bd)) 8)',
              '    (domainPins : LPins8 c.σ.mem domainGlobal.toNat bd)',
              '    (youngPins : LPins8 c.σ.mem (youngSlot (bytesVal .ld bd)).toNat byoung)',
              '    (limitPins : LPins8 c.σ.mem (limitSlot (bytesVal .ld bd)).toNat blimit)')
            facts=['globalRead.ld rfl ?_ domainPins', 'youngRead.ld rfl ?_ youngPins', 'limitRead.ld rfl ?_ limitPins', 'youngWrite.sd rfl']
        else:
            E('    (headerWrite : WriteWindow header 8)',
              '    (globalRead : ReadWindow domainGlobal 8)',
              '    (youngRead : ReadWindow (youngSlot (bytesVal .ld bd)) 8)',
              '    (dataWrite : WriteWindow (bytesVal .ld byoung + 8#64) 8)',
              '    (domainPins : LPins8 (writeLog c.σ.mem (headerLog header)) domainGlobal.toNat bd)',
              '    (youngPins : LPins8 (writeLog c.σ.mem (headerLog header)) (youngSlot (bytesVal .ld bd)).toNat byoung)')
            facts=['headerWrite.sd rfl', 'globalRead.ld rfl ?_ domainPins', 'youngRead.ld rfl ?_ youngPins', 'dataWrite.sd rfl']
        E(f'    : ProgFactsM c.σ.mem c.σ.mem {L} {loads} {name}_body := by',f'  chain_facts hc with "Vsa.Sim.Code.{fn}_at_"')
        for f in facts:
            if name=='initialize' and '.ld ' in f:
                E('  · change MemFacts (applyW c.σ.mem ((header + 0#64).toNat, 8, 1277#64)) _ _ _',
                  '    simp only [BitVec.add_zero]', '    apply '+f)
            else:
                E('  · apply '+f)
            E(
              f'    simp [eaddrM, youngSlot, limitSlot, domainGlobal, Layout.sym_Caml_state, Layout.off_young_ptr, Layout.off_young_limit, {pure}]')
        E('')
        log='reserveLog (bytesVal .ld bd) (bytesVal .ld byoung)' if name=='reserve' else 'initializeLog header (bytesVal .ld byoung) bits'
        E(f'theorem {name}_log ({params} : BitVec 64) ({bs} : List (BitVec 8)) :',
          f'    (evalBlocks {name}_blocks (SegEvalState.init {L} {loads})).log = {log} := by')
        if name=='reserve':
            E('  have down : LeanRV64DExecutable.Functions.sign_extend (m := 64) (0xff0#12) = -16#64 := by decide',
              '  change [((bytesVal .ld bd + 8#64).toNat, 8, bytesVal .ld byoung + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0xff0#12))] = _',
              '  rw [down, ← BitVec.sub_eq_add_neg]', '  rfl')
        else:
            E('  change [((header + 0#64).toNat, 8, 1277#64), ((bytesVal .ld byoung + 8#64).toNat, 8, bits)] = _',
              '  simp only [BitVec.add_zero, initializeLog, headerLog, List.cons_append, List.nil_append]')
        writes='[13, 14, 15, 16, 17]' if name=='reserve' else '[10, 14, 15]'
        pc=f'0x{b.term.addr+4:08x}#64' if name=='reserve' else 'ra'
        value='bits' if name=='reserve' else '(bytesVal .ld byoung + 8#64)'
        E('', f'theorem {name}_summary (c : Config) ({params} : BitVec 64) ({bs} : List (BitVec 8))',
          '    (h : LeafInput ra c)', f'    (hr : GHolds c.σ {L})',
          f'    (facts : ProgFactsM c.σ.mem c.σ.mem {L} {loads} {name}_body)',
          f'    (outside : ImageOutside ({log}))')
        if name=='reserve': E('    (branch : guardB .BLTU (bytesVal .ld byoung - 16#64) (bytesVal .ld blimit) = false)')
        E(f'    : FnSummary 0x{b.start:08x}#64 (fun d => d = c)',
          f'      (WriteRegistersPost {writes} ({log}) c {pc} {value} ({name}_regs {params} {bs})) := by',
          f'  have ht : TermFactsO (runGM {name}_body {L} {loads}) (some {term}) := by',
          f'    rw [{name}_eval]')
        if name=='reserve': E(f'    simpa [TermFactsO, TermFactsT, {name}_regs, srcVal, lookupG] using branch')
        else: E(f'    apply return_facts _ rfl rfl rfl ?_ h.aligned',f'    simp [{name}_regs, srcVal, lookupG]')
        E(f'  have S := block_summary {name}_blocks 0x{b.start:08x}#64 {L} {loads} c',
          f'    ⟨h.good, h.minstret, hr, (by change KeysOK {keys}; decide),',
          '      singleton_chain_facts facts',
          f'        (by have hc := loaded h.image; chain_facts hc with "Vsa.Sim.Code.{fn}_at_") ht,',
          f'      {name}_shape, h.tick⟩',
          '  apply registers_of_blocks h.image outside S',
          f'  · exact {name}_log {params} {bs}',
          f'  · simp only [evalBlocksPC, {name}_blocks, SegEvalState.init, chainEndPC, endPCB, tgtPCT]')
        if name=='reserve':E('    rfl')
        else:E(f'    rw [{name}_eval]', '    change Sail.BitVec.update (ra + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0#12)) 0 0#1 = ra',
               '    exact ret_tgt ra h.aligned')
        E(f'  · exact {name}_eval {params} {bs}', '  · rfl', '  · decide', '')
    E('end OCaml.Vm.Primitives.DoubleAllocation','')
    result[root/'OCaml/Vm/Primitives/DoubleAllocation.lean']=E.text()
    from ocaml_tail import emit_int64_tail
    result.update(emit_int64_tail(root, functions, decode, code, text_base, lib, build_cfg, literal))
    return result
