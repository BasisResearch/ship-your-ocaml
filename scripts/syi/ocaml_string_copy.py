"""Generated call boundaries for the scanned and explicit-length string constructors."""
from ocaml_certificates import emit_loaded
from ocaml_block_certificates import emit_block, emit_call


def emit_string_copy(root, functions, decode, code, text_base, lib, build_cfg, literal, initialized=False):
    fn = 'caml_alloc_initialized_string' if initialized else 'caml_copy_string'
    ins = functions[fn]['insts']
    di = {a: lib.Instr(a, w, op, args, f'{op} {args}') for a, w, op, args in ins}
    _, cfg = build_cfg(fn, ins[0][0], di, {fn: (ins[0][0], ins[-1][0] + 4)})
    if [b.kind for b in cfg] != (['jal', 'jal', 'ret'] if initialized else ['jal', 'jal', 'jal', 'ret']):
        raise ValueError(f'{fn} CFG changed')
    if [b.callee for b in cfg if b.kind == 'jal'] != (['caml_alloc_string', 'memcpy'] if initialized else ['strlen', 'caml_alloc_string', 'memcpy']):
        raise ValueError(f'{fn} callees changed')
    stem = 'Caml_alloc_initialized_string' if initialized else 'Caml_copy_string'
    namespace = 'InitializedString' if initialized else 'StringCopy'
    output_module = 'InitializedStringSteps' if initialized else 'StringCopy'
    pred = f'Vsa.Sim.Code.{stem}Loaded'
    result = {root / f'Vsa/Sim/Code/{stem}.lean': code.render(fn, [(a, w) for a, w, _, _ in ins]).replace(
        'generated by experiments/gen_code_lemmas.py', 'GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper')}
    E = lib.Emitter()
    for module in ['OCaml.Vm.Primitives.AccessPlan', 'OCaml.Vm.Primitives.Call',
                   'Vsa.Sim.ChainFactsTac', f'Vsa.Sim.Code.{stem}'] + sorted({decode[w] for _, w, _, _ in ins}):
        E('import ' + module)
    E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-string-wrapper. -/',
      f'namespace OCaml.Vm.Primitives.{namespace}', 'open Vsa.Machine Vsa.Sim LeanRV64DExecutable', '')
    emit_loaded(E, fn, ins, pred, text_base)
    selected = [('save', [1, 2, 10]), ('size', [1, 2, 10]),
                ('arguments', [1, 2, 10]), ('restore', [2, 10])]
    if initialized:
        selected = [('save', [1, 2, 10, 11]), ('arguments', [1, 2, 10]), ('restore', [2, 10])]
    for (name, keys), b in zip(selected, cfg):
        emit_block(E, fn, b, name, keys, lib, literal)
        regs = {
            'save': ('[(2, R 2 - 32#64), (1, R 1), (10, R 10), (11, R 11)]' if initialized else '[(2, R 2 - 32#64), (1, R 1), (10, R 10)]'),
            'size': '[(1, R 1), (2, R 2), (10, R 10)]',
            'arguments': '[(11, bytesVal .ld (loads.getD 1 [])), (12, bytesVal .ld (loads.getD 0 [])), (1, R 1), (2, R 2), (10, R 10)]',
            'restore': '[(2, R 2 + 32#64), (1, bytesVal .ld (loads.getD 0 [])), (10, R 10)]',
        }[name]
        E(f'def {name}_regs (R : Nat → BitVec 64) (loads : List (List (BitVec 8))) : GRegs :=',
          '  ' + regs,
          f'theorem {name}_eval (R : Nat → BitVec 64) (loads : List (List (BitVec 8))) :',
          f'    runGM {name}_body ({name}_input R) loads = {name}_regs R loads := by',
          f'  simp [{name}_body, {name}_input, {name}_regs, runGM, stepGM, stepLdsM,',
          '    wvalM, srcVal, lookupG, eraseG, LeanRV64DExecutable.Functions.sign_extend,',
          '    Sail.BitVec.signExtend, BitVec.sub_eq_add_neg, List.head?_eq_getElem?]', '')
        if b.kind != 'jal':
            continue
        emit_call(E, fn, b, name, functions, lib)
    E(f'end OCaml.Vm.Primitives.{namespace}', '')
    result[root / f'OCaml/Vm/Primitives/{output_module}.lean'] = E.text()
    return result
