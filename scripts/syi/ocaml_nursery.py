"""Common block certificates for the nursery allocation families."""
from ocaml_certificates import emit_loaded
from ocaml_block_certificates import emit_block


def emit_nursery(root, functions, decode, code, text_base, lib, build_cfg, literal):
    result = {}
    families = [
        ('caml_alloc_small', 'SmallAllocation', [
            ('reserve', [1, 10, 11]), ('initialize', [1, 10, 11, 14, 17])]),
        ('caml_alloc_string', 'StringAllocation', [
            ('prepare', [1, 2, 10]), ('reserve', [1, 2, 10, 14, 15]),
            ('initialize', [1, 2, 10, 13, 14, 15, 16])]),
    ]
    for fn, namespace, selected in families:
        ins = functions[fn]['insts']
        di = {a: lib.Instr(a, w, op, args, f'{op} {args}') for a, w, op, args in ins}
        _, cfg = build_cfg(fn, ins[0][0], di, {fn: (ins[0][0], ins[-1][0] + 4)})
        # A branch from the major allocator enters the nursery's final suffix;
        # merge that fallthrough split for the selected straight nursery path.
        from copy import copy
        normalized = []
        i = 0
        while i < len(cfg):
            b = cfg[i]
            if b.kind == 'fallthrough':
                tail = cfg[i + 1]
                merged = copy(tail)
                merged.start, merged.instrs = b.start, b.instrs + tail.instrs
                b = merged
                i += 1
            normalized.append(b)
            i += 1
        blocks = normalized[:len(selected)]
        assert [b.kind for b in blocks] == ['br'] * (len(blocks) - 1) + ['ret']
        stem = fn[0].upper() + fn[1:]
        pred = f'Vsa.Sim.Code.{stem}Loaded'
        result[root / f'Vsa/Sim/Code/{stem}.lean'] = code.render(fn, [(a, w) for a, w, _, _ in ins]).replace(
            'generated by experiments/gen_code_lemmas.py', 'GENERATED by scripts/syi/gen_fn.py --ocaml-allocation')
        E = lib.Emitter()
        for m in ['OCaml.Vm.Primitives.AccessPlan', 'OCaml.Vm.Primitives.Leaf',
                  'Vsa.Sim.ChainFactsTac', 'OCaml.Vm.Primitives.DoubleAllocation', f'Vsa.Sim.Code.{stem}'] + sorted({decode[i.word] for b in blocks for i in b.instrs + [b.term]}):
            E('import ' + m)
        E('', '/-! GENERATED by scripts/syi/gen_fn.py --ocaml-allocation.',
          'Nursery blocks; access plans contain scalar obligations only. -/',
          f'namespace OCaml.Vm.Primitives.{namespace}',
          'open Vsa.Machine Vsa.Sim LeanRV64DExecutable', '')
        emit_loaded(E, fn, ins, pred, text_base)
        for (name, keys), b in zip(selected, blocks):
            emit_block(E, fn, b, name, keys, lib, literal)
        if namespace == 'StringAllocation':
            E('def reserve_regs (R : Nat → BitVec 64) (bd byoung blimit : List (BitVec 8)) : GRegs :=',
              '  [(13, bytesVal .ld byoung - 8#64 - R 15), (17, bytesVal .ld blimit),',
              '   (11, -8#64 - R 15), (12, bytesVal .ld bd), (16, DoubleAllocation.domainGlobal),',
              '   (1, R 1), (2, R 2), (10, R 10), (14, R 14), (15, R 15)]',
              'theorem reserve_eval (R : Nat → BitVec 64) (bd byoung blimit : List (BitVec 8)) :',
              '    runGM reserve_body (reserve_input R) [bd, byoung, blimit] = reserve_regs R bd byoung blimit := by',
              '  simp [reserve_body, reserve_input, reserve_regs, runGM, stepGM, stepLdsM,',
              '    wvalM, srcVal, lookupG, eraseG, imm20Of, DoubleAllocation.domainGlobal, Layout.sym_Caml_state,',
              '    LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg]',
              '  bv_omega', '')
            E('def paddingWord (span length : BitVec 64) : BitVec 64 :=',
              '  LeanRV64DExecutable.Functions.sign_extend (m := 64)',
              '    (Sail.BitVec.extractLsb (span - 1#64) 31 0 - Sail.BitVec.extractLsb length 31 0)',
              'def initialize_regs (R : Nat → BitVec 64) (byoung bra : List (BitVec 8)) : GRegs :=',
              '  [(2, R 2 + 48#64), (1, bytesVal .ld bra),',
              '   (15, bytesVal .ld byoung + 8#64 + (R 15 - 1#64)),',
              '   (14, paddingWord (R 15) (R 14)), (13, bytesVal .ld byoung + 8#64 + R 15),',
              '   (10, bytesVal .ld byoung + 8#64), (16, R 16)]',
              'theorem initialize_eval (R : Nat → BitVec 64) (bd byoung bra : List (BitVec 8)) :',
              '    runGM initialize_body (initialize_input R) [bd, byoung, bra] = initialize_regs R byoung bra := by',
              '  simp [initialize_body, initialize_input, initialize_regs, paddingWord, runGM, stepGM, stepLdsM,',
              '    wvalM, srcVal, lookupG, eraseG,',
              '    LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg]', '')
            E('def stringWords (n : BitVec 64) : BitVec 64 := (n + 8#64) >>> 3',
              'def stringSpan (n : BitVec 64) : BitVec 64 := (n + 8#64) &&& (-8#64)',
              'def prepare_regs (R : Nat → BitVec 64) : GRegs :=',
              '  [(15, stringSpan (R 10)), (13, 256#64), (10, stringWords (R 10)),',
              '   (14, R 10), (2, R 2 - 48#64), (1, R 1)]',
              'theorem prepare_eval (R : Nat → BitVec 64) (loads : List (List (BitVec 8))) :',
              '    runGM prepare_body (prepare_input R) loads = prepare_regs R := by',
              '  simp [prepare_body, prepare_input, prepare_regs, stringWords, stringSpan,',
              '    runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG,',
              '    LeanRV64DExecutable.Functions.sign_extend, Sail.BitVec.signExtend, BitVec.sub_eq_add_neg,',
              '    shamtOf, Sail.BitVec.extractLsb, Sail.shift_bits_right]', '')
        E(f'end OCaml.Vm.Primitives.{namespace}', '')
        result[root / f'OCaml/Vm/Primitives/{namespace}.lean'] = E.text()
    return result
