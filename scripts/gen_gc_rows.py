#!/usr/bin/env python3
"""Generate collector/barrier row candidates through the mandatory gen_fn route.
All machine words come from the pinned ELF. No data address is supplied by hand.
"""
import argparse
import contextlib
import importlib.util
import io
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile
from census import ROOT, TOOLS

sys.path.insert(0, str(ROOT / 'scripts/syi'))
import gen_fn
spec = importlib.util.spec_from_file_location('gc_code', ROOT / 'experiments/syi/gen_code_lemmas.py')
code = importlib.util.module_from_spec(spec)
spec.loader.exec_module(code)


def immediate_route(name, entry, di, extents):
    _, blocks = gen_fn.build_cfg(name, entry, di, extents)
    first = blocks[0]
    assert first.kind == "br" and first.term.mnem == "bnez"
    last = next(b for b in blocks if b.start == first.succs[0])
    assert last.kind == "ret"
    text = IMMEDIATE_TEMPLATE
    for key, value in {"ENTRYSEG": gen_fn.block_name(name, first, True)+"Seg",
                       "EXITSEG": gen_fn.block_name(name, last)+"Seg",
                       "ENTRYREGS": gen_fn.block_name(name, first, True)+"L",
                       "PC": hex(entry)}.items():
        text = text.replace("@"+key+"@", value)
    return text


def outputs():
    result = {}
    audits = []
    pin_audits = []
    immediate_audits = []
    control_audits = []
    pop_audits = []
    modules = []
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        disasm = tmp / 'disasm.txt'
        with disasm.open('w') as f:
            subprocess.run([TOOLS + 'objdump', '-d', str(ROOT / 'c/ocamlrun-riscv-htif.elf')],
                           stdout=f, check=True)
        di = gen_fn.lib.parse_disasm(str(disasm))
        extents = gen_fn.function_extents(str(disasm))
        index = tmp / 'index.tsv'
        decodes = []
        for p in sorted((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean')):
            decodes += [w + '\tVsa.Sim.ElfDecode.' + p.stem
                        for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)]
        index.write_text('\n'.join(decodes) + '\n')
        for name, stem in [('caml_oldify_one', 'OldifyOne'), ('caml_modify', 'Modify'),
                           ('caml_oldify_mopup', 'Mopup')]:
            entry, end = extents[name]
            words = [(a, di[a].word) for a in sorted(di) if entry <= a < end]
            pin_name = name[0].upper() + name[1:]
            pins = code.render(name, words).replace(
                'generated by experiments/gen_code_lemmas.py',
                'GENERATED by scripts/gen_gc_rows.py via experiments/syi/gen_code_lemmas.py')
            result[ROOT / f'Vsa/Sim/Code/{pin_name}.lean'] = pins
            pin_audits += re.findall(r'^theorem (\w+)', pins, re.M)
            jobs = [(entry, stem, None)]
            if name == 'caml_oldify_mopup':
                # Real CFG cutpoints: prologue, deferred work loop, ephemeron loop.
                # These are CODE offsets; data references stay ELF-derived.
                heads = [entry, entry + 0x4c, entry + 0xdc]
                jobs = [(pc, 'Mopup' + part, [x for x in heads if x != pc])
                        for pc, part in zip(heads, ['Entry', 'Deferred', 'Ephemerons'])]
                seen, report = set(), []
                for pc, part, cuts in jobs:
                    body, blocks = gen_fn.build_cfg(name, pc, di, extents, region_exits=cuts)
                    covered = {i.addr for i in body}
                    assert not seen & covered, 'mopup regions overlap'
                    seen |= covered
                    report.append({'module': part, 'entry': hex(pc),
                                   'instructions': len(body), 'blocks': len(blocks),
                                   'branches': sum(b.kind == 'br' for b in blocks),
                                   'exits': sorted({hex(x) for b in blocks for x in b.succs if x in cuts})})
                assert seen == {a for a, _ in words}, 'mopup region coverage gap'
                result[ROOT / 'results/gc-mopup-regions.json'] = json.dumps(report, indent=2) + '\n'
                _, prologue = gen_fn.build_cfg(name, entry, di, extents, region_exits=heads[1:])
                pname = gen_fn.block_name(name, prologue[0])
                control = CONTROL_TEMPLATE.replace('@ENTRYPOST@', pname[0].upper() + pname[1:] + 'Post').replace('@ENTRYSEG@', pname + 'Seg').replace('@ENTRYREGS@', pname + 'L')
                result[ROOT / 'OCaml/Vm/Gc/Generated/MopupControl.lean'] = control
                control_audits = re.findall(r'^theorem ([\w.]+)', control, re.M)
                _, deferred = gen_fn.build_cfg(name, heads[1], di, extents, region_exits=[heads[0], heads[2]])
                head = next(b for b in deferred if b.start == heads[1])
                child = next(b for b in deferred if b.start == head.succs[1])
                assert head.kind == child.kind == 'br'
                pop = POP_TEMPLATE
                for key, val in {'HEAD': gen_fn.block_name(name, head, False)+'Seg',
                                 'TAKEN': gen_fn.block_name(name, child, True)+'Seg',
                                 'FALL': gen_fn.block_name(name, child, False)+'Seg',
                                 'PC': hex(head.start)}.items():
                    pop = pop.replace('@'+key+'@', val)
                result[ROOT / 'OCaml/Vm/Gc/Generated/MopupPop.lean'] = pop
                pop_audits = re.findall(r'^theorem ([\w.]+)', pop, re.M)
            for region_entry, part, cuts in jobs:
                modules.append(part)
                path = tmp / (part + '.lean')
                with contextlib.redirect_stdout(io.StringIO()):
                    gen_fn.emit_fn(name, region_entry, str(path), verify=False,
                                   disasm_path=str(disasm), decode_index=str(index), region_exits=cuts)
                text = path.read_text().replace(
                    'GENERATED by `scripts/gen_fn.py',
                    'GENERATED by scripts/gen_gc_rows.py via `scripts/syi/gen_fn.py').replace(
                    'from `experiments/disasm.txt`', 'from the pinned runtime ELF').replace(
                    'GENERATED whole-function summary blocks (scripts/gen_fn.py)',
                    'GENERATED machine segments (scripts/syi/gen_fn.py)')
                result[ROOT / f'OCaml/Vm/Gc/Generated/{part}.lean'] = text
                audits += re.findall(r'^theorem (\w+)', text, re.M)
                audits += [n + '_seg' for n in re.findall(r'^#derive_case (\w+)', text, re.M)]
            if name == "caml_oldify_one":
                immediate = immediate_route(name, entry, di, extents)
                result[ROOT / "OCaml/Vm/Gc/Generated/Immediate.lean"] = immediate
                immediate_audits = re.findall(r"^theorem ([\w.]+)", immediate, re.M)
    names = ['Vsa.Sim.' + n for n in audits] + ['Vsa.Sim.Code.' + n for n in pin_audits]
    names += ['OCaml.Vm.Gc.Immediate.' + n for n in immediate_audits]
    names += ['OCaml.Vm.Gc.MopupControl.' + n for n in control_audits]
    names += ['OCaml.Vm.Gc.MopupPop.' + n for n in pop_audits]
    literals = ',\n'.join('  ``' + n for n in names)
    result[ROOT / 'OCaml/Vm/Gc/Generated/Audit.lean'] = (
        ''.join('import OCaml.Vm.Gc.Generated.' + module + '\n' for module in modules + ['Immediate', 'MopupControl', 'MopupPop']) + '\n' +
        '/-! GENERATED by scripts/gen_gc_rows.py. Every generated row, segment and code pin. -/\n'
        'open Lean Elab Command\n\n'
        'private def gcAuditNames : Array Name := #[\n' + literals + '\n]\n\n'
        'elab "#audit_gc_rows" : command => do\n'
        '  for name in gcAuditNames do\n'
        '    elabCommand (← `(command| #print axioms $(mkIdent name)))\n')
    return result


IMMEDIATE_TEMPLATE = """import OCaml.Vm.Gc.Generated.OldifyOne
import Vsa.Sim.WriteLogLast
import Vsa.Sim.SegmentSummary

/-! GENERATED by scripts/gen_gc_rows.py from gen_fn's taken entry edge and
return block. This is the oldify immediate route, not the copying loop. -/
namespace OCaml.Vm.Gc.Immediate
open Vsa.Sim
open Vsa.Machine (Config)
open Vsa.Logic (Triple)

def blocks := @ENTRYSEG@ ++ @EXITSEG@
def pc : BitVec 64 := @PC@#64
def regs := @ENTRYREGS@

theorem chain_ok : ChainOK pc [2, 8, 9, 1, 10, 11] blocks := by decide

def outcome (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8))) :=
  evalBlocks blocks (SegEvalState.init (regs sp s0 s1 ra value root) lds)

/-- The last write is precisely the unchanged immediate to the destination.
The other writes are the three caller-save slots on the C stack. -/
theorem root_write (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8))) :
    (outcome sp s0 s1 ra value root lds).log.getLast? = some (root.toNat, 8, value) := by
  change some (((root + 0) + 0).toNat, 8, value + 0) = _
  have zero (x : BitVec 64) : x + 0 = x := BitVec.add_zero x
  simp only [zero]

/-- The return target is the first saved word loaded by the epilogue. -/
theorem return_pc (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8))) :
    evalBlocksPC pc (SegEvalState.init (regs sp s0 s1 ra value root) lds) blocks =
      Sail.BitVec.update (bytesVal .ld (lds.headD []) + 0) 0 0#1 := by
  rfl

/-- The stack pointer is restored by the generated prologue and epilogue. -/
theorem stack_restored (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8))) :
    lookupG 2 (outcome sp s0 s1 ra value root lds).regs = some sp := by
  change some ((sp + 18446744073709551504) + 112) = _
  rw [BitVec.add_assoc]
  exact congrArg some (BitVec.add_zero sp)

/-- The shared reflected post retains exact memory and register effects. -/
abbrev Post (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8)))
    (mem : Std.ExtHashMap Nat (BitVec 8)) :=
  SegmentPost blocks (regs sp s0 s1 ra value root) lds pc mem

/-- Readable root postcondition, extracted from the exact final store. -/
theorem Post.root_value {sp s0 s1 ra value root lds mem c}
    (post : Post sp s0 s1 ra value root lds mem c) : Pin8 c.σ.mem root.toNat value := by
  rw [post.memory]
  exact pin8_of_last_write mem _ root.toNat value (root_write sp s0 s1 ra value root lds)

/-- The concrete returned machine stack pointer equals its entry value. -/
theorem Post.stack {sp s0 s1 ra value root lds mem c}
    (post : Post sp s0 s1 ra value root lds mem c) : gprGet c.σ 2 = some sp :=
  gholds_lookup _ post.registers (stack_restored sp s0 s1 ra value root lds)

/-- A saved return-word read gives the caller target (RISC-V clears bit zero). -/
theorem Post.returns {sp s0 s1 ra value root lds mem c}
    (post : Post sp s0 s1 ra value root lds mem c)
    (saved : bytesVal .ld (lds.headD []) = ra) :
    c.σ.regs.get? LeanRV64DExecutable.Register.PC = some (Sail.BitVec.update ra 0 0#1) := by
  rw [post.pc, return_pc, saved]
  have zero : ra + 0 = ra := BitVec.add_zero ra
  rw [zero]

/-- Composed real machine run along the immediate branch, including ret.
SegPre supplies the concrete branch, code, load and store facts. -/
theorem run (sp s0 s1 ra value root : BitVec 64) (lds : List (List (BitVec 8)))
    (mem : Std.ExtHashMap Nat (BitVec 8)) :
    FnSummary pc (SegPre blocks (regs sp s0 s1 ra value root) lds pc mem)
      (Post sp s0 s1 ra value root lds mem) :=
  segmentSummary blocks (regs sp s0 s1 ra value root) lds pc mem chain_ok

end OCaml.Vm.Gc.Immediate
"""


CONTROL_TEMPLATE = """import OCaml.Vm.Gc.Generated.MopupEntry
import OCaml.Vm.Layout

/-! GENERATED by scripts/gen_gc_rows.py. Data addresses come from Layout;
the prologue's AUIPC-relative computations are checked against them. -/
namespace OCaml.Vm.Gc.MopupControl
open Vsa.Sim Vsa.Machine

structure Saved where
  sp : BitVec 64
  s4 : BitVec 64
  s5 : BitVec 64
  s6 : BitVec 64
  s7 : BitVec 64
  s8 : BitVec 64
  ra : BitVec 64
  s0 : BitVec 64
  s1 : BitVec 64
  s2 : BitVec 64
  s3 : BitVec 64

/-- Registers fixed by the real mopup prologue. -/
structure RuntimeRegisters (c : Config) : Prop where
  todo : gprGet c.σ 23 = some (BitVec.ofNat 64 Layout.sym_oldify_todo_list)
  domain : gprGet c.σ 22 = some (BitVec.ofNat 64 Layout.sym_Caml_state)
  epheNone : gprGet c.σ 20 = some (BitVec.ofNat 64 Layout.sym_caml_ephe_none)
  infixTag : gprGet c.σ 21 = some 249
  one : gprGet c.σ 24 = some 1

/-- The generated prologue establishes its runtime-address pins. -/
theorem entry_registers (r : Saved) {lds mem c}
    (post : @ENTRYPOST@ r.sp r.s4 r.s5 r.s6 r.s7 r.s8 r.ra r.s0 r.s1 r.s2 r.s3 lds mem c) :
    RuntimeRegisters c := by
  constructor <;> apply gholds_lookup _ post.registers
  all_goals simp [@ENTRYSEG@, @ENTRYREGS@, evalBlocks, evalBlock,
    SegEvalState.init, runGM, stepGM, mkLine, decodeM, wvalM, srcVal, lookupG,
    eraseG, imm20Of, LeanRV64DExecutable.Functions.sign_extend,
    Sail.BitVec.signExtend, Layout.sym_oldify_todo_list, Layout.sym_Caml_state,
    Layout.sym_caml_ephe_none]

end OCaml.Vm.Gc.MopupControl
"""

POP_TEMPLATE = """import OCaml.Vm.Gc.Generated.MopupDeferred
import OCaml.Vm.Layout
import Vsa.Sim.SegmentSummary
import Vsa.Sim.WriteLogLast

/-! GENERATED by scripts/gen_gc_rows.py. Pop the intrusive queue before any
recursive child visit. The two outcomes select the child immediate test. -/
namespace OCaml.Vm.Gc.MopupPop
open Vsa.Sim Vsa.Machine

def blocks (immediate : Bool) := @HEAD@ ++ if immediate then @TAKEN@ else @FALL@
def pc : BitVec 64 := @PC@#64
def regs : GRegs := [(23, BitVec.ofNat 64 Layout.sym_oldify_todo_list)]
def outcome (immediate : Bool) (lds : List (List (BitVec 8))) :=
  evalBlocks (blocks immediate) (SegEvalState.init regs lds)

theorem chain_ok (immediate : Bool) : ChainOK pc [23] (blocks immediate) := by
  cases immediate <;> decide

/-- Exactly one store: publish the next SOURCE pointer before scanning fields.
The next link is the third of the four loads in this composed path. -/
theorem queue_write (immediate : Bool) (lds : List (List (BitVec 8))) :
    (outcome immediate lds).log =
      [(Layout.sym_oldify_todo_list, 8, bytesVal .ld (lds.tail.tail.headD []))] := by
  cases immediate <;> rfl

abbrev Post (immediate : Bool) (lds : List (List (BitVec 8)))
    (mem : Std.ExtHashMap Nat (BitVec 8)) :=
  SegmentPost (blocks immediate) regs lds pc mem

/-- The concrete root of the work list now contains that next source pointer. -/
theorem Post.todo {immediate lds mem c} (post : Post immediate lds mem c) :
    Pin8 c.σ.mem Layout.sym_oldify_todo_list (bytesVal .ld (lds.tail.tail.headD [])) := by
  rw [post.memory]
  apply pin8_of_last_write
  change (outcome immediate lds).log.getLast? = _
  rw [queue_write]
  rfl

/-- The machine removes one pending copy before entering the child classifier.
No oldify call or loop invariant is assumed proved by this summary. -/
theorem run (immediate : Bool) (lds : List (List (BitVec 8)))
    (mem : Std.ExtHashMap Nat (BitVec 8)) :
    FnSummary pc (SegPre (blocks immediate) regs lds pc mem) (Post immediate lds mem) :=
  segmentSummary (blocks immediate) regs lds pc mem (chain_ok immediate)

end OCaml.Vm.Gc.MopupPop
"""

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'generated GC row drift: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(path.relative_to(ROOT))
