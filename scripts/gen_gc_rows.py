def immediate_route(name, entry, di, extents):
    _, blocks = gen_fn.build_cfg(name, entry, di, extents)
    first = blocks[0]
    assert first.kind == "br" and first.term.mnem == "bnez"
    last = next(b for b in blocks if b.start == first.succs[0])
    assert last.kind == "ret"
    text = IMMEDIATE_TEMPLATE
    for key, value in {"ENTRYSEG": gen_fn.block_name(name, first, True)+"Seg",
                       "EXITSEG": gen_fn.block_name(name, last)+"Seg",
                       "ENTRYREGS": gen_fn.block_name(name, first, True)+"L",
                       "PC": hex(entry)}.items():
        text = text.replace("@"+key+"@", value)
    return text


def native_return_certificate(name, module, namespace, epilogue, decode_modules, payload=False):
    """One native epilogue template, optionally returning header + payload offset."""
    assert epilogue.kind == 'ret'
    slots = []
    for ins in epilogue.instrs[:(-2 if payload else -1)]:
        assert ins.word & 0x707f == 0x3003 and (ins.word >> 15) & 31 == 2
        slots.append(((ins.word >> 7) & 31, gen_fn.lib.sext(ins.word >> 20, 12)))
    adjust = epilogue.instrs[-1].word
    assert adjust & 0xfffff == 0x10113
    size = gen_fn.lib.sext(adjust >> 20, 12)
    assert slots[0][0] == 1 and all(r != 2 and o >= 0 for r, o in slots)
    words = {f'{ins.word:08x}' for ins in [*epilogue.instrs, epilogue.term]}
    text = RETURN_TEMPLATE
    if payload:
        bump = epilogue.instrs[-2].word
        assert bump & 0xfffff == 0x50513
        increment = gen_fn.lib.sext(bump >> 20, 12)
        text = text.replace('(sp : BitVec 64)', '(sp hp : BitVec 64)')
        for definition in ('regs', 'loads', 'restored', 'returnWord', 'restored_regs', 'return_lookup'):
            text = re.sub(r'\b'+definition+r' sp\b', definition+' sp hp', text)
        text = text.replace(':= [(2, sp)]', ':= [(2, sp),(10,hp)]')
        text = text.replace('(2, sp + frameSize) :: slots.reverse.map',
                            f'(2, sp + frameSize) :: (10, hp + {increment}#64) :: slots.reverse.map')
        text = text.replace('ChainOK pc [2]', 'ChainOK pc [2,10]')
    text = text.replace('Generated.OldifyOne', 'Generated.'+module)
    text = text.replace('Gc.OldifyReturn', 'Gc.'+namespace)
    if payload:
        text = text.replace('Native oldify epilogue', 'Native '+name+' epilogue')
    pin = name[0].upper()+name[1:]
    text = text.replace('Caml_oldify_oneLoaded', pin+'Loaded').replace('caml_oldify_one_at_',name+'_at_')
    for key, val in {
        'DECODE_IMPORTS': '\n'.join('import '+m for m in sorted({decode_modules[w] for w in words})),
        'RETURN': gen_fn.block_name(name,epilogue)+'Seg', 'PC': hex(epilogue.start),
        'SLOTS': '['+', '.join(f'({r}, {o})' for r,o in slots)+']',
        'OFFSETS': str([o for r,o in slots]), 'SIZE': str(size),
        'RAOFFSET': str(slots[0][1]), 'WRITTEN': str([r for r,o in slots]+([10] if payload else [])+[2]),
        'WINDOW_CASES': '\n'.join(f'  · exact (windows {o} (by decide)).ld rfl rfl (read8_pins _ _)' for r,o in slots),
    }.items():
        text=text.replace('@'+key+'@',val)
    return text, slots, size


FFS_ZERO_TEMPLATE = r'''import OCaml.Vm.Gc.Generated.Ffs
import OCaml.Vm.Gc.ChainPlan
import Vsa.Sim.ChainFactsTac
@DECODE_IMPORTS@

/-! GENERATED by scripts/gen_gc_rows.py. Zero bitmap result of the actual
ffs callee used by the best-fit fallback. Nonzero search is a separate path. -/
namespace OCaml.Vm.Gc.FfsZero
open Vsa.Machine Vsa.Sim Primitives LeanRV64DExecutable

def headBlock : BBlock := @HEAD@.getD 0 {body := [],term := none}
def returnBlock : BBlock := @RETURN@.getD 0 {body := [],term := none}
def blocks := [headBlock,returnBlock]
def pc : BitVec 64 := @PC@#64
def regs (ra : BitVec 64) : GRegs := [(1,ra),(10,0)]
def afterHead (ra : BitVec 64) : GRegs := [(14,0),(1,ra),(10,0)]

theorem chain_ok : ChainOK pc [1,10] blocks := by decide

theorem code_facts {mem : Std.ExtHashMap Nat (BitVec 8)} (code : Code.FfsLoaded mem) :
    ChainCode mem blocks := by
  intro b member
  simp only [blocks,List.mem_cons,List.not_mem_nil,or_false] at member
  rcases member with rfl | rfl
  all_goals constructor
  all_goals simp only [headBlock,returnBlock,@HEAD@,@RETURN@,List.getD_cons_zero,CodeFacts]
  all_goals chain_facts code with "Vsa.Sim.Code.ffs_at_"

theorem head_regs (ra : BitVec 64) : runGM headBlock.body (regs ra) [] = afterHead ra := rfl

theorem result (ra : BitVec 64) :
    lookupG 10 (evalBlocks blocks (SegEvalState.init (regs ra) [])).regs = some 0 := rfl

theorem no_stores (ra : BitVec 64) :
    (evalBlocks blocks (SegEvalState.init (regs ra) [])).log = [] := rfl

theorem endpoint (ra : BitVec 64) (aligned : ra.toNat % 4 = 0) :
    evalBlocksPC pc (SegEvalState.init (regs ra) []) blocks = ra := by
  change Sail.BitVec.update (ra + Functions.sign_extend (m := 64) (0#12)) 0 0#1 = ra
  exact ret_tgt ra aligned

theorem access (mem : Std.ExtHashMap Nat (BitVec 8)) (ra : BitVec 64)
    (aligned : ra.toNat % 4 = 0) : ChainAccess mem (regs ra) [] blocks := by
  apply ChainAccess.cons (b := headBlock) ⟨?_,?_⟩
  · rw [head_regs]
    apply ChainAccess.cons (b := returnBlock) ⟨?_,?_⟩ ChainAccess.nil
    · simp [AccessPlan,returnBlock,@RETURN@,MemFacts,mkLine,decodeM]
    · change (Sail.BitVec.update (ra + Functions.sign_extend (m := 64) (0#12)) 0 0#1).toNat % 4 = 0
      rw [ret_tgt ra aligned]
      exact aligned
  · simp [AccessPlan,headBlock,@HEAD@,MemFacts,mkLine,decodeM]
  · rw [head_regs]
    simp [headBlock,@HEAD@,TermFactsO,TermFactsT,afterHead,srcVal,lookupG,guardB]

theorem written : ∀ n ∈ wrChain blocks, n ∈ [10,14] := by decide

end OCaml.Vm.Gc.FfsZero
'''


