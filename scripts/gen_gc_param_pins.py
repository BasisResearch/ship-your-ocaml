#!/usr/bin/env python3
"""Project caml_init_gc's `.data` parameters (`caml_init_policy` through
`caml_init_percent_free`) from the ELF into bounded loader-byte certificates."""
import argparse
from census import ROOT, symbols
from gen_ocaml_image import sections
from boot_certificate import emit_finite_family

FIRST, LAST = 'caml_init_policy', 'caml_init_percent_free'
PATH = ROOT / 'OCaml/Vm/Boot/Startup/GcParamPins.lean'


def output():
    elf = ROOT / 'c/ocamlrun-riscv-htif.elf'
    table = symbols(elf)
    start, _ = table[FIRST]
    last, size = table[LAST]
    end = last + size
    raw = next(data[start-base:end-base] for base, data in sections(elf.read_bytes()).values()
               if base <= start and end <= base+len(data))
    names = sorted((a, n) for n, (a, s) in table.items() if start <= a < end and s == 8 and n.startswith('caml_init_'))
    if [a for a, _ in names] != list(range(start, end, 8)):
        raise ValueError('caml_init_gc parameters are not consecutive words')
    out = ['import OCaml.Vm.Boot.WhileMinImage', '',
           '/-! GENERATED by scripts/gen_gc_param_pins.py. Bounded byte certificates for',
           'caml_init_gc\'s `.data` parameters: ' + ', '.join(f'`{n}`' for _, n in names) + '. -/',
           'namespace OCaml.Vm.Boot.Startup',
           'open Vsa.Sim Vsa.Sim.Boot', '',
           f'def gcParamAddr : Nat := {start:#x}',
           f'def gcParamBytes : Nat := {end - start}',
           'def gcParamByte (i : Nat) : BitVec 8 :=', '  match i with']
    out += [f'  | {i} => {v:#x}#8' for i, v in enumerate(raw)] + ['  | _ => 0#8', '']
    for i in range(len(raw)):
        out += [f'theorem gc_param_{i} :',
                f'    WhileMinImage.initialMem[gcParamAddr + {i}]? = some (gcParamByte {i}) :=',
                f'  (loaderMem_get WhileMinImage.pieces WhileMinImage.imageByte (gcParamAddr + {i})).trans (by decide +kernel)', '']
    emit_finite_family(out, 'gc_param_initial', [f'gc_param_{i}' for i in range(len(raw))],
                       lambda i: f'WhileMinImage.initialMem[gcParamAddr + {i}]? = some (gcParamByte {i})')
    out += ['end OCaml.Vm.Boot.Startup', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = output()
    if args.check:
        if not PATH.exists() or PATH.read_text() != text:
            raise SystemExit('gc parameter projection drift')
    else:
        PATH.write_text(text)
