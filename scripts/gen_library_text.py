#!/usr/bin/env python3
"""Certify that the retargeted library code footprints (snprintf/strlen and
memcpy) are bytes of the pinned executable image, in bounded chunks.

Writes OCaml/Vm/Boot/Startup/LibraryText.lean; --check compares instead."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHUNK = 256
TEXT_BASE = 0x80000000


def snp_ranges():
    text = (ROOT / 'VsaIris/Vsa/SnpCode.lean').read_text()
    body = re.search(r'def snpCodeRanges : List \(Nat × Nat\) :=\s*\[(.*?)\]', text, re.S).group(1)
    return [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\((0x[0-9a-f]+), (0x[0-9a-f]+)\)', body)]


def memcpy_layout():
    text = (ROOT / 'VsaIris/Vsa/MemcpyRun.lean').read_text()
    count = int(re.search(r'The (\d+) code bytes of `memcpy`', text).group(1))
    return count


def chunks(lo, hi):
    out = []
    a = lo
    while a < hi:
        b = min(a + CHUNK, hi)
        out.append((a, b - a))
        a = b
    return out


def output():
    ranges = snp_ranges()
    mcount = memcpy_layout()
    out = ['import VsaIris.Vsa.SnpCode', 'import VsaIris.Vsa.MemcpyRun', 'import OCaml.Vm.Platform', '',
           '/-! GENERATED by scripts/gen_library_text.py. The library code footprints are bytes of',
           'the pinned executable image, checked in chunks of at most 256 bytes. -/',
           'namespace OCaml.Vm.Boot.Startup',
           'open Vsa.Sim VsaIris.Sym VsaIris.Memcpy', '',
           '/-- `img` agrees with the executable text on `[lo, lo + n)`. -/',
           'def TextAgrees (img : Nat → BitVec 8) (lo n : Nat) : Prop :=',
           '  ∀ i, i < n → img (lo + i) = Image.textByte (lo - Image.textBase + i)', '',
           'theorem textAgrees_split {img : Nat → BitVec 8} {lo n m : Nat} (lower : Image.textBase ≤ lo)',
           '    (h1 : TextAgrees img lo n) (h2 : TextAgrees img (lo + n) m) : TextAgrees img lo (n + m) := by',
           '  intro i hi',
           '  by_cases low : i < n',
           '  · exact h1 i low',
           '  · have := h2 (i - n) (by omega)',
           '    rw [show lo + n + (i - n) = lo + i by omega, show lo + n - Image.textBase + (i - n) =',
           '      lo - Image.textBase + i by unfold Image.textBase at *; omega] at this',
           '    exact this', '',
           'theorem textAgrees_loaded {c : Vsa.Machine.Config} {img : Nat → BitVec 8} {lo n : Nat}',
           '    (image : ExecutableImage c) (h : TextAgrees img lo n) (lower : Image.textBase ≤ lo)',
           '    (upper : lo + n ≤ Image.textBase + Image.textSize) :',
           '    ∀ a, lo ≤ a → a < lo + n → c.σ.mem[a]? = some (img a) := by',
           '  intro a low high',
           '  have agree := h (a - lo) (by omega)',
           '  have byte := image.text (a - Image.textBase) (by omega)',
           '  rw [show lo + (a - lo) = a by omega, show lo - Image.textBase + (a - lo) = a - Image.textBase by omega] at agree',
           '  rw [show Image.textBase + (a - Image.textBase) = a by omega] at byte',
           '  rw [agree]',
           '  exact byte', '']
    for j, (lo, hi) in enumerate(ranges):
        names = []
        for k, (a, n) in enumerate(chunks(lo, hi)):
            name = f'snp_{j}_{k}'
            names.append((name, a, n))
            out += [f'private theorem {name} : TextAgrees snpCodeImg {a:#x} {n} := by',
                    '  unfold TextAgrees', '  decide +kernel', '']
        proof = names[0][0]
        total = names[0][2]
        for name, a, n in names[1:]:
            proof = f'(textAgrees_split (n := {total}) (by decide) {proof} {name})'
            total += n
        out += [f'private theorem snp_range_{j} : TextAgrees snpCodeImg {lo:#x} {hi - lo} :=',
                f'  {proof}', '']
    out += ['/-- The snprintf/strlen footprint is present in every executable image. -/',
            'theorem snp_text_loaded {c : Vsa.Machine.Config} (image : ExecutableImage c) :',
            '    ∀ p ∈ snpText, c.σ.mem[p.1]? = some p.2 := by',
            '  apply forall_piecesText (P := fun a b => c.σ.mem[a]? = some b)',
            '  intro q hq a ha',
            '  simp only [snpPieces, List.mem_singleton] at hq',
            '  subst hq',
            '  obtain ⟨r, hr, low, high⟩ := inRangesB_iff.1 ha',
            '  simp only [snpCodeRanges, List.mem_cons, List.not_mem_nil, or_false] at hr',
            '  rcases hr with ' + ' | '.join('rfl' for _ in ranges)]
    for j, (lo, hi) in enumerate(ranges):
        out += [f'  · exact textAgrees_loaded image snp_range_{j} (by decide) (by decide) a low (by simpa using high)']
    out += ['']
    mnames = []
    for k, (off, n) in enumerate(chunks(0, mcount)):
        name = f'memcpy_{k}'
        mnames.append((name, off, n))
        out += [f'private theorem {name} : TextAgrees (fun a => memcpyCode.getD (a - memcpyBase) 0#8)',
                f'    (memcpyBase + {off}) {n} := by',
                '  unfold TextAgrees', '  decide +kernel', '']
    proof = mnames[0][0]
    total = mnames[0][2]
    for name, off, n in mnames[1:]:
        proof = f'(textAgrees_split (n := {total}) (by decide) {proof} {name})'
        total += n
    out += ['private theorem memcpy_range :',
            f'    TextAgrees (fun a => memcpyCode.getD (a - memcpyBase) 0#8) (memcpyBase + 0) {mcount} :=',
            f'  {proof}', '',
            '/-- The memcpy footprint is present in every executable image. -/',
            'theorem memcpy_text_loaded {c : Vsa.Machine.Config} (image : ExecutableImage c) :',
            '    ∀ p ∈ mText, c.σ.mem[p.1]? = some p.2 := by',
            '  intro p hp',
            '  obtain ⟨⟨b, k⟩, member, rfl⟩ := List.mem_map.1 hp',
            '  have get := List.mem_zipIdx_iff_getElem?.1 member',
            '  simp only at get',
            '  have bound : k < memcpyCode.length := by',
            '    rcases Nat.lt_or_ge k memcpyCode.length with h | h',
            '    · exact h',
            '    · rw [List.getElem?_eq_none h] at get',
            '      cases get',
            '  have length : memcpyCode.length = ' + str(mcount) + ' := by decide +kernel',
            '  have loaded := textAgrees_loaded image memcpy_range (by decide) (by decide)',
            '    (memcpyBase + k) (by omega) (by omega)',
            '  simp only [Nat.add_sub_cancel_left, List.getD_eq_getElem?_getD, get, Option.getD_some] at loaded',
            '  exact loaded', '',
            'end OCaml.Vm.Boot.Startup', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'OCaml/Vm/Boot/Startup/LibraryText.lean'
    text = output()
    if args.check:
        if not path.exists() or path.read_text() != text:
            raise SystemExit('library text certificate drift')
    else:
        path.write_text(text)
