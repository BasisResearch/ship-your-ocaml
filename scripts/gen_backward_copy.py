#!/usr/bin/env python3
"""Instantiate both generated APPTERM copy branches over one counted invariant."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parent.parent

def render(kind):
    stem=kind.title()
    spec=json.loads((ROOT/f'scripts/syi/segments/appterm_copy_{kind}.json').read_text())
    regs=[p['reg'] for p in spec['pins']]
    assert regs==['x9','x14','x15','x12']
    for step in spec['steps']:
        rd=step.get('rd')
        if rd and rd!='x0':regs=[rd]+[r for r in regs if r!=rd]
    pin=lambda r:f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    condition='(positive : 0 < i)' if kind=='more' else '(zero : i = 0)'
    guard='backward_counter_live i positive (by have small := region.small; omega)' if kind=='more' else 'by subst i; decide'
    pcproof='simp only [positive, ite_true]; exact post.pcAt' if kind=='more' else 'simp only [zero, Nat.lt_irrefl, ite_false]; exact post.pcAt'
    return f'''-- GENERATED by scripts/gen_backward_copy.py; do not edit.
import OCaml.Vm.Sim.BackwardCopyState
import OCaml.Vm.Sim.ApptermCopy{stem}Segment
import OCaml.Vm.Sim.ApptermCopy{stem}Pins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- Concrete generated {kind} branch of the counted backward-copy loop. -/
theorem backward_copy_{kind} {{source target i : Nat}} {{words : List (BitVec 64)}} {{initial c : Config}}
    (region : BackwardCopyRegion source target words initial)
    (h : BackwardCopyAt source target words initial (i + 1) c) {condition} :
    ∃ nb after, StepsN nb c after ∧ BackwardCopyAt source target words initial i after := by
  have bound : i < words.length := by have b := h.bound; omega
  have targetRoom : 8 ≤ target := Nat.le_trans region.room region.direction
  have read := region.reads i bound
  have store := region.writes i bound
  have sourceNat : (BitVec.ofNat 64 (source + 8 * i)).toNat = source + 8 * i := read.toNat
  have targetNat : (BitVec.ofNat 64 (target + 8 * i)).toNat = target + 8 * i :=
    Nat.mod_eq_of_lt (by have upper := store.upper; omega)
  have sourceStep : BitVec.ofNat 64 (source + 8 * i) + sign_extend (m := 64) (0xff8#12) =
      BitVec.ofNat 64 (backwardCursor source i) := by
    simpa only [backward_cursor_succ source i region.room] using backward_cursor_step source i region.room
  have targetStep : BitVec.ofNat 64 (target + 8 * i) + sign_extend (m := 64) (0xff8#12) =
      BitVec.ofNat 64 (backwardCursor target i) := by
    simpa only [backward_cursor_succ target i targetRoom] using backward_cursor_step target i targetRoom
  have counterStep : sign_extend (m := 64) (Sail.BitVec.extractLsb
      (BitVec.ofNat 64 i + sign_extend (m := 64) (0xfff#12)) 31 0) = backwardCounter i := by
    simpa only [backward_counter_succ] using backward_counter_step i (by have small := region.small; omega)
  have guard : (backwardCounter i != -(1#64)) = {'true' if kind=='more' else 'false'} := {guard}
  have sourceReg : gpr c 9 = some (BitVec.ofNat 64 (source + 8 * i)) := by
    simpa only [backward_cursor_succ source i region.room] using h.sourceReg
  have targetReg : gpr c 15 = some (BitVec.ofNat 64 (target + 8 * i)) := by
    simpa only [backward_cursor_succ target i targetRoom] using h.targetReg
  have counterReg : gpr c 14 = some (BitVec.ofNat 64 i) := by
    simpa only [backward_counter_succ] using h.counter
  have loaded := h.read region (by omega : i < i + 1) (List.getElem?_eq_getElem bound)
  obtain ⟨nextMemory, written⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 c.σ.mem (target + 8 * i) (sdData_val words[i]) := ⟨_, rfl⟩
  have bp : SegSt (0x80002ab8#64)
      [⟨Register.x9, BitVec.ofNat 64 (source + 8 * i)⟩,
       ⟨Register.x14, BitVec.ofNat 64 i⟩,
       ⟨Register.x15, BitVec.ofNat 64 (target + 8 * i)⟩, ⟨Register.x12, -(1#64)⟩]
      (fun σ => Vsa.Sim.Code.CamlApptermCopy{stem}Loaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, by change pcOf c = some (0x80002ab8#64); simpa only [show 0 < i + 1 by omega, ite_true] using h.pc,
      ⟨sourceReg, counterReg, targetReg, h.sentinel, trivial⟩,
      h.good.minstret, h.tick, appterm_copy_{kind}_loaded h.image, rfl, rfl⟩
  have run := tr_appterm_copy_{kind} (BitVec.ofNat 64 (source + 8 * i)) (BitVec.ofNat 64 i)
    (BitVec.ofNat 64 (target + 8 * i)) (-(1#64)) c.σ.mem c.σ
  simp only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, sourceNat, targetNat, sourceStep, targetStep, counterStep] at run
  obtain ⟨nb, after, _, steps, post⟩ := run read.lower read.upper read.htif words[i] loaded.symm
    store.lower store.upper store.htif store.aligned
    (image_entry_code region.image (region.entry bound) (by decide) (by decide)) nextMemory written guard c bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have observed : BackwardCopyPost source target i words[i] c after := by
    refine ⟨post.good, post.tick, ?_, {pin('x9')}, {pin('x15')}, {pin('x14')},
      {pin('x12')}, ?_, ?_⟩
    · {pcproof}
    · rw [memory, written]; rfl
    · exact rawFrame.widenChecked (allowed := backwardWrites) (by decide)
  exact ⟨nb, after, steps, BackwardCopyAt.advance region h bound observed⟩

end OCaml.Vm.Sim
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for kind in ['more','last']:
        path=ROOT/f'OCaml/Vm/Sim/BackwardCopy{kind.title()}.lean';output=render(kind)
        if args.check:
            if not path.exists() or path.read_text()!=output:raise SystemExit(f'drift: {path}')
        else:path.write_text(output)
    print('Backward-copy branch adapters current')
