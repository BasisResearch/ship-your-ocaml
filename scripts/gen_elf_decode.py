#!/usr/bin/env python3
"""Generate kernel-checked decode facts for every word disassembled from the ELF.

All text is covered, a conservative superset of census reachability including
indirect calls. The Python decoder is only a statement generator: decodeW and
rfl check each proposed instruction against Sail in Lean's kernel.
"""
import argparse
from pathlib import Path
from census import ROOT, disasm


def ast(w):
    op, f3, f7 = w & 127, (w >> 12) & 7, w >> 25
    rd, r1, r2 = (f"regidx.Regidx {((w >> n) & 31)}#5" for n in (7, 15, 20))
    imm = f"{w >> 20}#12"
    def out(k, *args):
        return f"instruction.{k} ({', '.join(args)})"
    if op == 0x6f:
        i = ((w >> 31) << 20) | (((w >> 12) & 255) << 12) | (((w >> 20) & 1) << 11) | (((w >> 21) & 1023) << 1)
        return out('JAL', f'{i}#21', rd)
    if op in (0x17, 0x37):
        return out('UTYPE', f'{w >> 12}#20', rd, 'uop.' + ('AUIPC' if op == 0x17 else 'LUI'))
    if op == 0x67 and f3 == 0:
        return out('JALR', imm, r1, rd)
    if op == 0x63:
        i = ((w >> 31) << 12) | (((w >> 7) & 1) << 11) | (((w >> 25) & 63) << 5) | (((w >> 8) & 15) << 1)
        return out('BTYPE', f'{i}#13', r2, r1, 'bop.' + {0:'BEQ',1:'BNE',4:'BLT',5:'BGE',6:'BLTU',7:'BGEU'}[f3])
    if op == 3:
        return out('LOAD', imm, r1, rd, str(f3 >= 4).lower(), str(1 << (f3 & 3)))
    if op == 0x23:
        i = ((w >> 25) << 5) | ((w >> 7) & 31)
        return out('STORE', f'{i}#12', r2, r1, str(1 << f3))
    if op in (0x13, 0x1b):
        word = op == 0x1b
        if f3 in (1, 5):
            k = 'SLLI' if f3 == 1 else ('SRAI' if f7 & 32 else 'SRLI')
            width = 5 if word else 6
            return out('SHIFTIWOP' if word else 'SHIFTIOP', f'{(w >> 20) & ((1 << width)-1)}#{width}', r1, rd, ('sopw.' + k + 'W') if word else 'sop.' + k)
        if word and f3 == 0:
            return out('ADDIW', imm, r1, rd)
        if not word:
            return out('ITYPE', imm, r1, rd, 'iop.' + {0:'ADDI',2:'SLTI',3:'SLTIU',4:'XORI',6:'ORI',7:'ANDI'}[f3])
    if op in (0x33, 0x3b) and f7 in (0,32):
        k = {0:'SUB' if f7 else 'ADD',1:'SLL',2:'SLT',3:'SLTU',4:'XOR',5:'SRA' if f7 else 'SRL',6:'OR',7:'AND'}[f3]
        return out('RTYPEW' if op == 0x3b else 'RTYPE', r2, r1, rd, ('ropw.' + k + 'W') if op == 0x3b else 'rop.' + k)
    raise ValueError(f'unsupported instruction {w:08x}')


HEADER = '''import Vsa.Sim.DecodeNF

/-! GENERATED by scripts/gen_elf_decode.py. Every disassembled ELF word,
including all census-reachable functions. Statements are checked against Sail. -/

open LeanRV64DExecutable Sail ConcurrencyInterfaceV1
namespace Vsa.Sim.ElfDecode
variable (σ : SequentialState RegisterType trivialChoiceSource)
  (hmisa : σ.regs.get? Register.misa = some Vsa.Sim.initMisa)
  (hpriv : σ.regs.get? Register.cur_privilege = some Privilege.Machine)
  (hsec : σ.regs.get? Register.mseccfg = some (0#64))
include hmisa hpriv hsec

'''


def outputs(elf):
    funcs = disasm(elf)
    words = sorted({w for f in funcs.values() for _, w, _, _ in f['insts']})
    files, modules = {}, []
    for n, start in enumerate(range(0, len(words), 128)):
        module = f'Vsa.Sim.ElfDecode.Part{n:03d}'
        modules.append(module)
        s = HEADER
        for w in words[start:start+128]:
            s += f'theorem decode_{w:08x} :\n    (Functions.ext_decode {w}#32).run σ = .ok ({ast(w)}) σ :=\n  decodeW σ hmisa hpriv hsec\n\n'
        files[ROOT / (module.replace('.', '/') + '.lean')] = s + 'end Vsa.Sim.ElfDecode\n'
    files[ROOT / 'Vsa/Sim/ElfDecode.lean'] = ''.join(f'import {m}\n' for m in modules) + f'\n/-! GENERATED by scripts/gen_elf_decode.py: {len(words)} distinct words from all {len(funcs)} disassembled functions. -/\n'
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--elf', default=ROOT / 'c/ocamlrun-riscv-htif.elf', type=Path)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    files = outputs(args.elf)
    stale = set((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean')) - files.keys()
    if args.check:
        bad = stale | {p for p, s in files.items() if not p.exists() or p.read_text() != s}
        if bad:
            raise SystemExit('ELF decode drift: ' + ', '.join(str(p.relative_to(ROOT)) for p in sorted(bad)))
    else:
        for p in stale:
            p.unlink()
        for p, s in files.items():
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != s:
                p.write_text(s)
    print(f'ELF decode: {len(files)-1} chunks current')


if __name__ == '__main__':
    main()
