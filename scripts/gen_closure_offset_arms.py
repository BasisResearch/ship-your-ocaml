#!/usr/bin/env python3
"""Generate the four read-only closure-offset bridges over one shared contract."""
import argparse
import json
from census import ROOT


def outputs():
    result = {}
    for op, ofs, imm in [('OFFSETCLOSUREM3', '(-3)', 'fe8'),
                         ('OFFSETCLOSURE0', '0', '000'),
                         ('OFFSETCLOSURE3', '3', '018'),
                         ('OFFSETCLOSURE', 'w.toInt', None)]:
        stem, lower = op.title(), op.lower()
        generic = imm is None
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
        pc_reg = 'x8' if generic else 'x23'
        pc_word = 'BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)' + ('' if generic else ' + 4#64')
        pc_hold = '(dp.frame.frame Register.x8 (by decide)).trans h.pc' if generic else 'dp.nextCode'
        read = '''  have read : bytesT4 d.σ.mem (pl.codeBase + 4 * (s.pc + 1)) = w :=
    operand.read32 h.code dp.memory
''' if generic else ''
        address = ('''  have address : Sail.shift_bits_left (sign_extend (m := 64) w)
      (Sail.BitVec.extractLsb (0x03#6) 5 0) + BitVec.ofNat 64 (a + 8 * k) =
      BitVec.ofNat 64 (a + 8 * dest) := by
    rw [signed_index_word, BitVec.add_comm]
    exact pointer_offset_word a k dest w.toInt selected.target''' if generic else f'''  have address : BitVec.ofNat 64 (a + 8 * k) + sign_extend (m := 64) (0x{imm}#12) =
      BitVec.ofNat 64 (a + 8 * dest) := by
    rw [show sign_extend (m := 64) (0x{imm}#12) = BitVec.ofInt 64 (8 * {ofs}) from by decide]
    exact pointer_offset_word a k dest {ofs} selected.target''')
        simplify = ('''  simp only [show sign_extend (m := 64) (0x004#12) = 4#64 from by decide,
    codePc_succ, operand.geometry.toNat, read, address] at run''' if generic else
                    '  simp only [address] at run')
        run_args = 'operand.geometry.lower operand.geometry.upper operand.geometry.htif ' if generic else ''
        pc_result = ('''  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + sign_extend (m := 64) (0x008#12)) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [show sign_extend (m := 64) (0x008#12) = 8#64 from by decide,
      show BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 8#64 =
        BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 2)) from codePc_add pl s.pc 2] using hp''' if generic else
                     '''  · have hp : gpr after Layout.reg_pc = some
        ((BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
      BitVec.add_zero, codePc_succ] using hp''')
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.ClosureOffset
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_closure_offset_arms.py. Existing closure-root offset. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} adjusts the environment pointer while retaining the same live allocation.
The semantic target equation supplies the nonnegative resulting field offset. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a k dest : Nat}}{' {w : BitVec 32}' if generic else ''}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
{'    (operand : OperandAt P pl (s.pc + 1) w)' if generic else ''}
    (selected : ClosureOffset s pl {ofs} l a k dest) :
    ∃ c', Plus c c' ∧ Running L P
      {{s with pc := s.pc + {2 if generic else 1}, accu := .ptr l dest}} c' := by
  have source := represented_register h.env selected.sourceWord
  apply accu_arm stable h selected.resultWord selected.root
  intro d dp
{read}{address}
  have bp : SegSt ({spec['entry']}#64)
      [⟨Register.{pc_reg}, {pc_word}⟩,
       ⟨Register.x25, BitVec.ofNat 64 (a + 8 * k)⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨{pc_hold},
       (dp.frame.frame Register.x25 (by decide)).trans source, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} ({pc_word})
    (BitVec.ofNat 64 (a + 8 * k)) d.σ.mem d.σ
{simplify}
  obtain ⟨nb, after, _, hb, post⟩ := run {run_args}d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
{pc_result}
  · exact PinsHold.get post.pins ⟨0, by simp⟩

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'closure offset drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Closure-offset arm bridges current')
