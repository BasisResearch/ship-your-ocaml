#!/usr/bin/env python3
"""Generate represented ACC0..ACC7 bridges over checked total-load segments."""
import argparse
import json
from census import ROOT


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    for n in range(8):
        op, stem, lower = f'ACC{n}', f'Acc{n}', f'acc{n}'
        entry = int(arms[op]['addr'], 16)
        offset = 8*n
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.StackAcc
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_acc_arms.py. Represented stack-load arm. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} selects a represented stack value and restores the loop state.
The stack representation excludes wraparound; RAM/HTIF geometry is explicit. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{v : Val}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (selected : s.stack[{n}]? = some v)
    (read : ReadWindow (BitVec.ofNat 64 (sp + 8 * {n})) 8) :
    ∃ c', Plus c c' ∧ Running L P {{s with pc := s.pc + 1, accu := v}} c' := by
  apply accu_arm stable h (h.stack.2 {n} v selected) (stack_value_root selected)
  intro d dp
  have address : BitVec.ofNat 64 sp + sign_extend (m := 64) (0x{offset:03x}#12) =
      BitVec.ofNat 64 (sp + 8 * {n}) := by
    rw [BitVec.ofNat_add]
    rfl
  have natAddress := stack_slot_nat h.toVmReprAt selected
  have bp : SegSt (0x{entry:x}#64)
      [⟨Register.x9, BitVec.ofNat 64 sp⟩,
       ⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨(dp.frame.frame Register.x9 (by decide)).trans h.spReg, dp.nextCode, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} (BitVec.ofNat 64 sp)
    (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) d.σ.mem d.σ
  rw [address] at run
  obtain ⟨nb, after, _, hb, post⟩ := run read.lower read.upper read.htif d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
  · have hp : gpr after Layout.reg_pc = some
        ((BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
      BitVec.add_zero, codePc_succ] using hp
  · have hp : gpr after Layout.reg_accu = some
        (sign_extend (m := 64) (bytesT8 d.σ.mem (BitVec.ofNat 64 (sp + 8 * {n})).toNat)) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [natAddress, dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using hp

end OCaml.Vm.Sim
'''
    imports = ''.join(f'import OCaml.Vm.Sim.Acc{n}\n' for n in range(8))
    rows = ''.join(f'''
/-- **The ACC{n} row**: the real step from any loop head of the budget. -/
theorem acc{n}_row {{L : OCaml.Layout}} {{B : OCaml.Budget}} {{P : Prog}}
    (stable : MemoryStable L.runtimeOk) (fits : OCaml.Fits B P)
    (capacity : StackCapacity B)
    (code : ∀ s c, Reach P s → OCaml.LoopAt L P s c → DispatchCode P s .ACC{n}) :
    OCaml.OpArm P (OCaml.LoopAt L P) .ACC{n} := by
  intro s c i reach h _ op _
  obtain ⟨o, args⟩ := i
  cases op
  cases args with
  | cons a as => exact trivial
  | nil =>
    apply OCaml.ArmOutcome.of_next
    · intro s' step
      exact stack_read_next (fun _ _ _ _ _ input selected read => acc{n}_arm stable input selected read)
        h (code s c reach h) (by simpa using stack_fits fits capacity reach (k := 0)) step
    · intro e w
      exact opt_not_halt
''' for n in range(8))
    result[ROOT / 'OCaml/Vm/Sim/AccRows.lean'] = f'''{imports}import OCaml.Vm.Sim.StackRows

/-! GENERATED by scripts/gen_acc_arms.py. Unconditional ACC0..ACC7 rows of the
F1 arm table: every premise of the represented arm comes from `LoopAt`, the
dispatch code facts and the budget (`StackRows.lean`). -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine OCaml.Vm.Primitives
{rows}
end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'stack arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Stack-load arm bridges current')
