#!/usr/bin/env python3
"""Represented return adapters for the seven native caml_modify callers."""
import argparse
import json
import sys
from gen_arm_pilot import ROOT
sys.path.insert(0, str(ROOT / 'scripts/syi'))
from gen_segment import SegmentEmitter


def outputs():
    result = {}
    for stem, code_reg, code_delta, stack_delta in [
        *[(f'Setfield{i}', 23, 0, 0) for i in range(4)],
        ('Setfield', 8, 0, 8), ('Setglobal', 8, 8, 0), ('Setvectitem', 8, 0, 16),
    ]:
        lower = stem.lower()
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}_suffix.json').read_text())
        em = SegmentEmitter(spec)
        em.emit()
        pins = {r: (i, v) for i, (r, v) in enumerate(em.pins)}
        source = spec['pins'][0]['reg']
        value = 'stackWord' if source == 'x9' else 'codeWord'
        proof = 'h.stack' if source == 'x9' else 'h.code'
        code_expr = 'codeWord' + (f' + {code_delta}#64' if code_delta else '')
        stack_expr = 'stackWord' + (f' + {stack_delta}#64' if stack_delta else '')
        observations = []
        for reg, layout, fallback in [('x8', 'reg_pc', 'h.code'), ('x9', 'reg_sp', 'h.stack'), ('x21', 'reg_accu', None)]:
            if reg in pins:
                i, expr = pins[reg]
                expr = expr.replace(spec['pins'][0]['val'], value)
                observations.append(f'''  have {reg} : gpr after Layout.{layout} = some ({expr}) :=
    PinsHold.get post.pins ⟨{i}, by simp⟩''')
            else:
                expr = 'stackWord' if reg == 'x9' else 'codeWord'
                observations.append(f'''  have {reg} : gpr after Layout.{layout} = some {expr} :=
    (frame.frame _ (by decide)).trans {fallback}''')
        simp = ',\n      '.join(f'show sign_extend (m := 64) (0x{n:03x}#12) = {n}#64 from by decide' for n in [0, 1, 8, 16])
        result[ROOT / f'OCaml/Vm/Sim/{stem}Return.lean'] = f'''import OCaml.Vm.Sim.ModifyReturn
import OCaml.Vm.Sim.{stem}SuffixSegment
import OCaml.Vm.Sim.{stem}SuffixPins

/-! GENERATED by scripts/gen_modify_returns.py. Native barrier return to represented loop. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- Restore the represented state supplied by the barrier summary. -/
theorem {lower}_return {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{pl : Place}} {{cp : ChanPlace}}
    {{sp high : Nat}} {{codeWord stackWord : BitVec 64}}
    (stable : MemoryStable L.runtimeOk)
    (codeFits : {code_expr} = BitVec.ofNat 64 (pl.codeBase + 4 * s.pc))
    (stackFits : {stack_expr} = BitVec.ofNat 64 sp) :
    Vsa.Logic.Triple (ModifyReturn L P s pl cp sp high {code_reg} ({spec['entry']}#64) codeWord stackWord)
      (Running L P s) := by
  intro c h
  have bp : SegSt ({spec['entry']}#64) [⟨Register.{source}, {value}⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}SuffixLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.platform.control, h.returnPC, ⟨{proof}, trivial⟩,
      h.platform.control.minstret, h.tick, {lower}_suffix_loaded h.platform.image, rfl, rfl⟩
  obtain ⟨_, after, _, run, post⟩ := tr_{lower}_suffix {value} c.σ.mem c.σ c bp
  obtain ⟨_, memory, frame⟩ := post.extra
{chr(10).join(observations)}
  have observed : StackPost c pl s.pc sp (tag64 0) c.σ.mem after := by
    refine ⟨post.good, post.pcAt, ?_, ?_, ?_, memory, frame.out,
      fun r hr => frame.frame r (by revert r; decide)⟩
    · simpa only [{simp}, BitVec.add_zero, codeFits] using x8
    · simpa only [{simp}, BitVec.add_zero, stackFits] using x9
    · simpa only [show ((0#64) + sign_extend (m := 64) (0x001#12)) = tag64 0 from by decide] using x21
  exact ⟨after, run.toSteps, modify_return_restore stable h observed⟩

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    drift = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if drift:
        sys.exit('Modify return drift: ' + ', '.join(drift))
    print('Modify return adapters current')
