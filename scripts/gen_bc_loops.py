#!/usr/bin/env python3
"""Recognize compiler list-length loops and emit their symbolic path proofs."""
import argparse
import json
from gen_bc_rules import ROOT, OUT, DEFAULT_DUMP, inputs
from gen_bc_functions import certificate

PATTERN = [('GRAB',[1]),('ACC1',[]),('BRANCHIFNOT',[10]),('ACC1',[]),
           ('GETFIELD1',[]),('PUSHACC0',[]),('PUSHACC2',[]),('OFFSETINT',[1]),
           ('PUSHOFFSETCLOSURE0',[]),('APPTERM2',[5]),('ACC0',[]),('RETURN',[2])]


def render(entry, words, decoded, pcs):
    name, text, pin = certificate(entry, words, decoded, pcs)
    frame = '.code ret :: caller :: .int saved :: tail'
    def state(pc, accu, stack, extra=0):
        return f'⟨{pc}, {accu}, {stack}, .ptr closure 0, {extra}, trap, h, w⟩'
    nval = '.int (BitVec.ofNat 63 n)'
    nextval = '.int (BitVec.ofNat 63 (n+1))'
    original = f'{nval} :: .ptr l 0 :: {frame}'
    stget = state(pcs[4], '.ptr l 0', original)
    afterget = state(pcs[5], 'v', original)
    offsetstack = f'v :: v :: {original}'
    stoffset = state(pcs[7], nval, offsetstack)
    afteroffset = state(pcs[8], nextval, offsetstack)
    stcall = state(pcs[9], '.ptr closure 0', f'{nextval} :: {offsetstack}')
    result = state(entry, '.ptr closure 0', f'{nextval} :: v :: {frame}', 1)
    ctx = f'⟨{entry}, closure, ret, caller, saved, trap, h, w, tail⟩'
    text += f'''
/-- Exact compiler list-counting paths, with no assumption about a full run. -/
theorem {name}_certificate (P : Prog) (pin : {pin})
    (closure ret trap : Nat) (caller : Val) (saved : BitVec 63)
    (h : Heap) (w : World) (tail : List Val)
    (code : field? h (.ptr closure 0) 0 = some (.code {entry})) :
    LengthCertificate P {ctx} := by
  constructor
  · intro n l v a bound read
    apply {name}.run P pin
    change OCaml.Run.iter (decodedK P {name}.decode) 6 {stget} = .ok {result}
    have hg : stepI P {stget} ⟨.GETFIELD1, []⟩ = .next {afterget} := by
      change opt (field? h (.ptr l 0) 1) _ = _
      rw [read]
      rfl
    rw [decoded_sym_step (decode := {name}.decode) (n := 5) rfl hg]
    change OCaml.Run.iter (decodedK P {name}.decode) 3 {stoffset} = .ok {result}
    have ho : stepI P {stoffset} ⟨.OFFSETINT, [1]⟩ = .next {afteroffset} := by
      change Res.next {state(pcs[8], '.int (untag (tag64 (BitVec.ofNat 63 n) + (BitVec.ofInt 64 1 <<< 1)))', offsetstack)} = _
      rw [offsetInt_ofNat n bound]
    rw [decoded_sym_step (decode := {name}.decode) (n := 2) rfl ho]
    change OCaml.Run.iter (decodedK P {name}.decode) 1 {stcall} = .ok {result}
    have hc : stepI P {stcall} ⟨.APPTERM2, [5]⟩ = .next {result} := by
      change enter {stcall} ({nextval} :: v :: {frame}) 1 = _
      simp only [enter, code, opt]
    rw [decoded_sym_step (decode := {name}.decode) (n := 0) rfl hc]
    rfl
  · intro n a
    apply {name}.run P pin
    rfl

/-- Generated functional application summary: initial count plus spine length. -/
theorem {name}_summary (P : Prog) (pin : {pin})
    (closure ret trap : Nat) (caller : Val) (saved : BitVec 63)
    (h : Heap) (w : World) (tail : List Val)
    (code : field? h (.ptr closure 0) 0 = some (.code {entry}))
    (start len : Nat) (v a : Val) (spine : ListSpine h v len)
    (bound : start + len < 2^62) :
    ApplicationSummary P {entry} (EntryShape (({ctx} : LengthContext).state start v a))
      (fun _ t => t = ({ctx} : LengthContext).result (start+len)) :=
  length_application P {ctx}
    ({name}_certificate P pin closure ret trap caller saved h w tail code)
    start len v a spine bound
'''
    return text


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    words, decoded, units, entries, targets=inputs(ROOT/'vendor/ocaml-4.14.4/boot/ocamlc',DEFAULT_DUMP)
    lines=['-- GENERATED by scripts/gen_bc_loops.py. Do not edit.',
           'import OCaml.Logic.ListLoop','namespace OCaml.Programs.Generated.ListLoops','open OCaml.Bytecode']
    recognized=[]
    for entry in sorted(entries):
        pc=entry; pcs=[]
        for expected in PATTERN:
            if pc not in decoded or decoded[pc][:2]!=expected: break
            pcs.append(pc);pc+=decoded[pc][2]
        else:
            recognized.append(entry)
            lines.append(render(entry,words,decoded,pcs))
    assert 8372 in recognized, 'pinned Stdlib List.length_aux pattern disappeared'
    lines+=['end OCaml.Programs.Generated.ListLoops','']
    artifacts={OUT/'ListLoops.lean':'\n'.join(lines),
               OUT/'loops.json':json.dumps({'closure_entries':len(entries),'recognized_length_loops':recognized,
                 'loop_rule':'OCaml.Bytecode.length_loop',
                 'scope':'Exact list-length accumulator shape; other counting/list loops unresolved.'},indent=2)+'\n'}
    for path,text in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'drift: {path}')
        else:path.write_text(text)
    print(f'length loops: {len(recognized)} / {len(entries)} closure entries')

if __name__=='__main__':main()
