#!/usr/bin/env python3
"""Actual Stdlib.Int.abs bytes: symbolic functional summary and runbc harness."""
import argparse
import json
from gen_bc_rules import ROOT, OUT, DEFAULT_DUMP, inputs
from gen_bc_functions import certificate
from gen_bc_demo import loaded
from gen_opcodes import opcodes

PATTERN=[('ACC0',[]),('BGTINT',[0,4]),('ACC0',[]),('RETURN',[1]),
         ('ACC0',[]),('NEGINT',[]),('RETURN',[1])]


def render(entry,words,decoded,pcs):
    name,text,pin=certificate(entry,words,decoded,pcs)
    def state(pc,a):
        return f'⟨{pc}, {a}, .int n :: .code ret :: caller :: .int saved :: tail, env, 0, trap, h, w⟩'
    initial=state(entry,'a')
    for negative in [False,True]:
        mode='negative' if negative else 'nonnegative'
        value='-n' if negative else 'n'
        out=f'⟨ret, .int ({value}), tail, caller, saved.toNat, trap, h, w⟩'
        nextpc=pcs[4] if negative else pcs[2]
        nsteps=5 if negative else 4
        text+=f'''
theorem {name}_{mode} (P : Prog) (pin : {pin})
    (n : BitVec 63) (branch : (longVal n).slt (BitVec.ofInt 64 0) = {str(negative).lower()})
    (a env caller : Val) (ret trap : Nat) (saved : BitVec 63)
    (h : Heap) (w : World) (tail : List Val) :
    OCaml.Run.iter (bcK P) {nsteps} {initial} = .ok {out} := by
  apply {name}.run P pin
  change OCaml.Run.iter (decodedK P {name}.decode) {nsteps-1} {state(pcs[1],'.int n')} = .ok {out}
  have hb : stepI P {state(pcs[1],'.int n')} ⟨.BGTINT, [0, 4]⟩ =
      .next {state(nextpc,'.int n')} := by
    change brOp {state(pcs[1],'.int n')} 0 4 (fun a b => b.slt a) = _
    simp only [brOp, branch]
    rfl
  rw [decoded_sym_step (decode := {name}.decode) (n := {nsteps-2}) rfl hb]
'''
        if negative:
            text+=f'''  change OCaml.Run.iter (decodedK P {name}.decode) 2 {state(pcs[5],'.int n')} = .ok {out}
  have hn : stepI P {state(pcs[5],'.int n')} ⟨.NEGINT, []⟩ = .next {state(pcs[6],'.int (-n)')} := by
    change Res.next {state(pcs[6],'.int (untag (2#64 - tag64 n))')} = _
    rw [OCaml.Vm.Sim.untag_neg]
  rw [decoded_sym_step (decode := {name}.decode) (n := 1) rfl hn]
'''
        text+='  rfl\n'
    text+=f'''
/-- A functional postcondition for every signed OCaml integer, not a run premise. -/
theorem {name}_summary (P : Prog) (pin : {pin})
    (n : BitVec 63) (a env caller : Val) (ret trap : Nat) (saved : BitVec 63)
    (h : Heap) (w : World) (tail : List Val) :
    ApplicationSummary P {entry} (EntryShape {initial})
      (fun _ t => t = ⟨ret, .int (absWord n), tail, caller, saved.toNat, trap, h, w⟩) := by
  by_cases hn : n.toInt < 0
  · have branch : (longVal n).slt (BitVec.ofInt 64 0) = true := by change (longVal n).slt 0 = _; rw [abs_branch]; simp [hn]
    simpa only [absWord, if_pos hn] using application_of_run
      ({name}_negative P pin n branch a env caller ret trap saved h w tail)
  · have branch : (longVal n).slt (BitVec.ofInt 64 0) = false := by change (longVal n).slt 0 = _; rw [abs_branch]; simp [hn]
    simpa only [absWord, if_neg hn] using application_of_run
      ({name}_nonnegative P pin n branch a env caller ret trap saved h w tail)
'''
    return text


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    words,decoded,units,entries,targets=inputs(ROOT/'vendor/ocaml-4.14.4/boot/ocamlc',DEFAULT_DUMP)
    lo,hi=units['Stdlib__Int']
    matches=[]
    for entry in sorted(entries):
        if not lo<=entry<hi:continue
        pc=entry;pcs=[]
        for expected in PATTERN:
            if decoded[pc][:2]!=expected:break
            pcs.append(pc);pc+=decoded[pc][2]
        else:matches.append((entry,pc,pcs))
    assert len(matches)==1, 'Stdlib.Int.abs no longer has the certified pattern'
    entry,end,pcs=matches[0]
    raw=words[entry:end]
    ops=opcodes();op=lambda s:ops.index(s)
    prefix=[op('PUSH_RETADDR'),6,op('CONSTINT'),(-7)%2**32,op('PUSH'),op('BRANCH'),2,op('STOP')]
    harness=prefix+raw+[op('STOP')]
    relocated={8+p-entry:decoded[p] for p in pcs}
    hpcs=list(relocated)
    all_dec={0:('PUSH_RETADDR',[6],2),2:('CONSTINT',[-7],2),4:('PUSH',[],1),
             5:('BRANCH',[2],2),7:('STOP',[],1),**relocated}
    _,prefixcert,_=certificate(0,harness,all_dec,[0,2,4,5,7])
    text='''-- GENERATED by scripts/gen_bc_abs.py via dumpobj + CODE + runbc. Do not edit.
import OCaml.Logic.IntAbs
namespace OCaml.Programs.Generated.IntAbs
open OCaml.Bytecode
'''+loaded(harness,'absHarness')+render(entry,words,decoded,pcs)+render(8,harness,relocated,hpcs)+prefixcert+'''
/-- The invoked helper is a byte-for-byte copy of the compiler helper.
Only its placement changes; all internal branches remain relative. -/
theorem harness_helper_bytes : absHarness.code.extract 8 19 = SOURCE_CODE.extract 0 11 := rfl

/-- A concrete negative test runs the proved function summary with an arbitrary
caller stack, heap, environment and world. The returned accumulator is seven. -/
theorem harness_run (a env : Val) (tail : List Val) (trap : Nat) (h : Heap) (w : World) :
    OCaml.Run.iter (bcK absHarness) 9 ⟨0, a, tail, env, 0, trap, h, w⟩ =
      .ok ⟨7, Val.ofInt 7, tail, env, 0, trap, h, w⟩ := by
  have prefixRun : OCaml.Run.iter (bcK absHarness) 4 ⟨0, a, tail, env, 0, trap, h, w⟩ =
      .ok ⟨8, Val.ofInt (-7), Val.ofInt (-7) :: .code 7 :: env :: Val.ofInt 0 :: tail,
        env, 0, trap, h, w⟩ := f0.run absHarness rfl 4 _ _ rfl
  exact sym_seq (a := 4) (b := 5) prefixRun
    (f8_negative absHarness rfl (BitVec.ofInt 63 (-7)) rfl
      (Val.ofInt (-7)) env env 7 trap 0 h w tail)

end OCaml.Programs.Generated.IntAbs
'''
    text = text.replace('SOURCE_CODE', f'f{entry}_code')
    paths={OUT/'IntAbs.lean':text,OUT/'abs.json':json.dumps({'source_unit':'Stdlib__Int',
      'source_entry':entry,'source_end':end,'harness_entry':8,'helper_words':raw,
      'functional_postcondition':'signed modular absolute value, for every BitVec 63',
      'adequacy_example':'abs (-7) = 7'},indent=2)+'\n'}
    for path,text in paths.items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'drift: {path}')
        else:path.write_text(text)
    print(f'Stdlib.Int.abs: compiler words [{entry}, {end}); exact helper copied to harness')
if __name__=='__main__':main()
