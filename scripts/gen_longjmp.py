#!/usr/bin/env python3
"""Whole-function longjmp summary over the generated gen_fn block and saved-frame relation."""
import argparse
import re
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))
from census import disasm


def outputs():
    instructions = disasm(ROOT / 'c/ocamlrun-riscv-htif.elf')['longjmp']['insts']
    words = {word for _, word, _, _ in instructions}
    decoders = sorted(p.stem for p in (ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean')
                      if any(int(w, 16) in words for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)))
    decode_imports = '\n'.join('import Vsa.Sim.ElfDecode.' + name for name in decoders)
    loads = [((word >> 7) & 31, word >> 20) for _, word, _, _ in instructions if word & 0x7f == 3]
    normalized = []
    for pc, w, _, _ in instructions[:-1]:
        rd, rs1 = (w >> 7) & 31, (w >> 15) & 31
        if w & 0x7f == 3: kind, rs2, imm = '.ld', 0, w >> 20
        elif w & 0x7f == 0x13: kind, rs2, imm = '.slti true', 0, w >> 20
        else: kind, rs2, imm = '.add', (w >> 20) & 31, 0
        normalized.append('⟨' + ', '.join([f'0x{pc:x}#64', f'0x{w:08x}#32'] + [f'0x{(w >> (8*i)) & 255:02x}#8' for i in range(4)] + [kind, str(rd), str(rs1), str(rs2), f'0x{imm:03x}#12']) + '⟩')
    body = ',\n    '.join(normalized)
    reads = ', '.join(str(r) for r, _ in loads)
    raw_regs = ', '.join(['(10, compareValue true value 1#64 + value)'] + [f'({r}, bytesVal .ld (bytes {r}))' for r, _ in reversed(loads)] + ['(11, value)'])
    regs = ', '.join(['(10, longjmpValue value)'] + [f'({r}, saved {r})' for r, _ in reversed(loads)] + ['(11, value)'])
    value_facts = ', '.join(f'read {r} (by decide)' for r, _ in loads)
    memory = []
    for i, (r, off) in enumerate(loads):
        memory.append(f'''    · apply ReadWindow.ld (h.frame.reads {r} (by decide)).window rfl
        (by change BitVec.ofNat 64 buffer + sign_extend (m := 64) (0x{off:03x}#12) = BitVec.ofNat 64 (buffer + Layout.jumpSaveOffset {r}); rw [BitVec.ofNat_add]; rfl)
      change LPins8 c.σ.mem ((BitVec.ofNat 64 (buffer + Layout.jumpSaveOffset {r})).toNat) (read8 c.σ.mem (buffer + Layout.jumpSaveOffset {r}))
      simpa only [(h.frame.reads {r} (by decide)).toNat] using read8_pins c.σ.mem (buffer + Layout.jumpSaveOffset {r})''')
    mem_theorems = []
    for i, ((r, off), proof) in enumerate(zip(loads, memory)):
        proof = proof.replace('    · apply', '  apply', 1)
        proof = '\n'.join(line[4:] if j else line for j, line in enumerate(proof.splitlines()))
        mem_theorems.append(f'''theorem longjmp_mem_{i} {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{value : BitVec 64}} {{c : Config}}
    (h : LongjmpInput buffer saved value c) :
    MemFacts c.σ.mem (runGM (longjmpBody.take {i}) (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer))
      (((longjmpLoads c buffer).drop {i}).headD []) (longjmpBody[{i}]) := by
{proof}
''')
    mem_text = '\n'.join(mem_theorems)
    memory = [f'    · exact longjmp_mem_{i} h' for i in range(len(loads))]
    memory_text = '\n'.join('  ' + line for block in memory for line in block.splitlines())
    members = ' | '.join('rfl' for _ in loads)
    reg_proofs = '\n'.join('    · exact gholds_lookup _ regs (by rfl)' for _ in loads)
    text = f'''import OCaml.Vm.Sim.LongjmpState
import OCaml.Vm.Sim.LongjmpStructure
import OCaml.Vm.Sim.LongjmpImage
import Vsa.Sim.ChainFactsTac
{decode_imports}

/-! GENERATED by scripts/gen_longjmp.py. Native nonlocal return summary. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

def longjmpLoads (c : Config) (buffer : Nat) : List (List (BitVec 8)) :=
  [{reads}].map (fun r => read8 c.σ.mem (buffer + Layout.jumpSaveOffset r))

def longjmpAfterG (saved : Nat → BitVec 64) (value : BitVec 64) : GRegs :=
  [{regs}]

def longjmpBody : List MInstr := [{body}]

theorem longjmp_body : (longjmpX2c8cSeg[0]).body = longjmpBody := by rfl

/-- Evaluate register restoration independently of the machine memory representation. -/
theorem longjmp_eval (buffer value : BitVec 64) (bytes : Nat → List (BitVec 8)) :
    runGM (longjmpX2c8cSeg[0]).body (longjmpX2c8cL buffer value)
      ([{reads}].map bytes) = [{raw_regs}] := by
  rw [longjmp_body]
  simp [longjmpBody, longjmpX2c8cL, runGM, stepGM, stepLdsM, wvalM, srcVal, lookupG, eraseG,
    sign_extend, Sail.BitVec.signExtend]

/-- Normalize the generated load/register evaluator through the represented saved words. -/
theorem longjmp_body_regs {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{c : Config}} (value : BitVec 64)
    (h : JumpSavedFrame buffer saved c) :
    runGM (longjmpX2c8cSeg[0]).body (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer) = longjmpAfterG saved value := by
  have read (r : Nat) (hr : r ∈ Layout.jumpSavedRegs) :
      bytesVal .ld (read8 c.σ.mem (buffer + Layout.jumpSaveOffset r)) = saved r :=
    (read8_value _ _).trans (h.words r hr)
  unfold longjmpLoads
  rw [longjmp_eval]
  simp only [{value_facts}, longjmp_compare_value, longjmpAfterG]


/-- The normalized return address is the saved setjmp continuation. -/
theorem longjmp_ra {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{c : Config}} (value : BitVec 64)
    (h : JumpSavedFrame buffer saved c) :
    srcVal 1 (runGM (longjmpX2c8cSeg[0]).body (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer)) = saved 1 := by
  rw [longjmp_body_regs value h]
  rfl

{mem_text}
/-- The read-only body and saved return alignment discharge the function's complete block input. -/
theorem longjmp_input {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{value : BitVec 64}} {{c : Config}}
    (h : LongjmpInput buffer saved value c) :
    BlockInput longjmpX2c8cSeg (0x80042c8c#64) (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer) c := by
  refine ⟨h.good, h.good.minstret, ⟨h.bufferReg, h.valueReg, trivial⟩, ?_, ?_, longjmp_shape, h.tick⟩
  · change KeysOK [10, 11]; decide
  · have code := longjmp_loaded h.image
    apply singleton_chain_facts
    · change ProgFactsM c.σ.mem c.σ.mem (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer) longjmpBody
      chain_facts code with "Vsa.Sim.Code.longjmp_at_"
{memory_text}
    · chain_facts code with "Vsa.Sim.Code.longjmp_at_"
    · exact return_facts _ rfl rfl rfl (longjmp_ra value h.frame) h.aligned

end OCaml.Vm.Sim
'''
    summary = f'''import OCaml.Vm.Sim.LongjmpFacts

/-! GENERATED by scripts/gen_longjmp.py. Complete native nonlocal return. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable

/-- The native indirect return uses the saved, aligned continuation. -/
theorem longjmp_return_pc {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{value : BitVec 64}} {{c : Config}}
    (h : LongjmpInput buffer saved value c) :
    evalBlocksPC (0x80042c8c#64) (SegEvalState.init (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer)) longjmpX2c8cSeg = saved 1 := by
  simp only [evalBlocksPC, longjmpX2c8cSeg, SegEvalState.init, chainEndPC, endPCB, tgtPCT]
  exact (congrArg (fun r : BitVec 64 =>
    Sail.BitVec.update (r + LeanRV64DExecutable.Functions.sign_extend (m := 64) (0#12)) 0 0#1)
    (longjmp_ra value h.frame)).trans (ret_tgt (saved 1) h.aligned)

/-- Complete longjmp machine summary, including zero-to-one result normalization. -/
theorem longjmp_summary {{buffer : Nat}} {{saved : Nat → BitVec 64}} {{value : BitVec 64}} {{c : Config}}
    (h : LongjmpInput buffer saved value c) :
    FnSummary (0x80042c8c#64) (fun x => x = c) (LongjmpPost c saved value) := by
  have summary := block_summary _ _ _ _ _ (longjmp_input h)
  apply summary.weaken (fun _ eq => eq)
  intro after post
  have log : (evalBlocks longjmpX2c8cSeg (SegEvalState.init
      (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer))).log = [] :=
    readonly_log _ longjmp_readonly _ _
  have memory : after.σ.mem = c.σ.mem := by
    simpa only [log, writeLog, List.foldl_nil] using post.memory
  have regs : GHolds after.σ (longjmpAfterG saved value) := by
    have observed := post.regs
    change GHolds after.σ (runGM (longjmpX2c8cSeg[0]).body
      (longjmpX2c8cL (BitVec.ofNat 64 buffer) value) (longjmpLoads c buffer)) at observed
    rw [longjmp_body_regs value h.frame] at observed
    exact observed
  refine ⟨post.good, image_of_writeLog (log := []) h.image ⟨trivial, trivial⟩ memory,
    post.tick, post.pc.trans (congrArg some (longjmp_return_pc h)), ?_,
    gholds_lookup _ regs (by rfl), memory, ?_⟩
  · intro r member
    simp only [Layout.jumpSavedRegs, List.mem_cons, List.not_mem_nil, or_false] at member
    rcases member with {members}
{reg_proofs}
  · refine ⟨post.output, ?_⟩
    intro r outside
    apply post.frame r
    · intro q member
      exact outside q (List.mem_append_right _ member)
    · intro n member
      have written : ∀ n ∈ wrChain longjmpX2c8cSeg, gprReg n ∈ longjmpWrites := by decide
      exact outside _ (written n member)

end OCaml.Vm.Sim
'''
    return {ROOT / 'OCaml/Vm/Sim/LongjmpFacts.lean': text, ROOT / 'OCaml/Vm/Sim/Longjmp.lean': summary}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'longjmp summary drift: {path}')
        else:
            path.write_text(content)
    print('longjmp summary artifacts current')
