#!/usr/bin/env python3
"""Generate physical equality arms over named word-reflection evidence."""
import argparse
import json
from census import ROOT


def outputs():
    result = {}
    for op in ['EQ', 'NEQ']:
        for truth in [True, False]:
            stem = op.title() + ('True' if truth else 'False')
            lower = op.lower() + ('_true' if truth else '_false')
            equal = truth if op == 'EQ' else not truth
            bit, word = (1, 3) if truth else (0, 1)
            spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
            regs = [p['reg'] for p in spec['pins']]
            values = {'x9': 'BitVec.ofNat 64 sp', 'x21': 'w', 'x23': 'BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64'}
            holds = {'x9': '(dp.frame.frame Register.x9 (by decide)).trans h.spReg',
                     'x21': '(dp.frame.frame Register.x21 (by decide)).trans source', 'x23': 'dp.nextCode'}
            pins = ', '.join(f'⟨Register.{r}, {values[r]}⟩' for r in regs)
            pin_holds = ', '.join(holds[r] for r in regs)
            args = ' '.join(f'({values[r]})' for r in regs)
            for step in spec['steps']:
                if step.get('rd'):
                    regs = [step['rd']] + [r for r in regs if r != step['rd']]
            result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.StackConsume
import OCaml.Vm.Sim.WordEquality
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_equality_arms.py. Physical equality path. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op}'s {str(truth).lower()} path consumes the stack value and returns the represented Boolean.
Word equality reflection remains a named static representation obligation. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}} {{b : Val}} {{rest : List Val}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (stack : s.stack = b :: rest)
    (read : ReadWindow (BitVec.ofNat 64 sp) 8)
    (equality : WordEquality pl s.accu b)
    (test : physEq? s.accu b = some {str(equal).lower()}) :
    ∃ c', Plus c c' ∧ Running L P
      {{s with pc := s.pc + 1, accu := .int ({bit}#63), stack := rest}} c' := by
  have selected : s.stack[0]? = some b := by simp only [stack, List.getElem?_cons_zero]
  obtain ⟨w, source, value⟩ := h.accu
  have slot : valWord pl b = some (word c sp) := by
    simpa only [Nat.mul_zero, Nat.add_zero] using h.stack.2 0 b selected
  have compare := equality.guard value slot test
  have natAddress : (BitVec.ofNat 64 sp).toNat = sp := by
    simpa only [Nat.mul_zero, Nat.add_zero] using stack_slot_nat h.toVmReprAt selected
  have bound : 1 ≤ s.stack.length := by simp only [stack, List.length_cons]; omega
  have result := consume_arm (pc := s.pc + 1) (count := 1) (n := {bit}#63) stable h bound
  simp only [stack, List.drop_succ_cons, List.drop_zero] at result
  apply result
  intro d dp
  have loaded : sign_extend (m := 64) (bytesT8 d.σ.mem (BitVec.ofNat 64 sp).toNat) = word c sp := by
    simp only [natAddress, dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq]
  have bp : SegSt ({spec['entry']}#64)
      [{pins}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨{pin_holds}, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} {args} d.σ.mem d.σ
  simp only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, loaded] at run
  obtain ⟨nb, after, _, hb, post⟩ := run read.lower read.upper read.htif compare d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, ?_, hm, frame.out, ?_⟩
  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) :=
      PinsHold.get post.pins ⟨{regs.index('x8')}, by simp⟩
    simpa only [codePc_succ] using hp
  · have hp : gpr after Layout.reg_sp = some
        (BitVec.ofNat 64 sp + sign_extend (m := 64) (0x008#12)) :=
      PinsHold.get post.pins ⟨{regs.index('x9')}, by simp⟩
    simpa only [show sign_extend (m := 64) (0x008#12) = 8#64 from by decide,
      Nat.mul_one, BitVec.ofNat_add] using hp
  · have hp : gpr after Layout.reg_accu = some ((0#64) + sign_extend (m := 64) (0x{word:03x}#12)) :=
      PinsHold.get post.pins ⟨{regs.index('x21')}, by simp⟩
    simpa only [show ((0#64) + sign_extend (m := 64) (0x{word:03x}#12)) = tag64 ({bit}#63) from by decide] using hp
  · intro r hr
    exact frame.frame r (by revert r; decide)

end OCaml.Vm.Sim
'''
        stem = op.title()
        cases = ''
        for equal in [False, True]:
            truth = equal if op == 'EQ' else not equal
            cases += f'''      | {str(equal).lower()} =>
        have state : {{s with pc := s.pc + 1, accu := .int ({1 if truth else 0}#63), stack := rest}} = s' := by
          simpa [stepI, stack, test, opt, St.adv, Val.ofBool] using step
        rw [← state]
        exact {op.lower()}_{'true' if truth else 'false'}_arm stable h stack read ready test
'''
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.{stem}True
import OCaml.Vm.Sim.{stem}False

/-! GENERATED by scripts/gen_equality_arms.py. Physical equality composition. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine
open OCaml.Vm.Primitives

/-- Both paths implement a successful {op} step when represented words reflect physical equality. -/
theorem {op.lower()}_step_arm {{L : OCaml.Layout}} {{P : Prog}} {{s s' : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (read : ReadWindow (BitVec.ofNat 64 sp) 8)
    (equality : ∀ b, s.stack[0]? = some b → WordEquality pl s.accu b)
    (step : stepI P s ⟨.{op}, []⟩ = .next s') :
    ∃ c', Plus c c' ∧ Running L P s' c' := by
  cases stack : s.stack with
  | nil => simp [stepI, stack] at step
  | cons b rest =>
    have ready := equality b (by simp [stack])
    cases test : physEq? s.accu b with
    | none => simp [stepI, stack, test, opt] at step
    | some equal =>
      cases equal with
{cases}
end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'equality arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Equality arm bridges current')
