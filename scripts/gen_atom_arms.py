#!/usr/bin/env python3
"""Generate atom bridges using the runtime table binding and upper-immediate sites."""
import argparse
import json
from census import ROOT


def outputs():
    result = {}
    for generic in [False, True]:
        stem, op = ('Atom', 'ATOM') if generic else ('Atom0', 'ATOM0')
        lower = op.lower()
        spec = json.loads((ROOT / f'scripts/syi/segments/{lower}.json').read_text())
        ea = [p for p in spec['params'] if p.startswith('(hlo_')][-1].split(' ≤ ', 1)[1].removesuffix('.toNat)')
        tag, advance, pc_index = ('w.toInt.toNat', 2, 2) if generic else ('0', 1, 1)
        extra_binder = ' {w : BitVec 32}' if generic else ''
        extra_inputs = '''    (operand : OperandAt P pl (s.pc + 1) w)
    (nonnegative : 0 ≤ w.toInt)
''' if generic else ''
        pre_pin = '⟨Register.x8, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)⟩' if generic else '⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩'
        pre_hold = '(dp.frame.frame Register.x8 (by decide)).trans h.pc' if generic else 'dp.nextCode'
        run_arg = 'BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)' + ('' if generic else ' + 4#64')
        extra_read = '''  have read : bytesT4 d.σ.mem (pl.codeBase + 4 * (s.pc + 1)) = w :=
    operand.read32 h.code dp.memory
''' if generic else ''
        simps = ['address', 'table.toNat',
                 'show sign_extend (m := 64) (0x008#12) = 8#64 from by decide']
        simps += (['show sign_extend (m := 64) (0x004#12) = 4#64 from by decide',
                   'codePc_succ', 'operand.geometry.toNat', 'read', 'atom_index_offset w nonnegative']
                  if generic else ['show sign_extend (m := 64) (0x000#12) = 0#64 from by decide',
                                   'BitVec.add_zero'])
        simp_text = ',\n    '.join(simps)
        extra_args = 'operand.geometry.lower operand.geometry.upper operand.geometry.htif ' if generic else ''
        result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.IndexWord
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_atom_arms.py. Atom pointers through the runtime binding. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} reads the allocated table pointer and restores the represented atom.
All fixed data addresses come from Layout; dispatch and runtime framing remain explicit. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high : Nat}}{extra_binder}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
{extra_inputs}    : ∃ c', Plus c c' ∧ Running L P {{s with pc := s.pc + {advance}, accu := .atom ({tag})}} c' := by
  apply accu_arm stable h (atom_word_of_binding h.atomBase ({tag})) (fun _ hl => by cases hl)
  intro d dp
  have table : RamReadAt Layout.sym_caml_atom_table 8 := ⟨by decide, by decide, by decide⟩
  have address : {ea} = BitVec.ofNat 64 Layout.sym_caml_atom_table := by decide
{extra_read}  have bp : SegSt ({spec['entry']}#64)
      [{pre_pin}]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨{pre_hold}, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} ({run_arg}) d.σ.mem d.σ
  simp only [{simp_text}] at run
  obtain ⟨nb, after, _, hb, post⟩ := run {extra_args}table.lower table.upper table.htif d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
  · have hp : gpr after Layout.reg_pc = some
        (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + {4*advance}#64) := PinsHold.get post.pins ⟨{pc_index}, by simp⟩
    simpa only [show BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + {4*advance}#64 =
      BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + {advance})) from codePc_add pl s.pc {advance}] using hp
  · have hp : gpr after Layout.reg_accu = some
        (sign_extend (m := 64) (bytesT8 d.σ.mem Layout.sym_caml_atom_table) +
          BitVec.ofNat 64 (8 * ({tag}) + 8)) := PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using hp

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'atom arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Atom arm bridges current')
