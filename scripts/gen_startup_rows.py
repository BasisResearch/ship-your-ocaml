    lo, hi = extents['caml_init_backtrace']
    uses = [i for pc,i in di.items() if lo <= pc < hi and i.word & 0x000fffff == 0x00050513
            and gen_fn.lib.sext(i.word >> 20, 12) == offset]
    assert len(uses) == 1
    use = uses[0]
    E(f'def startupKeyOffset : Nat := {offset}',
      'theorem startup_key_line :',
      f'    mkLine 0x{use.addr:x}#64 0x{use.word:08x}#32 =',
      '      ' + gen_fn.ocaml_literal_mline(use.addr, use.word) + ' := by rfl', '',
      'theorem startup_key_value (domain : BitVec 64) :',
      f'    wvalM (mkLine 0x{use.addr:x}#64 0x{use.word:08x}#32) [(10, domain)] [] =',
      '      domain + BitVec.ofNat 64 startupKeyOffset := by',
      '  rw [startup_key_line]',
      '  simp only [wvalM, srcVal, lookupG, Option.getD_some, ite_true]',
      f'  rw [show Functions.sign_extend (m := 64) {offset}#12 = {offset}#64 by decide]', '  rfl', '')
