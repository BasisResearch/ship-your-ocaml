#!/usr/bin/env python3
"""Generate startup blocks through gen_fn, using only the pinned ELF."""
import argparse
import contextlib
import importlib.util
import io
import re
import subprocess
import sys
import tempfile
from types import SimpleNamespace
from pathlib import Path
from census import ROOT, TOOLS
from gen_ocaml_image import sections
from gen_arm_pilot import image_projection

sys.path.insert(0, str(ROOT / 'scripts/syi'))
import gen_fn
import gen_sites
from ocaml_block_certificates import emit_call
spec = importlib.util.spec_from_file_location('startup_pins', ROOT / 'experiments/syi/gen_code_lemmas.py')
code = importlib.util.module_from_spec(spec)
spec.loader.exec_module(code)


def outputs():
    result = {}
    text_base = sections((ROOT / "c/ocamlrun-riscv-htif.elf").read_bytes())[".text"][0]
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        disasm = tmp / 'disasm.txt'
        with disasm.open('w') as f:
            subprocess.run([TOOLS + 'objdump', '-d', str(ROOT / 'c/ocamlrun-riscv-htif.elf')], stdout=f, check=True)
        di = gen_fn.lib.parse_disasm(str(disasm))
        extents = gen_fn.function_extents(str(disasm))
        index = tmp / 'index.tsv'
        index.write_text('\n'.join(w + '\tVsa.Sim.ElfDecode.' + p.stem
            for p in sorted((ROOT / 'Vsa/Sim/ElfDecode').glob('Part*.lean'))
            for w in re.findall(r'^theorem decode_([0-9a-f]{8})', p.read_text(), re.M)) + '\n')
        for name, stem, region in [('_start', 'Crt0', None), ('main', 'Main', None),
                ('caml_build_primitive_table', 'PrimitiveLookup', (0x80024e0c, 0x80024e4c)),
                ('caml_stat_alloc_noexc', 'StatAlloc', None),
                ('caml_main', 'CamlMain', 'first-call'),
                ('getuid', 'UserId', None),
                ('geteuid', 'EffectiveUserId', None),
                ('getgid', 'GroupId', None),
                ('getegid', 'EffectiveGroupId', None),
                ('caml_init_domain', 'Domain', 'first-call'),
                ('caml_alloc_minor_tables', 'MinorTables', 'first-call'),
                ('caml_init_domain', 'DomainInit', (0x8002a8ec, 0x8002a938)),
                ('caml_init_domain', 'DomainFields', (0x8002a938, 0x8002a9d0)),
                ('caml_init_domain', 'DomainReturn', (0x8002a9d0, 0x8002a9dc)),
                ('memset', 'MemsetPrefix', (0x8004276c, 0x80042790)),
                ('memset', 'MemsetLoop', (0x80042790, 0x800427a0)),
                ('memset', 'MemsetTail', (0x800427a0, 0x800427fc)),
                ('memset', 'MemsetBytes', (0x800427d8, 0x800427fc)),
                ('caml_alloc_minor_tables', 'MinorTablePublish0', (0x8000982c, 0x8000983c)),
                ('caml_alloc_minor_tables', 'MinorTablePublish1', (0x80009854, 0x80009864)),
                ('caml_alloc_minor_tables', 'MinorTablePublish2', (0x8000987c, 0x8000988c)),
                ('caml_alloc_minor_tables', 'MinorTableZero0', (0x8000983c, 0x80009848)),
                ('caml_alloc_minor_tables', 'MinorTableZero1', (0x80009864, 0x80009870)),
                ('caml_alloc_minor_tables', 'MinorTableNext0', (0x80009848, 0x80009854)),
                ('caml_alloc_minor_tables', 'MinorTableNext1', (0x80009870, 0x8000987c)),
                ('caml_alloc_minor_tables', 'MinorTableTail', (0x8000988c, 0x800098a8))]:
            entry, end = extents[name]
            words = [(a, di[a].word) for a in sorted(di) if entry <= a < end]
            pins = code.render(name, words).replace('generated by experiments/gen_code_lemmas.py',
                'GENERATED by scripts/gen_startup_rows.py via experiments/syi/gen_code_lemmas.py')
            loaded = name[0].upper() + name[1:] + 'Loaded'
            chunks = re.findall(r'^def (' + re.escape(name) + r'Chunk[0-9]+)\b', pins, re.M)
            assert chunks, 'code emitter supplied no chunks'
            chunk_defs = ', '.join(chunks)
            transport = f"""
/-- Preserve this generated code predicate through byte agreement on its extent. -/
theorem {name}_transport {{m m' : ExtHashMap Nat (BitVec 8)}}
    (h : {loaded} m)
    (same : ∀ a, 0x{entry:x} ≤ a → a < 0x{end:x} → m'[a]? = m[a]?) :
    {loaded} m' := by
  simp (disch := decide) only [{loaded}, {chunk_defs}, same] at *
  exact h

"""
            pins = pins.replace('end Vsa.Sim.Code', transport + 'end Vsa.Sim.Code')
            # Existing library pins retain their own generator's ownership.
            if name != 'memset':
                result[ROOT / f'Vsa/Sim/Code/{name[0].upper() + name[1:]}.lean'] = pins
            projection = image_projection([(a, w, '', []) for a, w in words],
                'Vsa.Sim.Code.' + loaded, 'Vsa.Sim.Code.' + name[0].upper() + name[1:],
                ['Vsa.Sim.Code.' + chunk for chunk in chunks], stem[0].lower() + stem[1:] + '_code', text_base)
            projection = projection.replace('GENERATED by scripts/gen_arm_pilot.py.',
                'GENERATED by scripts/gen_startup_rows.py via gen_arm_pilot.image_projection.').replace(
                'namespace OCaml.Vm.Sim', 'namespace OCaml.Vm.Boot.Startup').replace(
                'end OCaml.Vm.Sim', 'end OCaml.Vm.Boot.Startup')
            result[ROOT / f'OCaml/Vm/Boot/Startup/{stem}Image.lean'] = projection
            if region == 'first-call':
                row_entry = entry
                row_end = next(a + 4 for a in sorted(di) if entry <= a < end and di[a].mnem == 'jal')
            else:
                row_entry, row_end = region if region else (entry, end)
            path = tmp / f'{stem}.lean'
            with contextlib.redirect_stdout(io.StringIO()):
                gen_fn.emit_fn(name, row_entry, str(path), verify=False,
                               region_end=row_end if region else None,
                               disasm_path=str(disasm), decode_index=str(index))
            text = path.read_text().replace('set_option maxRecDepth 100000\n', '').replace('GENERATED by `scripts/gen_fn.py',
                'GENERATED by scripts/gen_startup_rows.py via `scripts/syi/gen_fn.py').replace(
                'from `experiments/disasm.txt`', 'from the pinned runtime ELF')
            result[ROOT / f'OCaml/Vm/Boot/Startup/{stem}Rows.lean'] = text
            if region == 'first-call' or stem in ('DomainInit', 'DomainFields', 'DomainReturn') or stem.startswith(('Memset', 'MinorTable')):
                _, cfg = gen_fn.build_cfg(name, row_entry, di, extents, region_end=row_end)
                normalized = [f'import OCaml.Vm.Boot.Startup.{stem}Rows', '',
                              '/-! GENERATED by scripts/gen_startup_rows.py via gen_fn.ocaml_literal_mline. -/',
                              'namespace OCaml.Vm.Boot.Startup', 'open Vsa.Sim', '']
                for ins in (di[a] for a in sorted(di) if row_entry <= a < row_end and di[a].mnem != 'jal'):
                    if ins.mnem.startswith('b') or ins.mnem in ('ret', 'jr', 'jalr', 'j'):
                        continue
                    normalized += [f'theorem {stem.lower()}_line_{ins.addr:x} :',
                        f'    mkLine 0x{ins.addr:x}#64 0x{ins.word:08x}#32 =',
                        '      ' + gen_fn.ocaml_literal_mline(ins.addr, ins.word) + ' := by rfl', '']
                for block in cfg:
                    if block.kind != 'jal' and stem != 'DomainFields':
                        continue
                    norm = stem[0].lower() + stem[1:] + 'Save'
                    seg = f'{name}X{block.start & 0xffff:x}Seg'
                    normalized += [f'def {norm} : List BBlock := [⟨[',
                        ',\n'.join('  ' + gen_fn.ocaml_literal_mline(i.addr, i.word) for i in block.instrs),
                        '], none⟩]', f'theorem {norm}_eq : {norm} = {seg} := by rfl', '']
                normalized += ['end OCaml.Vm.Boot.Startup', '']
                result[ROOT / f'OCaml/Vm/Boot/Startup/{stem}Normalized.lean'] = '\n'.join(normalized)

            calls = [di[a] for a in sorted(di) if row_entry <= a < row_end and di[a].mnem == 'jal']
            emitter = gen_sites.Emitter(f'Vsa.Sim.Code.{name[0].upper()+name[1:]}Loaded',
                f'Vsa.Sim.Code.{name}_at_', '_startup', 'Vsa.Sim.ElfDecode')
            call_text = ['import OCaml.Vm.Boot.Startup.Call', 'import Vsa.Sim.FnSummary',
                f'import Vsa.Sim.Code.{name[0].upper()+name[1:]}']
            parts = dict(line.split('\t') for line in index.read_text().splitlines())
            call_text += ['import ' + x for x in sorted({parts[f'{i.word:08x}'] for i in calls})]
            call_text += ['', '/-! GENERATED by scripts/gen_startup_rows.py via gen_sites.py. -/',
                'namespace OCaml.Vm.Boot.Startup',
                'open Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions Sail', '']
            for ins in calls:
                imm = gen_fn.lib._jal_imm(ins.word)
                target = (ins.addr + gen_sites.sext(imm, 21)) % 2**64
                site = gen_sites.Site(ins.addr, ins.word, 'jal', ['1', hex(imm)], 0)
                call_text.append(emitter.emit_jal(site))
                call_text.append(f"""
theorem call_{ins.addr:08x} (c : Config) (good : GoodState c.σ) (tick : c.tick < 2)
    (code : Vsa.Sim.Code.{name[0].upper()+name[1:]}Loaded c.σ.mem) :
    FnSummary 0x{ins.addr:x}#64 (fun d => d = c)
      (CallPost 0x{target:x}#64 0x{ins.addr+4:x}#64 c) := by
  constructor
  rintro d ⟨pc, eq⟩
  subst d
  obtain ⟨vm, hvm⟩ := good.minstret
  obtain ⟨σ, tick', step, bound, good', memory, obs⟩ :=
    {emitter.site_name(ins.addr)} c.σ c.tick c.steps _ vm good pc hvm code rfl tick
  exact ⟨⟨σ, tick', c.steps + 1⟩, Steps.single step,
    CallPost.of_obs good' bound memory obs (by decide)⟩
""")
            if region == 'first-call' or stem in ('DomainInit', 'DomainFields', 'DomainReturn') or stem.startswith(('Memset', 'MinorTable')):
                interface = gen_fn.lib.Emitter()
                interface('import OCaml.Vm.Primitives.Call',
                          f'import OCaml.Vm.Boot.Startup.{stem}Image')
                for part in sorted({parts[f'{ins.word:08x}'] for ins in calls}):
                    interface('import ' + part)
                interface('', '/-! GENERATED by scripts/gen_startup_rows.py via ocaml_block_certificates.emit_call. -/',
                          'namespace OCaml.Vm.Boot.Startup',
                          'open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives', '')
                for ins in calls:
                    target = (ins.addr + gen_sites.sext(gen_fn.lib._jal_imm(ins.word), 21)) % 2**64
                    block = SimpleNamespace(term=ins, callee=target)
                    emit_call(interface, name, block, f'jal_{ins.addr:08x}',
                              {target: {'insts': [(target,)]}}, gen_fn.lib,
                              loaded=stem[0].lower() + stem[1:] + '_code')
                interface('end OCaml.Vm.Boot.Startup', '')
                result[ROOT / f'OCaml/Vm/Boot/Startup/{stem}CallInterface.lean'] = interface.text()
            call_text += ['end OCaml.Vm.Boot.Startup', '']
            result[ROOT / f'OCaml/Vm/Boot/Startup/{stem}Calls.lean'] = '\n'.join(call_text)

    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'startup row drift: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(path.relative_to(ROOT))
