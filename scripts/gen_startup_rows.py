def skip_first_eval(di, extents):
    """Bounded symbolic certificates for the zero-header, zero-seed route.

    This is partial evaluation of ELF words, checked by runGM/ldsRunM/wlogM.
    No execution, load pin or branch is assumed by these algebraic lemmas.
    """
    _, cfg = gen_fn.build_cfg('caml_skiplist_insert', extents['caml_skiplist_insert'][0], di, extents)
    route = [(0x8002aafc, False), (0x8002ab10, None), (0x8002ab3c, False),
             (0x8002ab48, False), (0x8002ab58, True), (0x8002ab68, True),
             (0x8002aca4, True), (0x8002acb8, None)]
    state = [(2, 'sp'), (1, 'ra'), (10, 0x800684e0), (11, 'key'), (12, 0), (8, 's0'), (9, 's1')]
    all_loads = [4, 8, 8, 4]
    consumed = 0
    mask = (1 << 64) - 1
    def expr(x):
        if isinstance(x, int): return f'{x & mask}#64'
        if isinstance(x, tuple): return f'({expr(x[0])} + {x[1] & mask}#64)'
        return x
    def add(x, y):
        if isinstance(x, int) and isinstance(y, int): return (x + y) & mask
        if y == 0: return x
        if x == 0: return y
        if isinstance(y, int):
            if isinstance(x, tuple): return (x[0], (x[1] + y) & mask)
            return (x, y & mask)
        raise ValueError(f'nonconstant first-route add: {x}, {y}')
    def regs(xs): return '[' + ', '.join(f'({k}, {expr(v)})' for k, v in xs) + ']'
    def loads(k): return '[' + ', '.join('[' + ','.join(['0#8'] * n) + ']' for n in all_loads[k:]) + ']'
    out = ['import OCaml.Vm.Boot.Startup.SkipFirstNormalized',
           'import OCaml.Vm.Primitives.Word32Access', '',
           '/-! GENERATED by scripts/gen_startup_rows.py. Bounded zero-seed evaluator certificates. -/',
           'namespace OCaml.Vm.Boot.Startup.SkipFirstEval',
           'set_option linter.unusedSimpArgs false',
           'set_option linter.unusedVariables false',
           'open Vsa.Sim LeanRV64DExecutable OCaml.Vm.Primitives', '']
    E = lambda *xs: out.extend(xs)
    E('theorem checkedLogStep (a : MInstr) (tail : List MInstr) (r r2 : GRegs)',
      '    (ld ld2 : List (List (BitVec 8)))',
      '    (kind : a.kind ≠ .sw ∧ a.kind ≠ .sd ∧ a.kind ≠ .sb ∧ a.kind ≠ .sh)',
      '    (reg : stepGM a r (ld.headD []) = r2) (load : stepLdsM a.kind ld = ld2) :',
      '    wlogM (a :: tail) r ld = wlogM tail r2 ld2 := by',
      '  rw [← reg, ← load]',
      '  cases hk : a.kind <;> simp_all [wlogM]', '',
      'theorem checkedLogStore (a : MInstr) (tail : List MInstr) (r : GRegs)',
      '    (ld : List (List (BitVec 8))) (entry : WEntry)',
      '    (kind : a.kind = .sw ∨ a.kind = .sd ∨ a.kind = .sb ∨ a.kind = .sh)',
      '    (store : wentryM a r = entry) :',
      '    wlogM (a :: tail) r ld = entry :: wlogM tail r ld := by',
      '  rcases kind with h | h | h | h <;> simp only [wlogM, h, store]', '')
    E(f'abbrev state0 (sp ra key s0 s1 : BitVec 64) : GRegs := {regs(state)}')
    for j, (pc, taken) in enumerate(route):
        b = next(b for b in cfg if b.start == pc)
        seg = gen_fn.block_name('caml_skiplist_insert', b, taken) + 'Seg' if taken is not None else gen_fn.block_name('caml_skiplist_insert', b) + 'Seg'
        # gen_fn's branch argument is a Boolean (the names carry T/F).
        if taken is not None:
            seg = f'caml_skiplist_insertX{pc & 0xffff:04x}{"T" if taken else "F"}Seg'
        E(f'abbrev block{j} : BBlock := {seg}.getD 0 {{body := [], term := none}}',
          f'abbrev loads{j} : List (List (BitVec 8)) := {loads(consumed)}')
        log = []
        before = consumed
        entry_state = list(state)
        def val(k): return 0 if k == 0 else next(v for r, v in state if r == k)
        def put(k, v):
            nonlocal state
            if k: state = [(k, v)] + [(r, x) for r, x in state if r != k]
        for i, ins in enumerate(b.instrs):
            old = list(state)
            old_consumed = consumed
            old_log_len = len(log)
            w = ins.word
            op, rd, f3 = w & 127, (w >> 7) & 31, (w >> 12) & 7
            r1, r2 = (w >> 15) & 31, (w >> 20) & 31
            imm = gen_fn.lib.sext(w >> 20, 12)
            if op == 3:
                assert (4 if f3 == 2 else 8) == all_loads[consumed]
                consumed += 1
                put(rd, 0)
            elif op == 0x23:
                off = gen_fn.lib.sext(((w >> 25) << 5) | ((w >> 7) & 31), 12)
                log.append((add(val(r1), off), 4 if f3 == 2 else 8, val(r2)))
            elif op == 0x17: put(rd, add(ins.addr, gen_fn.lib.sext(w & 0xfffff000, 32)))
            elif op == 0x37: put(rd, gen_fn.lib.sext(w & 0xfffff000, 32) & mask)
            elif op == 0x13:
                x = val(r1)
                if f3 == 0: put(rd, add(x, imm))
                elif f3 == 1: put(rd, (x << ((w >> 20) & 63)) & mask)
                elif f3 == 5: put(rd, x >> ((w >> 20) & 63))
                else: raise ValueError(ins)
            elif op == 0x1b:
                x = val(r1)
                y = x + imm if f3 == 0 else x << ((w >> 20) & 31)
                put(rd, gen_fn.lib.sext(y & 0xffffffff, 32) & mask)
            elif op in (0x33, 0x3b):
                x, y = val(r1), val(r2)
                z = add(x, y) if f3 == 0 and w >> 25 == 0 else x - y if f3 == 0 else x & y
                if op == 0x3b: z = gen_fn.lib.sext(z & 0xffffffff, 32) & mask
                put(rd, z)
            else: raise ValueError(ins)
            # Each certificate normalizes just one instruction. In particular,
            # never unfold a long runGM inside wlogM: that duplicates its state.
            tag = f'i{ins.addr:x}'
            instr = f'mkLine 0x{ins.addr:x}#64 0x{ins.word:08x}#32'
            rule = f'skipfirst_line_{ins.addr:x}'
            E(f'abbrev {tag}_before (sp ra key s0 s1 : BitVec 64) : GRegs := {regs(old)}',
              f'abbrev {tag}_after (sp ra key s0 s1 : BitVec 64) : GRegs := {regs(state)}')
            # Normalize registers structurally, keeping scalar arithmetic and
            # toNat opaque. In particular, default simp expands toNat_add under
            # a symbolic stack address into a very large kernel proof.
            structural = 'srcVal, lookupG, eraseG, Option.getD_some, Nat.reduceEqDiff, ite_true, ite_false'
            def addition_proof(x, y):
                # Only addition can carry a symbolic source on this route.
                lines = []
                if isinstance(x, tuple):
                    lines.append('  rw [BitVec.add_assoc]')
                    lines.append(f'  rw [show {expr(x[1])} + {expr(y)} = {expr((x[1] + y) & mask)} by decide]')
                elif not isinstance(x, int):
                    if y == 0: lines.append('  rw [BitVec.add_zero]')
                else:
                    lines.append('  decide')
                return lines
            if op != 0x23:
                # The value certificate is scalar: list bookkeeping is proved
                # separately and never sends a symbolic address through simp.
                E(f'theorem {tag}_value (sp ra key s0 s1 : BitVec 64) :',
                  f'    wvalM ({instr}) {regs(old)} ({loads(old_consumed)}.headD []) = {expr(state[0][1])} := by',
                  f'  rw [{rule}]',
                  f'  simp only [{tag}_before, wvalM, {structural}]')
                if op == 0x13 and f3 == 0 and not isinstance(next(v for r,v in old if r == r1) if r1 else 0, int):
                    x = next(v for r,v in old if r == r1) if r1 else 0
                    E(f'  rw [show Functions.sign_extend (m := 64) {w >> 20}#12 = {expr(imm)} by decide]')
                    E(*addition_proof(x, imm))
                    E('  try rfl')
                elif op == 0x33 and f3 == 0 and w >> 25 == 0 and (not isinstance(x, int) or not isinstance(y, int)):
                    E(*addition_proof(x, y), '  try rfl')
                else:
                    E('  decide')
                E('')
                E(f'theorem {tag}_regs (sp ra key s0 s1 : BitVec 64) :',
                  f'    stepGM ({instr}) {regs(old)} ({loads(old_consumed)}.headD []) = {regs(state)} := by',
                  f'  have value := {tag}_value sp ra key s0 s1',
                  f'  rw [{rule}] at value ⊢',
                  '  simp only [stepGM]',
                  '  rw [value]',
                  f'  simp only [{tag}_before, {tag}_after, {structural}]', '')
            else:
                E(f'theorem {tag}_regs (sp ra key s0 s1 : BitVec 64) :',
                  f'    stepGM ({instr}) {regs(old)} ({loads(old_consumed)}.headD []) = {regs(state)} := by',
                  f'  rw [{rule}]', '  rfl', '')
            E(f'theorem {tag}_loads : stepLdsM ({instr}).kind {loads(old_consumed)} = {loads(consumed)} := by',
              f'  rw [{rule}]', '  rfl', '')
            if len(log) != old_log_len:
                a, n, v = log[-1]
                x = next(v for r,v in old if r == r1) if r1 else 0
                E(f'theorem {tag}_address (sp ra key s0 s1 : BitVec 64) :',
                  f'    eaddrM ({instr}) {regs(old)} = {expr(a)} := by',
                  f'  rw [{rule}]',
                  f'  simp only [{tag}_before, eaddrM, {structural}]',
                  f'  rw [show Functions.sign_extend (m := 64) {off & 4095}#12 = {expr(off)} by decide]')
                E(*addition_proof(x, off), '  try rfl', '')
                E(f'theorem {tag}_store (sp ra key s0 s1 : BitVec 64) :',
                  f'    wentryM ({instr}) {regs(old)} = (({expr(a)}).toNat, {n}, {expr(v)}) := by',
                  f'  unfold wentryM',
                  f'  rw [{tag}_address, {rule}]',
                  '  rfl', '')
            if op == 0x23:
                E(f'theorem {tag}_memory (m : Std.ExtHashMap Nat (BitVec 8)) (sp ra key s0 s1 : BitVec 64) :',
                  f'    stepMemM m ({instr}) {regs(old)} = writeLog m [(({expr(a)}).toNat, {n}, {expr(v)})] := by',
                  f'  have store := {tag}_store sp ra key s0 s1',
                  f'  rw [{rule}] at store ⊢',
                  '  simp only [stepMemM, store, writeLog, List.foldl_cons, List.foldl_nil]', '')
            else:
                E(f'theorem {tag}_memory (m : Std.ExtHashMap Nat (BitVec 8)) (r : GRegs) :',
                  f'    stepMemM m ({instr}) r = m := by rw [{rule}]; rfl', '')
            if op == 3:
                x = next(v for r,v in old if r == r1) if r1 else 0
                a = add(x, imm)
                n = 4 if f3 == 2 else 8
                E(f'theorem {tag}_address (sp ra key s0 s1 : BitVec 64) :',
                  f'    eaddrM ({instr}) {regs(old)} = {expr(a)} := by',
                  f'  rw [{rule}]',
                  f'  simp only [eaddrM, {structural}]', '  decide', '')
            if op in (3, 0x23):
                window = 'ReadWindow' if op == 3 else 'WriteWindow'
                method = ('lw' if n == 4 else 'ld') if op == 3 else ('sw' if n == 4 else 'sd')
                pins = f' (pins : LPins{n} m ({expr(a)}).toNat ({loads(old_consumed)}.headD []))' if op == 3 else ''
                E(f'theorem {tag}_facts (m : Std.ExtHashMap Nat (BitVec 8)) (sp ra key s0 s1 : BitVec 64)',
                  f'    (window : {window} {expr(a)} {n}){pins} :',
                  f'    MemFacts m {regs(old)} ({loads(old_consumed)}.headD []) ({instr}) := by',
                  f'  have address := {tag}_address sp ra key s0 s1',
                  f'  rw [{rule}] at address ⊢',
                  f'  exact window.{method} rfl address' + (' pins' if op == 3 else ''), '')
            log_rhs = (f'(({expr(a)}).toNat, {n}, {expr(v)}) :: ' if op == 0x23 else '')
            E(f'theorem {tag}_log (sp ra key s0 s1 : BitVec 64) (tail : List MInstr) :',
              f'    wlogM (({instr}) :: tail) {regs(old)} {loads(old_consumed)} =',
              f'      {log_rhs}wlogM tail {regs(state)} {loads(consumed)} := by')
            if op == 0x23:
                E('  apply checkedLogStore',
                  f'  · rw [{rule}]; exact ' + ('Or.inr (Or.inl rfl)' if n == 8 else 'Or.inl rfl'),
                  f'  · exact {tag}_store sp ra key s0 s1', '')
            else:
                E('  apply checkedLogStep',
                  f'  · rw [{rule}]; decide',
                  f'  · exact {tag}_regs sp ra key s0 s1',
                  f'  · exact {tag}_loads', '')
        E(f'abbrev state{j+1} (sp ra key s0 s1 : BitVec 64) : GRegs := {regs(state)}',
          f'abbrev log{j} (sp ra key s0 s1 : BitVec 64) : List WEntry := [' + ', '.join(f'(({expr(a)}).toNat, {n}, {expr(v)})' for a,n,v in log) + ']')
