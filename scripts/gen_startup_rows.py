def seek_section_data():
    """Bounded descriptor reads from the chosen reset's initial image.

    The runtime code/literal comes from the ELF; the selected /prog payload
    comes from the same archived loader pieces as WhileMinImage, not a cut.
    Every emitted read is checked against loaderMem in Lean.
    """
    archive = json.loads(gzip.decompress((ROOT / 'results/boot/while_min-initial.json.gz').read_bytes()))
    pieces = [(a, bytes(bs)) for a, bs in archive['pieces'] if bs]
    def read(a, n):
        for base, raw in pieces:
            if base <= a and a + n <= base + len(raw):
                return raw[a-base:a-base+n]
        raise ValueError(f'missing loader slice {a:#x}+{n}')
    layout = (ROOT / 'OCaml/Vm/Layout.lean').read_text()
    embed = int(re.search(r'def sym_embed_start : Nat := (0x[0-9a-fA-F]+|[0-9]+)', layout).group(1), 0)
    table = int.from_bytes(read(embed, 8), 'little')
    start = int.from_bytes(read(table + 8, 8), 'little')
    end = int.from_bytes(read(table + 16, 8), 'little')
    count = int.from_bytes(read(end - 16, 4), 'big')
    if count != 7:
        raise ValueError('selected reset section count changed')
    source = end - 16 - 8 * count
    raw = read(source, 8 * count)
    lengths = [int.from_bytes(raw[i+4:i+8], 'big') for i in range(0, len(raw), 8)]
    names = [raw[i:i+4] for i in range(0, len(raw), 8)]
    if names[0] != b'CODE' or any(name == b'CODE' for name in names[1:]):
        raise ValueError('CODE reverse-scan route changed')
    offsets = [16 + 8 * count]
    for length in reversed(lengths):
        offsets.append(offsets[-1] + length)
    out = ['import OCaml.Vm.Boot.Startup.ReadSectionsLoop', '',
           '/-! GENERATED by scripts/gen_startup_rows.py from initial loader pieces; no execution claim. -/',
           'namespace OCaml.Vm.Boot.Startup',
           'open Vsa.Machine Vsa.Sim Vsa.Sim.Boot OCaml.Vm.Primitives LeanRV64DExecutable', '',
           'def seekSectionLengths : List Nat := [' + ', '.join(str(n) for n in lengths) + ']',
           'def seekSectionNames : List (List (BitVec 8)) := [' +
           ', '.join('[' + ', '.join(str(c) + '#8' for c in name) + ']' for name in names) + ']',
           'def seekSectionOffsets : List Nat := [' + ', '.join(str(n) for n in offsets) + ']', '']
    for i, value in enumerate(raw):
        out += [f'theorem seek_section_raw_{i} : sectionRaw {i} = {value}#8 := by',
                f'  change (WhileMinImage.initialMem[{source + i:#x}]?).getD 0 = {value}#8',
                f'  have pin : WhileMinImage.initialMem[{source + i:#x}]? = some {value}#8 :=',
                f'    (loaderMem_get WhileMinImage.pieces WhileMinImage.imageByte {source + i:#x}).trans (by decide +kernel)',
                '  rw [pin]',
                '  rfl', '']
    for i, length in enumerate(lengths):
        name = names[i]
        out += [f'theorem seek_section_name_{i} :',
                '    [' + ', '.join(f'sectionByte {8*i+j}' for j in range(4)) + '] = ' +
                '[' + ', '.join(f'{c}#8' for c in name) + '] := by',
                '  simp only [sectionByte, sectionSwap, Nat.reduceMod, Nat.reduceLT, ite_true, ' +
                ', '.join(f'seek_section_raw_{8*i+j}' for j in range(4)) + ']', '',
                f'theorem seek_section_length_{i} :',
                '    bytesVal .lwu [' + ', '.join(f'sectionByte {8*i+j}' for j in range(4,8)) + f'] = {length}#64 ∧',
                '    bytesVal .lw [' + ', '.join(f'sectionByte {8*i+j}' for j in range(4,8)) + f'] = {length}#64 := by',
                '  simp only [sectionByte, sectionSwap, Nat.reduceMod, Nat.reduceLT, ite_false, Nat.reduceSub, Nat.reduceAdd, ' +
                ', '.join(f'seek_section_raw_{8*i+j}' for j in range(4,8)) + ']',
                '  constructor <;> decide', '']
    out += ['theorem seek_section_offset_step (i : Fin 7) :',
            '    seekSectionOffsets[i.val + 1]! = seekSectionOffsets[i.val]! + seekSectionLengths[6 - i.val]! := by',
            '  revert i; decide', '',
            'theorem seek_section_offset_bounds (i : Fin 8) :',
            f'    0 < seekSectionOffsets[i.val]! ∧ seekSectionOffsets[i.val]! ≤ {end-start} ∧',
            '    seekSectionOffsets[i.val]! < 2 ^ 31 := by',
            '  revert i; decide', '',
            'theorem seek_section_modular_step (i : Fin 7) :',
            '    BitVec.ofNat 64 seekSectionOffsets[i.val]! + BitVec.ofNat 64 seekSectionLengths[6 - i.val]! =',
            '      BitVec.ofNat 64 seekSectionOffsets[i.val + 1]! := by',
            '  revert i; decide', '',
            'theorem seek_section_noncode (i : Fin 6) :',
            '    seekSectionNames[i.val + 1]! ≠ seekSectionNames[0]! := by',
            '  revert i; decide', '',
            'theorem seek_crcs_common_prefix :',
            '    seekSectionNames[6]![0]! = seekSectionNames[0]![0]! ∧',
            '    seekSectionNames[6]![1]! ≠ seekSectionNames[0]![1]! := by',
            '  constructor <;> decide', '',
            'theorem seek_code_seek_guards :',
            f'    guardB bop.BLT (0#64 - {offsets[-1]}#64) 0#64 = true ∧',
            f'    guardB bop.BGE {end-start}#64 (0#64 - (0#64 - {offsets[-1]}#64)) = true := by',
            '  constructor <;> decide', '',
            'theorem seek_code_arithmetic :',
            f'    {end-start}#64 + (0#64 - {offsets[-1]}#64) = {end-start-offsets[-1]}#64 ∧',
            f'    {lengths[0]}#64 ≠ -1#64 := by',
            '  constructor <;> decide', '',
            'end OCaml.Vm.Boot.Startup', '']
    return '\n'.join(out)


def seek_audit(generated):
    """Check the bounded seek certificates and newly exposed source frames."""
    audit = ['import OCaml.Vm.Boot.Startup.SeekCodeReset',
             'import OCaml.Vm.Boot.Startup.CodeSectionName', '',
             '/-! GENERATED by scripts/gen_startup_rows.py. Focused seek/source-frame audit. -/', '']
    sources = [('OCaml/Vm/Boot/Startup/' + name + '.lean', 'OCaml.Vm.Boot.Startup.')
               for name in ('CodeSectionName', 'SeekSectionData', 'SeekCodeCall', 'CallerFrame', 'DomainRecord',
                            'EmbedFrame', 'StatCheckedFrame', 'PageAdd', 'MakeFree', 'MinorHeap', 'MajorHeap',
                            'InitGc', 'InitStack', 'AtomTable', 'Backtrace')]
    audit.insert(0, 'import OCaml.Vm.Boot.Startup.SeekSectionData')
    sources += [('OCaml/Vm/Boot/Startup/' + name + '.lean', 'OCaml.Vm.Boot.WhileMinElfParse.')
                for name in ('InitGcReset', 'InitStackReset', 'AtomTableReset', 'BacktraceReset', 'InterpreterInitReset', 'SeekCodeReset')]
    sources += [('OCaml/Vm/Gc/SkiplistFirst.lean', 'OCaml.Vm.Gc.SkiplistFirst.')]
    for stem in SEEK_STEMS:
        for suffix in ('Rows', 'Normalized', 'Image', 'CallInterface', 'Calls'):
            relative = f'OCaml/Vm/Boot/Startup/{stem}{suffix}.lean'
            if ROOT / relative in generated:
                audit.insert(0, f'import OCaml.Vm.Boot.Startup.{stem}{suffix}')
                sources.append((relative, 'Vsa.Sim.' if suffix == 'Rows' else 'OCaml.Vm.Boot.Startup.'))
    relative = 'Vsa/Sim/Code/Caml_seek_optional_section.lean'
    audit.insert(0, 'import Vsa.Sim.Code.Caml_seek_optional_section')
    sources.append((relative, 'Vsa.Sim.Code.'))
    for relative, namespace in sources:
        path = ROOT / relative
        source = generated[path] if path in generated else path.read_text()
        # Reset adapters may also contain helpers in Startup before their
        # WhileMinElfParse namespace. Audit the declaration's actual namespace.
        for declaration in re.finditer(r'^namespace ([\w.]+)|^theorem ([\w.]+)', source, re.M):
            if declaration.group(1):
                namespace = declaration.group(1) + '.'
            else:
                audit.append('#print axioms ' + namespace + declaration.group(2))
    return '\n'.join(audit) + '\n'


