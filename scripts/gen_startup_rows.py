def literal_names(di, extents, elf_sections, function, names, stem, register=10):
    """Certify AUIPC/ADDI-selected literal C strings of one function from pinned rodata."""
    lo, hi = extents[function]
    base, raw = elf_sections['.rodata']
    found = {name: [] for name in names}
    for pc in sorted(di):
        if not lo <= pc < hi or pc + 4 not in di:
            continue
        upper, lower = di[pc].word, di[pc + 4].word
        if upper & 0x7f != 0x17 or (upper >> 7) & 31 != register:
            continue
        if lower & 0x7f != 0x13 or (lower >> 12) & 7 != 0:
            continue
        if (lower >> 7) & 31 != register or (lower >> 15) & 31 != register:
            continue
        upper_imm = upper & 0xfffff000
        if upper_imm >= 1 << 31:
            upper_imm -= 1 << 32
        lower_imm = lower >> 20
        if lower_imm >= 1 << 11:
            lower_imm -= 1 << 12
        address = (pc + upper_imm + lower_imm) % (1 << 64)
        for name in names:
            encoded = name.encode('ascii') + b'\0'
            if base <= address and raw[address-base:address-base+len(encoded)] == encoded:
                found[name].append(address)
    if any(len(found[name]) != 1 for name in names):
        raise ValueError(f'{stem} name selection drift: {found}')
    out = []
    for number, name in enumerate(names):
        address = found[name][0]
        out += [f'def {stem}Name{number} : BitVec 64 := {address:#x}#64',
                f'def {stem}Chars{number} : List Char := [' + ', '.join(repr(c) for c in name) + ']', '']
        for i, value in enumerate(name.encode('ascii') + b'\0'):
            index = address - base + i
            out += [f'private theorem {stem}Byte{number}_{i} {{c : Config}} (image : ExecutableImage c) :',
                    f'    c.σ.mem[{stem}Name{number}.toNat + {i}]? = some {value}#8 := by',
                    f'  have byte := image.rodata {index} (by decide)',
                    f'  have pin : Image.rodataByte {index} = {value}#8 := by decide +kernel',
                    '  rw [pin] at byte', '  exact byte', '']
        out += [f'theorem {stem}_name_{number} {{c : Config}} (image : ExecutableImage c) :',
                f'    EnvName {stem}Name{number} {stem}Chars{number} c := by',
                '  constructor', '  ·']
        for i, value in enumerate(name.encode('ascii')):
            out += [f'    apply CStr.cons (b := {value}#8) ({stem}Byte{number}_{i} image) (by decide) (by decide)']
        out += [f'    exact CStr.nil ({stem}Byte{number}_{len(name)} image)',
                '  · constructor <;> decide', '  · intro k hk',
                f'    have check : ∀ i : Fin {len(name)}, byteVal {stem}Chars{number} i.val ≠ 61 := by decide',
                '    exact check ⟨k, hk⟩', '']
    return out


