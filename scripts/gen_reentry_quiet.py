#!/usr/bin/env python3
"""Compose the generated interpreter nonlocal-return segment with named runtime facts."""
import argparse
import json
from gen_arm_pilot import ROOT
from gen_segment import SegmentEmitter


def outputs():
    spec = json.loads((ROOT / 'scripts/syi/segments/reentry_quiet.json').read_text())
    em = SegmentEmitter(spec)
    em.emit()
    pins = {r: i for i, (r, _) in enumerate(em.pins)}
    global_addr = next(p for p in spec['params'] if p.startswith('(hlo_')).split(' ≤ ', 1)[1].removesuffix('.toNat)')
    offsets = [('trapsp', 168), ('trap_barrier', 176), ('local_roots', 288), ('extern_sp', 160), ('exn_bucket', 192), ('backtrace_active', 232)]
    normalization = ',\n    '.join(f'show sign_extend (m := 64) (0x{imm:03x}#12) = BitVec.ofNat 64 Layout.off_{name} from by decide' for name, imm in offsets)
    read_nat = ', '.join(f'(h.reads Layout.off_{name} (by decide)).toNat' for name, _ in offsets if name != 'local_roots')
    def read_args(name, after=False):
        read = f'(h.reads Layout.off_{name} (by decide))'
        val = f'(word c ((word c Layout.sym_Caml_state).toNat + Layout.off_{name}))'
        proof = f'(afterRead Layout.off_{name} (by decide)).symm' if after else '(load _).symm'
        return f'{read}.lower {read}.upper {read}.htif {val} {proof}'
    text = f'''import OCaml.Vm.Sim.ReentryState
import OCaml.Vm.Sim.ReentryQuietSegment
import OCaml.Vm.Sim.ReentryQuietPins

/-! GENERATED by scripts/gen_reentry_quiet.py. Quiet nonlocal-return continuation. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim OCaml.Vm.Primitives LeanRV64DExecutable LeanRV64DExecutable.Functions

/-- Restore native local roots and reload VM exception registers at the common handler cut. -/
theorem reentry_quiet {{nativeSp : Nat}} {{result : BitVec 64}} {{c : Config}}
    (h : ReentryQuietInput nativeSp result c) :
    ∃ count after, StepsN count c after ∧ ReentryQuietPost nativeSp c after := by
  obtain ⟨m1, m1Eq⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 c.σ.mem ((word c Layout.sym_Caml_state).toNat + Layout.off_local_roots)
        (sdData_val (word c (nativeSp + Layout.interpSavedRootsOffset))) := ⟨_, rfl⟩
  have memoryLog : m1 = writeLog c.σ.mem (reentryLog nativeSp c) := by rw [m1Eq]; rfl
  have load (a : Nat) : sign_extend (m := 64) (bytesT8 c.σ.mem a) = word c a := by
    simp only [word, bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq]
  have afterRead (offset : Nat) (member : offset ∈ reentryReadOffsets) :
      sign_extend (m := 64) (bytesT8 m1 ((word c Layout.sym_Caml_state).toNat + offset)) =
        word c ((word c Layout.sym_Caml_state).toNat + offset) :=
    word_read_writeLog_out (reentry_read_outside nativeSp c offset member) memoryLog
  have bp : SegSt (0x80001e80#64) [⟨Register.x10, result⟩, ⟨Register.x2, BitVec.ofNat 64 nativeSp⟩]
      (fun σ => Vsa.Sim.Code.CamlReentryQuietLoaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, h.pc, ⟨h.resultReg, h.stack, trivial⟩, h.good.minstret, h.tick,
      reentry_quiet_loaded h.image, rfl, rfl⟩
  have native := tr_reentry_quiet result (BitVec.ofNat 64 nativeSp) c.σ.mem c.σ
  have globalAddress : {global_addr} = BitVec.ofNat 64 Layout.sym_Caml_state := by decide
  simp only [globalAddress, show (BitVec.ofNat 64 Layout.sym_Caml_state).toNat = Layout.sym_Caml_state from by decide] at native
  have domainStep := native (by decide) (by decide) (by decide) (word c Layout.sym_Caml_state) (load _).symm
  simp only [show sign_extend (m := 64) (0x0c8#12) = BitVec.ofNat 64 Layout.interpSavedRootsOffset from by decide,
    {normalization}, domain_field_address, ← BitVec.ofNat_add,
    h.savedRootsRead.toNat, h.rootsWrite.read.toNat, {read_nat}] at domainStep
  obtain ⟨count, after, _, run, post⟩ := domainStep
    (by simpa only [beq_eq_false_iff_ne] using h.nonzero)
    h.savedRootsRead.lower h.savedRootsRead.upper h.savedRootsRead.htif
      (word c (nativeSp + Layout.interpSavedRootsOffset)) (load _).symm
    {read_args('trapsp')}
    {read_args('trap_barrier')}
    h.rootsWrite.lower h.rootsWrite.upper h.rootsWrite.htif h.rootsWrite.aligned
    (image_entry_code (w := word c (nativeSp + Layout.interpSavedRootsOffset)) h.imageOutside
      (by simp [reentryLog]) (by decide) (by decide)) m1 m1Eq
    {read_args('extern_sp', True)}
    {read_args('exn_bucket', True)}
    (by simpa only [native_ult, BitVec.ule_eq_not_ult, Bool.not_not] using h.quiet)
    {read_args('backtrace_active', True)}
    (by rw [h.backtrace]; decide)
    {read_args('trapsp', True)} c bp
  obtain ⟨_, memory, frame⟩ := post.extra
  have writes := memory.trans memoryLog
  refine ⟨count, after, run, ⟨post.good, image_of_writeLog h.image h.imageOutside writes,
    post.tick, post.pcAt, ?_, ?_, ?_, ?_, (frame.frame Register.x2 (by decide)).trans h.stack, writes, frame.out,
    frame.frame Register.htif_payload_writes (by decide),
    by rw [show gpr after 26 = gpr c 26 from frame.frame Register.x26 (by decide)]; exact h.s10⟩,
    frame.widenChecked (by decide)⟩
  · exact PinsHold.get post.pins ⟨{pins['x15']}, by simp⟩
  · exact PinsHold.get post.pins ⟨{pins['x14']}, by simp⟩
  · exact PinsHold.get post.pins ⟨{pins['x9']}, by simp⟩
  · exact PinsHold.get post.pins ⟨{pins['x21']}, by simp⟩

end OCaml.Vm.Sim
'''
    return {ROOT / 'OCaml/Vm/Sim/ReentryQuiet.lean': text}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'reentry summary drift: {path}')
        else:
            path.write_text(text)
    print('quiet reentry summary current')
