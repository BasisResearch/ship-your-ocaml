#!/usr/bin/env python3
"""Extract real CamlinternalLazy.force bytes through runbc --lean; no invented opcodes."""
import argparse
import ast
import os
from pathlib import Path
import re
import subprocess
import tempfile
from gen_bc_rules import ROOT, DEFAULT_DUMP, inputs

HOST = Path(os.environ.get('HOST_OCAML', Path.home() / 'toolchains/ocaml-4.14.4/bin'))
OUT = ROOT/'OCaml/Programs/Generated/LazyForceCode.lean'


def generate():
    assert subprocess.check_output([str(HOST/'ocamlc'), '-version'], text=True).strip() == '4.14.4'
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        (tmp/'forceWitness.ml').write_text('let force = CamlinternalLazy.force\n')
        subprocess.run([str(HOST/'ocamlc'), '-o', 'force.byte', 'forceWitness.ml'], cwd=tmp, check=True)
        exe = tmp/'force.byte'
        emitted = subprocess.check_output([str(ROOT/'.lake/build/bin/runbc'), '--lean', str(exe), 'forceWitness'], text=True)
        words = ast.literal_eval(re.search(r'def forceWitnessCode : List Nat := (\[.*\])', emitted)[1])
        prims = ast.literal_eval(re.search(r'def forceWitnessPrims : Array String := #(\[.*\])', emitted)[1])
        actual, decoded, units, entries, _ = inputs(exe, DEFAULT_DUMP)
        assert words == actual
        a, b = units['CamlinternalLazy']
        candidates = [pc for pc in entries if a <= pc < b and
                      [decoded[pc+i][0] for i in range(3) if pc+i in decoded] == ['ACC0', 'PUSHACC0', 'PUSHACC0']]
        assert len(candidates) == 1, candidates
        start = candidates[0]
        end = min(pc for pc in entries if pc > start)
        code = words[start:end]
        pcs = [pc for pc in decoded if start <= pc < end]
        assert decoded[start+3][0] == 'C_CALL1' and prims[decoded[start+3][1][0]] == 'caml_obj_tag'
        assert decoded[start+14][0] == 'C_CALL2' and prims[decoded[start+14][1][0]] == 'caml_array_unsafe_get'
        obj_global = decoded[start+5][1][0]
        text = 'import OCaml.Bytecode.Semantics\n\n/-! GENERATED by scripts/gen_lazy_force.py via runbc --lean.\n'
        text += f'CamlinternalLazy.force CODE words {start}..{end}; operands unchanged.\n'
        text += 'Only the enclosing code array is sliced; branch offsets are relative.\n-/\nnamespace OCaml.Programs.LazyForce\nopen OCaml.Bytecode\n\n'
        text += 'def code : Code := #[' + ', '.join(str(w) for w in code) + ']\n'
        text += 'def prims : Array String := #[' + ', '.join('"'+p+'"' for p in prims) + ']\n'
        text += f'def objGlobal : Nat := {obj_global}\n\n'
        text += 'def program (globals : Val) : Prog :=\n  { code, prims, heap0 := ⟨#[]⟩, globals, exeName := [], argv := .atom 0, files0 := [] }\n\n'
        for pc in pcs:
            op,args,_=decoded[pc]
            text += f'theorem decode_{pc-start} : decodeAt code {pc-start} = some ⟨.{op}, {args}⟩ := by decide\n'
        text += f'\nset_option maxRecDepth 4096 in -- generated primitive-table literal\ntheorem tag_name : prims[{decoded[start+3][1][0]}]? = some \"caml_obj_tag\" := by decide\n'
        text += f'set_option maxRecDepth 4096 in -- generated primitive-table literal\ntheorem get_name : prims[{decoded[start+14][1][0]}]? = some \"caml_array_unsafe_get\" := by decide\n'
        text += '\nstructure ForceCode (P : Prog) : Prop where\n  decode : ∀ pc i, decodeAt code pc = some i → decodeAt P.code pc = some i\n'
        text += f'  tagName : P.prims[{decoded[start+3][1][0]}]? = some "caml_obj_tag"\n'
        text += f'  getName : P.prims[{decoded[start+14][1][0]}]? = some "caml_array_unsafe_get"\n'
        text += '\ntheorem checked (globals : Val) : ForceCode (program globals) :=\n  ⟨fun _ _ h => h, tag_name, get_name⟩\n'
        for pc in pcs:
            op,args,_=decoded[pc]
            text += f'theorem ForceCode.at_{pc-start} {{P : Prog}} (h : ForceCode P) : decodeAt P.code {pc-start} = some ⟨.{op}, {args}⟩ := h.decode _ _ decode_{pc-start}\n'
        text += '\nend OCaml.Programs.LazyForce\n' 
        return text


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__); p.add_argument('--check', action='store_true'); args=p.parse_args()
    text = generate()
    if args.check:
        assert OUT.read_text() == text, 'LazyForceCode drift'
    else:
        OUT.parent.mkdir(parents=True, exist_ok=True); OUT.write_text(text)
    print(OUT.relative_to(ROOT))
