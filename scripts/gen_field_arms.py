#!/usr/bin/env python3
"""Generate ENVACC1..4 and GETFIELD0..3 through shared field-read contracts."""
import argparse
import json
from census import ROOT


def outputs():
    arms = json.loads((ROOT / 'results/census.json').read_text())['caml_interprete']['arms']
    result = {}
    for prefix, stem_prefix, source, reg, indices in [
        ('ENVACC', 'Envacc', 'env', 25, range(1, 5)),
        ('GETFIELD', 'Getfield', 'accu', 21, range(4)),
    ]:
        for n in indices:
            op, stem, lower = f'{prefix}{n}', f'{stem_prefix}{n}', f'{prefix.lower()}{n}'
            entry = int(arms[op]['addr'], 16)
            offset = 8*n
            result[ROOT / f'OCaml/Vm/Sim/{stem}.lean'] = f'''import OCaml.Vm.Sim.FieldRead
import OCaml.Vm.Sim.{stem}Segment
import OCaml.Vm.Sim.{stem}Pins

/-! GENERATED by scripts/gen_field_arms.py. Represented heap-field load arm. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- {op} selects a represented heap field and restores the loop state.
Selection and placement witnesses follow from field_selection; geometry is explicit. -/
theorem {lower}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a k : Nat}} {{v : Val}}
    (stable : MemoryStable L.runtimeOk)
    (h : ArmInput L P s .{op} c pl cp sp high)
    (selected : FieldSelection s.heap pl s.{source} {n} v l a k)
    (read : RamReadAt (a + 8 * (k + {n})) 8) :
    ∃ c', Plus c c' ∧ Running L P {{s with pc := s.pc + 1, accu := v}} c' := by
  have value := FieldSelection.read h.toVmReprAt (by simp [roots]) selected
  have source := represented_register h.{source} selected.sourceWord
  apply accu_arm stable h value.word value.root
  intro d dp
  have address : BitVec.ofNat 64 (a + 8 * k) + sign_extend (m := 64) (0x{offset:03x}#12) =
      BitVec.ofNat 64 (a + 8 * (k + {n})) := by
    rw [show sign_extend (m := 64) (0x{offset:03x}#12) = BitVec.ofNat 64 (8 * {n}) from by decide]
    simp only [Nat.mul_add, ← Nat.add_assoc, BitVec.ofNat_add]
  have bp : SegSt (0x{entry:x}#64)
      [⟨Register.x{reg}, BitVec.ofNat 64 (a + 8 * k)⟩,
       ⟨Register.x23, BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64⟩]
      (fun σ => Vsa.Sim.Code.Caml{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc,
      ⟨(dp.frame.frame Register.x{reg} (by decide)).trans source, dp.nextCode, trivial⟩,
      dp.good.minstret, dp.tick, {lower}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_{lower} (BitVec.ofNat 64 (a + 8 * k))
    (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) d.σ.mem d.σ
  simp only [address, read.toNat] at run
  obtain ⟨nb, after, _, hb, post⟩ := run read.lower read.upper read.htif d bp
  obtain ⟨_, hm, frame⟩ := post.extra
  refine ⟨nb, after, hb, post.good, post.pcAt, ?_, ?_, hm, frame.out,
    immediate_preserved frame (by decide)⟩
  · have hp : gpr after Layout.reg_pc = some
        ((BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) + sign_extend (m := 64) (0x000#12)) :=
      PinsHold.get post.pins ⟨0, by simp⟩
    simpa only [show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
      BitVec.add_zero, codePc_succ] using hp
  · have hp : gpr after Layout.reg_accu = some
        (sign_extend (m := 64) (bytesT8 d.σ.mem (a + 8 * (k + {n})))) :=
      PinsHold.get post.pins ⟨1, by simp⟩
    simpa only [dp.memory, word, bytesT_eight_eq, sign_extend,
      Sail.BitVec.signExtend, BitVec.signExtend_eq] using hp

end OCaml.Vm.Sim
'''
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'field arm drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Field-load arm bridges current')
