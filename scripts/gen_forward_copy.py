#!/usr/bin/env python3
"""Instantiate RESTART's generated forward-copy branches over one invariant."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render(kind):
    stem = kind.title()
    spec = json.loads((ROOT / f'scripts/syi/segments/restart_copy_{kind}.json').read_text())
    regs = [p['reg'] for p in spec['pins']]
    assert regs == ['x15', 'x25', 'x13', 'x12']
    for step in spec['steps']:
        rd = step.get('rd')
        if rd and rd != 'x0': regs = [rd] + [r for r in regs if r != rd]
    pin = lambda r: f'PinsHold.get post.pins ⟨{regs.index(r)}, by simp⟩'
    condition = '(more : i + 1 < words.length)' if kind == 'more' else '(last : i + 1 = words.length)'
    guard = 'forward_copy_guard words.length i more region.small' if kind == 'more' else 'by rw [show words.length + 3 = 3 + i + 1 by omega]; simp'
    pcproof = 'simp only [more, ite_true]; exact post.pcAt' if kind == 'more' else 'simp only [last, Nat.lt_irrefl, ite_false]; exact post.pcAt'
    return f'''-- GENERATED by scripts/gen_forward_copy.py; do not edit.
import OCaml.Vm.Sim.ForwardCopyState
import OCaml.Vm.Sim.RestartCopy{stem}Segment
import OCaml.Vm.Sim.RestartCopy{stem}Pins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- Concrete generated {kind} branch of RESTART's counted forward-copy loop. -/
theorem forward_copy_{kind} {{a target i : Nat}} {{words : List (BitVec 64)}} {{initial c : Config}}
    (region : ForwardCopyRegion a target words initial)
    (h : ForwardCopyAt a target words initial i c) (bound : i < words.length) {condition} :
    ∃ nb after, StepsN nb c after ∧ ForwardCopyAt a target words initial (i + 1) after := by
  have read := region.reads i bound
  have store := region.writes i bound
  have sourceNat : (BitVec.ofNat 64 (a + 24 + 8 * i)).toNat = a + 24 + 8 * i := read.toNat
  have targetNat : (BitVec.ofNat 64 (target + 8 * i)).toNat = target + 8 * i :=
    Nat.mod_eq_of_lt (by have upper := store.upper; omega)
  have counterStep := forward_counter_step (3 + i) (by have small := region.small; omega)
  have guard : (BitVec.ofNat 64 (words.length + 3) != BitVec.ofNat 64 (3 + i + 1)) = {'true' if kind == 'more' else 'false'} :=
    {guard}
  have loaded := h.read region (List.getElem?_eq_getElem bound)
  obtain ⟨nextMemory, written⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),
      m = writeMap8 c.σ.mem (target + 8 * i) (sdData_val words[i]) := ⟨_, rfl⟩
  have bp : SegSt (0x80002b94#64)
      [⟨Register.x15, BitVec.ofNat 64 (3 + i)⟩, ⟨Register.x25, BitVec.ofNat 64 a⟩,
       ⟨Register.x13, BitVec.ofNat 64 (target + 8 * i)⟩, ⟨Register.x12, BitVec.ofNat 64 (words.length + 3)⟩]
      (fun σ => Vsa.Sim.Code.CamlRestartCopy{stem}Loaded σ.mem ∧ σ.mem = c.σ.mem ∧ σ = c.σ) c :=
    ⟨h.good, by change pcOf c = some (0x80002b94#64); simpa only [bound, ite_true] using h.pc,
      ⟨h.counter, h.sourceReg, h.targetReg, h.limit, trivial⟩,
      h.good.minstret, h.tick, restart_copy_{kind}_loaded h.image, rfl, rfl⟩
  have run := tr_restart_copy_{kind} (BitVec.ofNat 64 (3 + i)) (BitVec.ofNat 64 a)
    (BitVec.ofNat 64 (target + 8 * i)) (BitVec.ofNat 64 (words.length + 3)) c.σ.mem c.σ
  simp only [forward_store_address] at run
  simp only [forward_source_address, show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, sourceNat, targetNat, counterStep, forward_cursor_step] at run
  obtain ⟨nb, after, _, steps, post⟩ := run read.lower read.upper read.htif words[i] loaded.symm
    store.lower store.upper store.htif store.aligned
    (image_entry_code region.image (region.entry bound) (by decide) (by decide)) nextMemory written guard c bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have observed : ForwardCopyPost a target words.length i words[i] c after := by
    refine ⟨post.good, post.tick, ?_, {pin('x25')}, {pin('x13')}, ?_,
      {pin('x12')}, ?_, ?_⟩
    · {pcproof}
    · have counter : gpr after 15 = some (BitVec.ofNat 64 (3 + i + 1)) := {pin('x15')}
      simpa only [Nat.add_assoc] using counter
    · rw [memory, written]; rfl
    · exact rawFrame.widenChecked (allowed := forwardWrites) (by decide)
  exact ⟨nb, after, steps, ForwardCopyAt.advance region h bound observed⟩

end OCaml.Vm.Sim
'''

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for kind in ['more', 'last']:
        path = ROOT / f'OCaml/Vm/Sim/ForwardCopy{kind.title()}.lean'
        output = render(kind)
        if args.check:
            if not path.exists() or path.read_text() != output: raise SystemExit(f'drift: {path}')
        else: path.write_text(output)
    print('Forward-copy branch adapters current')
