#!/usr/bin/env python3
"""Generate the binary counted adapter from the shared unary composition.

Both native prefixes have the same ccall1Log; extra argument loads and the
suffix increment are supplied by the existing generated binary native rows.
"""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def output():
    setup = (ROOT / 'OCaml/Vm/Sim/CountedCcallSetup.lean').read_text()
    setup = setup[setup.index('theorem counted_c_call1_setup {'):setup.index('/-- Successful-state')]
    setup = setup.replace('c_call1', 'c_call2').replace('0x80003060', '0x80003004')
    setup = setup.replace('[s.accu]', '(s.accu :: s.stack.take 1)').replace('.C_CALL1', '.C_CALL2')
    setup = setup.replace('    (counts :', '    (arguments : CcallArguments s sp 1)\n    (counts :')
    setup = setup.replace('h.environment h.space dp', 'h.environment h.space arguments dp')
    base = (ROOT / 'OCaml/Vm/Sim/CountedCcall1.lean').read_text()
    paths = base[base.index('theorem counted_c_call1_arm {'):base.index('\nend OCaml.Vm.Sim')]
    paths = paths.replace('c_call1', 'c_call2').replace('0x80003060', '0x80003004').replace('.C_CALL1', '.C_CALL2')
    paths = paths.replace('[s.accu]', '(s.accu :: s.stack.take 1)')
    paths = paths.replace('    (counts :', '    (arguments : CcallArguments s sp 1)\n    (counts :')
    paths = paths.replace('custom h counts dp', 'custom h arguments counts dp')
    paths = paths.replace('f1_memoryStable at_.toCcallReturnAt', 'f1_memoryStable at_.toCcallReturnAt arguments.bound')
    paths = paths.replace('sp + 8 * 0', 'sp + 8 * 1')
    # Only the suffix consumes the argument stack. The native callee retains it.
    result = '{s with pc := s.pc + 2, accu := v, heap := heap, world := world}'
    dropped = '{s with pc := s.pc + 2, accu := v, heap := heap, world := world, stack := s.stack.drop 1}'
    paths = paths.replace(result + ' after', dropped + ' after')
    paths = paths.replace(result + ') := by', dropped + ') := by')
    paths = paths.replace('P\n        ' + result + ')', 'P\n        ' + dropped + ')')
    paths = paths.replace('    (decoded :', '    (depth : 1 ≤ s.stack.length)\n    (decoded :')
    paths = paths.replace('(0x80003004#64) 0 name', '(0x80003004#64) 1 name')
    paths = paths.replace('List.drop_zero]', 'List.length_take, Nat.min_eq_left depth, or_self]')
    paths = paths.replace('if_false, primitive', 'if_false, show ¬ s.stack.length < 1 by omega, if_false, primitive')
    paths = paths.replace('effect : stepI P s ⟨.C_CALL2, [index.toInt]⟩ =\n      .next ' + result,
                          'effect : stepI P s ⟨.C_CALL2, [index.toInt]⟩ =\n      .next ' + dropped)
    paths = paths.replace('  obtain ⟨after, run, running⟩ := counted_c_call2_arm custom ready counts callee',
        '  have arguments : CcallArguments s sp 1 :=\n    ⟨depth, fun j hj => ready.geometry.read ready.stack (stack_space ready.stack (by have := ready.stackFits; omega))\n      (i := j) (by omega)⟩\n  obtain ⟨after, run, running⟩ := counted_c_call2_arm custom ready arguments counts callee')
    return ("-- GENERATED by scripts/gen_counted_ccall2.py; do not edit.\n"
        "import OCaml.Vm.Sim.CountedCcall1\n\nnamespace OCaml.Vm.Sim\n"
        "set_option autoImplicit false\nopen OCaml.Bytecode Vsa.Machine Vsa.Sim Vsa.Logic OCaml.Vm.Primitives\n\n"
        + setup + paths.replace('successful unary call', 'successful binary call') + '\nend OCaml.Vm.Sim\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'OCaml/Vm/Sim/CountedCcall2.lean'
    content = output()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('counted C_CALL2 drift')
    else:
        target.write_text(content)
    print('Counted C_CALL2 adapter current')
