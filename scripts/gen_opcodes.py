#!/usr/bin/env python3
"""Generate OCaml/Bytecode/Opcode.lean from the vendored 4.14.4 runtime.

    python3 scripts/gen_opcodes.py > OCaml/Bytecode/Opcode.lean

Sources of truth (nothing typed by hand):
  * runtime/caml/instruct.h  `enum instructions` -> constructor order = the
    opcode numbers caml_interprete switches on;
  * runtime/fix_code.c  caml_init_opcode_nargs -> fixed operand counts
    (1 or 2; every other opcode 0), with SWITCH and CLOSUREREC variable
    (their counts are read from their first operand, as caml_thread_code
    does).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RT = ROOT / "vendor/ocaml-4.14.4/runtime"


def opcodes():
    txt = (RT / "caml/instruct.h").read_text()
    body = txt[txt.index("enum instructions {") + len("enum instructions {"):]
    body = re.sub(r"/\*.*?\*/", "", body[:body.index("}")], flags=re.S)
    names = [t.strip() for t in body.replace("\n", " ").split(",") if t.strip()]
    return [n for n in names if n != "FIRST_UNIMPLEMENTED_OP"]


def nargs():
    txt = (RT / "fix_code.c").read_text()
    body = txt[txt.index("int* caml_init_opcode_nargs(void)"):]
    out = {}
    for m in re.finditer(r"((?:l\[[A-Z0-9_]+\]\s*=\s*)+)([12]);", body):
        for n in re.findall(r"l\[([A-Z0-9_]+)\]", m.group(1)):
            out[n] = int(m.group(2))
    return out


def main():
    ops = opcodes()
    na = nargs()
    w = sys.stdout.write
    w("/-!\n# ZINC opcodes of OCaml 4.14.4 (generated)\n\n"
      "Generated by `scripts/gen_opcodes.py` from `runtime/caml/instruct.h`\n"
      "(constructor order = opcode number) and `runtime/fix_code.c`\n"
      "(`caml_init_opcode_nargs`: operand counts). Do not edit.\n-/\n\n"
      "namespace OCaml.Bytecode\n\nset_option maxRecDepth 8192\n\n")
    w("/-- The opcodes `caml_interprete` dispatches on, in `instruct.h` order. -/\n")
    w("inductive Opcode where\n")
    for n in ops:
        w(f"  | {n}\n")
    w("  deriving DecidableEq, Repr, Inhabited\n\n")
    w(f"/-- Number of opcodes (`FIRST_UNIMPLEMENTED_OP`). -/\n"
      f"def Opcode.count : Nat := {len(ops)}\n\n")
    w("/-- All opcodes, in opcode-number order. -/\ndef Opcode.all : List Opcode :=\n  [")
    w(",\n   ".join(", ".join(f".{n}" for n in ops[i:i + 6])
                   for i in range(0, len(ops), 6)))
    w("]\n\n")
    w("/-- Opcode number (the 32-bit code word). -/\ndef Opcode.toNat : Opcode → Nat\n")
    for i, n in enumerate(ops):
        w(f"  | .{n} => {i}\n")
    w("\n/-- Decode an opcode number. -/\ndef Opcode.ofNat? : Nat → Option Opcode\n")
    for i, n in enumerate(ops):
        w(f"  | {i} => some .{n}\n")
    w("  | _ => none\n\n")
    w("/-- Fixed operand count (`caml_init_opcode_nargs`); `SWITCH` and\n"
      "`CLOSUREREC` are variable-length and decoded specially. -/\n"
      "def Opcode.nargs : Opcode → Nat\n")
    for k in (2, 1):
        group = [n for n in ops if na.get(n) == k]
        w("  | " + " | ".join(f".{n}" for n in group) + f" => {k}\n")
    w("  | _ => 0\n\n")
    w("theorem Opcode.all_length : Opcode.all.length = Opcode.count := rfl\n\n")
    w("theorem Opcode.ofNat_toNat : ∀ o ∈ Opcode.all, Opcode.ofNat? o.toNat = some o := by decide\n\n")
    w("end OCaml.Bytecode\n")


if __name__ == "__main__":
    main()
