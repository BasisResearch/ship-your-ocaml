#!/usr/bin/env python3
"""Generate represented APPTERM1--3 adapters from their checked segments."""
import argparse
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parent.parent

def render(n):
    spec=json.loads((ROOT/f'scripts/syi/segments/appterm{n}.json').read_text())
    steps=spec['steps']
    start=f'tailcallStart sp {n} slot.toInt.toNat'
    rawstart=f'tailcallStart sp (stackWords c sp {n}).length slot.toInt.toNat'
    log=f'valueLog ({rawstart}) (stackWords c sp {n})'
    def source(i):return 'sp' if i==0 else f'sp + {8*i}'
    def dest(i):return start if i==0 else f'{start} + {8*i}'
    entries=[f'({dest(i)}, 8, word c ({source(i)}))' for i in range(n)]
    registers={'x8':'(BitVec.ofNat 64 (pl.codeBase + 4 * s.pc))','x9':'(BitVec.ofNat 64 sp)',
      'x18':'(BitVec.ofNat 64 s.extra)','x21':'(BitVec.ofNat 64 (a + 8 * k))',
      'x19':'(BitVec.ofNat 64 Layout.sym_Caml_state)',
      'x20':'(BitVec.ofNat 64 Layout.sym_caml_something_to_do)'}
    proofs={'x8':'h.pc','x9':'h.spReg','x18':'h.extra','x21':'(represented_register h.accu field.sourceWord)',
      'x19':'h.dispatch.loop.domain','x20':'h.dispatch.loop.pending'}
    header=f'''theorem appterm{n}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a k dest : Nat}} {{slot : BitVec 32}}
    (stable : WindowStable L.runtimeOk [⟨{start}, sp + 8 * slot.toInt.toNat⟩])
    (h : ArmInput L P s .APPTERM{n} c pl cp sp high)
    (operand : OperandAt P pl (s.pc + 1) slot) (nonnegative : 0 ≤ slot.toInt)
    (field : FieldSelection s.heap pl s.accu 0 (.code dest) l a k)
    (geometry : RamReadAt (a + 8 * k) 8) (ready : EnterReady c ({start}))
    (space : TailcallWriteOk P s c pl cp sp high slot.toInt.toNat (stackWords c sp {n})) :
    ∃ after, Plus c after ∧ Running L P (tailcallState s {n} slot.toInt.toNat dest) after'''
    lines=[f'''-- GENERATED by scripts/gen_tailcall_fixed.py; do not edit.
import OCaml.Vm.Sim.TailcallArithmetic
import OCaml.Vm.Sim.Appterm{n}Segment
import OCaml.Vm.Sim.Appterm{n}Pins
import Vsa.Sim.FrameWriteSet

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- Move represented arguments above the discarded frame, then enter the closure
through the generated no-growth/no-pending tail. -/
{header} := by
  have length : (stackWords c sp {n}).length = {n} := by simp [stackWords]
  have fits : {n} ≤ slot.toInt.toNat := by simpa only [length] using space.fits
  have bound : {n} ≤ s.stack.length := Nat.le_trans fits space.bound
  have fieldWord : word c (a + 8 * k) = BitVec.ofNat 64 (pl.codeBase + 4 * dest) :=
    (Option.some.inj (field.read h.toVmReprAt (by simp [roots])).word).symm
  have move : BitVec.ofNat 64 sp + (BitVec.ofNat 64 (8 * slot.toInt.toNat) +
      sign_extend (m := 64) (0x{(-8*n)%4096:03x}#12)) = BitVec.ofNat 64 ({start}) :=
    tailcall_address fits (by decide) (by decide)
  have thresholdAddress : word c Layout.sym_Caml_state + sign_extend (m := 64) (0x098#12) =
      BitVec.ofNat 64 ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold) := by
    rw [BitVec.ofNat_add, BitVec.ofNat_toNat]; rfl
  have domainWindow : RamReadAt Layout.sym_Caml_state 8 := ⟨by decide, by decide, by decide⟩
  have pendingWindow : RamReadAt Layout.sym_caml_something_to_do 4 := ⟨by decide, by decide, by decide⟩
  have logEq : {log} = [{', '.join(entries)}] := by
    simp [valueLog, indexedLog, valueEntries, stackWords, List.range_succ]
''']
    simps=['index_word slot nonnegative','move','codePc_succ','thresholdAddress','ready.threshold.toNat','geometry.toNat',
       'domainWindow.toNat','pendingWindow.toNat','operand.geometry.toNat',
       'show sign_extend (m := 64) (0x000#12) = 0#64 from by decide',
       'show sign_extend (m := 64) (0x004#12) = 4#64 from by decide','BitVec.add_zero']
    for i in range(n):
        lines.append(f'  have read{i} : RamReadAt ({source(i)}) 8 := by\n    simpa using space.reads {i} (by rw [length]; decide)\n')
        lines.append(f'  have member{i} : {entries[i]} ∈ {log} := by rw [logEq]; simp\n')
        lines.append(f'  have store{i} : RamWriteAt ({dest(i)}) 8 := space.writes _ member{i}\n')
        for kind,address,geo in [('read',source(i),f'read{i}'),('write',dest(i),f'store{i}')]:
            lines.append(f'  have {kind}Nat{i} : (BitVec.ofNat 64 ({address})).toNat = {address} :=\n    Nat.mod_eq_of_lt (by have upper := {geo}.upper; omega)\n')
            simps.append(f'{kind}Nat{i}')
            if i:
                base='sp' if kind=='read' else start
                lines.append(f'  have {kind}Address{i} : BitVec.ofNat 64 ({base}) + sign_extend (m := 64) (0x{8*i:03x}#12) =\n      BitVec.ofNat 64 ({address}) := by\n    change BitVec.ofNat 64 ({base}) + BitVec.ofNat 64 {8*i} = _\n    exact (BitVec.ofNat_add _ _).symm\n')
                simps.append(f'{kind}Address{i}')
    lines.append(f'''  have capacity : zopz0zI_u (BitVec.ofNat 64 ({start}))
      (word c ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold)) = false := by
    apply bltu_false_of_ge
    rw [writeNat0]
    exact ready.capacity
  apply dispatch_compose h.dispatch
  intro d dp
''')
    for i in range(n):
        prev='d.σ.mem' if i==0 else f'm{i}'
        lines.append(f'  obtain ⟨m{i+1}, hm{i+1}⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),\n      m = writeMap8 {prev} ({dest(i)}) (sdData_val (word c ({source(i)}))) := ⟨_, rfl⟩\n')
    lines.append(f'  have fullMemory : m{n} = writeLog c.σ.mem ({log}) := by\n    rw [logEq, '+', '.join(f'hm{i}' for i in range(n,0,-1))+', dp.memory]; rfl\n')
    lo=min(int(s['addr'],16) for s in steps);hi=max(int(s['addr'],16) for s in steps)+4
    lines.append(f'''  have code (a : Nat) (w : BitVec 64) (member : (a, 8, w) ∈ {log}) :
      a + 8 ≤ 0x{lo:x} ∨ 0x{hi:x} ≤ a := image_entry_code space.image member (by decide) (by decide)
''')
    pinregs=[p['reg'] for p in spec['pins']]
    pins=',\n       '.join(f'⟨Register.{r}, {registers[r]}⟩' for r in pinregs)
    ps=', '.join(f'(dp.frame.frame Register.{r} (by decide)).trans {proofs[r]}' for r in pinregs)
    lines.append(f'''  have bp : SegSt ({spec['entry']}#64) [{pins}]
      (fun σ => Vsa.Sim.Code.CamlAppterm{n}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨{ps}, trivial⟩,
      dp.good.minstret, dp.tick, appterm{n}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run0 := tr_appterm{n} {' '.join(registers[r] for r in pinregs)} d.σ.mem d.σ
''')
    stage=0;written=0
    for step in steps:
        asm=step['asm']
        if step['class']=='sd':
            i=written;written+=1
            args=f'store{i}.lower store{i}.upper store{i}.htif store{i}.aligned (code _ _ member{i}) m{i+1} hm{i+1}'
        elif asm.startswith(('ld ','lw ')):
            if '(s0)' in asm:
                geo='operand.geometry';value='(sign_extend (m := 64) slot)';proof='(by rw [operand.read32 h.code dp.memory])'
            elif '(s1)' in asm:
                i=int(re.search(r',(\d+)\(s1\)',asm)[1])//8
                geo=f'read{i}';value=f'(word c ({source(i)}))';proof='(word_read_writeLog_out (log := []) trivial dp.memory).symm'
            elif '(s5)' in asm:
                geo='geometry';value='(BitVec.ofNat 64 (pl.codeBase + 4 * dest))'
                proof='((space.payload.accu_field_load (payload_of_repr h.toVmReprAt) field fullMemory).trans fieldWord).symm'
            elif '(s3)' in asm:
                geo='domainWindow';value='(word c Layout.sym_Caml_state)';proof='(word_read_writeLog_out space.enter.domain fullMemory).symm'
            elif '(s4)' in asm:
                geo='pendingWindow';value='0#64';proof='(ready.toSignalCheckReady.read_log space.enter.pending fullMemory).symm'
            else:
                assert '152(' in asm
                geo='ready.threshold';value='(word c ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold))'
                proof='(word_read_writeLog_out space.enter.threshold fullMemory).symm'
            args=f'{geo}.lower {geo}.upper {geo}.htif {value}\n    ({proof})'
        elif step['class'] in ['btaken','bnottaken']:
            args='(by decide)' if asm.startswith('beqz ') else 'capacity'
        else:continue
        lines.append(f'  try simp only [{", ".join(simps)}] at run{stage}\n')
        lines.append(f'  have run{stage+1} := run{stage} {args}\n');stage+=1
    for step in steps:
        r=step.get('rd')
        if r and r!='x0':pinregs=[r]+[p for p in pinregs if p!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{pinregs.index(r)}, by simp⟩'
    allowed='['+', '.join('Register.'+r for r in sorted({s['rd'] for s in steps if s.get('rd') and s['rd']!='x0'}))+'] ++ noiseRegs'
    extraProof=f'''    have extra : gpr after Layout.reg_extra = some (BitVec.ofNat 64 s.extra + BitVec.ofNat 64 {n-1}) :=
      {get('x18')}
    have count : s.extra + {n} - 1 = s.extra + {n-1} := by omega
    simpa only [tailcallState, length, count, BitVec.ofNat_add] using extra
''' if n>1 else '''    have count : s.extra + 1 - 1 = s.extra := by omega
    have extra : gpr after Layout.reg_extra = some (BitVec.ofNat 64 s.extra) :=
      (frame.frame (gprReg Layout.reg_extra) (by decide)).trans
        ((dp.frame.frame (gprReg Layout.reg_extra) (by decide)).trans h.extra)
    simpa only [tailcallState, length, count] using extra
'''
    lines.append(f'''  obtain ⟨nb, after, _, steps, post⟩ := run{stage} d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := {allowed}) (by decide)
  have loop : LoopRegisters after := loopRegisters_frame (fun r hr =>
    (frame.frame r (by revert r; decide)).trans (dp.frame.frame r (by revert r; decide))) h.dispatch.loop
  have observed : TailcallPost c s pl sp slot.toInt.toNat dest (stackWords c sp {n}) after := by
    refine ⟨⟨post.pcAt, {get('x8')}, ?_,
      ⟨_, {get('x21')}, field.sourceWord⟩,
      ⟨_, {get('x25')}, field.sourceWord⟩, ?_⟩,
      post.good, memory.trans fullMemory, frame.out.trans dp.frame.out, loop,
      (frame.frame (gprReg 2) (by decide)).trans (dp.frame.frame (gprReg 2) (by decide))⟩
    · simp only [length]
      exact {get('x9')}
    ·
{''.join('  '+l+'\n' for l in extraProof.splitlines())}  refine ⟨nb, after, steps, ?_⟩
  have restored := tailcall_restore (by simpa only [length] using stable) h.toVmReprAt h.running.platform
    (by simpa only [length] using stack_value_words h.stack bound) space observed h.geometry h.native
  simpa only [length] using restored

''')
    wrapper=header.replace(f'appterm{n}_arm',f'appterm{n}_step_arm',1).replace('{s : St}',"{s s' : St}",1)
    wrapper=wrapper.replace(f'(stackWords c sp {n})) :',f"(stackWords c sp {n})) (step : stepI P s ⟨.APPTERM{n}, [slot.toInt]⟩ = .next s') :")
    wrapper=wrapper.replace(f'(tailcallState s {n} slot.toInt.toNat dest) after',"s' after")
    lines.append(f'''/-- The represented tail call matches the successful bytecode transition. -/
{wrapper} := by
  have length : (stackWords c sp {n}).length = {n} := by simp [stackWords]
  have fits : {n} ≤ slot.toInt.toNat := by simpa only [length] using space.fits
  have valid : ¬ (slot.toInt < {n} ∨ s.stack.length < slot.toInt.toNat) := by
    have bound := space.bound
    omega
  have state : tailcallState s {n} slot.toInt.toNat dest = s' := by
    have count : s.extra + {n} - 1 = s.extra + {n-1} := by omega
    simp only [stepI, valid, ite_false, enter, field.selected, opt, Res.next.injEq] at step
    simpa only [tailcallState, count, Nat.add_zero] using step
  rw [← state]
  exact appterm{n}_arm stable h operand nonnegative field geometry ready space

end OCaml.Vm.Sim
''')
    return ''.join(lines)

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--arity',type=int,choices=[1,2,3])
    args=parser.parse_args()
    for n in ([args.arity] if args.arity else [1,2,3]):
        target=ROOT/f'OCaml/Vm/Sim/Appterm{n}.lean';rendered=render(n)
        if args.check:
            if not target.exists() or target.read_text()!=rendered:raise SystemExit(f'drift: {target}')
        else:target.write_text(rendered)
    print('Fixed-arity tail-call bridges current')
