#!/usr/bin/env python3
"""Generate the focused counted-console audit; full Audit stays with the lead."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
GROUPS = {
    'OCaml.Vm.': [
        'ChannelRefsSame.of_chans', 'ChannelRefsSame.trans', 'ChannelRefsSame.set',
        'ChannelRefsSame.customs', 'ChannelRefsSame.set_after',
        'ChannelCustomsRepr.of_refs_same', 'ChannelCustomsRepr.of_chans_eq'],
    'OCaml.Vm.Sim.': [
        'ChannelCountFrame.of_observations', 'counted_refs_row', 'counted_row',
        'CcallReturnAt.of_countedLayout_refs', 'CcallReturnAt.of_countedLayout',
        'counted_prim_returns_of_refs', 'counted_prim_returns_of_local',
        'writeFd_refs_same', 'flushChan_refs_same', 'putChar_refs_same', 'putBlock_refs_same',
        'flush_primitive_refs_same', 'output_char_primitive_refs_same',
        'output_primitive_refs_same', 'primF1Impl_four_name',
        'console_fixed_out', 'console_static_out', 'f1_console_channelCountFrame',
        'counted_console_stable', 'counted_console_returns',
        'counted_caml_ml_flush_returns', 'counted_caml_ml_output_char_returns',
        'counted_caml_ml_output_returns', 'counted_caml_ml_output_bytes_returns',
        'counted_flush_next', 'counted_output_char_next', 'counted_output_next',
        'counted_c_call4_setup', 'counted_c_call4_arm', 'counted_c_call4_success',
        'counted_c_call4_local_returns', 'counted_c_call4_refs', 'counted_c_call4_row',
        'counted_supported_row', 'counted_opcode_census', 'counted_opcode_count',
        'counted_remaining_count',
        'counted_supported_prim_returns', 'counted_supported_c_call1_next',
        'counted_supported_c_call2_next'],
}
NAMES = [prefix + name for prefix, names in GROUPS.items() for name in names]

def output():
    return ('-- GENERATED by scripts/gen_counted_console_audit.py; do not edit.\n'
            'import OCaml.Vm.Sim.CountedConsoleRows\n'
            'import OCaml.Vm.Sim.CountedControlRows\n'
            'import OCaml.Vm.Sim.CountedPrimRows\n\n'
            + ''.join(f'#print axioms {name}\n' for name in NAMES))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'OCaml/Vm/Sim/CountedConsoleAudit.lean'
    if args.check:
        if not target.exists() or target.read_text() != output():
            raise SystemExit('counted console audit drift')
    else:
        target.write_text(output())
    print(f'Counted console audit current ({len(NAMES)} reports)')
