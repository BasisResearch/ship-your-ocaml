#!/usr/bin/env python3
"""All six C_CALL terminal outcomes consume the primitive lane's exit summary."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent


def render(arity):
    suffix = json.loads((ROOT / f'scripts/syi/segments/c_call{arity}_suffix.json').read_text())
    variable = arity == 'n'
    args = '[s.accu]' if arity == 1 else f'(s.accu :: s.stack.take {arity - 1})' if not variable else None
    natives = ' nativeSp' if variable else ''
    operands = 'index nargs' if variable else 'index'
    ready = (f'CcallnReady L P s c pl cp sp high domain table nativeSp entry value env index nargs name' if variable else
             f'CcallReady .C_CALL{arity} L P s c pl cp sp high domain table entry value env index name')
    callee = ('CcallnExitCallee L P s pl cp sp high nargs.toInt.toNat domain nativeSp entry env name code world' if variable else
              f'CcallExitCallee ({suffix["entry"]}#64) {args} L P s pl cp sp high domain entry env name code world')
    windows = 'ccallnWindows sp domain nativeSp' if variable else 'ccall1Windows sp domain'
    arguments = '' if variable or arity == 1 else f'\n    (arguments : CcallArguments s sp {arity - 1})'
    argument = '' if variable or arity == 1 else ' arguments'
    setup = ('h.countOperand h.positive h.bound h.operand h.nonnegative h.primitive h.entryName h.aligned\n    h.domainWord h.tableWord h.targetRead h.value h.environment h.nativeReg h.space' if variable else
             f'h.operand h.nonnegative h.primitive h.entryName h.aligned\n    h.domainWord h.tableWord h.targetRead h.value h.environment h.space{argument}')
    op = '.C_CALLN' if variable else f'.C_CALL{arity}'
    stepArgs = '[nargs.toInt, index.toInt]' if variable else '[index.toInt]'
    simp = (', Int.not_le.mpr h.positive, Nat.not_lt.mpr h.bound, List.length_take, Nat.min_eq_left h.bound' if variable else
            '' if arity == 1 else ', List.length_take, Nat.min_eq_left arguments.bound')
    params = f'''{{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high domain table{natives} entry : Nat}}
    {{value env : BitVec 64}} {{{operands} : BitVec 32}} {{name : String}} {{code : Nat}} {{world : World}}
    (writeStable : WindowStable L.runtimeOk ({windows}))
    (h : {ready}){arguments}
    (callee : {callee})'''
    return f'''-- GENERATED by scripts/gen_ccall_exits.py; do not edit.
import OCaml.Vm.Sim.CcallExit
import OCaml.Vm.Sim.Ccall{arity}Setup

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim OCaml.Vm.Primitives

/-- Dispatch and native argument setup reach the terminal primitive summary. -/
theorem c_call{arity}_exit_arm {params} :
    Halts c (bytesToString world.console) code := by
  apply dispatch_halts h.dispatch
  intro d dp
  obtain ⟨count, call, run, setup⟩ := c_call{arity}_setup writeStable h.toArmInput {setup} dp
  exact Halts.of_steps run.toSteps (callee.summary call setup)

/-- Match the actual bytecode primitive-exit outcome, including world and status. -/
theorem c_call{arity}_exit_step_arm {params}
    {{e : Nat}} {{w : World}} (step : stepI P s ⟨{op}, {stepArgs}⟩ = .halt e w) :
    Halts c (bytesToString w.console) e := by
  have outcome : Res.halt code world = Res.halt e w := by
    simpa [stepI, h.primitive, opt, cCall, prim, primF1, callee.fragment, callee.semantics{simp}] using Res.unguard_halt step
  obtain ⟨rfl, rfl⟩ := Res.halt.inj outcome
  exact c_call{arity}_exit_arm writeStable h{argument} callee

end OCaml.Vm.Sim
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    opts = parser.parse_args()
    for arity in [1, 2, 3, 4, 5, 'n']:
        path = ROOT / f'OCaml/Vm/Sim/Ccall{arity}Exit.lean'
        content = render(arity)
        if opts.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'C_CALL exit adapter drift: {path}')
        else:
            path.write_text(content)
    print('C_CALL exit adapters current')
