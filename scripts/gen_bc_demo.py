#!/usr/bin/env python3
"""Generate the minimal branch-function adequacy fixture through runbc --lean.
The executable is assembled from the vendored opcode enumeration. Its DATA
section is OCaml's small-format marshalled unit. No generated file is edited.
"""
import argparse
import struct
import subprocess
import tempfile
from pathlib import Path
from gen_opcodes import opcodes
from gen_bc_rules import ROOT


def loaded(words, name):
    code = struct.pack('<' + 'I' * len(words), *words)
    data = struct.pack('>5I', 0x8495a6be, 1, 0, 0, 0) + b'\x40'
    sections = [(b'CODE', code), (b'PRIM', b''), (b'DATA', data)]
    binary = (b''.join(body for _, body in sections) +
              b''.join(name + struct.pack('>I', len(body)) for name, body in sections) +
              struct.pack('>I', len(sections)) + b'Caml1999X031')
    with tempfile.TemporaryDirectory(prefix='bprime-demo-') as tmp:
        exe = Path(tmp)/'jump_stop.byte'
        exe.write_bytes(binary)
        prog = subprocess.run([str(ROOT/'.lake/build/bin/runbc'), '--lean', str(exe), name],
                              check=True, text=True, capture_output=True).stdout
    return prog


def render():
    ops = opcodes()
    words = [ops.index('BRANCH'), 1, ops.index('STOP'), ops.index('STOP')]
    prog = loaded(words, 'jumpStop')
    closure = loaded([ops.index('CLOSURE'), 1, 3, ops.index('GETFIELD2'), ops.index('STOP'), ops.index('STOP')], 'capture')
    return '''-- GENERATED by scripts/gen_bc_demo.py via runbc --lean. Do not edit.
import OCaml.Logic.Block
namespace OCaml.Programs.Generated.Demo
open OCaml.Bytecode

''' + prog + closure + f'''
def branchBlock : CertifiedBlock :=
  ⟨0, #[{', '.join(str(w)+'#32' for w in words)}],
    [⟨0, ⟨.BRANCH, [1]⟩, 2, by decide, rfl, rfl, rfl⟩,
     ⟨2, ⟨.STOP, []⟩, 1, by decide, rfl, rfl, rfl⟩]⟩

/-- Generated branch-function summary, polymorphic in every non-PC field. -/
theorem jumpStop_summary (a e : Val) (rest : List Val) (x t : Nat) (h : Heap) (w : World) :
    OCaml.Run.iter (bcK jumpStop) 1 ⟨0, a, rest, e, x, t, h, w⟩ =
      .ok ⟨2, a, rest, e, x, t, h, w⟩ :=
  branchBlock.run jumpStop rfl 1 _ _ rfl

/-- A generated closure-building program exercises allocation/read reduction
with an arbitrary caller heap and arbitrary captured accumulator. -/
theorem capture_summary (a e : Val) (rest : List Val) (x t : Nat) (h : Heap) (w : World) :
    OCaml.Run.iter (bcK capture) 2 ⟨0, a, rest, e, x, t, h, w⟩ =
      .ok ⟨4, a, rest, e, x, t,
        (h.alloc (.block closureTag [.code 5, Val.ofInt 2, a])).1, w⟩ :=
  closure_capture_read capture 0 3 rfl rfl a e rest x t h w

end OCaml.Programs.Generated.Demo
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT/'OCaml/Programs/Generated/Demo.lean'
    text = render()
    if args.check:
        if path.read_text() != text:
            raise SystemExit('generated Demo.lean differs')
    else:
        path.write_text(text)

if __name__ == '__main__':
    main()
