#!/usr/bin/env python3
"""Generate bounded, independently audited shards covering every compiler instruction."""
import argparse
import hashlib
import json
from gen_bc_rules import ROOT, OUT, DEFAULT_DUMP, inputs, module_text

DEST = OUT / 'All'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    exe = ROOT/'vendor/ocaml-4.14.4/boot/ocamlc'
    words, decoded, units, entries, targets = inputs(exe, DEFAULT_DUMP)
    pcs = list(decoded)
    artifacts = {}
    manifest = {'generator': 'scripts/gen_bc_all.py',
                'executable_sha256': hashlib.sha256(exe.read_bytes()).hexdigest(),
                'code_words': len(words), 'instructions': len(pcs), 'shard_limit': 2048,
                'closure_entries': len(entries), 'shards': {}}
    covered = []
    for index, start in enumerate(range(0, len(pcs), 2048)):
        chunk = pcs[start:start+2048]
        begin = chunk[0]
        end = chunk[-1] + decoded[chunk[-1]][2]
        name = f'All.S{index:03d}'
        source, stats = module_text(name, words, decoded, {name: (begin, end)}, entries, targets)
        source = source.replace('GENERATED by scripts/gen_bc_rules.py', 'GENERATED by scripts/gen_bc_all.py')
        filename = f'S{index:03d}'
        artifacts[DEST/f'{filename}.lean'] = source
        theorems = [f'OCaml.Programs.Generated.{name}.f{fn["entry"]}_b{b["pc"]}_run'
                    for fn in stats['functions'] for b in fn['blocks']]
        artifacts[DEST/f'{filename}Audit.lean'] = '\n'.join([
            '-- GENERATED by scripts/gen_bc_all.py. Do not edit.',
            f'import OCaml.Programs.Generated.{name}', '',
            *[f'#print axioms {thm}' for thm in theorems], ''])
        stats.update(begin=begin, end=end, theorems=theorems,
                     source_sha256=hashlib.sha256(source.encode()).hexdigest())
        manifest['shards'][filename] = stats
        covered.extend(chunk)
    assert covered == pcs and len(pcs) == 412087
    assert sum(s['words'] for s in manifest['shards'].values()) == len(words)
    artifacts[DEST/'manifest.json'] = json.dumps(manifest, indent=2) + '\n'
    expected = set(artifacts)
    stale = set(DEST.glob('*.lean')) - expected
    if stale:
        raise SystemExit(f'unexpected generated shards: {stale}')
    for path, source in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text() != source:
                raise SystemExit(f'generated file differs: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != source:
                path.write_text(source)
    print(f'compiler shards: {len(manifest["shards"])}; {len(pcs)} instructions; '
          f'{sum(s["blocks"] for s in manifest["shards"].values())} block rules')


if __name__ == '__main__':
    main()
