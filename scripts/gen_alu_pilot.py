#!/usr/bin/env python3
"""Kernel smoke sites for each additional ALU class, drawn from the real ELF.

Shares the arm pilot's code-pin/site generator path. All 18 additional classes must
occur in the pinned ELF; each generated theorem checks its exact Sail decode
and generic execute characterization. This is not an arm-family proof.
"""
import argparse
from census import ROOT, disasm
from gen_arm_pilot import site_outputs
from disasm_to_sites import classify
import alu_classes


def outputs():
    fs = disasm(ROOT / 'c/ocamlrun-riscv-htif.elf')
    selected = {}
    # Prefer interpreter sites; fallback only for classes unused by the interpreter.
    for f in [fs['caml_interprete'], *fs.values()]:
        for ins in f['insts']:
            a, w, mn, ops = ins
            rows = classify(a, w, mn + ' ' + ops, {})
            if len(rows) == 1 and rows[0].cls in alu_classes.CLASSES:
                selected.setdefault(rows[0].cls, (ins, rows[0]))
    if set(selected) != alu_classes.CLASSES:
        raise ValueError(f'missing ALU classes: {alu_classes.CLASSES - set(selected)}')
    chosen = sorted(selected.values(), key=lambda pair: pair[0][0])
    result = site_outputs([x for x, _ in chosen], [r for _, r in chosen], 'Alu', 'alu')
    for p in result:
        result[p] = result[p].replace('GENERATED by scripts/gen_arm_pilot.py',
                                      'GENERATED by scripts/gen_alu_pilot.py via scripts/gen_arm_pilot.py')
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'ALU pilot drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('ALU pilot artifacts current')
