"""Generate bounded byte-image lookups directly from this ELF."""
from census import ROOT, read_mem
from stdio_layout import layout


def image_source(old,new,secs,relocate):
    code=[]
    for name in old['functions']:
        for pc,w,*_ in new[name]['insts']:
            code.extend((pc+i,(w>>(8*i))&255) for i in range(4))
    base,size=old['conversion_table']; lo=relocate(base); hi=relocate(base+size)
    table=list(enumerate(read_mem(secs,lo,hi-lo),lo))
    out=['-- GENERATED by scripts/gen_stdio_image.py through retarget_stdio_specs.py.',
         'import Vsa.Sim.TextImage','namespace VsaIris.Sym']
    def emit(name, data):
        data=sorted(set(data))
        def tree(xs, label):
            if len(xs)<=4:
                expr='0#8'
                for a,b in reversed(xs):expr=f'if a = 0x{a:x} then 0x{b:02x}#8 else {expr}'
            else:
                mid=len(xs)//2
                left=tree(xs[:mid],label+'L');right=tree(xs[mid:],label+'R')
                expr=f'if a < 0x{xs[mid][0]:x} then {left} a else {right} a'
            out.append(f'def {label} (a : Nat) : BitVec 8 := {expr}')
            return label
        tree(data,name)
    emit('snpCodeImg',code);emit('snpTableImg',table)
    out.append('end VsaIris.Sym')
    return '\n'.join(out)+'\n'
