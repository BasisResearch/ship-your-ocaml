"""Emit a trace candidate using the existing packed-log reflection encoding.

The data does not certify execution. Kernel log checks certify only its
memory effect. All generated literal data is derived from the saved trace.
"""
from pathlib import Path
import argparse,gzip,hashlib,importlib.util,json
root=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument("--check",action="store_true")
args=ap.parse_args()
spec=importlib.util.spec_from_file_location('bootgen',root/'scripts/syi/gen_boot_witness.py')
gen=importlib.util.module_from_spec(spec);spec.loader.exec_module(gen)
raw=gzip.decompress((root/'results/boot/while_min-stores.jsonl.gz').read_bytes())
cut=json.loads((root/'results/boot/while_min-cut.json').read_text())
rows=[json.loads(line) for line in raw.splitlines()]
assert len(rows)==cut['stores']
assert all(rows[i][0]<rows[i+1][0] for i in range(len(rows)-1))
assert all(0<=step<cut['cut_step'] and 0<=addr<2**32 and width in (1,2,4,8) and 0<=value<2**64
           for step,addr,width,value in rows)
log=[tuple(row[1:]) for row in rows]
runs=gen.final_runs(log)
encoded=[a|(width<<32)|(value<<36) for a,width,value in log]
pages=[encoded[i:i+64] for i in range(0,len(encoded),64)]
out=['import Vsa.Sim.Boot.Log','', f'/-! GENERATED by scripts/gen_boot_log.py. Observed stores, not an execution certificate.\nTrace SHA256: {hashlib.sha256(raw).hexdigest()}. -/', 'namespace OCaml.Vm.Boot.WhileMinLog','open Vsa.Sim.Boot','']
for i,p in enumerate(pages):out.append(f'def logPage{i} : Nat := {hex(gen.pack(p,128))}')
out+=['def logPage (i : Nat) : Nat :=\n  '+gen.if_tree('i',len(pages),lambda k:f'logPage{k}'),f'def log : PackedLog := ⟨logPage, {len(log)}⟩','']
for i,(a,cells) in enumerate(runs):out.append(f'def run{i} : Vsa.Sim.Boot.Run := ⟨{a:#x}, {len(cells)}, {hex(gen.pack([k|(b<<24) for k,b in cells],32))}⟩')
def tree(lo,hi):
 if hi-lo==1:return f'(.leaf run{lo})'
 mid=(lo+hi)//2
 left,right=tree(lo,mid),tree(mid,hi)
 name=f'tree_{lo}_{hi}'
 out.append(f'def {name} : RunTree := .node {runs[mid][0]:#x} {left} {right}')
 return name
root_tree=tree(0,len(runs))
out += [f'def runs : RunTree := {root_tree}', 'end OCaml.Vm.Boot.WhileMinLog','']
outputs = {'OCaml/Vm/Boot/WhileMinLogData.lean': '\n'.join(out)}
imports = []
header = ['import OCaml.Vm.Boot.WhileMinLogData', 'import Vsa.Sim.Boot.Checks', '',
          '/-! GENERATED by scripts/gen_boot_log.py. Kernel checks of observed stores only. -/',
          'namespace OCaml.Vm.Boot.WhileMinLog', 'open Vsa.Sim.Boot', '']
end = ['end OCaml.Vm.Boot.WhileMinLog', '']
def emit_part(kind, lo, hi, body):
    name = f'OCaml.Vm.Boot.WhileMinLogParts.{kind}{lo}_{hi}'
    # A dependency chain bounds concurrent elaboration of the large data import.
    extra = [f'import {imports[-1]}'] if imports else []
    imports.append(name)
    outputs[name.replace('.', '/') + '.lean'] = '\n'.join(extra + header + body + end)

def store_tree(lo, hi, body, split=True):
    name = f'stores_{lo*64}_{min(hi*64,len(log))}'
    if split and hi-lo <= 16:
        local = []
        store_tree(lo, hi, local, False)
        emit_part('Stores', lo, hi, local)
        return name
    if hi-lo == 1:
        n = min(64, len(log)-lo*64)
        body.append(f'theorem {name} : StoresChecked log runs {lo*64} {lo*64+n} :=\n  StoresChecked.chunk (lo := {lo*64}) (n := {n}) (by decide +kernel)')
    else:
        mid = (lo+hi)//2
        left, right = store_tree(lo, mid, body, split), store_tree(mid, hi, body, split)
        body.append(f'theorem {name} : StoresChecked log runs {lo*64} {min(hi*64,len(log))} :=\n  StoresChecked.join {left} {right}')
    return name

def run_tree(lo, hi, body, split=True):
    name = f'run{lo}_checked' if hi-lo==1 else f'tree_{lo}_{hi}_checked'
    if split and hi-lo <= 64:
        local = []
        run_tree(lo, hi, local, False)
        emit_part('Runs', lo, hi, local)
        return name
    if hi-lo == 1:
        body.append(f'theorem {name} : RunTree.Checked log (.leaf run{lo}) :=\n  RunTree.Checked.leaf (by decide +kernel)')
    else:
        mid = (lo+hi)//2
        left, right = run_tree(lo, mid, body, split), run_tree(mid, hi, body, split)
        body.append(f'theorem {name} : RunTree.Checked log tree_{lo}_{hi} :=\n  RunTree.Checked.node {left} {right}')
    return name
body=[]
stores_checked=store_tree(0,len(pages),body)
runs_checked=run_tree(0,len(runs),body)
body += [f'theorem logOk : LogOk log runs :=\n  LogOk.of_checks {stores_checked} {runs_checked}',
         'theorem memory_view (m : Std.ExtHashMap Nat (BitVec 8)) (x : Nat) :\n  (Vsa.Sim.writeLog m log.log)[x]? = logView runs (fun a => m[a]?) x :=\n  writeLog_view logOk m x']
body += ['theorem fin_none_below {x : Nat} (hx : x < run0.base) : runs.fin x = none := by',
         f'  have bound : x < {runs[0][0]:#x} := hx',
         '  unfold RunTree.fin', '  rw [runs]']
hi=len(runs)
while hi > 1:
    mid=hi//2
    body += [f'  have h{hi} : x < {runs[mid][0]:#x} := by omega',
             f'  rw [tree_0_{hi}, RunTree.find, if_pos h{hi}]']
    hi=mid
body += ['  rw [RunTree.find, Run.cell, if_neg (fun h => Nat.not_le_of_lt hx h.1)]',
         'theorem memory_below (initial : Std.ExtHashMap Nat (BitVec 8)) {x : Nat}',
         '    (hx : x < run0.base) : (Vsa.Sim.writeLog initial log.log)[x]? = initial[x]? := by',
         '  rw [memory_view]', '  simp only [logView, fin_none_below hx]']
outputs['OCaml/Vm/Boot/WhileMinLogChecks.lean'] = '\n'.join([f'import {imports[-1]}'] + header + body + end)
for rel, text in outputs.items():
    path=root/rel
    if args.check:
        if not path.exists() or path.read_text()!=text:raise SystemExit(f'boot log drift: {rel}')
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        if not path.exists() or path.read_text()!=text:
            path.write_text(text)
print(f'Boot log: {len(log)} stores, {len(runs)} final runs, {len(outputs)} modules')
