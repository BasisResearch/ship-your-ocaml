#!/usr/bin/env python3
"""Generate counted field writes with explicit G2 full-growth boundary and focused audits."""
import argparse
from census import ROOT
from gen_counted_stack_rows import channel_certificate

BARRIERS = ['SETGLOBAL', 'SETFIELD0', 'SETFIELD1', 'SETFIELD2', 'SETFIELD3', 'SETFIELD']
ROWS = [*BARRIERS, 'OFFSETREF']
FRAME_THEOREMS = [
    'OCaml.LoopGeometry.retarget',
    *('OCaml.Vm.Sim.' + name for name in [
        'barrier_entry_of_idle', 'barrier_entry', 'object_custom_outside', 'f1_field_channelCountFrame', 'counted_fieldWriteReady',
        'globalBarrier_of_frames', 'field_callee_of_frames', 'fieldBarrier_of_frames',
        'fieldBarrierK_of_frames', 'f1_globalBarrier', 'f1_field_callee', 'f1_fieldBarrier', 'f1_fieldBarrierK',
        'barrierGrowth_gprs_of_runtime', 'barrierGrowth_of_runtime', 'f1_barrierGrowth_gprs',
        'f1_insert_channelCountFrame', 'counted_barrierRuntime', 'f1_grow_channelCountFrame',
        'counted_growRuntime', 'counted_barrierGrowth', 'counted_barrier_row']),
    *('OCaml.Vm.Gc.' + name for name in [
        'RefStorage.custom_alias', 'LibHeapAt.refCustomApart', 'f1_refCustomApart', 'f1_table_eq', 'LibHeapAt.insert_outside', 'RefCustomApart.entry_outside',
        'LibHeapAt.custom_realloc_kept', 'CallerApart.slot_outside', 'f1_afterGrow_custom', 'f1_afterGrow_customApart']),
]


def output():
    out = '''import OCaml.Vm.Sim.CountedBarrierFrame
import OCaml.Vm.Sim.A2TableRows
import OCaml.Vm.Sim.G1Capacity

/-! GENERATED by scripts/gen_counted_field_rows.py. OFFSETREF has a supplied
counted field frame. All insertion spatial suppliers come from the selected
heap invariant. The six barrier instances retain exactly G2's stronger
counted-layout full-growth boundary, also retained by the partial table. -/
namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine OCaml.Vm.Primitives
'''
    for op in ROWS:
        out += channel_certificate(op, 'stepI, opt')
    out += '''
/-- Counted OFFSETREF writes its actual represented object field. -/
theorem counted_offsetref_row {P : Prog}
    {Ready : Nat → Config → Prop} {state Customs : Config → Nat → Prop}
    (custom : Gc.CustomMemCall Ready state Customs) (fits : OCaml.Fits Gc.f1Layout.budget P) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .OFFSETREF :=
  counted_row (fun _ _ => offsetref_row (fun s c reach h =>
    counted_fieldWriteReady custom h.running.platform.runtime
      (by simpa using stack_fits fits g1_capacity reach (k := 0))))
    (fun _ i _ opcode effect => counted_offsetref_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    for op in BARRIERS:
        if op == 'SETGLOBAL':
            barrier = 'globalBarrier_of_frames br growth full rr fields fits g1_capacity'
            row = f'setglobal_row stable ({barrier})'
        elif op == 'SETFIELD':
            barrier = 'fieldBarrier_of_frames br growth full rr fields fits g1_capacity'
            row = f'setfield_row stable fits g1_capacity ({barrier})'
        else:
            barrier = 'fieldBarrierK_of_frames br growth full rr fields fits g1_capacity (by decide)'
            row = f'{op.lower()}_row stable fits g1_capacity ({barrier})'
        out += f'''
/-- Counted {op}, from actual runtime suppliers, retaining counted G2 full growth. -/
theorem counted_{op.lower()}_row {{P : Prog}}
    {{Ready : Nat → Config → Prop}} {{state Customs : Config → Nat → Prop}}
    (custom : Gc.CustomMemCall Ready state Customs) (fits : OCaml.Fits Gc.f1Layout.budget P)
    (full : ∀ cp world, BarrierGrowthFull (countedLayout Gc.f1Layout Customs cp world)) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) .{op} :=
  counted_barrier_row custom full (fun _ _ br growth full rr fields stable =>
    {row})
    (fun _ i _ opcode effect => counted_{op.lower()}_channels (P := P) (args := i.args)
      (by cases i; cases opcode; exact effect))
'''
    out += '\n/-- These six supplied row terms retain the counted G2 full-growth boundary. -/\ndef countedBarrierOpcodes : List Opcode :=\n  [' + ', '.join('.' + op for op in BARRIERS) + ']\n'
    out += '''
/-- Barrier subtable with actual insertion/empty-growth suppliers and explicit full growth. -/
theorem counted_barrier_supported_row {P : Prog} {op : Opcode}
    {Ready : Nat → Config → Prop} {state Customs : Config → Nat → Prop}
    (custom : Gc.CustomMemCall Ready state Customs) (fits : OCaml.Fits Gc.f1Layout.budget P)
    (full : ∀ cp world, BarrierGrowthFull (countedLayout Gc.f1Layout Customs cp world))
    (member : op ∈ countedBarrierOpcodes) :
    OCaml.OpArm P (CountedLoopAt Customs Gc.f1Layout P) op := by
  simp only [countedBarrierOpcodes, List.mem_cons, List.not_mem_nil, or_false] at member
  rcases member with rfl | rfl | rfl | rfl | rfl | rfl
'''
    out += ''.join(f'  · exact counted_{op.lower()}_row custom fits full\n' for op in BARRIERS)
    out += '''
/-- Exactly six distinct supplied barrier rows, relative to counted G2 full growth. -/
theorem counted_barrier_opcode_count :
    countedBarrierOpcodes.length = 6 ∧ countedBarrierOpcodes.Nodup := by decide
'''
    return out + '\nend OCaml.Vm.Sim\n'



def audits():
    names = FRAME_THEOREMS + [f'OCaml.Vm.Sim.counted_{op.lower()}_{suffix}'
                             for op in ROWS for suffix in ['channels', 'row']] + [
        'OCaml.Vm.Sim.counted_barrier_supported_row', 'OCaml.Vm.Sim.counted_barrier_opcode_count',
        'OCaml.Vm.Sim.counted_runtimeFrame', 'OCaml.Vm.Sim.counted_raiseRuntimeFrame',
        'OCaml.Vm.Sim.counted_allocFrame', 'OCaml.Vm.Sim.counted_primAllocFrame',
        'OCaml.Vm.Sim.counted_supported_row', 'OCaml.Vm.Sim.counted_opcode_census',
        'OCaml.Vm.Sim.counted_opcode_count', 'OCaml.Vm.Sim.counted_remaining_count']
    return '''import OCaml.Vm.Sim.CountedControlRows
import OCaml.Vm.Sim.CountedPrimAllocRows

/-! GENERATED by scripts/gen_counted_field_rows.py. Focused allowed-axiom audit.
Full OCaml.Audit remains the lead gate. -/
''' + ''.join(f'#print axioms {name}\n' for name in names)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for file, content in [('CountedFieldRows', output()), ('CountedFieldAudit', audits())]:
        target = ROOT / f'OCaml/Vm/Sim/{file}.lean'
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'counted field row/audit drift: {file}')
        else:
            target.write_text(content)
    print('Counted field rows current (7 supplied, 6 retaining counted G2 full growth)')
