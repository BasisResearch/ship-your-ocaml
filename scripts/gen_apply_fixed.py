#!/usr/bin/env python3
"""Generate represented APPLY1--3 compositions from checked segment JSON."""
import argparse
import json
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parent.parent

def render(n):
    spec = json.loads((ROOT / f'scripts/syi/segments/apply{n}.json').read_text())
    steps = spec['steps']
    stores = [s for s in steps if s['class'] == 'sd']
    order = [[3,1,2,0],[2,3,1,0,4],[5,2,1,4,0,3]][n-1]
    pc = 'BitVec.ofNat 64 (pl.codeBase + 4 * (s.pc + 1))'
    extra = 'tag64 (BitVec.ofNat 63 s.extra)'
    def addr(offset):
        return 'sp' if offset == 0 else f'sp {"+" if offset > 0 else "-"} {abs(offset)}'
    words = [f'word c ({addr(8*i)})' for i in range(n)] + [pc, 'env', extra]
    entries = [f'({addr(8*i-24)}, 8, {words[i]})' for i in order]
    log = f'applyFrameLog sp (stackWords c sp {n}) ({pc}) env ({extra})'
    registers = {'x9': '(BitVec.ofNat 64 sp)', 'x18':'(BitVec.ofNat 64 s.extra)',
        'x23':f'({pc})', 'x25':'env', 'x21':'(BitVec.ofNat 64 (a + 8 * k))',
        'x19':'(BitVec.ofNat 64 Layout.sym_Caml_state)',
        'x20':'(BitVec.ofNat 64 Layout.sym_caml_something_to_do)'}
    proofs = {'x9':'h.spReg','x18':'h.extra','x25':'(represented_register h.env envWord)',
        'x21':'(represented_register h.accu field.sourceWord)',
        'x19':'h.dispatch.loop.domain','x20':'h.dispatch.loop.pending'}
    lines = [f'''-- GENERATED by scripts/gen_apply_fixed.py; do not edit.
import OCaml.Vm.Sim.ApplyRestore
import OCaml.Vm.Sim.Apply{n}Segment
import OCaml.Vm.Sim.Apply{n}Pins
import Vsa.Sim.FrameWriteSet

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- The fixed-arity generated body preserves the represented caller frame and
enters its closure through the no-growth/no-pending tail. -/
theorem apply{n}_arm {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a k dest : Nat}} {{env : BitVec 64}}
    (stable : WindowStable L.runtimeOk [⟨sp - 24, sp + 8 * {n}⟩])
    (h : ArmInput L P s .APPLY{n} c pl cp sp high) (bound : {n} ≤ s.stack.length)
    (field : FieldSelection s.heap pl s.accu 0 (.code dest) l a k)
    (geometry : RamReadAt (a + 8 * k) 8) (ready : EnterReady c (sp - 24))
    (envWord : valWord pl s.env = some env)
    (space : ApplyWriteOk P s c pl cp sp high (stackWords c sp {n}) env) :
    ∃ after, Plus c after ∧ Running L P (applyState s {n} dest) after := by
  have length : (stackWords c sp {n}).length = {n} := by simp [stackWords]
  have room := space.room
  have spSmall : sp < 2^64 := by
    have shape := h.stack.1
    have highBound : high < 2^64 := by rw [← h.stackHigh]; exact BitVec.isLt _
    omega
  have extraWord : Sail.shift_bits_left (BitVec.ofNat 64 s.extra) (Sail.BitVec.extractLsb (0x01#6) 5 0) +
      sign_extend (m := 64) (0x001#12) = {extra} := retaddr_extra_word s.extra
  have fieldWord : word c (a + 8 * k) = BitVec.ofNat 64 (pl.codeBase + 4 * dest) :=
    (Option.some.inj (field.read h.toVmReprAt (by simp [roots])).word).symm
  have thresholdAddress : word c Layout.sym_Caml_state + sign_extend (m := 64) (0x098#12) =
      BitVec.ofNat 64 ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold) := by
    rw [BitVec.ofNat_add, BitVec.ofNat_toNat]; rfl
  have domainWindow : RamReadAt Layout.sym_Caml_state 8 := ⟨by decide, by decide, by decide⟩
  have pendingWindow : RamReadAt Layout.sym_caml_something_to_do 4 := ⟨by decide, by decide, by decide⟩
  have logEq : {log} = [{', '.join(entries)}] := by
    have address0 : sp - 24 + 0 = sp - 24 := by omega
''']
    for i in range(1,n+3):
        lines.append(f'    have address{i} : sp - 24 + {8*i} = {addr(8*i-24)} := by omega\n')
    lines.append('    simp [applyFrameLog, indexedLog, applyFrameEntries, applyFrameOrder, applyFrameWords,\n      stackWords, List.range_succ, '+', '.join(f'address{i}' for i in range(n+3))+']\n')
    for i in range(n):
        lines.append(f'  have read{i} : RamReadAt ({addr(8*i)}) 8 := by\n    simpa using space.reads {i} (by rw [length]; decide)\n')
    for j,idx in enumerate(order,1):
        lines.append(f'  have member{j} : {entries[j-1]} ∈ {log} := by rw [logEq]; simp\n')
        lines.append(f'  have store{j} : RamWriteAt ({addr(8*idx-24)}) 8 := space.writes _ member{j}\n')
    offsets = sorted(set([8*i-24 for i in order]+[8*i for i in range(n)]+[-24]))
    simps = ['extraWord','codePc_succ','thresholdAddress','ready.threshold.toNat','geometry.toNat',
        'domainWindow.toNat','pendingWindow.toNat',
        'show sign_extend (m := 64) (0x000#12) = 0#64 from by decide','BitVec.add_zero']
    for off in offsets:
        name = f'address{"m" if off<0 else "p"}{abs(off)}'
        if off:
            lines.append(f'  have {name} : BitVec.ofNat 64 sp + sign_extend (m := 64) (0x{off%4096:03x}#12) =\n      BitVec.ofNat 64 ({addr(off)}) := by\n')
            if off<0: lines.append('    exact stack_decrement (by omega) (by decide) (by decide)\n')
            else: lines.append(f'    change BitVec.ofNat 64 sp + BitVec.ofNat 64 {off} = _\n    exact (BitVec.ofNat_add _ _).symm\n')
            simps.append(name)
        natname = f'nat{"m" if off<0 else "p"}{abs(off)}'
        upper = 'spSmall' if off<=0 else f'read{off//8}.upper'
        lines.append(f'  have {natname} : (BitVec.ofNat 64 ({addr(off)})).toNat = {addr(off)} :=\n    Nat.mod_eq_of_lt (by have upper := {upper}; omega)\n')
        simps.append(natname)
    guard = 'zopz0zKzJ_u' if n==2 else 'zopz0zI_u'
    boolval = 'true' if n==2 else 'false'
    guardlemma = 'bgeu_of_le' if n==2 else 'bltu_false_of_ge'
    lines.append(f'''  have capacity : {guard} (BitVec.ofNat 64 (sp - 24))
      (word c ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold)) = {boolval} := by
    apply {guardlemma}
    rw [natm24]
    exact ready.capacity
  apply dispatch_compose h.dispatch
  intro d dp
''')
    for j,idx in enumerate(order,1):
        prev = 'd.σ.mem' if j==1 else f'm{j-1}'
        lines.append(f'  obtain ⟨m{j}, hm{j}⟩ : ∃ m : Std.ExtHashMap Nat (BitVec 8),\n      m = writeMap8 {prev} ({addr(8*idx-24)}) (sdData_val ({words[idx]})) := ⟨_, rfl⟩\n')
        lines.append(f'  have memory{j} : m{j} = writeLog c.σ.mem (({log}).take {j}) := by\n    rw [logEq, '+', '.join(f'hm{i}' for i in range(j,0,-1))+', dp.memory]; rfl\n')
    total = len(order)
    lines.append(f'  have fullMemory : m{total} = writeLog c.σ.mem ({log}) := by\n    rw [logEq, '+', '.join(f'hm{i}' for i in range(total,0,-1))+', dp.memory]; rfl\n')
    lo = min(int(s['addr'],16) for s in steps)
    hi = max(int(s['addr'],16) for s in steps)+4
    lines.append(f'''  have code (a : Nat) (w : BitVec 64) (member : (a, 8, w) ∈ {log}) :
      a + 8 ≤ 0x{lo:x} ∨ 0x{hi:x} ≤ a := image_entry_code space.image member (by decide) (by decide)
''')
    pinregs = [p['reg'] for p in spec['pins']]
    pintext = ',\n       '.join(f'⟨Register.{r}, {registers[r]}⟩' for r in pinregs)
    regproof = []
    for r in pinregs:
        regproof.append('(by change gpr d 23 = _; simpa only [codePc_succ] using dp.nextCode)' if r=='x23' else f'(dp.frame.frame Register.{r} (by decide)).trans {proofs[r]}')
    lines.append(f'''  have bp : SegSt ({spec['entry']}#64) [{pintext}]
      (fun σ => Vsa.Sim.Code.CamlApply{n}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨{', '.join(regproof)}, trivial⟩,
      dp.good.minstret, dp.tick, apply{n}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run0 := tr_apply{n} {' '.join(registers[r] for r in pinregs)} d.σ.mem d.σ
''')
    stage=0; written=0
    for step in steps:
        asm=step['asm']; ident=step['addr'][2:]
        if step['class']=='sd':
            written+=1
            j=written
            args=f'store{j}.lower store{j}.upper store{j}.htif store{j}.aligned (code _ _ member{j}) m{j} hm{j}'
        elif asm.startswith(('ld ','lw ')):
            if '(s1)' in asm:
                i=int(re.search(r',(-?\d+)\(s1\)',asm)[1])//8
                geo=f'read{i}'; value=f'(word c ({addr(8*i)}))'
                proof='(word_read_writeLog_out (log := []) trivial dp.memory).symm'
            else:
                mem=f'memory{written}'; outside=f'(space.enter.sublist (List.take_sublist {written} _))'
                if '(s5)' in asm:
                    geo='geometry'; value='(BitVec.ofNat 64 (pl.codeBase + 4 * dest))'
                    proof='((space.payload.accu_field_load (payload_of_repr h.toVmReprAt) field fullMemory).trans fieldWord).symm'
                elif '(s3)' in asm:
                    geo='domainWindow'; value='(word c Layout.sym_Caml_state)'
                    proof=f'(word_read_writeLog_out {outside}.domain {mem}).symm'
                elif '(s4)' in asm:
                    geo='pendingWindow'; value='0#64'
                    proof=f'(ready.toSignalCheckReady.read_log {outside}.pending {mem}).symm'
                else:
                    assert '152(' in asm
                    geo='ready.threshold'; value='(word c ((word c Layout.sym_Caml_state).toNat + Layout.off_stack_threshold))'
                    proof=f'(word_read_writeLog_out {outside}.threshold {mem}).symm'
            args=f'{geo}.lower {geo}.upper {geo}.htif {value}\n    ({proof})'
        elif step['class'] in ['btaken','bnottaken']:
            args='(by decide)' if asm.startswith('beqz ') else 'capacity'
        else: continue
        lines.append(f'  try simp only [{", ".join(simps)}] at run{stage}\n')
        lines.append(f'  have run{stage+1} := run{stage} {args}\n')
        stage+=1
    for step in steps:
        r=step.get('rd')
        if r and r!='x0': pinregs=[r]+[p for p in pinregs if p!=r]
    get=lambda r:f'PinsHold.get post.pins ⟨{pinregs.index(r)}, by simp⟩'
    writes = sorted({s['rd'] for s in steps if s.get('rd') and s['rd']!='x0'})
    allowed='['+', '.join('Register.'+r for r in writes)+'] ++ noiseRegs'
    lines.append(f'''  obtain ⟨nb, after, _, steps, post⟩ := run{stage} d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have frame := rawFrame.widenChecked (allowed := {allowed}) (by decide)
  have loop : LoopRegisters after := loopRegisters_frame (fun r hr =>
    (frame.frame r (by revert r; decide)).trans (dp.frame.frame r (by revert r; decide))) h.dispatch.loop
  have observed : ApplyPost c s pl sp dest (stackWords c sp {n}) env after := by
    refine ⟨⟨post.pcAt, {get('x8')}, ?_,
      ⟨_, {get('x21')}, field.sourceWord⟩,
      ⟨_, {get('x25')}, field.sourceWord⟩, ?_⟩,
      post.good, memory.trans fullMemory, frame.out.trans dp.frame.out, loop,
      (frame.frame (gprReg 2) (by decide)).trans (dp.frame.frame (gprReg 2) (by decide))⟩
    · exact {get('x9')}
    · simp only [applyState, length]
      exact {get('x18')}
  refine ⟨nb, after, steps, ?_⟩
  have restored := apply_frame_restore (by simpa only [length] using stable) h.toVmReprAt h.running.platform
    (by rw [length]; decide) (by rw [length]; decide) (by simpa only [length] using bound)
    (by simpa only [length] using stack_value_words h.stack bound) envWord space observed h.geometry h.native
  simpa only [length] using restored

end OCaml.Vm.Sim
''')
    body = ''.join(lines)
    header = body[body.index(f'theorem apply{n}_arm'):body.index(' := by')]
    header = header.replace(f'apply{n}_arm', f'apply{n}_step_arm', 1).replace('{s : St}', "{s s' : St}", 1)
    header = header.replace('env) :\n    ∃ after',
        f"env) (step : stepI P s ⟨.APPLY{n}, []⟩ = .next s') :\n    ∃ after")
    header = header.replace(f'(applyState s {n} dest) after', "s' after")
    wrapper = ['/-- The generated represented transition agrees with the actual bytecode step. -/\n', header, ' := by\n',
        "  have state : applyState s " + str(n) + " dest = s' := by\n"]
    eqs=[]
    for i in range(n):
        indent='    '+'  '*i
        source='s.stack' if i==0 else f'tail{i}'
        eqs.append(f'stack{i}')
        wrapper.append(indent+f'cases stack{i} : {source} with\n')
        wrapper.append(indent+'| nil => have impossible := bound; simp ['+', '.join(eqs)+'] at impossible\n')
        wrapper.append(indent+f'| cons arg{i+1} tail{i+1} =>\n')
    wrapper.append('    '+'  '*n+'simpa [stepI, enter, field.selected, opt, applyState, '+', '.join(eqs)+'] using step\n')
    wrapper.append(f'  rw [← state]\n  exact apply{n}_arm stable h bound field geometry ready envWord space\n\n')
    return body.replace('end OCaml.Vm.Sim', ''.join(wrapper)+'end OCaml.Vm.Sim')

if __name__ == '__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--arity',type=int,choices=[1,2,3])
    args=parser.parse_args()
    for n in ([args.arity] if args.arity else [1,2,3]):
        target=ROOT/f'OCaml/Vm/Sim/Apply{n}.lean'
        rendered=render(n)
        if args.check:
            if not target.exists() or target.read_text()!=rendered:
                raise SystemExit(f'drift: {target}')
        else: target.write_text(rendered)
    print('Fixed-arity application bridges current')
