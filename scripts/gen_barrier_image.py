#!/usr/bin/env python3
"""Generate the barrier's image projections: the pinned ELF image loads the code
regions of caml_modify and the remembered set's growth (`Vsa.Sim.Code.*Loaded`,
generated by gen_gc_rows.py)."""
import argparse
from census import ROOT, disasm
from gen_arm_pilot import code, image_projection
from gen_ocaml_image import sections

# (symbol, module stem, chunk prefix, theorem, output file)
FUNCTIONS = [
    ('caml_modify', 'Caml_modify', 'caml_modify', 'caml_modify_loaded', 'CamlModifyImage'),
    ('caml_realloc_ref_table', 'Caml_realloc_ref_table', 'caml_realloc_ref_table',
     'caml_realloc_ref_table_loaded', 'ReallocRefTableImage'),
    ('realloc_generic_table.isra.0', 'Realloc_generic_table_isra_0', 'realloc_generic_table_isra_0',
     'realloc_generic_table_loaded', 'ReallocGenericImage'),
]


def outputs():
    elf = ROOT / 'c/ocamlrun-riscv-htif.elf'
    funcs = disasm(elf)
    text_base = sections(elf.read_bytes())['.text'][0]
    out = {}
    for sym, stem, prefix, thm, name in FUNCTIONS:
        instructions = funcs[sym]['insts']
        chunks = [f'Vsa.Sim.Code.{prefix}Chunk{i}'
                  for i in range((len(instructions) + code.CHUNK - 1) // code.CHUNK)]
        text = image_projection(instructions, f'Vsa.Sim.Code.{stem}Loaded', f'Vsa.Sim.Code.{stem}',
                                chunks, thm, text_base)
        out[ROOT / f'OCaml/Vm/Sim/{name}.lean'] = text.replace(
            'GENERATED by scripts/gen_arm_pilot.py.', 'GENERATED by scripts/gen_barrier_image.py.')
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'barrier image drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('barrier image projections current')


if __name__ == '__main__':
    main()
