#!/usr/bin/env python3
"""Generate caml_modify's image projection: the pinned ELF image loads the
code region `Vsa.Sim.Code.Caml_modifyLoaded` (generated by gen_gc_rows.py)."""
import argparse
from census import ROOT, disasm
from gen_arm_pilot import code, image_projection
from gen_ocaml_image import sections

OUT = ROOT / 'OCaml/Vm/Sim/CamlModifyImage.lean'


def outputs():
    elf = ROOT / 'c/ocamlrun-riscv-htif.elf'
    instructions = disasm(elf)['caml_modify']['insts']
    text_base = sections(elf.read_bytes())['.text'][0]
    chunks = [f'Vsa.Sim.Code.caml_modifyChunk{i}'
              for i in range((len(instructions) + code.CHUNK - 1) // code.CHUNK)]
    text = image_projection(instructions, 'Vsa.Sim.Code.Caml_modifyLoaded', 'Vsa.Sim.Code.Caml_modify',
                            chunks, 'caml_modify_loaded', text_base)
    return {OUT: text.replace('GENERATED by scripts/gen_arm_pilot.py.', 'GENERATED by scripts/gen_barrier_image.py.')}


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'caml_modify image drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('caml_modify image projection current')


if __name__ == '__main__':
    main()
