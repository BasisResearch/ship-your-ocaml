#!/usr/bin/env python3
"""Compose the represented fixed-arity calls with named primitive summaries."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = r'''-- GENERATED by scripts/gen_ccall_arms.py; do not edit.
import OCaml.Vm.Sim.Ccall
import OCaml.Vm.Sim.Ccall@ARITY@Setup
import OCaml.Vm.Sim.Ccall@ARITY@Return

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim Vsa.Logic
open OCaml.Vm.Primitives

/-- Fixed-arity C_CALL with a successful F1 primitive result. Dispatch, native setup,
the named callee summary and native restoration compose through callSeg. -/
theorem c_call@ARITY@_arm {L : OCaml.Layout} {P : Prog} {s : St} {c : Config}
    {pl : Place} {cp : ChanPlace} {sp high domain table entry : Nat}
    {value env result : BitVec 64} {index : BitVec 32} {name : String}
    {v : Val} {heap : Heap} {world : World}
    (writeStable : WindowStable L.runtimeOk (ccall1Windows sp domain))
    (readStable : MemoryStable L.runtimeOk)
    (h : CcallReady .C_CALL@ARITY@ L P s c pl cp sp high domain table entry value env index name)
    (arguments : CcallArguments s sp @COUNT@)
    (callee : CcallCallee (@PC@#64) (s.accu :: s.stack.take @COUNT@) L P s pl cp sp high domain entry env name v result heap world) :
    ∃ after, Plus c after ∧
      Running L P {s with pc := s.pc + 2, accu := v, heap := heap, world := world, stack := s.stack.drop @COUNT@} after := by
  apply dispatch_compose h.dispatch
  intro d dp
  obtain ⟨n, call, prefixSteps, setup⟩ := c_call@ARITY@_setup writeStable h.toArmInput h.operand h.nonnegative
    h.primitive h.entryName h.aligned h.domainWord h.tableWord h.targetRead h.value h.environment h.space arguments dp
  have pre : Triple (fun x => x = d) (fun x => PCAt (BitVec.ofNat 64 entry) x ∧ x = call) := by
    rintro x rfl
    exact ⟨call, prefixSteps.toSteps, setup.target, rfl⟩
  have composed := callSeg pre (callee.summary call setup).run (c_call@ARITY@_return_triple readStable arguments.bound)
  obtain ⟨after, run, represented⟩ := composed d rfl
  exact ⟨_, after, run.toN_of_stepsField, represented⟩

/-- Match the actual C_CALL@ARITY@ bytecode rule to the named successful primitive
result; the resulting arm uses the same generated setup/return segments. -/
theorem c_call@ARITY@_step_arm {L : OCaml.Layout} {P : Prog} {s s' : St} {c : Config}
    {pl : Place} {cp : ChanPlace} {sp high domain table entry : Nat}
    {value env result : BitVec 64} {index : BitVec 32} {name : String}
    {v : Val} {heap : Heap} {world : World}
    (writeStable : WindowStable L.runtimeOk (ccall1Windows sp domain))
    (readStable : MemoryStable L.runtimeOk)
    (h : CcallReady .C_CALL@ARITY@ L P s c pl cp sp high domain table entry value env index name)
    (arguments : CcallArguments s sp @COUNT@)
    (callee : CcallCallee (@PC@#64) (s.accu :: s.stack.take @COUNT@) L P s pl cp sp high domain entry env name v result heap world)
    (step : stepI P s ⟨.C_CALL@ARITY@, [index.toInt]⟩ = .next s') :
    ∃ after, Plus c after ∧ Running L P s' after := by
  have state : {s with pc := s.pc + 2, accu := v, heap := heap, world := world, stack := s.stack.drop @COUNT@} = s' := by
    simpa [stepI, h.primitive, opt, cCall, prim, primF1, callee.fragment, callee.semantics, List.length_take, Nat.min_eq_left arguments.bound] using Res.unguard step
  rw [← state]
  exact c_call@ARITY@_arm writeStable readStable h arguments callee

end OCaml.Vm.Sim
'''


def render(arity):
    suffix = json.loads((ROOT / f"scripts/syi/segments/c_call{arity}_suffix.json").read_text())
    return TEMPLATE.replace("@ARITY@", str(arity)).replace("@COUNT@", str(arity - 1)).replace("@PC@", suffix["entry"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for arity in range(2, 6):
        path = ROOT / f"OCaml/Vm/Sim/Ccall{arity}.lean"
        out = render(arity)
        if args.check:
            if not path.exists() or path.read_text() != out:
                raise SystemExit(f"represented C_CALL arm drift: {path}")
        else:
            path.write_text(out)


if __name__ == "__main__":
    main()
