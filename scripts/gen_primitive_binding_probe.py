#!/usr/bin/env python3
"""Generate the primitive-binding regression through the real bytecode loader.

Compile one tiny F1 program, then swap two equally-total constant primitive
names in PRIM without changing CODE/DATA or the PRIM section's total length.
Host ocamlrun and runbc must observe the two different exits.
"""
import argparse
import os
from pathlib import Path
import re
import subprocess
import tempfile
from census import ROOT


def outputs():
    compiler = Path(os.environ.get('OCAMLC', str(Path.home() / 'toolchains/ocaml-4.14.4/bin/ocamlc')))
    host = compiler.with_name('ocamlrun')
    runbc = ROOT / '.lake/build/bin/runbc'
    version = subprocess.check_output([str(compiler), '-version'], text=True).strip()
    if version != '4.14.4':
        raise ValueError('probe requires pinned OCaml 4.14.4')
    stdlib = subprocess.check_output([str(compiler), '-where'], text=True).strip()
    pieces = ['import OCaml.Bytecode.Semantics', '',
              '/-! GENERATED by scripts/gen_primitive_binding_probe.py via runbc --lean. -/',
              'namespace OCaml.Vm.Sim.PrimitiveBinding', 'open OCaml.Bytecode', '']
    literals = []
    with tempfile.TemporaryDirectory(prefix='a1-primitive-binding-') as directory:
        directory = Path(directory)
        source = directory / 'probe.ml'
        executable = directory / 'probe.byte'
        source.write_text('external size : unit -> int = "caml_sys_const_word_size"\n'
                          'external exit : int -> \'a = "caml_sys_exit"\n'
                          'let () = exit (size ())\n')
        subprocess.run([str(compiler), '-nopervasives', '-nostdlib', '-I', stdlib,
                        '-o', str(executable), str(source)], check=True, capture_output=True)
        original = executable.read_bytes()
        word = b'caml_sys_const_word_size\0'
        integer = b'caml_sys_const_int_size\0'
        if original.count(word) != 1 or original.count(integer) != 1:
            raise ValueError('primitive names must occur exactly once')
        swapped = re.sub(b'caml_sys_const_(?:word|int)_size\x00',
                         lambda m: integer if m[0] == word else word, original)
        if len(original) != len(swapped):
            raise ValueError('primitive swap changed section lengths')
        for name, data, code in [('wordProbe', original, 64), ('swappedProbe', swapped, 63)]:
            executable.write_bytes(data)
            observed = subprocess.run([str(host), str(executable)], capture_output=True)
            if observed.returncode != code or observed.stdout:
                raise ValueError('host primitive probe disagrees')
            observed = subprocess.run([str(runbc), str(executable), '100'],
                                      capture_output=True, text=True)
            if f'halt exit (some {code})' not in observed.stderr or observed.stdout:
                raise ValueError('runbc primitive probe disagrees')
            literal = subprocess.check_output([str(runbc), '--lean', str(executable), name], text=True)
            pieces += [literal]
            literals.append([line.replace(name, 'probe') for line in literal.splitlines()
                             if not line.startswith(f'def {name}Prims')])
        if literals[0] != literals[1]:
            raise ValueError('probe programs differ outside primitive names')
    pieces += ['end OCaml.Vm.Sim.PrimitiveBinding', '']
    return {ROOT / 'OCaml/Vm/Sim/PrimitiveBindingData.lean': '\n'.join(pieces)}


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    for p, text in outputs().items():
        if args.check:
            if not p.exists() or p.read_text() != text:
                raise SystemExit(f'primitive probe drift: {p.relative_to(ROOT)}')
        else:
            p.write_text(text)
    print('Primitive binding probe current (host/runbc exits 64 and 63)')
