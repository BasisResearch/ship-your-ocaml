#!/usr/bin/env python3
"""Compose RESTART's generated empty/nonempty prefixes with represented inputs."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def render(kind):
    stem = kind.title()
    condition = '(positive : 3 < fields.length)' if kind == 'more' else '(empty : fields.length = 3)'
    branch = 'exact decide_eq_false (by omega)' if kind == 'more' else 'exact decide_eq_true (by omega)'
    pcproof = 'have positiveCount : 0 < fields.length - 3 := by omega\n      simp only [length, positiveCount, ite_true]; exact post.pcAt' if kind == 'more' else 'rw [length]; simp only [empty, Nat.sub_self, Nat.lt_irrefl, ite_false]; exact post.pcAt'
    return f'''-- GENERATED by scripts/gen_restart_setup.py; do not edit.
import OCaml.Vm.Sim.RestartInput
import OCaml.Vm.Sim.Immediate
import OCaml.Vm.Sim.StackPush
import OCaml.Vm.Sim.RestartPrefix{stem}Segment
import OCaml.Vm.Sim.RestartPrefix{stem}Pins

namespace OCaml.Vm.Sim
set_option autoImplicit false
open OCaml.Bytecode Vsa.Machine Vsa.Sim LeanRV64DExecutable LeanRV64DExecutable.Functions
open OCaml.Vm.Primitives

/-- RESTART's generated {kind} prefix prepares the saved-field copy. -/
theorem restart_setup_{kind} {{L : OCaml.Layout}} {{P : Prog}} {{s : St}} {{c d : Config}}
    {{pl : Place}} {{cp : ChanPlace}} {{sp high l a tag : Nat}} {{fields : List Val}}
    (h : ArmInput L P s .RESTART c pl cp sp high)
    (block : BlockSelection s.heap pl s.env l a tag fields)
    (space : RestartInput P s c pl cp sp high a fields) {condition}
    (dp : DispatchPost c .RESTART (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc)) d) :
    ∃ nb after, StepsN nb d after ∧
      RestartCopyStart c sp a (pl.codeBase + 4 * (s.pc + 1)) fields after := by
  have countSmall : fields.length - 3 < 2^31 := by have small := space.small; omega
  obtain ⟨header, headerEq⟩ : ∃ w : BitVec 64, w = word c (a - 8) := ⟨_, rfl⟩
  have size : header.toNat / 1024 = fields.length := by
    rw [headerEq]; exact block.header (payload_of_repr h.toVmReprAt) (by simp [roots])
  have shifted : Sail.shift_bits_right header (Sail.BitVec.extractLsb (0x0a#6) 5 0) =
      BitVec.ofNat 64 fields.length := header_words header fields.length size
  have count := restart_count_word fields.length space.lower space.small
  have limit : sign_extend (m := 64) (Sail.BitVec.extractLsb (BitVec.ofNat 64 fields.length) 31 0) =
      BitVec.ofNat 64 fields.length := by
    change ((BitVec.ofNat 64 fields.length).extractLsb' 0 32).signExtend 64 = _
    rw [low32_nat _ (by have small := space.small; omega)]
    exact sign_extend_nat32 _ space.small
  have base := restart_stack_word sp (fields.length - 3) space.room countSmall
  have guard : zopz0zKzJ_s (0#64) (BitVec.ofNat 64 (fields.length - 3)) = {'false' if kind == 'more' else 'true'} := by
    rw [restart_empty_guard _ countSmall]
    {branch}
  have loaded : sign_extend (m := 64) (bytesT8 d.σ.mem (a - 8)) = word c (a - 8) := by
    simp only [dp.memory, word, bytesT_eight_eq, sign_extend, Sail.BitVec.signExtend, BitVec.signExtend_eq]
  have bp : SegSt (0x80002b70#64) [⟨Register.x25, BitVec.ofNat 64 a⟩, ⟨Register.x9, BitVec.ofNat 64 sp⟩]
      (fun σ => Vsa.Sim.Code.CamlRestartPrefix{stem}Loaded σ.mem ∧ σ.mem = d.σ.mem ∧ σ = d.σ) d :=
    ⟨dp.good, dp.pc, ⟨(dp.frame.frame Register.x25 (by decide)).trans (represented_register h.env block.sourceWord),
      (dp.frame.frame Register.x9 (by decide)).trans h.spReg, trivial⟩,
      dp.good.minstret, dp.tick, restart_prefix_{kind}_loaded (dp.image h.dispatch.image), rfl, rfl⟩
  have run := tr_restart_prefix_{kind} (BitVec.ofNat 64 a) (BitVec.ofNat 64 sp) d.σ.mem d.σ
  simp only [push_address space.headerRoom, space.headerRead.toNat] at run
  have body := run space.headerRead.lower space.headerRead.upper space.headerRead.htif header (headerEq.trans loaded.symm)
  simp only [shifted, count, show sign_extend (m := 64) (0x000#12) = 0#64 from by decide,
    BitVec.add_zero, limit, base, show (0#64) + sign_extend (m := 64) (0x003#12) = 3#64 from by decide] at body
  obtain ⟨nb, after, _, steps, post⟩ := body guard d bp
  obtain ⟨_, memory, rawFrame⟩ := post.extra
  have fullMemory := memory.trans dp.memory
  have image : ExecutableImage after :=
    ⟨fun i hi => by rw [fullMemory]; exact h.dispatch.image.text i hi,
      fun i hi => by rw [fullMemory]; exact h.dispatch.image.rodata i hi⟩
  have frame := (dp.frame.trans rawFrame).widenChecked (allowed := restartSetupWrites) (by decide)
  refine ⟨nb, after, steps, ?_⟩
  constructor
  · have length : (stackWords c (a + 24) (fields.length - 3)).length = fields.length - 3 := by simp [stackWords]
    refine ⟨post.good, post.tick, image, Nat.zero_le _, ?_, PinsHold.get post.pins ⟨6, by simp⟩,
      ?_, PinsHold.get post.pins ⟨5, by simp⟩, ?_, rfl, ?_⟩
    · {pcproof}
    · simp only [Nat.mul_zero, Nat.add_zero, restartStart]
      exact PinsHold.get post.pins ⟨0, by simp⟩
    · have sizeEq : (stackWords c (a + 24) (fields.length - 3)).length + 3 = fields.length := by
        rw [length]; have low := space.lower; omega
      rw [sizeEq]
      exact PinsHold.get post.pins ⟨1, by simp⟩
    · exact (StepFrameOut.refl after.σ).widenChecked (allowed := forwardWrites) (by decide)
  · exact PinsHold.get post.pins ⟨2, by simp⟩
  · have next : gpr after 23 = some (BitVec.ofNat 64 (pl.codeBase + 4 * s.pc) + 4#64) :=
      (rawFrame.frame Register.x23 (by decide)).trans dp.nextCode
    simpa only [codePc_succ] using next
  · exact PinsHold.get post.pins ⟨4, by simp⟩
  · exact fullMemory
  · exact frame

end OCaml.Vm.Sim
'''

if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    for kind in ['more', 'empty']:
        path = ROOT / f'OCaml/Vm/Sim/RestartSetup{kind.title()}.lean'; output = render(kind)
        if args.check:
            if not path.exists() or path.read_text() != output: raise SystemExit(f'drift: {path}')
        else: path.write_text(output)
    print('RESTART setup adapters current')
