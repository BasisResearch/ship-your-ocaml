#!/usr/bin/env python3
"""Obligation census: hand proofs by cluster, with date and cost.

    python3 scripts/abstraction_census.py > abstractions/clusters.tsv

Clusters are declared in abstractions/clusters.def (cluster id, then
`file theorem` lines). For each member this tool finds the proof in the
file, measures its cost (lines from the `theorem` line to the next
top-level declaration, blank lines and comments excluded), and dates it by
the first commit that introduced the theorem's name into that file — in
this repository, or, for files copied from ship-your-interpreter, in that
repository (`~/Documents/code/syi`). Output rows are ordered by date within
each cluster: `cluster  date  cost  file  theorem`.

The gate (`scripts/check_abstraction_gate.py`) reads the TSV.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYI = Path.home() / "Documents/code/syi"
TOP = re.compile(r"^(theorem|lemma|def|abbrev|structure|inductive|instance|private|noncomputable|"
                 r"@\[|end |namespace |section |open |set_option|/-|--|#|example)")


def proof_cost(path: Path, name: str) -> int:
    lines = path.read_text().splitlines()
    pat = re.compile(r"^(private )?(theorem|lemma) (_root_\.)?" + re.escape(name) + r"(?=[\s({:]|$)")
    for i, l in enumerate(lines):
        if pat.match(l):
            n, j = 0, i
            while j < len(lines):
                s = lines[j].strip()
                if j > i and lines[j] and not lines[j][0].isspace() and TOP.match(lines[j]):
                    break
                if s and not s.startswith("--"):
                    n += 1
                j += 1
            return n
    raise SystemExit(f"abstraction_census.py: no theorem {name} in {path}")


def first_date(repo: Path, rel: str, name: str) -> str:
    short = name.split(".")[-1]
    out = subprocess.run(["git", "-C", str(repo), "log", "--reverse", "--format=%aI",
                          "-S", f"theorem {name}", "--", rel], capture_output=True, text=True).stdout.split()
    if not out:
        out = subprocess.run(["git", "-C", str(repo), "log", "--reverse", "--format=%aI",
                              "-S", short, "--", rel], capture_output=True, text=True).stdout.split()
    return out[0] if out else "unknown"


def main():
    defs = (ROOT / "abstractions/clusters.def").read_text().splitlines()
    rows, cluster = [], None
    for l in defs:
        l = l.split("#", 1)[0].strip()
        if not l:
            continue
        if l.startswith("cluster "):
            cluster = l.split()[1]
            continue
        rel, name = l.split()
        path = ROOT / rel
        # a file copied from ship-your-interpreter is dated by that history
        # (this repository's first commit only copied it)
        date = first_date(SYI, rel, name) if (SYI / rel).exists() else "unknown"
        if date == "unknown":
            date = first_date(ROOT, rel, name)
        rows.append((cluster, date, proof_cost(path, name), rel, name))
    rows.sort(key=lambda r: (r[0], r[1]))
    print("# cluster\tdate\tcost_lines\tfile\ttheorem  (generated by scripts/abstraction_census.py)")
    for r in rows:
        print("\t".join(map(str, r)))


if __name__ == "__main__":
    main()
