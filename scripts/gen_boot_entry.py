#!/usr/bin/env python3
"""Emit entry code and domain-field reads of the checked while_min store log."""
import argparse
import gzip
import json
import re
from pathlib import Path
from boot_certificate import emit_read, finite_cases

ROOT=Path(__file__).resolve().parents[1]
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--check', action='store_true')
args=ap.parse_args()
layout={k:int(v,0) for k,v in re.findall(r'^def (\w+) : Nat := (\w+)$',
    (ROOT/'OCaml/Vm/Layout.lean').read_text(), re.M)}
mem={}
for _,a,n,v in map(json.loads,gzip.open(ROOT/'results/boot/while_min-stores.jsonl.gz')):
    for i in range(n):mem[a+i]=(v>>(8*i))&255

def read(a,n=8):return sum(mem[a+i]<<(8*i) for i in range(n))
source=(ROOT/'OCaml/Programs/WhileMin.lean').read_text()
code=[int(x) for x in source.split('def whileMinCode : List Nat := [')[1].split(']')[0].split(', ')]
base=read(layout['sym_caml_start_code'])
domain=read(layout['sym_Caml_state'])
high=read(domain+layout['off_stack_high'])
out=['import OCaml.Vm.Boot.WhileMinHeap','import OCaml.Vm.Boot.WhileMinRuntime','import OCaml.Vm.Boot.WhileMinHeapChunks','',
     '/-! GENERATED by scripts/gen_boot_entry.py. Entry memory facts; no execution claim. -/',
     'namespace OCaml.Vm.Boot.WhileMinEntry','open OCaml.Bytecode OCaml.Programs',
     'open Vsa.Machine Vsa.Sim Vsa.Sim.Boot WhileMinLog WhileMinHeap','',
     f'def high : Nat := {high:#x}',
     'variable {c : Config} {initial : Vsa.MemRepr.Mem}','']
for name in ['caml_start_code','caml_global_data','caml_verb_gc','caml_cleanup_on_exit','atexit','stdio_exit_handler','caml_channel_mutex_unlock_exn',
             'fs_ready','caml_something_to_do','caml_channel_mutex_lock',
             'caml_channel_mutex_unlock','caml_all_opened_channels']:
    emit_read(out,name,f'Layout.sym_{name}',read(layout['sym_'+name]))
for name in ['stack_high','stack_low','stack_threshold','extern_sp','trapsp','trap_barrier','backtrace_active','ref_table','minor_heap_wsz']:
    emit_read(out,name,f'WhileMinRuntime.domain + Layout.off_{name}',read(domain+layout['off_'+name]))
emit_read(out,'prim_contents','Layout.sym_caml_prim_table + Layout.off_prim_contents',
          read(layout['sym_caml_prim_table']+layout['off_prim_contents']))
table=read(domain+layout['off_ref_table'])
for f in ['base','ptr','limit']:
    emit_read(out,f'ref_table_{f}',f'WhileMinHeapChunks.refTablePayload + Layout.off_ref_table_{f}',
              read(table+layout['off_ref_table_'+f]))
emit_read(out,'caml_gc_phase','Layout.sym_caml_gc_phase',read(layout['sym_caml_gc_phase'],4),4)
for fd in (1,2):
    emit_read(out,f'fd{fd}_kind',f'Layout.sym_fds + {24*fd}',read(layout['sym_fds']+24*fd))
pending=[emit_read(out,f'pending{i}',f'Layout.sym_caml_pending_signals + 8 * {i}',
                   read(layout['sym_caml_pending_signals']+8*i)) for i in range(32)]
assert all(read(layout['sym_caml_pending_signals']+8*i)==0 for i in range(32))
out += ['theorem pending (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        '    ∀ i : Fin 32, word c (Layout.sym_caml_pending_signals + 8 * i.val) = 0#64 :=',
        '  '+finite_cases(pending),'']
for i,w in enumerate(code):
    assert read(base+4*i,4)==w
    emit_read(out,f'code{i}',f'place.codeBase + 4 * {i}',w,4)
for lo in range(0,len(code),24):
    hi=min(lo+24,len(code))
    out += [f'theorem code_{lo}_{hi} (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
            f'    ∀ i : Fin {hi-lo}, word32 c (place.codeBase + 4 * ({lo} + i.val)) =',
            f"      (whileMinCode.map (BitVec.ofNat 32))[{lo} + i.val]'(by change {lo} + i.val < {len(code)}; omega) :=",
            '  '+finite_cases([f'read_code{i} memory' for i in range(lo,hi)]),'']
out += ['theorem code (memory : Vsa.Densify.MemEqv c.σ.mem (observedMem initial log)) :',
        '    ∀ i w, whileMin.code[i]? = some w → word32 c (place.codeBase + 4 * i) = w := by',
        '  intro i w hi',
        '  change (whileMinCode.map (BitVec.ofNat 32)).toArray[i]? = some w at hi',
        '  rw [List.getElem?_toArray] at hi',
        '  obtain ⟨bound, rfl⟩ := List.getElem?_eq_some_iff.mp hi',
        f'  have size : i < {len(code)} := bound']
for lo in range(0,len(code),24):
    hi=min(lo+24,len(code))
    out += [f'  by_cases h{hi} : i < {hi}',
            f'  · have low : {lo} ≤ i := by omega',
            f'    have index : i - {lo} < {hi-lo} := by omega',
            f'    simpa only [Nat.add_sub_cancel\' low] using code_{lo}_{hi} memory ⟨i - {lo}, index⟩']
out += ['  omega','end OCaml.Vm.Boot.WhileMinEntry','']
path=ROOT/'OCaml/Vm/Boot/WhileMinEntryReads.lean'
text='\n'.join(out)
if args.check:
    if not path.exists() or path.read_text()!=text:raise SystemExit('boot entry read drift')
elif not path.exists() or path.read_text()!=text:path.write_text(text)
print(f'Entry certificate: {len(code)} code words, stack high {high:#x}')
