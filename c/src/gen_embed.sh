#!/bin/sh
# Emit embed.S: everything that varies with the embedded program, in the
# `.embed` section at a FIXED address (src/link.ld), so the runtime's code
# and data are byte-identical whatever program is embedded:
#   gen_embed.sh [--cargs '"a","b",'] [--runparam S] /path/in/image=host/file ...
# The section starts with a fixed three-pointer header (so the code's
# addresses do not depend on how many files or arguments follow):
# * `embedded_files`: -> {path, start, end} triples, NULL-terminated (htif.c);
# * `embedded_argv`: -> { "ocamlrun", "/prog", args..., NULL } (main.c);
# * `embedded_env`: -> { "OCAMLRUNPARAM=<S>", NULL } (main.c).
set -e
cargs=; runparam=
while :; do
  case "$1" in
    --cargs) cargs=$2; shift 2 ;;
    --runparam) runparam=$2; shift 2 ;;
    *) break ;;
  esac
done
echo '/* Generated by gen_embed.sh: the embedded program, its files and command line (see main.c, htif.c). */'
echo '    .section .embed,"aw"'
echo '    .balign 8'
echo '    .globl embedded_files, embedded_argv, embedded_env'
echo 'embedded_files: .dword _files_table'
echo 'embedded_argv: .dword _argv_table'
echo 'embedded_env: .dword _env_table'
echo '_files_table:'
i=0
for spec in "$@"; do
  echo "    .dword _file${i}_path, _file${i}_start, _file${i}_end"
  i=$((i+1))
done
echo '    .dword 0, 0, 0'
echo '_argv_table:'
echo '    .dword _arg_ocamlrun, _arg_prog'
n=0
args=$(printf '%s' "$cargs" | grep -o '"[^"]*"' || true)
# one argument per line, quotes kept (they are asm string literals)
echo "$args" | while IFS= read -r a; do [ -n "$a" ] && echo "    .dword _arg${n}_$(printf '%s' "$a" | cksum | cut -d' ' -f1)"; n=$((n+1)); done
echo '    .dword 0'
echo '_env_table:'
echo '    .dword _env_runparam, 0'
echo '_arg_ocamlrun: .asciz "ocamlrun"'
echo '_arg_prog: .asciz "/prog"'
n=0
echo "$args" | while IFS= read -r a; do [ -n "$a" ] && echo "_arg${n}_$(printf '%s' "$a" | cksum | cut -d' ' -f1): .asciz $a"; n=$((n+1)); done
echo "_env_runparam: .asciz \"OCAMLRUNPARAM=$runparam\""
i=0
for spec in "$@"; do
  path=${spec%%=*}; file=${spec#*=}
  [ -f "$file" ] || { echo "gen_embed.sh: no such file: $file" >&2; exit 1; }
  echo "    .balign 8"
  echo "_file${i}_start:"
  echo "    .incbin \"$file\""
  echo "_file${i}_end:"
  echo "    .byte 0"
  echo "_file${i}_path:"
  echo "    .asciz \"$path\""
  i=$((i+1))
done
