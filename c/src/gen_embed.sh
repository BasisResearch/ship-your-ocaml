#!/bin/sh
# Emit embed.S linking files into the image for htif.c's file system.
#   gen_embed.sh /path/in/image=host/file ... > embed.S
# The table `embedded_files` is {path, start, end} triples, NULL-terminated.
set -e
echo '/* Generated by gen_embed.sh: files embedded in the image (see htif.c). */'
echo '    .section .rodata'
i=0
for spec in "$@"; do
  path=${spec%%=*}; file=${spec#*=}
  [ -f "$file" ] || { echo "gen_embed.sh: no such file: $file" >&2; exit 1; }
  echo "    .balign 8"
  echo "_file${i}_start:"
  echo "    .incbin \"$file\""
  echo "_file${i}_end:"
  echo "    .byte 0"
  echo "_file${i}_path:"
  echo "    .asciz \"$path\""
  i=$((i+1))
done
echo '    .balign 8'
echo '    .globl embedded_files'
echo 'embedded_files:'
j=0
while [ $j -lt $i ]; do
  echo "    .dword _file${j}_path, _file${j}_start, _file${j}_end"
  j=$((j+1))
done
echo '    .dword 0, 0, 0'
